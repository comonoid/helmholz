#ifndef HZ_CUT_DCSLICE_H
#define HZ_CUT_DCSLICE_H

/* СРЕЗ (PLAN_ELEMENTS.md §382, §397; шаг Ш2).
 *
 * ЧТО ЭТО. Плоский МАССИВ ячеек в мортоновом порядке — материализованный
 * результат обхода дерева. Единственное, что читает фронт; дерево, таблицу рёбер
 * и формы QEF он не читает вовсе. Отсюда и деление А662: хранить плотно надо то,
 * что горячий путь читает ПОСЛЕДОВАТЕЛЬНО И НА КАЖДУЮ ЯЧЕЙКУ, а не всё подряд.
 *
 * МАССИВ, А НЕ ДЕРЕВО, И ЭТО ПРОВЕРЯЕМОЕ УТВЕРЖДЕНИЕ (§382): запрос К СРЕЗУ ПО
 * КООРДИНАТЕ есть признак того, что заведено второе дерево. Здесь такого запроса
 * нет ни одного — только последовательный проход.
 *
 * РАЗМЕР ЯЧЕЙКИ — 20 Б, И ЭТО ИСХОД ЗАМЕРА, А НЕ ПРОЕКТА (§399). Сначала было
 * 16 Б с МОРТОНОВЫМ КОДОМ в четырёх байтах, и обход стоил 60 нс на ячейку при
 * потоке 2.4 нс: 36…41 нс уходили на разбор кода ЦИКЛОМ ПО УРОВНЯМ. Компактность
 * адреса покупалась распаковкой на каждую ячейку — ровно тот размен, который
 * правило А662 запрещает на ГОРЯЧЕМ пути. Поэтому координата ячейки лежит прямо:
 *     lo[3]   6 Б  координаты в сетке САМОГО МЕЛКОГО уровня (предел lev <= 16);
 *     нормаль 2 Б  октаэдрическая, 8+8 бит; измеренная ошибка p90 0.43 град;
 *     облучённость 6 Б  три half — РЕЗЕРВ, потребителя ещё нет (Ш5);
 *     вершина 3 Б  доли ячейки, по байту на ось; смещение ровно полкванта;
 *     уровень 1 Б, материал 1 Б (РЕЗЕРВ), выравнивание 1 Б.
 * Резерв назван резервом сознательно: иначе «20 Б» читается как «всё есть».
 * ПРЕДЕЛ lev <= 16 назван прямо: координата не влезает в uint16 выше него, и
 * молча это ломаться не должно.
 *
 * ЧТО КВАНТУЕТСЯ, А ЧТО НЕТ (А723). Квантуется ВЕРШИНА — она ПРОИЗВОДНОЕ и
 * пересчитывается из долговечного. Эрмитово `t` на ребре НЕ квантуется: это
 * данные, а не раскладка, и трогать их надо отдельным разбором.
 */

#include "cut/dc.h"
#include <stdint.h>

/* Квант вершины по умолчанию — 8 бит на ось, то есть `h/255`. Число не
 * магическое: это ровно байт, и его цена печатается замером против измеренной
 * ошибки поверхности (А721). Негативный контроль ставит 1 бит. */
#define HZ_SLICE_VBITS 8

/* Предел уровня: координата ячейки лежит в uint16. Названа константой, а не
 * подразумевается, чтобы выход за неё был ошибкой, а не тихой порчей. */
#define HZ_SLICE_MAX_LEV 16

typedef struct {
  uint16_t lo[3];  /* координаты ячейки в сетке самого мелкого уровня */
  uint16_t noct;   /* нормаль ячейки, октаэдрическая 8+8 */
  uint16_t irr[3]; /* облучённость — РЕЗЕРВ под Ш5 */
  uint8_t vx[3];   /* вершина в долях ячейки */
  uint8_t lvl;     /* уровень ячейки: её сторона = 1 << (lev - lvl) */
  uint8_t mat;     /* материал — РЕЗЕРВ */
  uint8_t pad;
} hz_dccell;

typedef struct {
  hz_dccell *c;
  int32_t n, cap;
  int lev;
  int vbits; /* сколько бит вершины реально значимо (негативный контроль) */
} hz_dcslice;

int hz_slice_init(hz_dcslice *s, int lev);
void hz_slice_free(hz_dcslice *s);

/* Построить срез обходом дерева в МОРТОНОВОМ порядке (порядок детей 0..7 и есть
 * мортонов, если бит 0 — это x). `stop` — тот же предикат среза, что у
 * `hz_dc_walk`; NULL = полная глубина. Ячейка попадает в срез тогда и только
 * тогда, когда у неё ЕСТЬ вершина.
 * Нормаль ячейки берётся как нормированная сумма нормалей её пересечённых рёбер:
 * своего поля у узла нет и заводить его незачем — величина производная. */
int hz_slice_build(hz_dcslice *s, const hz_dctree *t, const hz_htab *ht, hz_dc_stop stop,
                   void *sctx);

/* Мировая (в координатах ДЕРЕВА, то есть в ячейках) позиция вершины ячейки `i`. */
void hz_slice_vertex(const hz_dcslice *s, int32_t i, double v[3]);
void hz_slice_normal(const hz_dcslice *s, int32_t i, double n[3]);

/* Октаэдрическое кодирование — наружу, потому что его ошибку надо МЕРИТЬ, а не
 * предполагать: замер угла между исходной и восстановленной нормалью идёт в
 * доклад шага. */
uint16_t hz_oct_encode(const double n[3]);
void hz_oct_decode(uint16_t o, double n[3]);

#endif
