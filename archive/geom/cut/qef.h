#ifndef HZ_CUT_QEF_H
#define HZ_CUT_QEF_H

/* ОБЩИЙ СЛОЙ (PLAN_CUT.md, Р-5б). Квадратичная ошибка эрмитовых образцов:
 *
 *     E(x) = Σ (n_i · (x − p_i))²  =  xᵀAx − 2 bᵀx + c,
 *     A = Σ n nᵀ (6 чисел по симметрии),  b = Σ n (n·p) (3),  c = Σ (n·p)² (1)
 *
 * ХРАНИТСЯ МАТРИЦА, А НЕ ТОЛЬКО ВЕРШИНА, и это не запас: на АДДИТИВНОСТИ формы
 * стоит восходящее упрощение (Г13) и починка после разрушения сложением по
 * цепочке предков за O(глубины). Вершина — производное от формы.
 *
 * КООРДИНАТЫ ЛОКАЛЬНЫЕ ПО УЗЛУ, И ЭТО НЕ УДОБСТВО (Г41). В едином кадре дерева
 * c ~ |p|²N: при log2size = 19 это ~1e11, а невязка считается вычитанием близких
 * больших чисел, то есть её абсолютная ошибка ~1e-5 при самой невязке ~1e-6.
 * Решение об упрощении уровня принимается ПО НЕВЯЗКЕ, значит в едином кадре LOD
 * выбирался бы по шуму. Сложение поэтому идёт СО СДВИГОМ (hz_qef_add_shifted) —
 * точный перенос квадратичной формы, а не приближение.
 *
 * АДДИТИВНОСТЬ НЕ ПОБИТОВА (Г49). В точной арифметике «форма родителя = сумма
 * форм детей» — тождество; в двойной сложение неассоциативно, поэтому «всё
 * подряд» и «сумма половин» совпадают лишь до округления. Побитовым является
 * другое, и именно оно нужно Г13: ПОЧИНКА против ПОЛНОЙ ПЕРЕСТРОЙКИ, где
 * порядок и группировка сложений одни и те же. */

#include <stdint.h>

typedef struct {
  double a[6]; /* AᵀA в порядке xx, xy, xz, yy, yz, zz */
  double b[3]; /* Aᵀb */
  double c;    /* bᵀb */
  double m[3]; /* Σ p — МАССА. Не роскошь: при усечении вырожденных направлений
                * вершина обязана уехать в массу, а не в ноль, иначе плоская
                * стена отправила бы её в начало координат. */
  int32_t n;
} hz_qef;

typedef enum {
  HZ_QEF_OK = 0,
  HZ_QEF_CLAMPED = 1, /* минимум был вне коробки, вершина загнана внутрь */
  HZ_QEF_EMPTY = 2    /* образцов нет: вершины не существует, а не «она в нуле» */
} hz_qef_status;

/* Порог усечения собственных чисел, ОТНОСИТЕЛЬНЫЙ к максимальному. Выведен, а не
 * подобран (CLAUDE.md: магических порогов нет): AᵀA возводит число
 * обусловленности в квадрат, поэтому направление с λ ниже sqrt(DBL_EPSILON) от
 * максимума в двойной точности неотличимо от нулевого. sqrt(2^-52) = 2^-26.
 * Общепринятое в литературе по DC 0.1 (по сингулярным числам, то есть 0.01 по
 * собственным) — ровно магический порог, и здесь он запрещён; в тестах он стоит
 * НЕГАТИВНЫМ КОНТРОЛЕМ и обязан сдвигать вершину на гладкой поверхности. */
#define HZ_QEF_TAU_REL 0x1p-26

/* Обметаний циклического Якоби. Верхняя граница, а не расчёт: цикл выходит
 * раньше по норме внедиагонали (сходимость квадратичная, на 3x3 хватает 5-6);
 * тест меряет и норму внедиагонали, и ошибку восстановления A = VΛVᵀ. */
#define HZ_QEF_SWEEPS 12

void hz_qef_zero(hz_qef *q);

/* Один эрмитов образец: точка на поверхности и ЕДИНИЧНАЯ нормаль в ней. Вес
 * образца есть |n|², поэтому неединичная нормаль молча перевесила бы остальные. */
void hz_qef_add_sample(hz_qef *q, const double p[3], const double nrm[3]);

/* dst += src, перенесённая на t: если src записана в координатах y, а dst в
 * координатах x = y + t, то A не меняется, b += A t, c += 2 tᵀb + tᵀA t.
 * Точная алгебра переноса квадратичной формы (Г41). */
void hz_qef_add_shifted(hz_qef *dst, const hz_qef *src, const double t[3]);

double hz_qef_eval(const hz_qef *q, const double x[3]);

/* Минимум формы с усечением по tau_rel (см. HZ_QEF_TAU_REL). Вырожденные
 * направления дают массу: x = x̄ + Σ_{λ>τ} (v·(b − A x̄))/λ · v. */
int hz_qef_solve_tau(const hz_qef *q, double tau_rel, double x[3], double *resid);

/* То же с порогом по умолчанию и ЗАЖИМОМ в коробку [lo, hi] — ВТОРОЙ, отдельный
 * механизм (Г12, оговорка 1): порог из точности не спасает от почти вырожденного
 * направления, где вершина уезжает далеко, но законно. Зажим НЕ МОЛЧИТ:
 * возвращается HZ_QEF_CLAMPED, и хозяин обязан его считать — «вершина внутри» и
 * «вершина загнана внутрь» разные вещи (класс Г38). */
int hz_qef_solve(const hz_qef *q, const double lo[3], const double hi[3], double x[3],
                 double *resid);

/* Симметричная 3x3: собственные числа val и столбцы-векторы vec[][i]. Вынесена в
 * заголовок ради собственного фальсификатора (ошибка восстановления A = VΛVᵀ). */
void hz_qef_jacobi3(const double a[6], double val[3], double vec[3][3]);

#endif
