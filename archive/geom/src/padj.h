/* padj.h — СМЕЖНОСТЬ РЁБЕР ТРЕУГОЛЬНОГО СУПА: уникальные рёбра и их грани.
 *
 * ЛИНИЯ ПЕРЕНОСА, PLAN_ELEMENTS.md. Вынесено из `tools/psil.c` (шаг О55) по
 * тому же доводу, что сетка и форм-фактор: стенду фронта нужен ТОТ ЖЕ набор
 * рёбер, что стенду силуэтов, иначе «`8 585 954` рёбер у города» в двух
 * докладах будет означать два разных множества, и сравнить их будет нельзя.
 *
 * КАК СТРОИТСЯ — ВЁДРАМИ ПО МЛАДШЕЙ ВЕРШИНЕ (CSR), а не хешем и не сортировкой:
 * у `20.1` млн рёбер-слотов это один линейный проход плюс разбор вёдер по шесть
 * записей, то есть тот класс, который в А285 давал двухчасовые зависания, здесь
 * не заводится вовсе. Замерено: `0.4` с на городе.
 *
 * ТРИ КЛАССА РЕБРА, И ОНИ РАЗНЫЕ (А336):
 *   ГРАНИЧНОЕ    — одна смежная грань; от наблюдателя НЕ зависит вовсе;
 *   МАНИФОЛДНОЕ  — ровно две; только на нём определён силуэт;
 *   НЕМАНИФОЛДНОЕ — больше двух. У Rungholt их `9.2 %` (воксельные стыки,
 *                  §105.2). «Лицевая и изнаночная» для них определено, но
 *                  неоднозначно, поэтому они считаются ОТДЕЛЬНО и не
 *                  подмешиваются в главные таблицы.
 */
#ifndef HZ_PADJ_H
#define HZ_PADJ_H

#include "scene_obj.h"
#include <stdint.h>

/* СКОЛЬКО ГРАНЕЙ РЕБРА ХРАНИТСЯ. У воксельного стыка их четыре; рёбра с
 * бо́льшим числом считаются в `nover`, чтобы «не поместилось» не выглядело как
 * «не бывает». */
#define HZ_PADJ_MAXF 4

typedef struct {
  int32_t *ea, *eb;   /* ne, вершины ребра; всегда `ea < eb` */
  int32_t *ef;        /* ne * HZ_PADJ_MAXF, индексы смежных граней */
  unsigned char *enf; /* ne, число смежных граней, насыщено на 255 */
  int64_t ne;         /* уникальных рёбер */
  int64_t nb1;        /* из них граничных (одна грань) */
  int64_t nb2;        /* манифолдных (две грани) */
  int64_t nbm;        /* неманифолдных (больше двух) */
  int64_t nover;      /* из неманифолдных: граней больше HZ_PADJ_MAXF */
} hz_padj;

/* Возврат: 0 — успех, 2 — нет памяти. При ненулевом возврате звать
 * `hz_padj_free` можно и нужно. */
int hz_padj_build(hz_padj *A, const hz_objmesh *m);
void hz_padj_free(hz_padj *A);

#endif
