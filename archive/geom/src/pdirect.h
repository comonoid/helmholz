/* pdirect.h — ПРЯМОЙ СВЕТ ОТ КОМПАКТНЫХ ИСТОЧНИКОВ: аналитически, ВНЕ ординат.
 *
 * PLAN_ELEMENTS.md §1.5 (Р6, К9). Ш5 измерил, чего стоит нарушение этого
 * правила: восемь светильников `0.3×0.3` м, пропущенные через ординаты, при
 * `ND = 256` оставляют **11% площади сцены с ошибкой радианса больше 10%**, и
 * сходимости по `ND` не видно. Тот же зал с протяжённым источником той же
 * мощности даёт `0.07%`. Разница — лучевой эффект (К3): источник углового
 * размера `α ≈ 0.15` рад виден лишь вдоль тех немногих ординат, что в него
 * попали.
 *
 * ЗАМКНУТАЯ ФОРМА, А НЕ ВЫБОРКА ПО ИСТОЧНИКУ. Облучённость точки `x` с нормалью
 * `n` от ПЛОСКОГО ламбертова многоугольника с радиансом `L` есть
 *
 *     E = (L/2) · Σ_рёбра θ_i · (n · û_i),
 *
 * где `θ_i` — угол между направлениями на концы ребра, `û_i` — единичная
 * нормаль треугольника `(x, p_i, p_{i+1})`. Это ТОЧНО, без квадратуры и без
 * зависимости от углового размера источника — то есть ровно то, чего ординаты
 * дать не могут.
 *
 * ИСТОЧНИК ОБРЕЗАЕТСЯ ПО ГОРИЗОНТУ ПРИЁМНИКА. Формула верна, когда источник
 * целиком в полупространстве `n·(p−x) > 0`; иначе она считает и то, что ниже
 * горизонта, со ЗНАКОМ, и даёт заниженное или отрицательное значение. Поэтому
 * многоугольник источника сперва отсекается плоскостью приёмника — обычным
 * отсечением выпуклого многоугольника полупространством.
 *
 * ЗАСЛОНЁННОСТЬ — ВЫЧИСЛЕНИЕ, А НЕ ТАБЛИЦА (§6). Она берётся лучами к
 * нескольким точкам источника; доля непрозрачных даёт `V ∈ [0,1]`, и полутень
 * получается ступенчатой по числу проб. Это ЗАЯВЛЕННАЯ грубость: сглаживать её
 * должен не рост числа проб, а РАЗРЕЗ (Ш6) — там, где полутень уже резолюции.
 *
 * КОРРЕЛЯЦИЯ `V` С УГЛОВЫМ ВЕСОМ НЕ УЧТЕНА, и это записано как приближение:
 * произведение «замкнутая форма × средняя видимость» точно лишь когда
 * заслонённая часть источника не выделена. У края тени это не так, и ошибка
 * там порядка `1/nvis`; ровно там Ш6 и ставит разрез.
 */
#ifndef HZ_PDIRECT_H
#define HZ_PDIRECT_H

#include "pray.h"
#include "psweep.h"

/* Облучённость от полигона-источника `src` в точке `x` с нормалью `n`,
 * БЕЗ заслонения. Радианс источника берётся как `t->Le[src]`. */
double hz_direct_unocc(const hz_polyset *ps, int32_t src, double Le, const double x[3],
                       const double n[3]);

/* Добавляет моменты прямого света в `t->acc`. Вызывается ПОСЛЕ обнуления и ДО
 * решения — то есть в паре с `hz_psweep_gather`, а не вместо него.
 * `nvis` — проб видимости на источник по каждой оси (`nvis²` лучей).
 * `hsamp` — желаемый шаг выборки по полигону-приёмнику, м.
 *
 * `Le` — РАДИАНС ИСТОЧНИКОВ ОТДЕЛЬНЫМ МАССИВОМ, А НЕ `t->Le`, и эта разница
 * однажды уже стоила прогона. Чтобы источник не излучал ЕЩЁ И в ординатной
 * развёртке (двойной учёт, К9), его `t->Le` обнуляют; прямой свет, читавший
 * оттуда же, молча становился нулём, и картинка оставалась без прямого света
 * вовсе. Подпись у ошибки была характерная и её стоит запомнить: **метрика
 * перестала зависеть ОТ ВСЕГО** — ни от числа полигонов, ни от разрезов, ни от
 * шага дробящей сетки. Величина, не реагирующая ни на один параметр, которым её
 * меняют, не измеряет ничего (третья подпись артефакта из CLAUDE.md). */
/* ПОТОЛОК ВЫБОРКИ ПО ПРИЁМНИКУ — ПАРАМЕТР, А НЕ КОНСТАНТА (§80). Стояло `64` по
 * оси, то есть до `4096` точек на элемент, при том что подгоняются ТРИ
 * коэффициента. Комментарий рядом честно говорил «с огромным запасом», но запас
 * никто не мерил, и он оказался тысячекратным: на городе это `116 022` элемента ×
 * до `4096` точек = до `475` млн теневых лучей, то есть `101.6 с` прямого света
 * при `1.2 с` свипа. `0` читается как прежние `64`. */
int hz_direct_add(hz_ptrans *t, const hz_pray *g, const int32_t *src, int nsrc, const double *Le,
                  int nvis, double hsamp, int cap, hz_pstats *st);

#endif
