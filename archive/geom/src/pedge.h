/* pedge.h — СОГЛАСОВАННОЕ УПРОЩЕНИЕ КРАЯ.
 *
 * PLAN_ELEMENTS.md, §10, открытый пункт 1. Ш7 (четвёртая поправка) измерил, что
 * край жмётся приближением `2.4×` практически даром (57 → 24 вершины на полигон
 * при ошибке площади `1.2e−4`), и там же назвал предел: **упрощение шло
 * НЕЗАВИСИМО по полигонам, и общее ребро двух соседей переставало совпадать**.
 * После 5 мм это давало щели, а щель — не «грубее», это ДРУГАЯ поверхность.
 *
 * ЛЕЧЕНИЕ НЕ «ЗАПЕРЕТЬ ГРАНИЦЫ ГРУПП», А ПРИПИСАТЬ РЕШЕНИЕ ВЕРШИНЕ. У Nanite
 * границы группы заперты целиком, потому что там группа — это единица
 * упрощения, и внутри неё делается edge-collapse, двигающий вершины. Здесь
 * ход другой и дешевле: Дуглас–Пекер вершин не двигает, он их только
 * ВЫБРАСЫВАЕТ, — а значит достаточно, чтобы выброшенное множество было ОДНИМ И
 * ТЕМ ЖЕ у всех полигонов, которые вершину делят. Тогда щель невозможна ПО
 * ПОСТРОЕНИЮ, а не по замеру: оба соседа проходят по одной и той же ломаной.
 *
 * ЕДИНИЦА РАБОТЫ — ЦЕПЬ, А НЕ ПЕТЛЯ. Край сцены распадается на цепи между
 * СТЫКАМИ. Стык — вершина, у которой соседей по краю не два (там сходятся три и
 * более полигона либо край сам себя касается); такая вершина ЗАПИРАЕТСЯ, потому
 * что выбросить её значило бы решать за несколько цепей сразу. Внутренность
 * цепи упрощается ОДИН раз, и результат читают оба её владельца.
 *
 * РАССТОЯНИЕ МЕРЯЕТСЯ В МИРЕ, А НЕ В (u,v). У соседей рамы разные, и одна и та
 * же дуга в плоскости A может проецироваться в прямую в плоскости B: меряя в
 * (u,v), два владельца получили бы РАЗНЫЕ отклонения от одной хорды. Мировая
 * точка берётся КАНОНИЧЕСКИ — по первому (наименьшему) полигону-владельцу;
 * расхождение мировых точек у владельцев не превышает `dmax ≤ δ` и уже учтено.
 *
 * НЕЗАВИСИМЫЙ РЕЖИМ ОСТАВЛЕН НАРОЧНО — это НЕГАТИВНЫЙ КОНТРОЛЬ. Он отличается
 * от согласованного РОВНО одним: кто принимает решение. Метод, допуск, мера
 * расстояния и канонические точки те же. Иначе сравнение мерило бы разницу
 * реализаций, а не разницу схем.
 *
 * ЧТО НЕ ТРОГАЕТСЯ. `mom`, `area` и `dmax` полигона считаны по ТРЕУГОЛЬНИКАМ
 * (`polygon.c`) и упрощением края не меняются — упрощается только ломаная, по
 * которой луч и растеризатор решают «внутри или нет». Расхождение между
 * площадью по моментам и площадью по краю ограничено допуском и ДОКЛАДЫВАЕТСЯ
 * стендом, а не подразумевается нулевым.
 */
#ifndef HZ_PEDGE_H
#define HZ_PEDGE_H

#include "polygon.h"

typedef enum {
  HZ_EDGE_SHARED = 0, /* решение приписано ВЕРШИНЕ: цепь упрощается один раз */
  HZ_EDGE_INDEP = 1,  /* НЕГАТИВНЫЙ КОНТРОЛЬ: каждый полигон решает сам */
  /* То же, что SHARED, но ОТКРЫТЫЙ край (вершина принадлежит одному полигону)
   * заперт. Согласование лечит ШОВ; открытый край соседа не имеет, и сдвинуть
   * его на допуск значит открыть дыру, за которой сразу видно дальнюю стену. У
   * зала таких рёбер 44.6% — не мелочь, и разделить две причины можно только
   * замером, а не рассуждением. */
  HZ_EDGE_SHARED_INNER = 2
} hz_edgemode;

typedef struct {
  int64_t nbv_in, nbv_out; /* вершин края до и после */
  int64_t nlock;           /* запертых сварных вершин (стыки и несварные) */
  int64_t nfree;           /* свободных сварных вершин */
  int64_t nchain;          /* цепей между стыками */
  int64_t ncycle;          /* из них замкнутых (стыков нет вовсе) */
  int64_t nloop_short;     /* петель, упавших ниже 3 вершин и оставленных как есть */
} hz_edgestat;

/* Упростить край НА МЕСТЕ. `tol` — допуск в метрах (мировых). */
int hz_edge_simplify(hz_polyset *ps, double tol, hz_edgemode mode, hz_edgestat *st);

/* НЕСОПРЯЖЁННЫЕ РЁБРА — прямая мера щели, не требующая ни лучей, ни картинки.
 * Ребро края, взятое в СВАРНЫХ номерах, обязано принадлежать либо двум
 * полигонам (внутренний шов), либо одному (открытый край сцены, у зала это
 * 4.77% полурёбер — измерено в Ш2). Упрощение НЕ ИМЕЕТ ПРАВА менять число
 * одиночных: выброс вершины у обоих владельцев заменяет два общих ребра одним
 * общим. Рост одиночных и есть щель.
 * Рёбра с несварной вершиной (`bw < 0`) не считаются вовсе. */
void hz_edge_unpaired(const hz_polyset *ps, int64_t *nedge, int64_t *nsingle);

#endif
