/* psweep.h — ЯДРО: ПРОЕКЦИЯ РАСТЕРИЗОВАННОГО НА ПОЛИНОМИАЛЬНЫЙ БАЗИС.
 *
 * PLAN_ELEMENTS.md, Ш3 — внутренний цикл всей схемы, делаемый ТРЕТЬИМ, а не
 * последним: картинка есть следствие, а не проверка ядра.
 *
 * ЧТО СЧИТАЕТСЯ. Неизвестная — ОБЛУЧЁННОСТЬ `E(u,v)` на полигоне, линейная по
 * двум местным переменным (§1.2: `P0` дал бы ошибку `~h` вместо `~h²`, а при
 * цели 1% это ×33 по числу полигонов). Радианс НЕ хранится:
 * `L_out = L_e + ρ·E/π`, альбедо применяется при чтении (Т1), поэтому текстура
 * не режет полигоны ради изображения.
 *
 * КАК СЧИТАЕТСЯ. На направление `ω` — параллельная проекция всех полигонов
 * (`prast.h`), порядок по глубине, и на КАЖДОЙ паре соседей вдоль луча
 * «излучатель → приёмник» накапливаются три момента:
 *
 *     m₀ += w_ω·h²·L,   m_u += w_ω·h²·L·u,   m_v += w_ω·h²·L·v
 *
 * После обхода ВСЕХ направлений решается малая система `M·c = m`, где
 *
 *     M = [[∫1, ∫u, ∫v], [∫u, ∫u², ∫uv], [∫v, ∫uv, ∫v²]]
 *
 * — ровно моменты полигона, посчитанные ОДИН РАЗ при импорте (Ш2). От
 * направления `M` не зависит, поэтому обращается она один раз на полигон за всю
 * развёртку, а не один раз на (полигон × направление).
 *
 * МНОЖИТЕЛЯ `cos θ` В КОДЕ НЕТ, и это не забывчивость: он сокращается с
 * якобианом проекции точно (разбор в `prast.h`). Заодно исчезает вырождение на
 * скользящих углах.
 *
 * ОГРАНИЧИТЕЛЬ СОХРАНЯЕТ И КОНСТАНТУ, И ЭНЕРГИЮ (К6: «ограничитель обязан
 * сохранять константы, иначе печь бессмысленна»). Линейное `E` может уйти в
 * минус у края полигона; тогда градиент домножается на `α < 1` до касания нуля,
 * а `c₀` правится так, что `∫E` не меняется. У постоянного поля градиент нулевой
 * ⇒ ограничитель его не трогает ВООБЩЕ, то есть печь он завалить не может по
 * построению, а не по замеру.
 *
 * ПРЯМОЙ СВЕТ — ОТДЕЛЬНЫМ ПРОХОДОМ, ВНЕ ОРДИНАТ (§1.5, Р6, К9). Удалённый
 * источник даёт коллимированный пучок, который ни одна ординатная квадратура не
 * представляет; он гоняется ТЕМ ЖЕ растеризатором по своему направлению, и
 * первый фрагмент каждого пикселя получает `E_perp·h²`. Двойного учёта нет,
 * потому что в ординатной развёртке этого источника нет вовсе.
 */
#ifndef HZ_PSWEEP_H
#define HZ_PSWEEP_H

#include "polygon.h"
#include "prast.h"
#include "transport/dirs3.h"

typedef struct {
  const hz_polyset *ps;
  int32_t np;
  double *rho; /* альбедо, np */
  double *Le;  /* собственный радианс, np */
  double *E;   /* 3·np: E(u,v) = c0 + c1·u + c2·v */
  double *acc; /* 3·np: накопитель моментов текущего отскока */
  /* ПОПРАВКА КВАДРАТУРЫ ПО НОРМАЛИ (§127), `np` штук; `NULL` — не поправлять.
   * Косинус в `psweep` сокращается с якобианом проекции ТОЧНО, поэтому вся
   * угловая ошибка сидит в одном: дискретный набор направлений интегрирует
   * `cosθ` по полусфере неточно, и дефект `S(n) = Σ_{ω·n<0} w_ω|ω·n|` против `π`
   * зависит ТОЛЬКО от нормали и от набора. Значит он считается один раз на
   * полигон и делением снимается — лишних проходов не требуется вовсе.
   * Величину эту меряет стенд `pconv` (замер A), но нигде не применялась. */
  double *qn;
  /* РАЗРУШЕННАЯ ГЕОМЕТРИЯ (§124): `live[k] == 0` — полигона в сцене больше нет,
   * он не рисуется, не заслоняет и не светит. `NULL` — все живы. Заведено
   * затем, что цель §108 — изменяемая геометрия, и мерить её надо не
   * рассуждением, а выключением кусков сцены. */
  const unsigned char *live;
  /* ЧЕРНОВИК ПОТОКОВ, ПЕРЕЖИВАЮЩИЙ ВЫЗОВ (§128). Замерено профилем: буферы
   * потоков (`3·np` double на поток плюс буфер фрагментов) выделялись на КАЖДЫЙ
   * сбор, то есть на каждую итерацию заново. Здесь они держатся у переноса и
   * переиспользуются, пока совпадают параметры, под которые заведены. */
  void *pool;
  int pool_nt, pool_layout;
  int64_t pool_maxpix, pool_cap;
  int32_t pool_np;
  /* ГАБАРИТ СЦЕНЫ — ОДИН РАЗ, А НЕ НА КАЖДОЕ НАПРАВЛЕНИЕ (§128, `3.2 %` профиля). */
  double box_lo[3], box_hi[3];
  int box_ok;
  /* ЗАПИСЬ ПАР «приёмник ← излучатель» (§137, З1). Включается ненулевой ёмкостью;
   * иначе не стоит ничего. Нужна затем, что связность соседних направлений
   * мерится по ПАРАМ, а не по пикселям: рама растра строится от направления, и
   * «тот же пиксель» у разных `ω` не определён (А307/А309). */
  int32_t *pair_k, *pair_j;
  double *pair_w;
  int64_t pair_n, pair_cap;

  /* §145 А325/А326: ДИАГНОСТИКА ШИРИНЫ ФРОНТА, до всякого фильтра.
   * Прежде чем расплывать, надо знать, ЕСТЬ ЛИ ЧЕМУ расплываться: радиус
   * `ρ = θ·Δd/h` в клетках растра. Если медиана ниже единицы, фильтр вырождается
   * в тождество, и «механизм не работает» будет неотличимо от «не проверено».
   * `diag_theta` — половинный угол корзины `sqrt(4/N_D)` (А324); 0 — выключено. */
  /* §148: половинный угол корзины для ФИЛЬТРА; 0 — фильтр выключен. */
  double blur_theta;
  double diag_theta;
  int64_t *diag_depth; /* HZ_PSW_RHOBINS корзин по длине цепочки фрагментов */
  int64_t *diag_hist;  /* HZ_PSW_RHOBINS корзин по удвоению ρ */
} hz_ptrans;

/* Границы корзин: 0.25 0.5 1 2 4 8 16 32 и «свыше». */
#define HZ_PSW_RHOBINS 9

#define HZ_BLUR_LAYERS 15
#define HZ_BLUR_SHIFT 2
#define HZ_BLUR_RMIN 2.0

/* Альбедо берётся из материалов входа (`Kd`, один канал); Le обнуляется. */
int hz_ptrans_init(hz_ptrans *t, const hz_polyset *ps, const hz_objmesh *m);
void hz_ptrans_free(hz_ptrans *t);

/* Исходящий радианс полигона k в его местной точке (u,v). */
double hz_ptrans_lout(const hz_ptrans *t, int32_t k, double u, double v);

/* РАСКЛАДКА ФРАГМЕНТОВ — ПАРАМЕТР, А НЕ ВКУС. Ш3 предупреждает: если упор
 * окажется не там, где ждали, «менять надо раскладку данных, а не число
 * полигонов». Значит обе раскладки обязаны существовать одновременно и
 * МЕРЯТЬСЯ; выбрать одну до замера значило бы предрешить его исход. */
#define HZ_LAYOUT_RUNS 0 /* сплошные пробеги на пиксель: чтение последовательно */
#define HZ_LAYOUT_LIST 1 /* односвязные списки: чтение — гонка по указателям */

typedef struct {
  double t_raster, t_sort, t_reduce, t_solve;
  int64_t nfrag, nspan, npair, nover, nbytes;
  int64_t nclip;  /* сколько полигонов тронул ограничитель */
  double phi_in;  /* Σ ∫E dA — принято */
  double phi_out; /* Σ π∫L_out dA — испущено */
  double dE;      /* Σ |ΔE| / Σ |E| — изменение за отскок, для остановки */
} hz_pstats;

/* ОДИН ОТСКОК: обход всех ординат, накопление, решение, ограничитель.
 * `h` — шаг растра, м. `nthr` — потоков (по направлениям); 0 = сколько дал OpenMP.
 * `Lsky` — радианс фона, приходящий из пустоты по каждому направлению. */
int hz_psweep_bounce(hz_ptrans *t, const tr3_dirs *d, double h, int nthr, double Lsky, int layout,
                     hz_pstats *st);

/* ПРЯМОЙ СВЕТ от удалённого источника: один проход по направлению `w`,
 * `Eperp` — облучённость площадки, ПЕРПЕНДИКУЛЯРНОЙ пучку. Кладётся в `acc`,
 * поэтому вызывается ДО решения, между обнулением и `hz_psweep_solve`. */
int hz_psweep_direct(hz_ptrans *t, const double w[3], double Eperp, double h, hz_pstats *st);

/* Раздельные части отскока — нужны, когда прямой свет идёт вместе с развёрткой. */
void hz_psweep_zero(hz_ptrans *t);
int hz_psweep_gather(hz_ptrans *t, const tr3_dirs *d, double h, int nthr, double Lsky, int layout,
                     hz_pstats *st);
void hz_psweep_solve(hz_ptrans *t, hz_pstats *st);

#endif
