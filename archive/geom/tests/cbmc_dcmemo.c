/* CBMC-стенд для ПАМЯТИ ОТВЕТА КРИТЕРИЯ СРЕЗА (`src/cut/dc.c`, §585).
 *
 * ЗАЧЕМ ИМЕННО ЭТО. Шаг §585 завёл ИНДЕКСИРУЕМЫЙ БУФЕР в горячем пути обхода:
 * `w->memo[r->ni]`, ровно один байт на узел. `CLAUDE.md` требует формального
 * слоя именно на такое — обход дерева плюс буфер, адресуемый читаемым из памяти
 * индексом. Класс отказа тихий: буфер выделен на `t->n` байт, а `r->ni` приходит
 * из `nd[...].child0 + bit`, то есть из данных. Уехал индекс — испортилась
 * чужая память, и картинка при этом может остаться правдоподобной.
 *
 * ЧТО ДОКАЗЫВАЕТСЯ, И ЭТО ВЕСЬ ОБХОД, А НЕ ОДНА ФУНКЦИЯ. На дереве размера
 * `2^1` (корень плюс блок из восьми — минимальная форма, у которой есть и
 * `cellProc`, и `faceProc`, и `edgeProc`) при ЛЮБОМ содержимом масок углов,
 * пересечённых рёбер, флагов и вершин:
 *   (1) `hz_dc_walk` не читает и не пишет за пределами `memo`;
 *   (2) то же для массива узлов и для всего, чего касается обход;
 *   (3) обход завершается.
 * Проверяется не «дано, что `ni` в границах» (это была бы перепись предпосылки
 * в вывод), а то, что САМ ОБХОД других `ni` не порождает.
 *
 * ЧЕГО СТЕНД НЕ ПОКРЫВАЕТ, И ЭТО НАДО НАЗВАТЬ: глубокое дерево. Рекурсия
 * `cellProc/faceProc/edgeProc` растёт с глубиной, и CBMC её в разумном бюджете
 * не берёт — доказано на глубине 1. На рабочей глубине (`L = 9`,
 * `2 215 233` узла) то же место закрывается санитайзером на реальной сцене, и
 * буфер там ПЛОТНЫЙ (`t->n` байт ровно), то есть выход за него ловится сразу, а
 * не тонет в запасе, как это было бы у массива узлов по `160` Б.
 *
 * КОНТРОЛЬ НАД САМИМ СТЕНДОМ: `-DHZ_CHECK_FALSE` требует заведомо ложного
 * «обход не тронул ни одного узла», и CBMC ОБЯЗАН выдать контрпример. Первая
 * редакция требовала «не выдал ни одного полигона» и НЕ сработала — см. А1021
 * у самой проверки: на глубине 1 полигонов не бывает вовсе, и это ПРОБЕЛ
 * покрытия, названный прямо.
 *
 * Прогон:
 *   scripts/cverify.sh tests/cbmc_dcmemo.c --function harness --unwind 6 \
 *     src/cut/dc.c src/cut/qef.c
 *   ... -DHZ_CHECK_FALSE   (ОБЯЗАН дать контрпример)
 */
#include "cut/dc.h"
#include <string.h>

int nondet_i(void);
unsigned char nondet_uc(void);

#if !defined(__CPROVER) && !defined(__CPROVER__)
#define __CPROVER_assume(x) ((void)(x))
#define __CPROVER_assert(x, s) ((void)(x))
int nondet_i(void) {
  return 0;
}
unsigned char nondet_uc(void) {
  return 0;
}
#endif

void harness(void);

/* Корень плюс один блок из восьми — минимальная форма с настоящими гранями и
 * рёбрами между детьми. Больше CBMC здесь не нужно и не по силам. */
#define HZ_NB 9

static int64_t g_npoly;

static int count_poly(void *ctx, const hz_dcref *ref, const double (*v)[3], int nv) {
  (void)ctx;
  (void)ref;
  (void)v;
  (void)nv;
  g_npoly++;
  return 0;
}

/* Предикат среза, зависящий от НЕДЕТЕРМИНИРОВАННОГО поля: так проверяется, что
 * безопасность обхода не держится на том, что срез устроен «разумно». */
static int stop_nondet(void *ctx, const hz_dctree *t, const hz_dcref *r) {
  const unsigned char *tab = (const unsigned char *)ctx;
  (void)t;
  return (tab[r->ni] & 1u) != 0;
}

void harness(void) {
  hz_dcnode nd[HZ_NB];
  unsigned char stoptab[HZ_NB];
  hz_dctree t;

  memset(nd, 0, sizeof nd);
  for (int i = 0; i < HZ_NB; i++) {
    /* Корень имеет блок детей с индекса 1; дети — листья. Это ЕДИНСТВЕННОЕ, что
     * задано жёстко: форма дерева. Всё содержимое узла — недетерминированное. */
    nd[i].child0 = (i == 0) ? 1 : -1;
    nd[i].corner = nondet_uc();
    nd[i].ecross = (uint16_t)nondet_i();
    nd[i].edir = (uint16_t)nondet_i();
    nd[i].flags = nondet_uc();
    /* ВЕРШИНА ЗАДАНА, А НЕ НЕДЕТЕРМИНИРОВАНА, И ЭТО ОСОЗНАННОЕ СУЖЕНИЕ.
     * Она входит только в ЗНАЧЕНИЯ выданных полигонов и ни в один индекс, а
     * недетерминированные double раздувают задачу до нехватки памяти у решателя
     * (замерено: при них CBMC падает с «Out of memory» на 16 ГБ). Безопасность
     * адресации от неё не зависит; что зависит — маска углов, пересечённые
     * рёбра, флаги и предикат среза — осталось недетерминированным. */
    for (int a = 0; a < 3; a++)
      nd[i].vx[a] = 0.5;
    stoptab[i] = nondet_uc();
  }

  memset(&t, 0, sizeof t);
  t.nd = nd;
  t.n = HZ_NB;
  t.cap = HZ_NB;
  t.log2size = 1;
  t.unsgn = nondet_i() & 1;

  g_npoly = 0;
  hz_dc_walk_memo(HZ_DC_MEMO_ON);
  int rc = hz_dc_walk(&t, stop_nondet, stoptab, count_poly, NULL);

  /* Код возврата — любой из объявленных; молчаливого мусора быть не должно. */
  __CPROVER_assert(rc == HZ_DC_OK || rc == HZ_DC_ETOPO || rc == HZ_DC_EMULTI,
                   "обход возвращает объявленный код, а не что попало");

  /* Память ответа посчитала не больше узлов, чем есть в дереве. Ноль законен:
   * при `calloc == NULL` обход идёт прежним путём, и это НЕ ошибка. */
  __CPROVER_assert(hz_dc_walk_memo_evals() >= 0 && hz_dc_walk_memo_evals() <= (long long)HZ_NB,
                   "различных узлов посчитано не больше, чем их есть");

  /* Порча выключена — перевёрнутых ответов быть не может. */
  __CPROVER_assert(hz_dc_walk_memo_flips() == 0,
                   "при выключенной порче ответы не переворачиваются");

#ifdef HZ_CHECK_FALSE
  /* КОНТРОЛЬ НАД СТЕНДОМ: заведомо ложно — обход обязан тронуть хотя бы корень
   * и его детей, иначе стенд ничего не гоняет.
   *
   * ПЕРВАЯ РЕДАКЦИЯ КОНТРОЛЯ ТРЕБОВАЛА `g_npoly == 0` — И НЕ СРАБОТАЛА, ЧТО
   * ЗАПИСЫВАЕТСЯ, А НЕ ЗАМАЛЧИВАЕТСЯ (А1021). CBMC доказал, что на дереве
   * глубины 1 полигонов не выдаётся ВОВСЕ: минимальное ребро здесь делят
   * меньше трёх РАЗЛИЧНЫХ ячеек, и `process_edge` выходит по `nv < 3`. Значит
   * стенд покрывает СПУСК, СМЕЖНОСТЬ и АДРЕСАЦИЮ памяти ответа, но НЕ покрывает
   * путь выдачи полигона; для него нужна глубина 2, а это уже вне бюджета
   * решателя. Пробел назван здесь, а не выведен потом из молчания. */
  __CPROVER_assert(hz_dc_walk_memo_evals() == 0,
                   "заведомо ложное: обход не трогает ни одного узла");
#endif
}
