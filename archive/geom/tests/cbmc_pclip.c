/* CBMC-стенд для ОТСЕЧЕНИЯ ТРЕУГОЛЬНИКА КОРОБКОЙ (`src/pclip.c`, шаг О70).
 *
 * ЗАЧЕМ ИМЕННО ЗДЕСЬ. §244 п. 6 требует CBMC на `pclip` прямым текстом, и по
 * делу: постусловие `nv ≤ 9` заявлено ДОКАЗАННЫМ (§241.3), буфер под него
 * фиксированный, а обрезания нет сознательно — обрезание спрятало бы ошибку
 * отсечения, которая проявляется потерянным заслоном, то есть молча неверной
 * тенью. Доказывать здесь надо ровно две вещи:
 *   (1) `assert(n < HZ_PCLIP_MAXV)` в `pc_emit` НЕДОСТИЖИМ, то есть счёт вершин
 *       за девять не выходит ни при каких координатах;
 *   (2) записи в буферы `buf[2][9]` и в `out->v/out->p` лежат в границах.
 *
 * ЧТО НЕДЕТЕРМИНИРОВАНО И ПОЧЕМУ ИМЕННО ТАК. Число вершин на выходе задаётся не
 * величинами координат, а ПОРЯДКОВЫМИ ОТНОШЕНИЯМИ между координатой вершины и
 * координатой секущей плоскости: весь ход Сазерленда—Ходжмана определяют
 * предикаты `v[a] >= c` и `v[a] < c`. Поэтому каждая из девяти координат
 * треугольника берётся НЕДЕТЕРМИНИРОВАННО ИЗ ПЯТИ ЗНАЧЕНИЙ, накрывающих все
 * пять положений относительно грани единичной коробки:
 *
 *     -0.5  строго снаружи со стороны `lo`
 *      0.0  РОВНО на `lo`   — сторона `>=`, вершина внутри
 *      0.5  строго внутри
 *      1.0  РОВНО на `hi`   — сторона `<`,  вершина СНАРУЖИ (соглашение А475)
 *      1.5  строго снаружи со стороны `hi`
 *
 * то есть перебираются ВСЕ `5^9 = 1 953 125` расстановок, включая вырожденные
 * (треугольник в плоскости грани, вершина ровно на секущей, нулевая площадь) —
 * ровно те, из-за которых А475 и заведён. Это ПОЛНЫЙ перебор по классам
 * эквивалентности предикатов, а не выборка.
 *
 * ЧЕГО ЭТОТ СТЕНД НЕ ПОКРЫВАЕТ, СКАЗАНО ПРЯМО. Свободные символьные `double`
 * (ключ `-DHZ_FREE_DOUBLE`) на этой машине НЕ СХОДЯТСЯ: CBMC 6.9.0 разворачивает
 * плавающую арифметику в биты и падает с «Solver ran out of memory» и при
 * `minisat`, и при `cadical --slice-formula`, дойдя до `52` ГБ. Поэтому случаи,
 * где промежуточная вершина рождает НОВОЕ порядковое отношение, не выразимое
 * пятёркой значений (например, вершина, попавшая по счёту точно на следующую
 * секущую), формально не перебраны. Держать это на виду важнее, чем показать
 * «VERIFICATION SUCCESSFUL» на стенде, который проверяет меньше, чем кажется.
 *
 * ЛЕСТНИЦА ПО СЛОЖНОСТИ — ключами, а не переписыванием (тот же приём, что в
 * `cbmc_octree.c`/`cbmc_ptrace.c`):
 *   (по умолчанию)   коробка `[0,1]³`, девять координат из пятёрки значений;
 *   -DHZ_PIN_Z       z закреплены — плоский случай, дешёвая ступень;
 *   -DHZ_FREE_DOUBLE свободные символьные double (не сходится, см. выше).
 *
 * КОНТРОЛЬ НАД САМИМ СТЕНДОМ (по образцу А431). Ключ `-DHZ_CHECK_FALSE`
 * требует заведомо ложного `nv ≤ 2`, и CBMC ОБЯЗАН выдать контрпример. Без
 * этого «SUCCESS» неотличим от стенда, чьи утверждения не дошли до решателя, —
 * а такое здесь уже случилось: см. сторож имени `__CPROVER__` ниже.
 *
 * Прогон:
 *   scripts/cverify.sh tests/cbmc_pclip.c --function harness --unwind 32 src/pclip.c
 *   ... -DHZ_PIN_Z      ... -DHZ_CHECK_FALSE      ... -DHZ_FREE_DOUBLE
 */
#include "pclip.h"

double nondet_d(void);
int nondet_i(void);

/* СТОРОЖ ПРОВЕРЯЕТ ОБА ИМЕНИ, И ЭТО НЕ ПЕРЕСТРАХОВКА. CBMC 6.9.0 определяет
 * `__CPROVER__` (с двумя подчёркиваниями на конце), а НЕ `__CPROVER` —
 * проверено прямым прогоном `#error`. Стенды проекта писаны на `#ifndef
 * __CPROVER`, то есть под этим CBMC у них подменялись пустышками и
 * `__CPROVER_assume`, и `nondet_*`: предпосылки не действовали, а «недетерми-
 * нированный» вход был КОНСТАНТОЙ. Здесь имя закрыто с обеих сторон. */
#if !defined(__CPROVER) && !defined(__CPROVER__)
/* чтобы гейт качества (gcc/clang-tidy/cppcheck) разбирал и этот файл */
#define __CPROVER_assume(x) ((void)(x))
#define __CPROVER_assert(x, s) ((void)(x))
double nondet_d(void) {
  return 0.0;
}
int nondet_i(void) {
  return 0;
}
#endif

void harness(void);

/* Одна координата: недетерминированный выбор из пяти положений относительно
 * грани. `assume` на диапазон индекса — не ограничение задачи, а определение
 * выбора: индекс вне пятёрки просто не есть выбор. */
static double pick(void) {
#ifdef HZ_FREE_DOUBLE
  return nondet_d();
#else
  static const double tab[5] = {-0.5, 0.0, 0.5, 1.0, 1.5};
  int i = nondet_i();
  __CPROVER_assume(i >= 0 && i < 5);
  return tab[i];
#endif
}

void harness(void) {
  double A[3], B[3], C[3], lo[3], hi[3];
  for (int c = 0; c < 3; c++) {
    A[c] = pick();
    B[c] = pick();
    C[c] = pick();
#ifdef HZ_FREE_DOUBLE
    lo[c] = nondet_d();
    hi[c] = nondet_d();
#else
    lo[c] = 0.0;
    hi[c] = 1.0;
#endif
  }
#ifdef HZ_PIN_Z
  A[2] = 0.5;
  B[2] = 0.5;
  C[2] = 0.5;
#endif
  /* Ступени лестницы: закрепить вторую и третью вершины. Число СВОБОДНЫХ
   * координат — единственный рычаг, которым эта задача вообще двигается, и
   * он печатается вместе с результатом, чтобы «SUCCESS» нельзя было прочесть
   * шире, чем он есть. */
#ifdef HZ_PIN_B
  B[0] = 1.5;
  B[1] = 0.5;
  B[2] = 0.5;
#endif
#ifdef HZ_PIN_C
  C[0] = 0.5;
  C[1] = 1.5;
  C[2] = -0.5;
#endif
  hz_pclip_poly P;
  int nv = hz_pclip_tri(A, B, C, lo, hi, &P);
#ifdef HZ_CHECK_FALSE
  /* контроль над стендом: заведомо ложное требование обязано дать контрпример */
  __CPROVER_assert(nv <= 2, "КОНТРОЛЬ: nv <= 2 обязан провалиться");
#else
  __CPROVER_assert(nv <= HZ_PCLIP_MAXV, "постусловие: вершин не больше девяти");
  __CPROVER_assert(P.nv == nv, "число вершин согласовано с возвратом");
  __CPROVER_assert(P.nv == 0 || P.nv >= 3, "кусок либо пуст, либо многоугольник");
#endif
}
