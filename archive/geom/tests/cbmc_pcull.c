/* CBMC-стенд для ИНДЕКСНОЙ ЧАСТИ ПОМЕТОК НЕВИДИМОСТИ (`src/pcull.c`, §278).
 *
 * ЗАЧЕМ ИМЕННО ЗДЕСЬ. Односторонность пометки держится на двух утверждениях,
 * и оба — про индексы, а не про физику:
 *   (1) запрос по прямоугольнику пикселей возвращает величину НЕ МЕНЬШУЮ, чем
 *       любое значение буфера внутри этого прямоугольника. Если это неверно,
 *       ячейка объявляется заслонённой по заниженному максимуму, и приёмка
 *       ловит видимое среди помеченных — то есть ровно тот дефект, ради
 *       которого §278 и переписан;
 *   (2) ни пирамида, ни запрос не выходят за границы своих массивов при любой
 *       стороне буфера, в том числе НЕЧЁТНОЙ, где грубый уровень не делится
 *       нацело и добор идёт `+∞`.
 * Первое доказывается здесь ПОЛНЫМ перебором значений буфера, второе — обычными
 * проверками CBMC (границы, указатели, переполнение).
 *
 * ПОЧЕМУ СТОРОНА НЕДЕТЕРМИНИРОВАНА, А ЗНАЧЕНИЯ — ИЗ ДВОЙКИ. Выбор уровня в
 * `rect_max` идёт сдвигами (`i >> L`), и вся его логика определяется тем, в
 * какие клетки грубого уровня попали концы прямоугольника, — то есть ЦЕЛЫМИ
 * отношениями. Величины же участвуют только сравнением `>`; для утверждения
 * «максимум не занижен» достаточно двух различимых значений, и перебор по
 * `2^(side²)` расстановкам полон по классам эквивалентности этих сравнений.
 * Свободные символьные `double` на этой машине не сходятся (класс, записанный в
 * `cbmc_pclip.c`), и здесь они не нужны вовсе.
 *
 * ЧЕГО СТЕНД НЕ ПОКРЫВАЕТ, СКАЗАНО ПРЯМО:
 *   - растеризацию заслонителей (`hz_pcull_draw`) и построение рамы камеры
 *     (`hz_pcull_init`): там существенна ПЛАВАЮЩАЯ арифметика, а она на этой
 *     машине в CBMC не сходится;
 *   - утверждение «дальняя точка пикселя лежит в его углу», которое
 *     геометрическое, а не индексное, и доказано в `pcull.h` рассуждением.
 *
 * ЛЕСТНИЦА ПО СЛОЖНОСТИ КЛЮЧАМИ:
 *   (по умолчанию)     сторона 2…5, значения из двойки, обе проверки;
 *   -DHZ_PCULL_SIDE=N  сторона закреплена — дешёвая ступень;
 *   -DHZ_CHECK_FALSE   КОНТРОЛЬ НАД СТЕНДОМ: `rect_max` подменяется заведомо
 *                      заниженным ответом, и стенд ОБЯЗАН упасть. Без этого
 *                      «VERIFICATION SUCCESSFUL» ничего не значит.
 *
 * СТЕНД НА ЭТОЙ МАШИНЕ НЕ СХОДИТСЯ, И ЭТО ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО (08-06):
 *
 *     сторона 2…5, unwind 40, 16 ГБ   > 1800 с, вердикта нет
 *     сторона 3,   unwind 40, 16 ГБ   >  900 с, вердикта нет
 *     сторона 2,   unwind 40, 16 ГБ   «Solver ran out of memory»
 *     сторона 2,   unwind 40, 60 ГБ   >  540 с, вердикта нет
 *
 * Причина та же, что записана в `cbmc_pclip.c` про свободные `double`: CBMC
 * 6.9.0 разворачивает плавающую арифметику в биты, а буфер здесь `float`, и
 * сравнений в пирамиде довольно, чтобы задача перестала помещаться. Поэтому
 * УТВЕРЖДЕНИЕ «ЗАПРОС НЕ ЗАНИЖЕН» ОСТАЁТСЯ ДОКАЗАННЫМ РАССУЖДЕНИЕМ, А НЕ
 * МАШИНОЙ, и говорить о нём надо именно так. Стенд оставлен готовым: он
 * пойдёт, как только у пирамиды появится целочисленный вариант либо у CBMC —
 * пригодная теория плавающих чисел.
 */
#include "../src/pcull.c"

#include <assert.h>

int nondet_i(void);

/* СТОРОЖ ИМЕНИ CBMC — по образцу `cbmc_pclip.c`, и там записано, почему оба:
 * CBMC 6.9.0 определяет `__CPROVER__`, а не `__CPROVER`, и стенд под неверным
 * именем молча превращается в прогон с КОНСТАНТНЫМ входом. */
#if !defined(__CPROVER) && !defined(__CPROVER__)
#define __CPROVER_assume(x) ((void)(x))
int nondet_i(void) {
  return 0;
}
#endif

#ifndef HZ_PCULL_SIDE
#define HZ_PCULL_SIDE 0 /* 0 — сторона недетерминирована */
#endif

void harness(void);

void harness(void) {
  int side = HZ_PCULL_SIDE;
  if (side == 0) {
    side = nondet_i();
    __CPROVER_assume(side >= 2 && side <= 5);
    /* ВНЕ CBMC предпосылка — пустышка, а `nondet_i` — константа `0`, и дальше
     * стенд считал бы пирамиду нулевой стороны. Под CBMC эта ветвь недостижима
     * по самой предпосылке и потому ничего не стоит; вне его она честно
     * останавливает стенд, который там и не имеет смысла. Поймано гейтом
     * (`gcc -fanalyzer`), а не рассуждением. */
    if (side < 2 || side > 5) return;
  }
  hz_pcull C;
  memset(&C, 0, sizeof C);
  C.side = side;
  int n = 0;
  for (int s = side; s >= 1; s = (s + 1) / 2) {
    n++;
    if (s == 1) break;
  }
  C.nlev = n;
  C.lvl = malloc((size_t)n * sizeof *C.lvl);
  C.lw = malloc((size_t)n * sizeof *C.lw);
  if (C.lvl == NULL || C.lw == NULL) return;
  int s = side;
  for (int k = 0; k < n; k++) {
    C.lw[k] = s;
    C.lvl[k] = malloc((size_t)s * (size_t)s * sizeof *C.lvl[k]);
    if (C.lvl[k] == NULL) return;
    for (int i = 0; i < s * s; i++)
      C.lvl[k][i] = INFINITY;
    s = (s + 1) / 2;
  }
  /* Значения нижнего уровня — из двойки: важны только сравнения. */
  for (int i = 0; i < side * side; i++)
    C.lvl[0][i] = nondet_i() ? 1.0f : 2.0f;
  hz_pcull_pyramid(&C);

  int i0 = nondet_i(), i1 = nondet_i(), j0 = nondet_i(), j1 = nondet_i();
  __CPROVER_assume(i0 >= 0 && i0 <= i1 && i1 < side);
  __CPROVER_assume(j0 >= 0 && j0 <= j1 && j1 < side);
  float q = rect_max(&C, i0, i1, j0, j1);
#ifdef HZ_CHECK_FALSE
  q = 1.0f; /* заведомо заниженный ответ: стенд обязан упасть */
#endif
  /* ГЛАВНОЕ УТВЕРЖДЕНИЕ: запрос НЕ ЗАНИЖЕН ни в одной клетке прямоугольника. */
  for (int j = j0; j <= j1; j++)
    for (int i = i0; i <= i1; i++)
      assert(q >= C.lvl[0][(size_t)j * (size_t)side + (size_t)i]);

  for (int k = 0; k < n; k++)
    free(C.lvl[k]);
  free(C.lvl);
  free(C.lw);
}
