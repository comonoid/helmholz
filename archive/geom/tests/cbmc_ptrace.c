/* CBMC-стенд для ОБХОДА ВОСЬМИДЕРЕВА `hz_ptrace_cnt` (шаг О63, план §215).
 *
 * ЗАЧЕМ ИМЕННО ЗДЕСЬ. Гейт `CLAUDE.md` требует формального слоя на обходе и
 * правке деревьев. Обход `pt_walk` рекурсивен и индексирует ТРИ массива по
 * данным из узла (`nd[child+q]`, `ref[t0+i]`, `m->f[3·tr]`), причём завершение
 * держится на инварианте «ребёнок имеет больший номер, чем родитель». Инвариант
 * этот НИГДЕ НЕ ПРОВЕРЯЕТСЯ в рабочем коде — он свойство построителя
 * (`ptree.c`: `c0 = t->nnd; N->child = c0; t->nnd += 8`), — и стенд делает его
 * ЯВНОЙ ПРЕДПОСЫЛКОЙ, а не молчаливой надеждой.
 *
 * ЧТО ДОКАЗЫВАЕТСЯ: отсутствие выходов за границы трёх массивов, разыменований
 * и переполнений на ЛЮБОЙ топологии, удовлетворяющей предпосылкам, и завершение
 * рекурсии в пределах развёртки (`--unwinding-assertions`).
 *
 * ОГРАНИЧЕНИЯ СТЕНДА, И ОНИ ОБЪЯВЛЯЮТСЯ ОГРАНИЧЕНИЯМИ, А НЕ ТЕОРЕМОЙ.
 *   - ГЕОМЕТРИЯ КОНКРЕТНА (коробки узлов и вершины треугольников — числа), а
 *     недетерминированы ТОПОЛОГИЯ (`child`, `t0`, `ntri`, `ref`) и ЛУЧ. Довод:
 *     проверяемые свойства — про индексы, а не про значения координат, тогда как
 *     символьные double по бит-точной арифметике дают SAT-задачу на порядки
 *     дороже и не покрывают ни одного нового пути по индексам;
 *   - ЛУЧ выбирается из восьми знаковых комбинаций плюс направления с НУЛЕВОЙ
 *     компонентой (ветка `HZ_PGRID_DTINY`) — то есть все восемь значений маски
 *     порядка октантов и вырожденный случай, а не произвольный вектор;
 *   - размер `HZ_N = 9` (корень и восемь детей) — при нём предпосылка
 *     «ребёнок больше родителя» допускает ровно два уровня, чего хватает и для
 *     спуска, и для проверки границ; лестница по размеру — отдельные прогоны.
 *
 * ОДНО УТВЕРЖДЕНИЕ ИЗ 1770 НЕ ЗАКРЫВАЕТСЯ, И ЭТО АРТЕФАКТ CBMC 6.9.0, ЧТО
 * ПОКАЗАНО, А НЕ ОБЪЯВЛЕНО. `[pt_walk.recursion] recursion unwinding assertion`
 * остаётся FAILURE при любой развёртке (пробовано `2, 4, 16, 32` — число
 * утверждений не меняется вовсе) И ПРИ ПОЛНОСТЬЮ ЗАКРЕПЛЁННОЙ ТОПОЛОГИИ.
 * Решающий контроль — ключ `-DHZ_PIN_FLAT`: у всех узлов `child = -1`, то есть
 * `pt_walk` входится РОВНО ОДИН РАЗ и не рекурсирует НИ РАЗУ, а утверждение
 * всё равно FAILURE. Значит инструмент не разряжает его для рекурсивного вызова,
 * стоящего ВНУТРИ ЦИКЛА, — это не глубина обхода и не свойство дерева.
 * Остальные 1769 (границы трёх массивов, разыменования, переполнения, NaN,
 * деление на ноль) — SUCCESS при НЕДЕТЕРМИНИРОВАННОЙ топологии.
 *
 * Прогон (приёмочный и два диагностических):
 *   scripts/cverify.sh tests/cbmc_ptrace.c --function harness \
 *       --unwind 16 --unwinding-assertions src/ptrace.c src/pgrid.c
 *   ... -DHZ_PIN_TOPO   топология закреплена: корень и восемь листьев
 *   ... -DHZ_PIN_FLAT   детей нет вовсе — контроль над самим инструментом
 */
#include "ptrace.h"
#include <stdint.h>

/* Без тела намеренно: CBMC считает такую функцию недетерминированной. */
int32_t nondet_i32(void);
int nondet_i(void);

#ifndef __CPROVER
/* чтобы гейт качества (gcc/clang-tidy/cppcheck) тоже разбирал этот файл */
#include <stdlib.h>
#define __CPROVER_assume(x) ((void)(x))
int32_t nondet_i32(void) {
  return 0;
}
int nondet_i(void) {
  return 0;
}
#endif

/* ЛЕСТНИЦА ПО РАЗМЕРУ — параметрами, а не переписыванием (тот же приём, что в
 * `tests/cbmc_octree.c`): каждая ступень дешёвый отдельный прогон, а их
 * объединение покрывает то, что покрыл бы один символьный размер. */
#ifndef HZ_N
#define HZ_N 9 /* узлов: корень и восемь детей */
#endif
#ifndef HZ_NREF
#define HZ_NREF 4 /* длина массива ссылок */
#endif
#ifndef HZ_NT
#define HZ_NT 2 /* треугольников */
#endif
#ifndef HZ_NV
#define HZ_NV 4 /* вершин */
#endif

void harness(void);

void harness(void) {
  static hz_ptnode nd[HZ_N];
  static int32_t ref[HZ_NREF];
  static int32_t fidx[3 * HZ_NT];
  static int32_t tags[HZ_NT]; /* тег на треугольник — фильтр самозаслона (О69) */
  static double vtx[3 * HZ_NV];

  /* ГЕОМЕТРИЯ КОНКРЕТНА (см. заголовок). Корень — куб [0,2]^3, дети — его
   * восемь октантов, как их строит `ptree.c`. */
  for (int c = 0; c < 3; c++) {
    nd[0].lo[c] = 0.0;
    nd[0].hi[c] = 2.0;
  }
  for (int k = 0; k < 8; k++)
    for (int c = 0; c < 3; c++) {
      nd[1 + k].lo[c] = (k & (1 << c)) ? 1.0 : 0.0;
      nd[1 + k].hi[c] = (k & (1 << c)) ? 2.0 : 1.0;
    }
  vtx[0] = 0.25;
  vtx[1] = 0.25;
  vtx[2] = 0.25;
  vtx[3] = 1.75;
  vtx[4] = 0.25;
  vtx[5] = 0.25;
  vtx[6] = 0.25;
  vtx[7] = 1.75;
  vtx[8] = 0.25;
  vtx[9] = 1.0;
  vtx[10] = 1.0;
  vtx[11] = 1.75;
  for (int i = 0; i < 3 * HZ_NT; i++) {
    fidx[i] = nondet_i32();
    __CPROVER_assume(fidx[i] >= 0 && fidx[i] < HZ_NV);
  }
  /* Теги НЕДЕТЕРМИНИРОВАНЫ И НИЧЕМ НЕ ОГРАНИЧЕНЫ: фильтр обязан быть безопасен
   * при любом их значении, включая совпадение со всеми и ни с одним. */
  for (int i = 0; i < HZ_NT; i++)
    tags[i] = nondet_i32();

  /* ТОПОЛОГИЯ НЕДЕТЕРМИНИРОВАНА, при трёх предпосылках — ровно тех, что
   * обеспечивает построитель и на которых держится обход. */
  for (int32_t i = 0; i < HZ_N; i++) {
    nd[i].child = nondet_i32();
    nd[i].t0 = nondet_i32();
    nd[i].ntri = nondet_i32();
    /* (1) РЕБЁНОК БОЛЬШЕ РОДИТЕЛЯ — на этом и только на этом держится
     *     завершение рекурсии. Восьмёрка детей лежит подряд. */
    __CPROVER_assume(nd[i].child == -1 || (nd[i].child > i && nd[i].child + 7 < HZ_N));
    /* (2) СПИСОК ССЫЛОК УЗЛА ЛЕЖИТ В МАССИВЕ ссылок целиком. */
    __CPROVER_assume(nd[i].t0 >= 0 && nd[i].ntri >= 0 && nd[i].t0 + nd[i].ntri <= HZ_NREF);
  }
#ifdef HZ_PIN_FLAT
  /* Ступень «детей нет вовсе»: `pt_walk` входится РОВНО ОДИН РАЗ и не
   * рекурсирует ни разу. Если и здесь срабатывает утверждение о развёртке
   * рекурсии — оно артефакт инструмента, а не свойство кода. */
  for (int32_t i = 0; i < HZ_N; i++)
    __CPROVER_assume(nd[i].child == -1);
#endif
#ifdef HZ_PIN_TOPO
  /* Ступень «топология закреплена» — только для диагностики того, чем именно
   * ограничена глубина рекурсии; в приёмочный прогон не входит. */
  __CPROVER_assume(nd[0].child == 1);
  for (int32_t i = 1; i < HZ_N; i++)
    __CPROVER_assume(nd[i].child == -1);
#endif
  for (int i = 0; i < HZ_NREF; i++) {
    ref[i] = nondet_i32();
    /* (3) ССЫЛКА — НОМЕР СУЩЕСТВУЮЩЕГО ТРЕУГОЛЬНИКА. */
    __CPROVER_assume(ref[i] >= 0 && ref[i] < HZ_NT);
  }

  hz_ptree t;
  t.nd = nd;
  t.ref = ref;
  t.nnd = HZ_N;
  t.ndcap = HZ_N;
  t.nref = HZ_NREF;
  t.refcap = HZ_NREF;
  t.maxlev = 12;
  t.leafmax = 16;
  t.n_inner = 0;
  t.n_leaf_tri = 0;
  t.nleaf = 0;
  t.redundancy = 1.0;
  t.loose = 0;

  hz_objmesh m;
  m.v = vtx;
  m.f = fidx;
  m.nt = HZ_NT;
  m.nv = HZ_NV;
  m.vn = NULL;
  m.nvn = 0;
  m.fn = NULL;
  m.fm = NULL;
  m.mtl = NULL;
  m.nmtl = 0;
  m.ndegen = 0;
  m.nquad = 0;
  for (int c = 0; c < 3; c++) {
    m.lo[c] = 0.0;
    m.hi[c] = 2.0;
  }

  /* ЛУЧ. Начало — узлы решётки в габарите и вне его; направление — все восемь
   * знаковых комбинаций и вырожденные с нулевой компонентой. */
  double o[3], d[3];
  int nz = 0;
  for (int c = 0; c < 3; c++) {
    int s = nondet_i();
    __CPROVER_assume(s >= -1 && s <= 3);
    o[c] = (double)s;
    int q = nondet_i();
    __CPROVER_assume(q >= -1 && q <= 1);
    d[c] = (double)q;
    if (q != 0) nz = 1;
  }
  /* Ненулевое направление — условием на ЦЕЛЫХ, а не сравнением double: гейт
   * запрещает `==` на плавающих (`-Wfloat-equal`), и он прав. */
  __CPROVER_assume(nz != 0);

  int32_t skip1 = nondet_i32();
  int nskip = nondet_i();
  __CPROVER_assume(nskip == 0 || nskip == 1);
  int anyhit = nondet_i();
  __CPROVER_assume(anyhit == 0 || anyhit == 1);

  double thit = 0.0;
  int32_t tri = -1;
  int64_t nnode = 0, ntest = 0;
  (void)hz_ptrace_cnt(&t, &m, o, d, 0.0, 100.0, &skip1, nskip, anyhit, &thit, &tri, &nnode, &ntest,
                      tags, nondet_i32());
}
