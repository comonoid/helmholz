/* gather3.h — ПРОХОД 3 (сбор по пикселю) с ЗЕРКАЛАМИ.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). До этого файла сбор жил внутри `main`
 * инструмента `render3.c`, и проверять его было негде; здесь он вынесен, потому
 * что зеркало добавляет в него ЦИКЛ, а цикл надо фальсифицировать.
 *
 * ЗЕРКАЛО ИДЁТ ПРОСЛЕЖИВАНИЕМ, А НЕ ЧЕРЕЗ ОРДИНАТЫ, И ЭТО К5, А НЕ ЭКОНОМИЯ.
 * Отражённое направление в наборе ординат ОТСУТСТВУЕТ, а интерполировать между
 * ординатами запрещено правилом К3 — иначе на картинке будут полосы. Поэтому:
 *
 *     развёртка на зеркальной границе ОБРЫВАЕТСЯ;
 *     дальше идёт ОДНО направление на отскок, прослеживанием, здесь.
 *
 * ЦЕНА ЭТОГО РЕШЕНИЯ, ВСЛУХ: для развёртки зеркало есть ЧЁРНОЕ тело. Свет,
 * упавший на зеркало, из объёмного решения ПРОПАДАЕТ — он не рассеивается в
 * ординаты и не возвращается в комнату. Значит комната с зеркалами выходит
 * ТЕМНЕЕ физической, и ровно на ту долю, которую зеркала перехватывают. Это не
 * ошибка реализации, а граница метода в его нынешнем виде: чтобы вернуть эту
 * энергию, нужен отдельный проход, переносящий зеркальную компоненту вдоль
 * ЛОМАНОЙ, а не по ординатам. Записано, а не забыто.
 *
 * ЧИСЛО ОТСКОКОВ — ПАРАМЕТР СЦЕНЫ СО СВОИМ СВИПОМ, А НЕ ПОРОГ. Магического
 * числа здесь нет ровно по той же причине, по какой его нет у `τ_max` в T3
 * (находка К22): предел объявляется параметром, а фальсификатор требует, чтобы
 * ответ ПЕРЕСТАЛ меняться при его росте, и свип печатается. Между двумя
 * зеркалами ряд отскоков бесконечен, и обрыв там виден глазом — потому и
 * меряется.
 *
 * ε НЕТ И ЗДЕСЬ. Отражённый луч выходит РОВНО с поверхности, где `n·x − off`
 * тождественно ноль. Самопопадания не происходит без всякого смещения, потому
 * что вход в полупространство требует `ds/dt < 0` СТРОГО, а попадание в
 * примитив — `n·d < 0` СТРОГО (см. `ray3.h`); у луча, уходящего наружу,
 * производная положительна. Это ПРОВЕРЯЕТСЯ фальсификатором, а не
 * предполагается.
 *
 * НОРМАЛЬ БЕРЁТСЯ У ПРИМИТИВА (К15), И У ЗЕРКАЛА ЭТО ВАЖНЕЕ, ЧЕМ ГДЕ-ЛИБО.
 * Ошибка нормали входит в отражённое направление С УДВОЕНИЕМ и дальше
 * умножается на расстояние до отражаемого. Поэтому зеркало есть самый чуткий
 * измеритель ошибки геометрии, какой в проекте вообще есть, и негативный
 * контроль «отразить по нормали ФАСЕТА» здесь обязан быть виден сразу.
 */
#ifndef TR_GATHER3_H
#define TR_GATHER3_H

/* Сколько спектральных каналов держит сбор. Три — RGB; больше не нужно, а
 * массив на стеке при этом остаётся крошечным. */
#define TR3_MAXCH 3

#include "transport/cut3.h"
#include "transport/mesh3.h"
#include "transport/ray3.h"

typedef struct {
  const tr3_scene *sc; /* геометрия для марша */
  const tr3_mesh *m;
  const tr3_cut *cut;
  /* ХРАНИМОЕ ПО КАНАЛАМ: `bout` есть [nch][4·nf], `sout` — [nch][4·nse].
   *
   * ЭТАП E, И РАСКЛАДКА ЗДЕСЬ — ЭТО РЕШЕНИЕ, А НЕ ОФОРМЛЕНИЕ. Каналы суть
   * НЕЗАВИСИМЫЕ задачи переноса: развёртка гоняется по разу на канал со своими
   * свойствами, и смешаться они не могут ПО ПОСТРОЕНИЮ. А вот сбор обязан
   * остаться ОДНИМ: марш по лучу есть почти вся цена кадра, геометрия у каналов
   * общая, и на попадании читаются три числа вместо одного. Звать сбор трижды
   * значило бы утроить кадр там, где честная цена — проценты. */
  const double *bout;
  const double *sout;
  int nch; /* 1 — как прежде; 3 — RGB */
  /* ЗЕРКАЛЬНАЯ ДОЛЯ ПО ФАСЕТУ. NULL — зеркал нет, сбор работает как прежде.
   * Величина есть коэффициент отражения ВДОЛЬ зеркального направления; она НЕ
   * складывается с диффузной `facet_rho` автоматически — за раздельность
   * отвечает тот, кто строит сцену, и у зеркала диффузная доля обязана быть
   * нулевой, иначе энергия учтётся дважды. */
  const double *facet_spec;
  int32_t nfacet;
  /* ИНДЕКС ГРАНИЧНЫХ ГРАНЕЙ (стенка, u, v) -> грань; сторона = nwall.
   * Линейный перебор здесь стоил 3930 нс на луч против 1133 (К36). */
  const int32_t *wallidx;
  int32_t nwall;
  /* Предел числа отскоков. 0 — зеркала выключены. Ответ ОБЯЗАН перестать
   * меняться при его росте, и это фальсификатор, а не пожелание. */
  int maxbounce;
  /* К45: СРЕДА ВДОЛУЧА, И ОБА СЛАГАЕМЫХ ВМЕСТЕ, А НЕ ПОРОЗНУЛЬ.
   *
   *     L = T·L_поверхности + ∫_0^s T(s′)·(σ_s/4π)·φ(s′) ds′
   *
   * Прежде `sigma` сцены стояла NULL: накопленная τ не читалась вовсе, хотя по
   * комнате τ ≈ 0.24 — до 20% на дальней стенке. Чинить ТОЛЬКО ослаблением
   * было нельзя и записано в плане: ослабление без подсветки делает картинку
   * темнее правильной, а не точнее. Поэтому здесь ОБА члена: сегменты среды
   * даёт tr3_march_sink, φ — хранимое DG1 нулевой итерации развёртки
   * ([4·ncell], та же раскладка, что у развёртки; изотропное рассеяние,
   * фазовая функция 1/4π — та же, что в шаге C).
   *
   * НУЛЕВЫЕ УКАЗАТЕЛИ (любой из трёх) — ВАКУУМ: мир прежний ПОБИТОВО, и это
   * встроенный негативный контроль. Отдельно: `sig_t = 0` в ячейке — вакуум
   * той же формулой, вырожденный случай замкнутой формы, а не особый путь. */
  const double *sig_t; /* [ncell] σ_t по ячейке сетки или NULL */
  const double *sig_s; /* [ncell] σ_s по ячейке сетки или NULL */
  const double *phi;   /* [4·ncell] DG1 скалярного потока или NULL */
} tr3_gather;

/* Радианс, приходящий по лучу (o, d). nbounce (может быть NULL) — сколько
 * зеркальных отскоков реально сделано; число нужно фальсификатору `ρ^k·L`,
 * потому что без него степень не с чем сверять. */
/* `out` — `nch` значений (при `nch = 0` считается один канал, как прежде).
 * ВОЗВРАТ — нулевой канал, чтобы одноканальные потребители не переписывались. */
double tr3_gather_ray(const tr3_gather *g, const double o[3], const double d[3], int *nbounce,
                      double *out);

#endif
