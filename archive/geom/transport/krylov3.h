/* krylov3.h — ЭТАП B плана перехода: Крылов вместо ряда Неймана.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md, «план перехода», этап B).
 *
 * ЗАЧЕМ. Итерация по рассеянию есть ряд Неймана `φ = Σ Tⁿ b`, и число её шагов
 * равно `ln(tol/e₀)/ln(ρ)`, где `ρ` — спектральный радиус, то есть примерно
 * альбедо. Уменьшать `e₀` бесполезно: К85 измерила, что тёплый старт даёт
 * `×0.93…×1.37` и «на грани» не решает. **Решает то, что меняет `ρ`**, и это
 * крыловский метод: на печи измерено ШЕСТЬ ПРОХОДОВ при оптической толщине
 * ячейки от 0.05 до 4.0, тогда как ряд Неймана идёт `13 → 227`.
 *
 * НЕИЗВЕСТНОЕ ЗДЕСЬ — ВСЁ СОСТОЯНИЕ, А НЕ ОДНО `φ` (К84). Прежний опыт в
 * `test_sweep3.c` применял оператор к `φ` и выбрасывал `bout`/`sout`; там это
 * было законно, потому что у печи отражающих границ нет, и в самом файле стоит
 * оговорка «для сцен с отражением так НЕЛЬЗЯ». В рендерной сцене поверхность
 * есть половина состояния итерации, и картинка делается ИЗ НЕЁ, а не из `φ`.
 * Поэтому вектор здесь — тройка `(φ, bout, sout)` длиной `4·(ncell + nf + nse)`.
 *
 * ЛИНЕЙНОСТЬ ПОКУПАЕТСЯ ДВУМЯ ОТКАЗАМИ, И ОБА НАЗВАНЫ.
 *   1. ОГРАНИЧИТЕЛЬ ВЫКЛЮЧЕН. Он нелинеен, а крыловские векторы физическим
 *      радиансом не являются — у них есть отрицательные компоненты, и на них
 *      ограничитель сработает. К65 ИЗМЕРИЛА цену: без него поле уходит в минус
 *      в шести ячейках из 4096, а картинка меняется на 0.2% в среднем и 6.8% в
 *      худшем пикселе. **Значит Крылов сходится к ДРУГОЙ неподвижной точке**, и
 *      это надо не замалчивать, а мерить: сравнение идёт с рядом Неймана,
 *      прогнанным ТОЖЕ без ограничителя.
 *   2. ИЗЛУЧЕНИЕ ЗАНУЛЯЕТСЯ ВНУТРИ ОПЕРАТОРА. Отображение прохода аффинно,
 *      `S(x) = T·x + b`; оператору нужен `T`, и берётся он проходом с
 *      выключенными источниками, а не вычитанием `S(0)`. Вычитание дало бы
 *      сокращение близких чисел там, где его можно не делать вовсе.
 */
#ifndef TR_KRYLOV3_H
#define TR_KRYLOV3_H

#include "transport/sweep3.h"

typedef struct {
  int iters;       /* итераций BiCGStab */
  long npass;      /* ПРОХОДОВ развёртки — вот честная единица сравнения */
  double resid;    /* достигнутая невязка, отнесённая к норме правой части */
  int converged;   /* 1 — по невязке; 0 — предел итераций либо обрыв */
  const char *why; /* «сошлось» / «предел итераций» / «обрыв: …» */
} tr3_kstats;

/* Решает `(I − T)·x = b` по всему состоянию `(φ, bout, sout)`.
 *
 * `phi`   — [4·ncell], на входе начальное приближение, на выходе решение;
 * `bout`  — [4·nf],  то же для стенок;
 * `sout`  — [4·nse], то же для поверхностных элементов (nse может быть 0).
 *
 * `p` берётся КАК ЕСТЬ и внутри копируется: ограничитель выключается, источники
 * зануляются для оператора и остаются для правой части. Поле `p->limiter` у
 * вызывающего не меняется.
 *
 * Возврат 0 — задача решена (см. `st->converged`), иначе нехватка памяти. */
int tr3_krylov_solve(const tr3_problem *p, int maxit, double tol, double *phi, double *bout,
                     double *sout, tr3_kstats *st);

/* НЕВЯЗКА ЗАДАННОГО СОСТОЯНИЯ ПОД ТЕМ ЖЕ ОПЕРАТОРОМ: `‖A·x − b‖ / ‖b‖`.
 *
 * Нужна не для решения, а для ПРОВЕРКИ ПРИБОРА. Если сошедшийся ответ ряда
 * Неймана даёт здесь не ноль, то оператор или правая часть построены неверно, и
 * спорить о числе проходов бессмысленно. Это ровно тот вопрос, который К84
 * заставила задавать: сначала убедиться, что мерится то самое.
 *
 * Возврат 0 — посчитано, иначе нехватка памяти. */
int tr3_krylov_residual(const tr3_problem *p, const double *phi, const double *bout,
                        const double *sout, double *rel);

#endif
