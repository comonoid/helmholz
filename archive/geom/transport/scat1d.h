/* scat1d.h — T3: слой в ОПТИЧЕСКОЙ ГЛУБИНЕ с изотропным рассеянием.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Отвечает на единственный вопрос: СКОЛЬКО
 * ОРДИНАТ нужно нести в трёхмерную развёртку. Ни T1 (свободный пролёт), ни T2
 * (константа и линейное поле) на него не отвечают — там точных решений с
 * МНОГОКРАТНЫМ рассеянием нет вовсе.
 *
 *     μ dI/dτ = I − S(τ),   S(τ) = c·J(τ) + Q₁(τ),   J = ½∫I dμ
 *
 * ПУЧОК ИДЁТ ИСТОЧНИКОМ ПЕРВОГО СТОЛКНОВЕНИЯ (К23 = К9 в одномерном виде).
 * Дельта по углу в набор ординат не попадает по построению, и влёт «по
 * ближайшей ординате» дал бы луч-эффект, который не лечится числом ординат.
 * Поэтому незатенённая часть считается ТОЧНО, а в правую часть идёт только
 * однократно рассеянная компонента Q₁(τ) = (c/4)·F·e^{−τ/μ0}.
 *
 * ОБНОВЛЕНИЕ ЯЧЕЙКИ — ТА ЖЕ ХАРАКТЕРИСТИЧЕСКАЯ ФОРМА, ЧТО В T1, со вторым
 * слагаемым, которое T1 и обещала: L_вых = L_вх·e^{−τ} + S·(1 − e^{−τ}). При
 * ПОСТОЯННОМ по ячейке S это точное решение уравнения на ячейке, а не
 * приближение; порядок по пространству при этом первый, и К25 требует, чтобы
 * пространственная ошибка была заведомо ниже угловой — иначе O(ND⁻²) не увидеть.
 */
#ifndef TR_SCAT1D_H
#define TR_SCAT1D_H

#include "transport/sweep.h"

typedef struct {
  /* СЕТКА ГРАДУИРОВАННАЯ, и задаётся она НЕ числом ячеек, а шагом У ПОВЕРХНОСТИ.
   * Причина измеренная (К25 сработал на первом же прогоне): выходящий радианс по
   * скользящей ординате μ ~ 0.02 набирается в слое толщиной ~μ, и равномерная
   * сетка требует там 3e4 ячеек, тогда как в глубине столько же ячеек лежит
   * мёртвым грузом. И отдельно: при задании ЧИСЛОМ ячеек свип по taumax менял бы
   * заодно и разрешение у поверхности, то есть К22 мерил бы ДВЕ вещи сразу. */
  double dtau0;   /* шаг первой ячейки, у самой поверхности */
  double growth;  /* во сколько раз растёт шаг на ячейку, > 1 */
  double taumax;  /* полная оптическая толщина (модель полубесконечной, К22) */
  double c;       /* альбедо однократного рассеяния */
  double mu0;     /* косинус падающего пучка, > 0 */
  double f;       /* πF — поток пучка на площадку, перпендикулярную ему */
  int beam_as_bc; /* 1 = НЕГАТИВНЫЙ КОНТРОЛЬ К23: пучок влётом по ординате */
  double pscale;  /* НЕГАТИВНЫЙ КОНТРОЛЬ: множитель нормировки рассеяния (1 = норма) */
} tr_scat1d;

typedef struct {
  double *iout;  /* [o->n] радианс на ВЕРХНЕЙ границе по каждой ординате */
  double albedo; /* плоское альбедо: отражённый поток / падающий */
  int iters;
  double resid;
} tr_scat1d_out;

/* Итерация по рассеянию до сходимости. Возврат 0 — успех. Память под iout
 * выделяет вызывающий (o->n значений). */
int tr_scat1d_solve(const tr_scat1d *p, const tr_ordinates *o, int maxit, double tol,
                    tr_scat1d_out *out);

/* H-функция Чандрасекара для изотропного рассеяния — ЭТАЛОН, вычисляемый
 * НЕЗАВИСИМО от развёртки: неподвижная точка
 *     H(μ) = 1 + (c/2)·μ·H(μ)·∫₀¹ H(μ')/(μ+μ') dμ'
 * на своей (мелкой) квадратуре. Это ВТОРОЙ численный результат, а не аналитика
 * (К24), поэтому у него обязан быть свой контроль — моментное тождество
 * ∫₀¹H dμ = (2/c)(1−√(1−c)), к итерации отношения не имеющее. */
int tr_hfunc(double c, int nquad, int maxit, double tol, const double *mu, int nmu, double *h);

/* Само моментное тождество, чтобы контроль стоял рядом с эталоном. */
double tr_hfunc_moment0(double c);

#endif
