/* xfer3.h — ЭТАП A, ШАГ 3: перенос хранимого DG1 между LOD-сетками.
 *
 * PLAN_TRANSPORT.md, доклад «ШАГ 3 — ПЛАН». Сетка этапа A привязана к камере
 * (`L = εR`), значит при движении камеры меняется САМА сетка, и хранимое поле
 * надо переносить со старого дерева на новое — иначе каждый кадр есть холодный
 * старт. Поле от камеры не зависит, меняется ПРЕДСТАВЛЕНИЕ; перенос между
 * двоичными сетками одного корня — двухмасштабное преобразование, а не
 * аппроксимация.
 *
 * ПОЧЕМУ ЭТО ТОЧНО, А НЕ ПРИБЛИЖЕНИЕ. Оба дерева живут над ОДНОЙ целочисленной
 * коробкой и делят её пополам, поэтому коробки любых двух листов либо вложены,
 * либо не пересекаются. Трёх случаев ровно:
 *   - равные коробки         — побитовая копия (сетка та же — тождество);
 *   - dst мельче (пролонгация) — ограничение DG1-полинома родителя на потомка:
 *     свободный член переносится по полиному, наклон умножается на отношение
 *     размеров. Тождество полинома, не аппроксимация;
 *   - dst крупнее (ограничение) — средняя по ОБЪЁМУ с ТОЧНЫМИ моментами DG1 по
 *     коробке (те же V/12, что в матрицах масс): замкнутая форма, квадратуры
 *     нет.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Переноса `bout`/`sout` (хранимое на гранях и поверхностных
 * элементах): грани двух сеток не совпадают, и это отдельная работа, заводимая
 * только если замер покажет нужду. Переноса между деревьями РАЗНЫХ корней не
 * существует по постановке: сетка всегда над одной комнатой.
 */
#ifndef TR_XFER3_H
#define TR_XFER3_H

#include "transport/mesh3.h"

/* phi_dst[4·ncell(dst)] из phi_src[4·ncell(src)]. Деревья обязаны иметь ОДИН
 * корень (один log2size) и одну раму — иначе 1 и перенос не выполняется.
 * Возврат 0 — успех. Порядок обхода листьев src детерминирован (обход дерева),
 * ограничение суммирует в этом порядке: побитовости МЕЖДУ клетками здесь не
 * обещается (класс Г61 — это метрика, не топология), но повторяемость прогона
 * есть. */
int tr3_xfer(const tr3_mesh *dst, double *phi_dst, const tr3_mesh *src, const double *phi_src);

#endif
