#!/usr/bin/env bash
# ccheck.sh — ИСТОРИЧЕСКОЕ имя гейта (07-10 стал обёрткой).
#
# Прежняя редакция гоняла три движка по кругу на каждый файл: gcc -fanalyzer
# (самый дорогой — первым), затем -O2, clang-tidy, cppcheck, без раннего выхода
# и без базы. Замеры 07-10 показали цену этого порядка (-fanalyzer 44 с на
# sweep.c, clang-tidy 5 с даже на 400-строчном файле) и главное — гейт был
# КРАСЕН ВСЕГДА, поэтому настоящую находку нельзя было отличить от стоячего
# шума. Теперь вся работа — в scripts/cgate.sh: ступени S0…S4 по цене, ранний
# выход, кэш, база разобранных находок, отчёт в build/cgate/.
#
# Обёртка оставлена потому, что на `scripts/ccheck.sh` ссылаются прошлые
# редакции CLAUDE.md и записи журнала. Она равна:
#   scripts/cgate.sh --stage=0,1,2,3,4 "$@"
#
# Usage:  scripts/ccheck.sh FILE.c [...]      (без файлов — весь живой слой)
# Env:    CCHECK_EXTRA больше не поддерживается — общий набор флагов один и
#         живёт в scripts/cflags.mk (иначе снова расходятся копии).
#
# Exit: 0 = новых находок нет; 1 = есть новые/сбой ступени; 2 = ошибка вызова.
set -uo pipefail
HZ="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
exec "$HZ/scripts/cgate.sh" --stage=0,1,2,3,4 "$@"
