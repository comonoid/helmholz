#!/usr/bin/env bash
# cflags.sh — загрузчик scripts/cflags.mk для bash-скриптов.
#
# Единый источник флагов — scripts/cflags.mk (его же читает Makefile через
# `include`). Здесь только чтение: файл плоский, поэтому разбор — один sed.
# Ошибка в формате файла должна быть ГРОМКОЙ, а не молча давать пустой флаг.
hz_load_cflags() {
  local f="${1:?usage: hz_load_cflags scripts/cflags.mk}"
  [ -r "$f" ] || {
    echo "cflags.sh: не читается $f" >&2
    return 1
  }
  # $ и backtick в ЗНАЧЕНИЯХ сделали бы eval опасным; в комментариях они
  # допустимы (там как раз и написано, почему их нельзя в значениях).
  if grep -vE '^[[:space:]]*#' "$f" | grep -qE '[`$]'; then
    echo "cflags.sh: в $f есть \$ или backtick — загрузчик такой файл не разбирает" >&2
    return 1
  fi
  # Разбираются обе формы: «ИМЯ := значение» и «ИМЯ ?= значение».
  # Внимание: без ветки ?= переменная ARCH молча оставалась пустой, а гейт
  # падал на set -u уже внутри ступени (ловля 07-10).
  defs=$(sed -n 's/^\([A-Z_][A-Z0-9_]*\)[[:space:]]*\(:=\|?=\)[[:space:]]*\(.*\)$/\1="\3"/p' "$f")
  [ -n "$defs" ] || {
    echo "cflags.sh: в $f не нашлось ни одного определения ИМЯ := значение" >&2
    return 1
  }
  eval "$defs"
}
