#!/usr/bin/env bash
# Скачивание ЭТАЛОННЫХ СЦЕН в assets/. В git они НЕ кладутся (см. .gitignore):
# данные чужие, весят мегабайты и воспроизводимы этой командой.
#
# АТРИБУЦИЯ (требование copyright.txt внутри архива, воспроизводится здесь,
# чтобы она не потерялась вместе с распакованным каталогом):
#   conference — Greg Ward's conference room model, recreated by Kenzie Lamar
#                from various sources. Раздаётся McGuire Computer Graphics
#                Archive (casual-effects.com). Масштаб: ×0.003 даёт МЕТРЫ.
#
# ЗАЧЕМ ИМЕННО КОНФЕРЕНЦ-ЗАЛ. Это канонический эталон НЕПРЯМОГО освещения, то
# есть ровно то, что считает линия переноса; в нём есть и тонкие тела (ножки
# стульев — проверка пола по двугранному углу), и сложное перекрытие (стулья под
# столом — проверка теневых плоскостей). Источников в нём НЕТ, и это удобно:
# число компактных источников — параметр замера, а не свойство сцены.
set -eu

DEST="${1:-assets}"
mkdir -p "$DEST"

fetch() { # имя url
  # РАЗДЕЛЬНЫЕ local: в bash `local a=1 b=$a` объявляет ОБА имени локальными
  # ДО присваивания, поэтому $a внутри той же строки ещё не связан, и под
  # `set -u` это падает.
  local name="$1"
  local url="$2"
  local dir="$DEST/$name"
  if [ -d "$dir" ]; then
    echo "== $name: уже на месте ($dir), пропуск"
    return 0
  fi
  echo "== $name: качаю $url"
  mkdir -p "$dir"
  curl -fsSL -o "$dir/pack.zip" "$url"
  ( cd "$dir" && unzip -oq pack.zip && rm -f pack.zip )
  echo "== $name: готово"
  ls -la "$dir" | head -10
}

#   rungholt   — Minecraft-город «Rungholt», раздаётся тем же архивом.
#                ~6.7 млн треугольников, 47 МБ.
#
# ДВЕ СЦЕНЫ, И РОЛИ У НИХ РАЗНЫЕ — иначе выйдет К71/К82 (замер, снятый в одних
# условиях, перенесён в другие):
#   conference — ПРАВИЛЬНОСТЬ. Мелкая (124k граней), итерация секунды, есть
#                тонкие тела и сложное перекрытие. На ней видно, верен ли импорт.
#   rungholt   — МАСШТАБ и главное утверждение модели. Город из кубов: миллионы
#                треугольников при том, что РАЗЛИЧНЫХ ПЛОСКОСТЕЙ должно быть на
#                порядки меньше (стена из ста блоков — одна плоскость). Если
#                схлопывания нет, модель неверна, и это видно сразу.
#                Оговорка: кривых поверхностей и тонких тел в ней НЕТ, пол по
#                двугранному углу и гомогенизацию она не проверяет вовсе.
#   San_Miguel — двор гасиенды Сан-Мигель (Guillermo M. Leal Llaguno), тот же
#                архив. ~10 млн треугольников, 535 МБ.
#                РОЛЬ: РАЗБРОС РАЗМЕРОВ ДЕТАЛИ — пункт 6 реестра (§170).
#                Заведена 08-04 по требованию пользователя: Rungholt воксельный,
#                прямоугольный и с ЕДИНСТВЕННЫМ характерным размером (метр), и
#                на это свойство проект наткнулся четырежды — А339, А365, А374
#                (множитель огрубления не зависит от расстояния, потому что
#                огрублять нечего) и А406 (недосчёт слияний 0.88 держится на
#                избыточности партнёров, а она есть свойство сетки с одним
#                размером). У Сан-Мигеля листва против аркад — сантиметры против
#                метров в одном кадре, — плюс КРИВЫЕ поверхности и ТОНКИЕ тела,
#                которых у Rungholt нет вовсе. Оговорка: это двор, а не улица,
#                и городской масштабной ступени (сотни метров) она не даёт.

fetch conference \
  "https://casual-effects.com/g3d/data10/research/model/conference/conference.zip"

fetch rungholt \
  "https://casual-effects.com/g3d/data10/research/model/rungholt/rungholt.zip"

fetch San_Miguel \
  "https://casual-effects.com/g3d/data10/research/model/San_Miguel/San_Miguel.zip"

echo
echo "Сцены в $DEST. В git не вносить."
