#!/usr/bin/env bash
# Скачивание ЭТАЛОННЫХ СЦЕН в assets/. В git они НЕ кладутся (см. .gitignore):
# данные чужие, весят мегабайты и воспроизводимы этой командой.
#
# АТРИБУЦИЯ (требование copyright.txt внутри архива, воспроизводится здесь,
# чтобы она не потерялась вместе с распакованным каталогом):
# КОНФЕРЕНЦ-ЗАЛ УДАЛЁН 08-11 ПО ПРЯМОМУ УКАЗАНИЮ ПОЛЬЗОВАТЕЛЯ И БОЛЬШЕ НЕ
# КАЧАЕТСЯ. Он был каноническим эталоном непрямого освещения, но его сетка
# негодна как ИЗМЕРИТЕЛЬ: `12.63 %` рёбер с одним владельцем, обмотка
# несогласована. Замерено, что на нём неизмеримы ориентация многоугольников
# (метрика даёт `max 180°` у заведомо верных ячеек, А845), заливка внутренностей
# (протечка `1 572 696` ячеек, §477) и знаковый объём (`−88.17` м³ — величина
# без смысла). Писать софт для лечения входных сеток проект НЕ БУДЕТ: это
# отдельный продукт, и он не наш.
# ЧЕМ ЗАМЕНЁН: `assets/synth/room.obj` (`scripts/gen_room.sh`) — комната со
# стенами ТОЛЩИНОЙ, тремя масштабами кривизны, колонной и столом; замкнута,
# обмотка согласована, рёбер с одним владельцем `0`. На ней знаковый объём,
# заливка и матрицы масс стыка сходятся между собой.
set -eu

DEST="${1:-assets}"
mkdir -p "$DEST"

fetch() { # имя url
  # РАЗДЕЛЬНЫЕ local: в bash `local a=1 b=$a` объявляет ОБА имени локальными
  # ДО присваивания, поэтому $a внутри той же строки ещё не связан, и под
  # `set -u` это падает.
  local name="$1"
  local url="$2"
  local dir="$DEST/$name"
  if [ -d "$dir" ]; then
    echo "== $name: уже на месте ($dir), пропуск"
    return 0
  fi
  echo "== $name: качаю $url"
  mkdir -p "$dir"
  curl -fsSL -o "$dir/pack.zip" "$url"
  ( cd "$dir" && unzip -oq pack.zip && rm -f pack.zip )
  echo "== $name: готово"
  ls -la "$dir" | head -10
}

# ДВЕ СЦЕНЫ, И РОЛИ У НИХ РАЗНЫЕ — иначе выйдет К71/К82 (замер, снятый в одних
# условиях, перенесён в другие):
#   conference — УДАЛЕНА 08-11 ПО УКАЗАНИЮ ПОЛЬЗОВАТЕЛЯ и НЕ КАЧАЕТСЯ БОЛЬШЕ.
#                Причина: 12.63 % рёбер с одним владельцем и несогласованная
#                обмотка. На такой сцене неизмеримы ориентация (А845), заливка
#                внутренностей (§477) и знаковый объём (−88.17 м³). Софт для
#                лечения входных сеток проект не пишет — это чужой продукт.
#                РОЛЬ «правильность» перешла к assets/synth/room.obj
#                (scripts/gen_room.sh): замкнута, обмотка согласована, знаковый
#                объём сходится с заливкой и с матрицами масс стыка.
#   rungholt   — УДАЛЁН 08-12 ПО УКАЗАНИЮ ПОЛЬЗОВАТЕЛЯ и НЕ КАЧАЕТСЯ БОЛЬШЕ.
#                Причина: это ЭКСПОРТ ИЗ MINECRAFT («Neu Rungholt medieval
#                village Minecraft map»), воксельный ПО ПРОИСХОЖДЕНИЮ. Пока
#                мерился только МАСШТАБ, это было безразлично; с постановкой
#                «насколько недостаёт до UE5» сцена стала негодной: блочность
#                там от исходника, а не от рендерера, и по картинке она не
#                говорит ничего. Роль «масштаб» остаётся за San_Miguel
#                (5 млн треугольников, 281 материал, 323 текстуры), городской
#                масштабной ступени в сотни метров у проекта теперь НЕТ —
#                это названный пробел, а не молчание.
#   San_Miguel — двор гасиенды Сан-Мигель (Guillermo M. Leal Llaguno), тот же
#                архив. ~10 млн треугольников, 535 МБ.
#                РОЛЬ: РАЗБРОС РАЗМЕРОВ ДЕТАЛИ — пункт 6 реестра (§170).
#                Заведена 08-04 по требованию пользователя: Rungholt воксельный,
#                прямоугольный и с ЕДИНСТВЕННЫМ характерным размером (метр), и
#                на это свойство проект наткнулся четырежды — А339, А365, А374
#                (множитель огрубления не зависит от расстояния, потому что
#                огрублять нечего) и А406 (недосчёт слияний 0.88 держится на
#                избыточности партнёров, а она есть свойство сетки с одним
#                размером). У Сан-Мигеля листва против аркад — сантиметры против
#                метров в одном кадре, — плюс КРИВЫЕ поверхности и ТОНКИЕ тела,
#                которых у Rungholt нет вовсе. Оговорка: это двор, а не улица,
#                и городской масштабной ступени (сотни метров) она не даёт.

fetch San_Miguel \
  "https://casual-effects.com/g3d/data10/research/model/San_Miguel/San_Miguel.zip"

echo
echo "Сцены в $DEST. В git не вносить."
