#!/usr/bin/env bash
# КОМНАТА-ИНСТРУМЕНТ (§470, шаг Ш11). Сцена, на которой картинка имеет смысл и
# при этом ничего не врёт: зал комнатообразен, но у него 12.63 % рёбер с одним
# владельцем; сферы честны, но у них нет ни пола, ни света.
#
# ЧТО ЗДЕСЬ ГЛАВНОЕ — СТЕНЫ С ТОЛЩИНОЙ. Лист нулевой толщины воспроизвёл бы
# ровно ту патологию, от которой уходим: у него ячейки стоят по обе стороны,
# нормали смотрят врозь, и всякая метрика ориентации становится двусмысленной.
# Здесь каждое тело ЗАМКНУТО, и «внутри» определено.
#
# ОБМОТКА: у наружной оболочки нормаль наружу, у полости — в комнату. Обе
# согласованы ОТНОСИТЕЛЬНО МАТЕРИАЛА. Проверяется это не топологией (scenechk
# знаков не видит), а СВЕТОМ: перепутай — и комната выйдет чёрной (А862).
#
# РАЗМЕР ПОДОГНАН ПОД СУЩЕСТВУЮЩИЕ КОНСТАНТЫ scene_cfg.h: лампы на y = 1.95 м,
# глаз на y = 1.54 м. Потолок полости на 2.2 м, пол на 0. Ни одной новой
# константы конфигурации.
#
#   gen_room.sh [выход] [--thin]
#   --thin добавляет ПЕРЕГОРОДКУ НУЛЕВОЙ ТОЛЩИНЫ — негативный контроль самой
#   сцены: метрика обязана на ней испортиться, иначе чистота комнаты ничего не
#   доказывает.
set -eu
out="assets/synth/room.obj"
thin=0
soup=0
for a in "$@"; do
  case "$a" in
    --thin) thin=1 ;;
    --soup) soup=1 ;;
    *) out="$a" ;;
  esac
done

awk -v THIN="$thin" -v SOUP="$soup" '
# Порядок вершин коробки: бит 1 = x, 2 = y, 4 = z — как у ячейки октодерева.
# Обходы граней ВЫВЕДЕНЫ, а не подобраны: для каждой считано векторное
# произведение и проверен знак нормали. dir = +1 нормали наружу, -1 внутрь.
function setm(a,b2,c,d,e,f) { FM[0]=a; FM[1]=b2; FM[2]=c; FM[3]=d; FM[4]=e; FM[5]=f; }
function one(a) { setm(a,a,a,a,a,a); }
function box(x0,y0,z0, x1,y1,z1, dir,   b,i) {
  b = nv;
  for (i = 0; i < 8; i++)
    printf "v %.6f %.6f %.6f\n", (i%2 ? x1 : x0), (int(i/2)%2 ? y1 : y0), (int(i/4)%2 ? z1 : z0);
  nv += 8;
  printf "usemtl %s\n", FM[0]; quad(b+1, b+2, b+6, b+5, dir); # y = y0, нормаль -y
  printf "usemtl %s\n", FM[1]; quad(b+3, b+7, b+8, b+4, dir); # y = y1, нормаль +y
  printf "usemtl %s\n", FM[2]; quad(b+1, b+3, b+4, b+2, dir); # z = z0
  printf "usemtl %s\n", FM[3]; quad(b+5, b+6, b+8, b+7, dir); # z = z1
  printf "usemtl %s\n", FM[4]; quad(b+1, b+5, b+7, b+3, dir); # x = x0
  printf "usemtl %s\n", FM[5]; quad(b+2, b+4, b+8, b+6, dir); # x = x1
}
function quad(a,b,c,d, dir) {
  if (dir > 0) { printf "f %d %d %d\n", a, b, c; printf "f %d %d %d\n", a, c, d; }
  else         { printf "f %d %d %d\n", a, c, b; printf "f %d %d %d\n", a, d, c; }
}
# Сфера: полюс ОДНОЙ вершиной, иначе рёбра полюса остаются с одним владельцем.
function sphere(cx,cy,cz,r, nu,nw,   b,i,j,th,ph,np,sp,i2) {
  b = nv;
  printf "usemtl %s\n", FM[0];
  printf "v %.6f %.6f %.6f\n", cx, cy + r, cz; nv++;
  for (j = 1; j < nw; j++) {
    th = PI * j / nw;
    for (i = 0; i < nu; i++) {
      ph = 2.0 * PI * i / nu;
      printf "v %.6f %.6f %.6f\n", cx + r*sin(th)*cos(ph), cy + r*cos(th), cz + r*sin(th)*sin(ph);
      nv++;
    }
  }
  printf "v %.6f %.6f %.6f\n", cx, cy - r, cz; nv++;
  np = b + 1; sp = b + 1 + (nw-1)*nu + 1;
  for (i = 0; i < nu; i++) {
    i2 = (i + 1) % nu;
    printf "f %d %d %d\n", np, b+1+i2+1, b+1+i+1;
    printf "f %d %d %d\n", sp, b+1+(nw-2)*nu+i+1, b+1+(nw-2)*nu+i2+1;
  }
  for (j = 1; j < nw - 1; j++)
    for (i = 0; i < nu; i++) {
      i2 = (i + 1) % nu;
      printf "f %d %d %d\n", b+1+(j-1)*nu+i+1, b+1+j*nu+i2+1, b+1+j*nu+i+1;
      printf "f %d %d %d\n", b+1+(j-1)*nu+i+1, b+1+(j-1)*nu+i2+1, b+1+j*nu+i2+1;
    }
}
# Цилиндр с крышками: ОДИНАРНАЯ кривизна — одна главная кривизна нулевая, и
# складка квада обязана вести себя иначе, чем на сфере. Крышки веером от центра,
# иначе край остался бы с одним владельцем.
function cyl(cx,cz,r, y0,y1, nu,   b,i,i2,c0,c1) {
  b = nv;
  printf "usemtl %s\n", FM[0];
  for (i = 0; i < nu; i++) {
    printf "v %.6f %.6f %.6f\n", cx + r*cos(2*PI*i/nu), y0, cz + r*sin(2*PI*i/nu); nv++;
    printf "v %.6f %.6f %.6f\n", cx + r*cos(2*PI*i/nu), y1, cz + r*sin(2*PI*i/nu); nv++;
  }
  c0 = nv + 1; printf "v %.6f %.6f %.6f\n", cx, y0, cz; nv++;
  c1 = nv + 1; printf "v %.6f %.6f %.6f\n", cx, y1, cz; nv++;
  for (i = 0; i < nu; i++) {
    i2 = (i + 1) % nu;
    printf "f %d %d %d\n", b+2*i+1, b+2*i2+2, b+2*i2+1;
    printf "f %d %d %d\n", b+2*i+1, b+2*i+2, b+2*i2+2;
    printf "f %d %d %d\n", c0, b+2*i+1, b+2*i2+1;
    printf "f %d %d %d\n", c1, b+2*i2+2, b+2*i+2;
  }
}
BEGIN {
  PI = 3.14159265358979323846;
  nv = 0;
  printf "# КОМНАТА-ИНСТРУМЕНТ (§470). Замкнутые тела, согласованная обмотка,\n";
  printf "# стены С ТОЛЩИНОЙ. Сгенерировано scripts/gen_room.sh — не править руками.\n";
  printf "mtllib room.mtl\n";

  # МАТЕРИАЛЫ ПО ГРАНЯМ, А НЕ ПО ТЕЛАМ: у полости пол, потолок и стены разные,
  # и без этого комната читается как одна серая коробка (замечание пользователя
  # 08-11). Порядок граней в box(): y0, y1, z0, z1, x0, x1.
  one("outer");
  box(-4.2,-0.2,-3.2,  4.2, 2.4, 3.2,  1);   # наружная оболочка, нормали наружу
  setm("floor", "ceiling", "wall", "wall", "wall", "wall");
  box(-4.0, 0.0,-3.0,  4.0, 2.2, 3.0, -1);   # полость, нормали В КОМНАТУ

  one("ballred");   sphere(-1.5, 0.70, 1.5, 0.70, 48, 24);
  one("ballblue");  sphere( 0.6, 0.40,-1.2, 0.40, 40, 20);
  one("ballgreen"); sphere( 2.6, 0.25, 0.8, 0.25, 32, 16);

  one("stone"); cyl(-2.8, -1.6, 0.25, 0.0, 2.2, 48);

  one("tabletop"); box( 0.2, 0.72,-0.4,  1.8, 0.78, 0.4,  1);
  one("metal");
  box( 0.28,0.00,-0.32, 0.36,0.72,-0.24, 1);
  box( 1.64,0.00,-0.32, 1.72,0.72,-0.24, 1);
  box( 0.28,0.00, 0.24, 0.36,0.72, 0.32, 1);
  box( 1.64,0.00, 0.24, 1.72,0.72, 0.32, 1);

  # НК СЦЕНЫ. ДВА РАЗНЫХ ДЕФЕКТА, И ЭТО НЕ ПРИДИРКА (§472): «тонкий» и
  # «несогласованно обмотанный» — не одно и то же, и первый метрику НЕ ЛОМАЕТ
  # (замерено: доля вывернутых не сдвинулась ни на знак). Ломает второй.
  if (THIN || SOUP) {
    b = nv;
    printf "v %.6f %.6f %.6f\n", -3.0, 0.0, -1.0; nv++;
    printf "v %.6f %.6f %.6f\n", -1.0, 0.0, -1.0; nv++;
    printf "v %.6f %.6f %.6f\n", -1.0, 2.0, -1.0; nv++;
    printf "v %.6f %.6f %.6f\n", -3.0, 2.0, -1.0; nv++;
    if (SOUP) {
      # Полоса из ЧЕРЕДУЮЩИХСЯ по обмотке треугольников — суп, как у зала.
      for (k = 0; k < 16; k++) {
        y0 = 2.0 * k / 16.0; y1 = 2.0 * (k + 1) / 16.0;
        printf "v %.6f %.6f %.6f\n", -3.0, y0, -1.0; nv++;
        printf "v %.6f %.6f %.6f\n", -1.0, y0, -1.0; nv++;
        printf "v %.6f %.6f %.6f\n", -1.0, y1, -1.0; nv++;
        printf "v %.6f %.6f %.6f\n", -3.0, y1, -1.0; nv++;
        c = nv - 4;
        if (k % 2 == 0) {
          printf "f %d %d %d\n", c+1, c+2, c+3;
          printf "f %d %d %d\n", c+1, c+3, c+4;
        } else {
          printf "f %d %d %d\n", c+1, c+3, c+2;
          printf "f %d %d %d\n", c+1, c+4, c+3;
        }
      }
    } else {
      printf "f %d %d %d\n", b+1, b+2, b+3;
      printf "f %d %d %d\n", b+1, b+3, b+4;
    }
  }
}' > "$out"
echo "написано $out: $(grep -c '^v ' "$out") вершин, $(grep -c '^f ' "$out") треугольников"
