#!/usr/bin/env bash
# СЦЕНА-ИНСТРУМЕНТ ДЛЯ Ш7 (§457). Зал не годится измерителем ориентации: у него
# 12.63 % рёбер с одним владельцем и 5.333 % вывернутых многоугольников уже при
# ПОЛНОЙ ГЛУБИНЕ, то есть вклад модели того же порядка, что искомый наш.
#
# Здесь каждая поверхность ЗАМКНУТА и обмотана согласованно (наружу), поэтому
# доля вывернутых при полной глубине обязана быть РОВНО НОЛЬ, и всё, что
# показывает метрика на срезе, — наше.
#
# Сферы, а не коробки: нужна КРИВИЗНА, иначе LOD огрубляет всё до одной ячейки и
# перепада уровней не возникает. Восемь штук стоят вдоль луча зрения зальной
# камеры (scene_cfg.h) на 2…37 м, поэтому угловой размер меняется в 18 раз и
# уровни среза расходятся широко — ровно то, что проверяет Ш7.
set -eu
out="${1:-assets/synth/spheres.obj}"
awk 'BEGIN {
  PI = 3.14159265358979323846;
  ex = -2.42; ey = 1.54; ez = -2.66;      # камера зала
  dx =  3.42; dy = -0.54; dz =  2.16;     # направление взгляда
  dl = sqrt(dx*dx + dy*dy + dz*dz); dx /= dl; dy /= dl; dz /= dl;
  nd = split("2 4 7 11 16 22 29 37", dist, " ");
  nu = 48; nv = 24;                        # долготы, широты
  printf "# СФЕРЫ ДЛЯ Ш7: замкнуты, обмотка согласована наружу, открытых рёбер нет.\n";
  printf "# Сгенерировано scripts/gen_spheres.sh — не править руками.\n";
  base = 0;
  for (s = 1; s <= nd; s++) {
    d = dist[s] + 0.0; r = 0.6;
    cx = ex + dx*d; cy = ey + dy*d; cz = ez + dz*d;
    # ПОЛЮС — ОДНА вершина, а не nu копий. Копии геометрически совпадают, но
    # индексами не сшиты, и сцена вышла бы с 1536 рёбрами при одном владельце —
    # то есть ровно с тем дефектом, ради ухода от которого она и делается.
    printf "v %.6f %.6f %.6f\n", cx, cy + r, cz;
    for (j = 1; j < nv; j++) {
      th = PI * j / nv;
      for (i = 0; i < nu; i++) {
        ph = 2.0 * PI * i / nu;
        printf "v %.6f %.6f %.6f\n", cx + r*sin(th)*cos(ph), cy + r*cos(th), cz + r*sin(th)*sin(ph);
      }
    }
    printf "v %.6f %.6f %.6f\n", cx, cy - r, cz;
    np = base + 1;                       # северный полюс
    sp = base + 1 + (nv - 1)*nu + 1;     # южный полюс
    # Обмотка ПРОТИВ ЧАСОВОЙ, если смотреть снаружи; проверяется тем, что доля
    # вывернутых при ПОЛНОЙ ГЛУБИНЕ выходит нулём.
    for (i = 0; i < nu; i++) {
      i2 = (i + 1) % nu;
      printf "f %d %d %d\n", np, base + 1 + i + 1, base + 1 + i2 + 1;
      printf "f %d %d %d\n", sp, base + 1 + (nv-2)*nu + i2 + 1, base + 1 + (nv-2)*nu + i + 1;
    }
    for (j = 1; j < nv - 1; j++)
      for (i = 0; i < nu; i++) {
        i2 = (i + 1) % nu;
        a = base + 1 + (j-1)*nu + i + 1; b = base + 1 + (j-1)*nu + i2 + 1;
        c = base + 1 + j*nu + i2 + 1;    e = base + 1 + j*nu + i + 1;
        printf "f %d %d %d\n", a, e, c;
        printf "f %d %d %d\n", a, c, b;
      }
    base += (nv - 1) * nu + 2;
  }
}' > "$out"
echo "написано $out: $(grep -c '^v ' "$out") вершин, $(grep -c '^f ' "$out") треугольников"
