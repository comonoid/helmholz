#!/usr/bin/env bash
# night.sh — ОЧЕРЕДЬ ЗАМЕРОВ НА НОЧЬ (PLAN_ELEMENTS.md, §44).
#
# ЗАЧЕМ ИМЕННО ЭТО. Все сравнения огрубителя до сих пор сняты в ОДНОЙ точке по
# допуску, а число участков немонотонно по любому порогу (А102, А117): свип по
# порогу дал разброс вдвое, из которого нельзя сделать вывод. Лечение одно —
# мерить КРИВУЮ «элементы против ошибки» при нескольких допусках, тогда качели
# усредняются и конфигурации сравнимы. Это и есть главное содержание очереди.
#
# ПОРЯДОК ВАЖЕН: сперва зал (минуты) — он даёт кривые быстро и ловит поломки
# оснастки; потом город (минуты на прогон, часы на всё). Каждый прогон пишется
# СВОИМ файлом, поэтому очередь можно читать по частям и она не теряет сделанное
# при обрыве.
#
# ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ: случайного огрубления на ГОРОДЕ. Оно замерено (§36.3)
# и стоило больше часа — разрушенная геометрия вырождает сетку лучей (А110).
# Повторять его в очереди незачем; контроль на зале идёт.
set -u
cd "$(dirname "$0")/.."
OUT=build/night
mkdir -p "$OUT"
LOG="$OUT/log.txt"
: > "$LOG"

run() { # run <имя> <аргументы pmetric...>
  local name=$1
  shift
  if [ -s "$OUT/$name.txt" ]; then
    echo "SKIP $name (уже есть)" >> "$LOG"
    return
  fi
  echo "=== $name : $* : $(date +%H:%M:%S)" >> "$LOG"
  OMP_NUM_THREADS=16 timeout 5400 ./build/pmetric "$@" > "$OUT/$name.txt" 2>&1
  echo "    выход $? : $(date +%H:%M:%S)" >> "$LOG"
  grep -E "участков|пикселях|попали в обеих" "$OUT/$name.txt" >> "$LOG" 2>/dev/null
}

# --- ЗАЛ: кривая «элементы против ошибки» по четырём конфигурациям ---
for D in 0.1 0.2 0.3 0.6 1.2; do
  run "hall_d${D}_plain" hall simp d=$D
  run "hall_d${D}_cone30" hall simp d=$D cone=30
  run "hall_d${D}_loss15" hall simp d=$D loss=1.5
  run "hall_d${D}_vfit" hall simp d=$D vfit=0.25
done
# Контроль на зале: случайное огрубление с подгонкой вершин — метрика обязана
# остаться разрушенной (иначе подгонка «улучшает» мусор, и это надо знать).
run "hall_rand_vfit" hall simp rand vfit=0.25

# --- ГОРОД: та же кривая. Главный замер очереди ---
for D in 0.5 1.0 2.0 4.0 8.0; do
  run "city_d${D}_plain" city simp d=$D
  run "city_d${D}_cone30" city simp d=$D cone=30
  run "city_d${D}_loss15" city simp d=$D loss=1.5
  run "city_d${D}_vfit" city simp d=$D vfit=0.25
done

# --- ГОРОД: предел смещения вершины и совмещение с угловыми условиями ---
run "city_d2_vfit100" city simp d=2.0 vfit=1.0
run "city_d2_vfit005" city simp d=2.0 vfit=0.05
run "city_d2_vfit_loss15" city simp d=2.0 vfit=0.25 loss=1.5
run "city_d2_vfit_cone30" city simp d=2.0 vfit=0.25 cone=30

echo "ОЧЕРЕДЬ ЗАКОНЧЕНА $(date +%H:%M:%S)" >> "$LOG"
