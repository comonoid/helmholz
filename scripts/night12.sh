#!/usr/bin/env bash
# night12.sh — §71: проверка предсказания про радиус и силуэт + ДАЛЬНЯЯ камера.
#
# ДВА ВОПРОСА, И ОБА ПОСТАВЛЕНЫ ДО ПРОГОНА.
# (1) `rad>1` бриджит через разрывы ШИРЕ принятой ошибки, то есть заполняет проёмы.
#     Предсказание: силуэтный сдвиг у `rad=4` и `rad=16` ОБЯЗАН вырасти против
#     `rad=1`. Не вырос — значит бридж идёт не через проёмы, и объяснение неверно.
#     Мерить стало чем только теперь: силуэтный канал был сломан дважды (А172).
# (2) LOD меряется в своей НЕРАБОЧЕЙ точке: при нынешней камере ε·R по кадру
#     0.1…1 м, то есть ровно размер грани города (p50 = 1.414 м), и огрублять
#     нечего по построению. Свип по ε — это и есть отодвигание камеры, поэтому
#     кривая при равной цене снимается заново уже с ПОЧИНЕННЫМ силуэтом.
set -u
cd "$(dirname "$0")/.."
LOG=build/night/log12.txt
: > "$LOG"
run() {
  local name=$1; shift
  echo "=== $name : $* : $(date +%H:%M:%S)" >> "$LOG"
  ulimit -v 60000000 || true
  OMP_NUM_THREADS=16 timeout 43200 ./build/plod "$@" > "build/night/$name.txt" 2>&1
  echo "    выход $? : $(date +%H:%M:%S)" >> "$LOG"
  grep -E "КРИВАЯ|СРЕЗ по камере|РАЗМЕР ГРАНИ|ПРЕДСКАЗАНИЕ" "build/night/$name.txt" >> "$LOG" 2>/dev/null
}
run o24_city_rad1   city simp lev=8 viamerge curve
run o24_city_rad4   city simp lev=8 viamerge curve rad=4
run o24_city_rad16  city simp lev=8 viamerge curve rad=16
echo "ОЧЕРЕДЬ 12 ЗАКОНЧЕНА $(date +%H:%M:%S)" >> "$LOG"
