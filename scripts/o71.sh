#!/usr/bin/env bash
# Прогоны шага О71 (Ф2, план §247, аудит §248). Порядок: сперва НЕГАТИВНЫЙ
# КОНТРОЛЬ (равномерная сетка, «запрет подъёма» — обязан дать линейный рост и
# одну моду), потом замер по трём сценам в двух режимах среза.
#
# Потолок памяти обязателен (А492): 08-05 глобальный OOM-киллер снял не тот
# процесс, который был виноват. 32 ГБ — впятеро выше самого тяжёлого законного
# прогона.
set -u
R=${R:-result/O71_march.txt}
CAP=${CAP:-32G}
: > $R
SM=assets/San_Miguel/san-miguel.obj
HALL=assets/conference/conference.obj
CITY=assets/rungholt/rungholt.obj

run() { echo "### $*" | tee -a $R; scripts/cap.sh $CAP ./build/pmarchx "$@" 2>&1 | tee -a $R; echo | tee -a $R; }

echo '##### НЕГАТИВНЫЙ КОНТРОЛЬ: РАВНОМЕРНАЯ СЕТКА («запрет подъёма»).' | tee -a $R
echo '##### ОБЯЗАН дать линейный рост касаний по октавам и ОДНУ моду длины шага.' | tee -a $R
run $HALL 0.003 uni=1
run $CITY 1.0 uni=1

echo '##### ЗАМЕР: три сцены, два режима среза (пол 4 px и фиксированный уровень 8).' | tee -a $R
echo '##### Логарифм меряется на Rungholt (~7 октав) и Сан-Мигеле (~6); зал октав не имеет (А500).' | tee -a $R
run $CITY 1.0 px=4 fix=8
run $SM 1.0 px=4 fix=8
run $HALL 0.003 px=4 fix=8

echo '##### СКАН ПО ПОЛУ, ЧАСТЬ 1: рабочий диапазон 8…1 пиксель.' | tee -a $R
echo '##### ДИАГНОСТИКА (урок О67) обязана показать, ВХОДИТ ли пол в сбор вообще.' | tee -a $R
run $CITY 1.0 px=8
run $CITY 1.0 px=2
run $CITY 1.0 px=1

echo '##### СКАН ПО ПОЛУ, ЧАСТЬ 2: пол ГРУБЕЕ листьев (16…256 px).' | tee -a $R
echo '##### Здесь пол перехватывает управление у листьев, и только здесь П1 проверяема.' | tee -a $R
run $CITY 1.0 px=16
run $CITY 1.0 px=64
run $CITY 1.0 px=256
run $SM 1.0 px=64
run $SM 1.0 px=256
