#!/usr/bin/env bash
# tex_prep.sh — разовый перевод текстур сцены в PPM с ПОНИЖЕНИЕМ (§575, Ш8).
#
# ПОЧЕМУ НЕ ЧИТАТЬ PNG ПРЯМО. PNG есть чужой формат со своим `inflate`, и
# держать его декодер в проекте ради разовой конверсии — лишняя зависимость,
# которую пришлось бы сопровождать и проверять на недоверенном входе. Здесь
# конверсия делается ОДИН раз внешним инструментом, а в проект входит читатель
# `P6` в десяток строк.
#
# ПОЧЕМУ 256. Ячейка среза у Сан-Мигеля `0.135` м, кадр `512²`; текстура
# подробнее `256²` на поверхность в кадр не попадает. Число названо замером, а
# не вкусом, и меняется первым аргументом.
#
# Выход: `<dir>/ppm256/<имя>.ppm`. Уже переведённые пропускаются.
set -eu
DIR=${1:-assets/San_Miguel/textures}
MAX=${2:-256}
OUT="$DIR/ppm$MAX"
mkdir -p "$OUT"
n=0
skip=0
for f in "$DIR"/*.png "$DIR"/*.jpg; do
  [ -e "$f" ] || continue
  b=$(basename "$f")
  o="$OUT/${b%.*}.ppm"
  if [ -e "$o" ]; then
    skip=$((skip + 1))
    continue
  fi
  nix-shell -p imagemagick --run \
    "magick \"$f\" -resize ${MAX}x${MAX}\\> -colorspace sRGB -type TrueColor ppm:\"$o\"" \
    >/dev/null 2>&1 || echo "  НЕ ПЕРЕВЕДЁН: $b"
  n=$((n + 1))
done
echo "== ТЕКСТУРЫ: переведено $n, пропущено (уже есть) $skip -> $OUT"
du -sh "$OUT" 2>/dev/null || true
