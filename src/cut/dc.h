#ifndef HZ_CUT_DC_H
#define HZ_CUT_DC_H

/* ОБЩИЙ СЛОЙ (PLAN_CUT.md, Р-5б и Р-5в). Граница, ВЫВЕДЕННАЯ ИЗ ОБЪЁМНЫХ ДАННЫХ
 * — второй источник плоскостей из Г9 (первый, аналитический примитив, живёт в
 * cut/surf.c). Адаптивное dual contouring: на узел ОДНА вершина (минимум QEF),
 * полигоны НЕ ХРАНЯТСЯ, а порождаются обходом (Г12).
 *
 * СВОЁ ДЕРЕВО, А НЕ hz_octree И НЕ tr2_mesh. hz_onode несёт k² — волновую
 * физику; tr2_mesh двумерна и переносная. Объёмные данные границы общие для
 * обеих линий, поэтому здесь своя арена, устроенная как у hz_octree: блок из 8
 * подряд, child0 < 0 = лист, индексы строго вперёд. Наружу ключом идёт
 * абстрактный int32 (Г20) — индекс узла ЭТОГО дерева.
 *
 * ЭРМИТОВЫ ДАННЫЕ, А НЕ ЗАНЯТОСТЬ (Г12, и это измерено в test_qef): точка на
 * ребре ПЛЮС НОРМАЛЬ. Занятость даёт лесенку и скругляет стык стены с полом;
 * нормаль держит его острым. Ребро принадлежит ЧЕТЫРЁМ ячейкам, поэтому оно —
 * ОБЩИЙ объект в таблице, а не копия в каждой (иначе Г3/Г10 заново, только на
 * уровне данных). */

#include "cut/poly3.h"
#include "cut/qef.h"
#include "cut/surf.h"
#include <stdint.h>

/* Ключ ребра — ось (2 бита) плюс три координаты нижнего конца по 20 бит. Верхний
 * конец включительно, поэтому координата доходит до 2^19 и 20 бит её вмещают.
 * Предел разрядный, а не геометрический: 1.4e17 минимальных ячеек. */
#define HZ_DC_MAX_LOG2SIZE 19

/* ЧЕСТНЫЙ ПРЕДЕЛ ПЛОТНОГО ПОСТРОИТЕЛЯ, а не формата и НЕ предел этого файла:
 * hz_dc_sample опрашивает источник во ВСЕХ узлах сетки, то есть стоит O(8^L) —
 * цена ПО ВХОДУ. Плотный путь держится НЕЗАВИСИМОЙ реализацией для сверки (Г42)
 * и этим пределом связан.
 * ЛЕНИВЫЙ СПУСК СО ЗНАКОМ УДАЛЁН 08-10 вместе с адаптером (Р7, §393): знака
 * «внутри/снаружи» у сцены из односторонних треугольников не существует, и это
 * ЗАМЕРЕНО (§391). Его место занял `hz_dc_shape_occ` — спуск по ЗАНЯТОСТИ,
 * ограниченный только разрядным HZ_DC_MAX_LOG2SIZE. Плотный знаковый путь ниже
 * оставлен: на нём стоят Г49, Г50 и Г11.4 (А707). */
#define HZ_DC_SAMPLE_MAX_LOG2SIZE 6

typedef enum {
  HZ_DC_OK = 0,
  HZ_DC_ENOMEM = 1,
  HZ_DC_ERANGE = 2, /* log2size вне предела */
  HZ_DC_EDUP = 3,   /* одно ребро занесено дважды */
  HZ_DC_EMULTI = 4, /* встречена неманифолдная ячейка (Г47) — вершины НЕ выдано */
  HZ_DC_ETOPO = 5   /* обход пришёл в конфигурацию, которой по инварианту нет */
} hz_dc_status;

/* --- 1. эрмитовы рёбра ----------------------------------------------------- */

typedef struct {
  uint64_t key;
  int32_t p[3];  /* НИЖНИЙ конец, целочисленный */
  int32_t axis;  /* 0,1,2 */
  double t;      /* доля вдоль оси, [0,1] */
  double nrm[3]; /* ЕДИНИЧНАЯ нормаль поверхности в точке */
  uint8_t in_lo; /* 1 = материал у НИЖНЕГО конца */
} hz_hedge;

typedef struct {
  hz_hedge *e;
  int32_t n, cap;
} hz_htab;

int hz_htab_init(hz_htab *h);
void hz_htab_free(hz_htab *h);
uint64_t hz_hedge_key(int axis, const int32_t p[3]);
int hz_htab_add(hz_htab *h, int axis, const int32_t p[3], double t, const double nrm[3], int in_lo);
int hz_htab_sort(hz_htab *h); /* сортирует и ловит повторы (HZ_DC_EDUP) */

/* Сортирует и СХЛОПЫВАЕТ повторы — нужно ленивому спуску, который приходит к
 * ребру из каждой из четырёх делящих его ячеек. Схлопывание не молчаливое:
 * копии сверяются ПОБИТОВО, и расхождение даёт HZ_DC_EDUP. Обещание Г3 («формула
 * одна, поэтому все четверо читают точку одинаково») до сих пор держалось
 * построением, здесь оно ещё и меряется. Число схлопнутых — в *ndup. */
int hz_htab_uniq(hz_htab *h, int32_t *ndup);

/* Сводит записи одного ребра по ПЕРВОМУ пересечению от нижнего конца (наименьшее
 * `t`). Нужно беззнаковому источнику, который заносит ребро по разу на каждый
 * пересекающий треугольник; записи законно разные, и `hz_htab_uniq` тут не
 * годится. Порядок строгий и от порядка занесения не зависит. В *ndrop —
 * сколько записей отброшено. Разбор — в `dc.c` над функцией. */
int hz_htab_reduce_min(hz_htab *h, int32_t *ndrop);
const hz_hedge *hz_htab_find(const hz_htab *h, int axis, const int32_t p[3]);

/* Точка пересечения: нижний конец плюс t вдоль оси. Формула ОДНА, поэтому все
 * четыре ячейки, делящие ребро, читают ПОБИТОВО одну и ту же точку. */
void hz_hedge_point(const hz_hedge *e, double p[3]);

/* --- 2. сетка знаков (объёмные данные) ------------------------------------- */

typedef struct {
  uint8_t *s; /* (2^L+1)^3, 1 = внутри материала */
  int32_t n1; /* 2^L + 1 */
  int log2size;
} hz_signgrid;

void hz_signgrid_free(hz_signgrid *g);
int hz_signgrid_at(const hz_signgrid *g, const int32_t c[3]);

/* Источник объёмных данных. ЕДИНСТВЕННОЕ, что общий слой знает про сцену (Г9:
 * «ядро от источника не зависит»). cross возвращает 0, если пересечение найдено. */
typedef int (*hz_dc_sign)(void *ctx, const int32_t c[3]);
typedef int (*hz_dc_cross)(void *ctx, const int32_t a[3], int axis, double *t, double nrm[3]);

/* Опросить источник: сетка знаков + эрмитовы данные на всех минимальных рёбрах
 * со сменой знака. Ребро заносится РОВНО ОДИН раз. */
int hz_dc_sample(hz_signgrid *g, hz_htab *ht, int log2size, hz_dc_sign sg, hz_dc_cross cr,
                 void *ctx);

/* --- 3. дерево ------------------------------------------------------------- */

enum {
  HZ_DC_HASVERT = 1u, /* вершина посчитана */
  HZ_DC_CLAMPED = 2u, /* и она была ЗАГНАНА в узел (Г12, оговорка 1) */
  HZ_DC_MULTI = 4u    /* неманифолдная маска: вершины НЕТ, и это не молчание (Г47) */
};

typedef struct {
  int32_t child0; /* индекс первого из 8 детей, или -1 у листа */
  uint8_t corner; /* бит c: угол c (биты 1=x, 2=y, 4=z) ВНУТРИ материала */
  uint8_t flags;
  /* БЕЗЗНАКОВЫЙ КЛЮЧ ПОВЕРХНОСТИ (Р7, §393). Знака «внутри/снаружи» у сцены из
   * односторонних треугольников не существует (замерено, §391), поэтому
   * поверхность опознаётся РЕБРОМ С ПЕРЕСЕЧЕНИЕМ. Нумерация рёбер — `unit_edge`,
   * та же, что у формы листа, и на ней стоит побитовость починки (Г49).
   *   ecross  бит i: на ребре i есть эрмитов образец;
   *   edir    бит i: нормаль этого образца смотрит ВДОЛЬ оси ребра. Заменяет
   *           знак у верхнего конца в выборе обхода многоугольника.
   * У КРУПНОГО УЗЛА `edir` НЕ ОПРЕДЕЛЁН (А708): его ребро накрывает несколько
   * сеточных, и «вдоль оси» перестаёт быть одним битом. Обход читает маску
   * только у САМОЙ МЕЛКОЙ из четырёх ячеек (Г43), поэтому при полной глубине
   * это всегда ребро сетки; для адаптивного среза долг записан в Ш3.
   * `ecross` у крупного узла — ИЛИ по детям, и у недробившегося он обязан быть
   * нулём: спуск идёт по занятости, а ребро, задетое треугольником, лежит в
   * задетой коробке (А709). */
  uint16_t ecross, edir;
  hz_qef q;     /* форма в ЛОКАЛЬНЫХ координатах узла (Г41) */
  double vx[3]; /* вершина в координатах ДЕРЕВА */
  double err;   /* невязка QEF в вершине — по ней выбирается уровень */
} hz_dcnode;

typedef struct {
  hz_dcnode *nd;
  int32_t n, cap;
  int log2size;
  int32_t nclamped, nmulti; /* СЧИТАЮТСЯ, а не замалчиваются */
  /* БЕЗЗНАКОВЫЙ РЕЖИМ (Р7). Ставится `hz_dc_shape_occ`; обход тогда берёт и
   * критерий, и ориентацию из масок рёбер, а не из маски углов. Знаковый путь
   * (`hz_dc_build` от сеточного знака) остаётся нетронутым — на нём стоят Г49,
   * Г50 и Г11.4, и сносить проверенное вместе с адаптером нельзя (А707). */
  int unsgn;
  int32_t nbigmask; /* А709: крупный лист с ненулевой маской рёбер — обязан быть 0 */
} hz_dctree;

int hz_dc_init(hz_dctree *t, int log2size);
void hz_dc_free(hz_dctree *t);

/* ПРОИЗВОДНЫЕ ВЕЛИЧИНЫ УЗЛА — ТОЛЬКО ЧЕРЕЗ ФУНКЦИИ (А722). Вершина, невязка и
 * форма суть ПРОИЗВОДНОЕ (А661): они пересчитываются из долговечного и по замыслу
 * не должны храниться в узле вовсе. Сегодня это ещё поля; когда они уедут в
 * побочные массивы или на стек сборки, потребители не заметят — при условии, что
 * читают их отсюда, а не полем напрямую. */
static inline const double *hz_dc_vx(const hz_dctree *t, int32_t ni) { return t->nd[ni].vx; }
static inline double hz_dc_err(const hz_dctree *t, int32_t ni) { return t->nd[ni].err; }
static inline int hz_dc_hasvert(const hz_dctree *t, int32_t ni) {
  return (t->nd[ni].flags & HZ_DC_HASVERT) != 0;
}

/* Построение: спуск, пока в коробке есть смена знака; в листе размера 1 — маска
 * углов и QEF из его 12 рёбер; на подъёме форма родителя = сумма СДВИНУТЫХ форм
 * детей, и вершина решается для КАЖДОГО узла. Это и есть предвычисленная
 * иерархия Г11: на кадре из неё только читают. */
int hz_dc_build(hz_dctree *t, const hz_signgrid *g, const hz_htab *ht);

/* ФОРМЫ И ВЕРШИНЫ СНИЗУ ВВЕРХ по готовому дереву и готовой таблице рёбер.
 * Источник не спрашивается вовсе — потому этот проход и пережил снос адаптера и
 * служит обоим путям, знаковому и беззнаковому. */
int hz_dc_forms_lazy(hz_dctree *t, const hz_htab *ht);

/* --- 3б. БЕЗЗНАКОВЫЙ ПУТЬ (Р7, §393) --------------------------------------- */

/* ЕДИНСТВЕННЫЙ ВОПРОС К СЦЕНЕ, И ОН ГЕОМЕТРИЧЕСКИЙ: есть ли в коробке
 * `[lo, lo+size)` геометрия. Ответ КОНСЕРВАТИВЕН и односторонен, как и прежний
 * `hz_dc_box`: `0` = геометрии ТОЧНО нет (спуск прекращается). Ошибка в сторону
 * «есть» стоит лишних узлов; ошибка в сторону «нет» теряет геометрию МОЛЧА —
 * fail-open, запрещённый Г25.
 *
 * ПОЧЕМУ ЭТО НЕ ВОЗВРАТ К АДАПТЕРУ (Р1, А707). Здесь остаётся ОДИН вопрос
 * вместо трёх, и он не про поле, а про коробку; сцена по-прежнему не спрашивается
 * ни про знак, ни про пересечение — рёбра она ПЕРЕДАЁТ таблицей. Когда источник
 * научится отдавать и топологию, этот вызов уйдёт тоже. */
typedef int (*hz_dc_occ)(void *ctx, const int32_t lo[3], int32_t size);

/* Спуск по занятости: дробить, пока в коробке есть геометрия, до размера 1.
 * Маску углов не ставит вовсе. Ставит `t->unsgn`. */
int hz_dc_shape_occ(hz_dctree *t, int log2size, hz_dc_occ oc, void *ctx);

/* Маски рёбер из готовой таблицы: у листьев размера 1 — прямым поиском, у
 * внутренних — ИЛИ по детям. Считает `t->nbigmask` (А709). Зовётся ПОСЛЕ того,
 * как таблица заполнена, и ДО `hz_dc_forms_lazy`. */
int hz_dc_masks_occ(hz_dctree *t, const hz_htab *ht);

/* Починка после правки эрмитовых данных (Г13): пересчитать лист, накрывающий
 * ячейку cell, и ПЕРЕСЛОЖИТЬ предков, O(глубины). Топологию не трогает: если
 * правка создаёт поверхность там, где её не было, меняется СЕТКА ЗНАКОВ, а с ней
 * форма дерева — это перестройка поддерева, а не починка, и здесь возвращается
 * HZ_DC_ETOPO. */
int hz_dc_repair(hz_dctree *t, const hz_htab *ht, const int32_t cell[3]);

/* Одна ли компонента у внутренних углов и у внешних. Маска с двумя диагонально
 * противоположными углами несёт ДВА листа поверхности, а «коробка ∩
 * полуплоскости» — тело ВЫПУКЛОЕ и двух листов не несёт вовсе (Г47). */
int hz_dc_manifold(uint8_t corner);

/* --- 4. обход (Р-5в) ------------------------------------------------------- */

typedef struct {
  int32_t ni;
  int32_t lo[3];
  int32_t size;
} hz_dcref;

/* Предикат «считать этот узел листом»: так задаётся срез дерева по LOD. NULL =
 * спускаться до настоящих листьев. */
typedef int (*hz_dc_stop)(void *ctx, const hz_dctree *t, const hz_dcref *r);

/* Полигон: 3 или 4 вершины ячеек ЛЮБЫХ уровней, в порядке ПРОТИВ ЧАСОВОЙ, если
 * смотреть СНАРУЖИ материала. Отдаются сами ячейки (индекс, коробка), а не одни
 * индексы: мосту к разрезу нужна коробка, чтобы точно решить, режет ли плоскость
 * эту ячейку, и узел своей коробки не хранит — она известна только обходу. */
typedef int (*hz_dc_poly)(void *ctx, const hz_dcref *ref, const double (*v)[3], int nv);

/* РАБОЧИЙ обход: cellProc -> faceProc -> edgeProc. Цена — число ВЫДАННЫХ
 * полигонов, то есть ПО ВЫХОДУ. */
int hz_dc_walk(const hz_dctree *t, hz_dc_stop stop, void *sctx, hz_dc_poly emit, void *pctx);

/* ЭТАЛОННЫЙ обход по таблице рёбер: очевидно бескрак-фри, но цена — число
 * МИНИМАЛЬНЫХ РЁБЕР, то есть ПО ВХОДУ, и на грубом LOD он всё равно обходит
 * самый мелкий уровень. Держится не как запасной, а как НЕЗАВИСИМАЯ РЕАЛИЗАЦИЯ
 * для сверки (Г42) — тем же приёмом CLAUDE.md требует сверять ядра GPU. */
int hz_dc_walk_ref(const hz_dctree *t, const hz_htab *ht, hz_dc_stop stop, void *sctx,
                   hz_dc_poly emit, void *pctx);

/* --- 5. мост к разрезу ----------------------------------------------------- */

/* Полигоны -> треугольники -> плоскости в таблицу фасетов, и раздача ЯЧЕЙКАМ,
 * которым принадлежат вершины: ячейка получает ВЕЕР плоскостей вокруг своей
 * вершины (Г10). Плоскость считается ОДИН раз, поэтому весь веер видит её
 * побитово (Г3).
 *
 * dmax у этих фасетов остаётся HZ_FACET_DMAX_UNKNOWN, и это не недоделка (Г44):
 * невязка QEF есть СРЕДНЕКВАДРАТИЧНОЕ отклонение НА ОБРАЗЦАХ, а dmax по смыслу —
 * максимум смещения по всей области фасета. У идеально подогнанной плоскости
 * невязка ноль, а смещение от истинной кривой поверхности нулю не равно.
 * Волновая линия по Г25 обязана отказаться; переносу они законны (Г9). */
int hz_dc_facets(const hz_dctree *t, hz_dc_stop stop, void *sctx, hz_facettab *ft, hz_cutmap *cm);

#endif
