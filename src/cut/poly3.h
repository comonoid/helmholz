#ifndef HZ_CUT_POLY3_H
#define HZ_CUT_POLY3_H

/* ОБЩИЙ СЛОЙ (PLAN_CUT.md, Р-4). Ни волновой, ни переносный: отсечение коробки
 * набором полуплоскостей и ТОПОЛОГИЯ результата. Дальше линии расходятся —
 * перенос тетраэдризует и берёт полиномы, волна обходит грани и рёбра и берёт
 * полином x экспоненту в замкнутой форме (Г1, Г6). Интегратор здесь не живёт.
 *
 * ЧТО ЯДРО НЕ ЗНАЕТ, И ЭТО НАМЕРЕННО (Г7, Г18, Г20): ни про одно из двух
 * деревьев, ни про материалы. Вход — целочисленная коробка плюс ОРИЕНТИРОВАННЫЕ
 * полупространства; какой стороне какой материал, решает вызывающий.
 *
 * КООРДИНАТЫ — ЦЕЛОЧИСЛЕННЫЕ ЕДИНИЦЫ ХОЗЯИНА, А НЕ МИР. Плоскость переводится в
 * единицы ОДИН РАЗ на (поверхность x дерево) через hz_frame_plane, поэтому все
 * ячейки видят ПОБИТОВО одну и ту же плоскость — на этом стоит
 * водонепроницаемость, и только на этом: допуска здесь нет нигде.
 *
 * НО МЕТРИКА В ЕДИНИЦАХ НЕВЕРНА (Г21). Переход в единицы — аффинное сжатие с
 * разными множителями по осям; объём переносится точно (умножением на u0*u1*u2),
 * УГЛЫ И ПЛОЩАДИ — нет. Поэтому ядро отдаёт топологию и вершины В ЕДИНИЦАХ, а
 * всякая метрическая величина считается функцией, которой hz_frame передаётся
 * ЯВНО. Ошибка «нормаль в единицах = нормаль в мире» не проявилась бы на
 * кубической ячейке и вылезла бы на анизотропной (Г15: 4 мм x 1 м x 1 м —
 * штатный случай). */

#include <stdint.h>

/* мир = o + u∘i ; u > 0 покомпонентно, оси могут иметь РАЗНЫЙ масштаб */
typedef struct {
  double o[3], u[3];
} hz_frame;

/* держим {n·x <= off}. Противоположная сторона получается отрицанием ОБОИХ:
 * в IEEE это точно, s меняет ровно знак, а параметр пересечения
 * t = s_a/(s_a - s_b) не меняется ВОВСЕ — поэтому сосед, держащий другую
 * сторону той же плоскости, строит те же точки побитово. */
typedef struct {
  double n[3], off;
} hz_hspace;

/* Ёмкости ВЫВЕДЕНЫ, а не назначены (CLAUDE.md: магических порогов нет).
 * У выпуклого многогранника F граней: V <= 2F - 4, E <= 3F - 6, а сумма длин
 * петель равна 2E. Коробка даёт 6 граней, каждое отсечение добавляет не больше
 * одной (крышку). HZ_P3_MAXH согласован с HZ_CUT_MAXHP из cut2d.h. */
enum {
  HZ_P3_MAXH = 96,
  HZ_P3_MAXF = 6 + HZ_P3_MAXH,
  HZ_P3_MAXV = 2 * HZ_P3_MAXF - 4,
  HZ_P3_MAXFL = 6 * HZ_P3_MAXF - 12
};

/* Выпуклый многогранник: вершины в ЕДИНИЦАХ + петли граней.
 * fsrc >= 0  — грань лежит на полуплоскости с этим hid;
 * fsrc <  0  — грань коробки, номер ~fsrc в 0..5 (-x,+x,-y,+y,-z,+z).
 * Петля грани f — fl[floff[f] .. floff[f+1]), ПРОТИВ ЧАСОВОЙ СТРЕЛКИ, ЕСЛИ
 * СМОТРЕТЬ СНАРУЖИ. Рёбра отдельным массивом не хранятся: петли их задают, а
 * волновой линии рёберный интеграл нужен внутри обхода грани, то есть в том же
 * порядке. Общее ребро двух граней проходится ими в ПРОТИВОПОЛОЖНЫХ
 * направлениях — это и есть проверка замкнутости. */
typedef struct {
  int32_t nv, nf;
  double v[HZ_P3_MAXV][3];
  int32_t fsrc[HZ_P3_MAXF];
  int32_t floff[HZ_P3_MAXF + 1];
  int32_t fl[HZ_P3_MAXFL];
} hz_poly3;

typedef enum {
  HZ_P3_OK = 0,
  HZ_P3_EMPTY = 1,    /* всё отсечено: тела не осталось */
  HZ_P3_ECAP = 2,     /* крышка не замкнулась — вырождение, не молчать о нём */
  HZ_P3_ECAPACITY = 3 /* вышли за выведенные ёмкости */
} hz_p3_status;

/* Плоскость из МИРОВЫХ (n, off) в единицы кадра. Считается ОДИН РАЗ на
 * поверхность: два вызова для одной плоскости обязаны дать одинаковые биты, а
 * это гарантировано только тем, что вызов один. */
void hz_frame_plane(const hz_frame *fr, const double n[3], double off, hz_hspace *h);

/* Коробка [lo, hi) в единицах: 8 вершин, 6 граней, fsrc = ~(0..5). */
int hz_poly3_box(hz_poly3 *p, const int32_t lo[3], const int32_t hi[3]);

/* out = in ^ {n·x <= off}. in и out должны быть РАЗНЫМИ объектами.
 * Вырождения лечит топология, а не допуск: вершина с s == 0 считается лежащей
 * НА плоскости (третий случай, не «внутри с погрешностью»), грань с петлёй
 * короче трёх различных вершин выбрасывается, куска нулевого объёма не
 * рождается. Допуск не нужен именно потому, что обе соседние ячейки вычисляют
 * s от одной плоскости в одной точке и получают побитово одно и то же. */
int hz_poly3_clip(const hz_poly3 *in, const hz_hspace *h, int32_t hid, hz_poly3 *out);

/* Коробка, отсечённая всеми nh полуплоскостями. hid[] — метки для fsrc. */
int hz_poly3_cut(hz_poly3 *out, const int32_t lo[3], const int32_t hi[3], const hz_hspace *h,
                 const int32_t *hid, int nh);

/* ДОПОЛНЕНИЕ — до nh НЕПЕРЕСЕКАЮЩИХСЯ ВЫПУКЛЫХ кусков. Внешность выпуклого тела
 * не выпукла, а переносу нужны настоящие тетраэдры и снаружи. Точное разбиение:
 * кусок j = коробка, отсечённая h_0..h_{j-1} как есть и h_j ПЕРЕВЁРНУТОЙ; куски
 * не пересекаются, объединение есть ровно дополнение. Пустые не выдаются, так
 * что *nout <= nh и ЗАВИСИТ ОТ ПОРЯДКА полуплоскостей — проверяемая величина
 * здесь Σ объёмов, а не число кусков (Г30). Грань, порождённая перевёрнутой
 * h_j, получает fsrc = ~hid[j] ... нет: ~ занято коробкой, поэтому метка
 * перевёрнутой стороны передаётся вызывающим в hid и здесь не изобретается. */
int hz_poly3_complement(hz_poly3 *out, int maxout, int *nout, const int32_t lo[3],
                        const int32_t hi[3], const hz_hspace *h, const int32_t *hid,
                        const int32_t *hid_flipped, int nh);

/* Метрика. fr передаётся ЯВНО, потому что в единицах она неверна (Г21). */
double hz_poly3_volume(const hz_poly3 *p, const hz_frame *fr);
double hz_poly3_area(const hz_poly3 *p, int f, const hz_frame *fr);
void hz_poly3_normal(const hz_poly3 *p, int f, const hz_frame *fr, double nout[3]);

#endif
