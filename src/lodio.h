/* lodio.h — ФАЙЛ ЛЕСТНИЦЫ LOD (PLAN_ELEMENTS.md, §62, пункт 2).
 *
 * ЗАЧЕМ ФАЙЛ. Критерий слияния не зависит от света (`pmerge.h`), значит иерархия
 * строится ОДИН РАЗ при импорте сцены и потом только читается. На городе
 * постройка стоит 200…280 с — столько же ждать перед каждым кадром нельзя,
 * поэтому лестница есть АРТЕФАКТ СЦЕНЫ, а не промежуточная величина в памяти.
 *
 * ФОРМАТ ПО ОБРАЗЦУ `PLAN_CUT.md` Р-2, и три вещи в нём не косметические.
 *
 * 1. СВИДЕТЕЛИ ПРЕДСТАВЛЕНИЯ. В заголовке лежат `sizeof(double)`,
 *    `sizeof(hz_lodnode)`, образец порядка байт и образец самого `double`
 *    (`1.0`). Файл пишется СЫРЫМИ структурами — быстро и без разметки, — а это
 *    значит, что он привязан к ABI. Свидетели превращают перенос на другую
 *    платформу в ОТКАЗ, а не в тихую порчу: без них чужое выравнивание дало бы
 *    сдвинутые поля, то есть правдоподобную чепуху.
 * 2. КОНТРОЛЬНАЯ СУММА ПО ВСЕЙ НАГРУЗКЕ (А147). Проверка вложенности
 *    СЕМАНТИЧЕСКАЯ: она ловит метку вне диапазона и разрыв иерархии, но НЕ
 *    ловит обмен двух меток внутри одного родителя — вложенность при этом цела.
 *    Обещать «порча байта ловится» без суммы значит обещать больше, чем даёт
 *    проверка. Сумма — FNV-1a 64, детектор порчи, а не подписи.
 * 3. ПОЛНАЯ ЦЕЛОЧИСЛЕННАЯ ПРОВЕРКА ПРИ ЧТЕНИИ, а не при отладке: метки в
 *    `[0, nnd)`, уровень узла равен номеру слоя, родитель уровнем ниже,
 *    вложенность по меткам (все полигоны одного узла уровня `L` лежат в ОДНОМ
 *    узле уровня `L+1`). Несогласованность — ОТКАЗ с кодом, а не починка:
 *    починенная иерархия дала бы срез, про который неизвестно, чему он равен.
 *
 * ПРОИСХОЖДЕНИЕ ПИШЕТСЯ В ФАЙЛ (`bands`, `bycount`, `delta0`, `eps`): срез
 * сверяет `eps` (А131), а тактика и порядок нужны, чтобы два файла нельзя было
 * спутать по одному имени.
 */
#ifndef HZ_LODIO_H
#define HZ_LODIO_H

#include "plod.h"

/* Коды отказа. Отдельные, а не «не ноль»: по номеру видно, чужой это файл,
 * побитая нагрузка или несогласованная иерархия, и это три разных диагноза. */
typedef enum {
  HZ_LODIO_OK = 0,
  HZ_LODIO_ERR_IO = 1,      /* не открылся, короткое чтение, ошибка записи */
  HZ_LODIO_ERR_MAGIC = 2,   /* не тот файл */
  HZ_LODIO_ERR_VERSION = 3, /* тот файл, другая версия */
  HZ_LODIO_ERR_ABI = 4,     /* свидетели представления не совпали */
  HZ_LODIO_ERR_SUM = 5,     /* контрольная сумма нагрузки */
  HZ_LODIO_ERR_RANGE = 6,   /* метка или родитель вне диапазона */
  HZ_LODIO_ERR_LEVEL = 7,   /* уровень узла не равен номеру слоя */
  HZ_LODIO_ERR_NEST = 8,    /* вложенность нарушена */
  HZ_LODIO_ERR_MEM = 9,
  HZ_LODIO_ERR_SEG = 10 /* лестница построена на ДРУГОЙ сегментации */
} hz_lodio_err;

const char *hz_lodio_str(int err);

/* БАЗОВАЯ РАЗМЕТКА ПЕРЕДАЁТСЯ И ЗАПИСЫВАЕТСЯ СУММОЙ (версия 2). Метки лестницы
 * ссылаются на ПОЛИГОНЫ СЕГМЕНТАЦИИ, поэтому лестница без своей сегментации не
 * значит ничего: пара «файл лестницы + другая сегментация» дала бы правдоподобную
 * чепуху, а не отказ. Число треугольников `nt` передаётся отдельно: в `hz_pseglist` его нет —
 * `label` там размером `nt`, а сама длина живёт у сетки. Пишется `nt` и сумма по `sg->label`;
 * потребитель обязан предъявить ту же разметку, иначе чтение отказывает кодом `SEG`. */
int hz_lod_write(const hz_lod *L, const char *path, const hz_pseglist *sg, int32_t nt, int simp);

/* ОГОВОРКА, НАЙДЕННАЯ КОНТРОЛЕМ: сумма по `sg->label` НЕ ловит `hz_edge_simplify`.
 * Упрощение края правит ПОЛИГОНЫ (границы, моменты), а метки треугольников не
 * трогает вовсе — значит сумма у разметки с упрощением и без него одна и та же.
 * Поэтому `simp` есть отдельный признак в заголовке, и сверять его обязан
 * ПОТРЕБИТЕЛЬ: сумма разметки флага не заменяет. Проверено негативным контролем —
 * прогон без `simp` на файле с `simp` сперва прошёл молча.
 *
 * Читает и ПРОВЕРЯЕТ. `L` заполняется только при `HZ_LODIO_OK`; при любом отказе
 * память освобождается, чтобы половина лестницы не досталась потребителю. */
int hz_lod_read(hz_lod *L, const char *path, const hz_pseglist *sg, int32_t nt, int *simp);

/* Проверка иерархии в памяти — та же, что при чтении. Вынесена наружу потому, что
 * ею обязан пользоваться и ПОСТРОИТЕЛЬ: проверять только прочитанное значит
 * проверять чтение, а не иерархию. */
int hz_lod_check(const hz_lod *L);

#endif
