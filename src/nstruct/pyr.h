/* pyr.h — ПИРАМИДА ШАГОВ ПЕРЕНОСА: шаг 1 СНИМКА (PLAN_ELEMENTS.md §833).
 *
 * ЛИНИЯ ПЕРЕНОСА, новая структура — STRUCTURE.md (согласована 09-10). Это
 * ТОПОЛОГИЯ И БЮДЖЕТ без поля: биннинг треугольников в регулярную сетку
 * листа, CSR кусков, разреженные предки ×8, три состояния узла. Свипа здесь
 * нет; поле — нулевой слот `hz_piece.e`.
 *
 * ДВА РАЗНЫХ СЧЁТЧИКА ЗАНЯТОСТИ (А1457 — не сливать):
 *   владение  — по ЦЕНТРОИДУ, ровно одна клетка на треугольник; это куски
 *               (носители поля, BC-события);
 *   занятость — КОНСЕРВАТИВНАЯ по bbox: лист помечается всеми
 *               пересекающими его bbox-ами; это запрос марша «есть ли тут
 *               геометрия», fail-closed. Пометок ≥ кусков.
 *
 * КУСКИ ХРАНЯТСЯ В ПОРЯДКЕ ТРЕУГОЛЬНИКОВ (А1456): CSR строится отдельным
 * counting-sort в собственный массив, поэтому ΔΣ площади по треугольному
 * порядку — битовое тождество, а не совпадение до перестановки слагаемых.
 *
 * Целочисленная арифметика индексов: линейный индекс клетки в int64,
 * `i + nx*(j + ny*k)`; никаких хешей (урок §5.4 — здесь regular grid).
 */
#ifndef HZ_PYR_H
#define HZ_PYR_H

#include <stddef.h>
#include <stdint.h>

/* Состояния узла (STRUCTURE.md §2.1). ПУСТ узлы не хранятся вовсе —
 * разреженное хранение: существуют только непустые узлы и их предки. */
#define HZ_PYR_EMPTY 0u
#define HZ_PYR_FINE 1u
#define HZ_PYR_AGGR 2u

/* Кусок — носитель поля, 16 Б (бюджет STRUCTURE.md §2.3). Геометрии нет:
 * треугольник берётся у меша по `tri`, клип куска выводим и не хранится. */
typedef struct {
  int32_t tri;  /* индекс треугольника меша; pcs[t].tri == t (биекция) */
  int32_t cell; /* ВЛАДЕНИЕ: индекс в `leaf` (отсортированные занятые листья) */
  float e;      /* облучённость; §833 — нулевой слот */
  int32_t mtl;  /* индекс материала */
} hz_piece;     /* 16 */

/* Лист — 12 Б. `pcs_first` — офсет в CSR, `npcs` — кусков (может быть 0:
 * bbox задел клетку, центроидов внутри нет — марш спускается зря, это
 * консервативность, не ошибка). */
typedef struct {
  int32_t pcs_first;
  int32_t npcs;
  uint8_t state;
} hz_pyr_leaf; /* 12 */

/* Внутренний узел уровня — 16 Б (выравнивание int64). `id` — линейный
 * индекс клетки СВОЕГО уровня; у агрегата на месте state будет HZ_PYR_AGGR
 * и ссылка на отклик — в §833 агрегатов нет (HZ_PYR_AGGR не ставится). */
typedef struct {
  int64_t id;
  uint8_t state;
} hz_pyr_node; /* 16 */

typedef struct {
  /* сетка листа */
  double lo[3]; /* габарит сцены, м */
  double cell;  /* размер клетки листа, м */
  int32_t nx, ny, nz;
  int64_t ncells;

  /* куски — В ПОРЯДКЕ ТРЕУГОЛЬНИКОВ */
  hz_piece *pcs;
  int32_t nt;

  /* CSR по владению (центроид): группы по `leaf` в порядке возрастания id */
  int32_t *csr;

  /* занятые (bbox-ом) листья, отсортированы по линейному индексу */
  int64_t *leaf_id;
  hz_pyr_leaf *leaf; /* параллельно leaf_id */
  int32_t nleaf;

  /* предки по уровням: уровень 1 — родители листов, и т.д.; на каждом
   * уровне отсортированные уникальные id непустых клеток */
  hz_pyr_node **lev; /* [nlev] */
  int32_t *nlev_nodes;
  int32_t nlev; /* уровней над листом; 0, если лист один на всю сцену */

  int32_t *perm; /* §839: перестановка Morton (слот → исходный кусок); NULL до Morton */

  /* счётчики отчёта */
  int64_t nmarks;    /* bbox-пометок (сумма по треугольникам пересечённых клеток) */
  int64_t nmarkleaf; /* листьев с ≥1 bbox-пометкой (= nleaf) */
  int64_t ncentleaf; /* листьев с ≥1 центроидом (npcs > 0) */
} hz_pyr;

/* Линейный индекс клетки по точке, с ЗАЖИМОМ в сетку. Отдельная чистая
 * функция — под CBMC (индексная арифметика на недоверенных координатах). */
int64_t hz_pyr_leaf_index(const double lo[3], double cell, int32_t nx, int32_t ny, int32_t nz,
                          const double p[3]);

/* НК-скремблинг: соседняя клетка по линейному индексу с заворотом (А1454 —
 * без заворота это выход за сетку). Отдельная чистая функция — под CBMC. */
int64_t hz_pyr_wrap(int64_t c, int64_t n);

/* §839: переукладка кусков по Morton-коду клетки владения. Куски вдоль
 * любой линии луча становятся приближённо смежными в памяти. После вызова
 * НЕДЕЙСТВИТЕЛЕН инвариант pcs[t].tri == t (А1490): исходный треугольник
 * куска p есть pcs[p].tri — по нему переставляются параллельные массивы
 * потребителя (area/nrm/kd). CSR пересобирается, leaf-структуры не
 * трогаются. Возврат 0/не-0. */
int hz_pyr_morton(hz_pyr *py);

/* §839: переставить массив потребителя (nt элементов по elem байт) той же
 * перестановкой, что Morton применил к pcs — циклами на месте, без
 * временных массивов. Требует вызова ПОСЛЕ hz_pyr_morton. */
int hz_pyr_permute(hz_pyr *py, void *base, size_t elem);

/* Построение. tri_min/tri_max/centroid — [3*nt], метры; mtl — [nt].
 * cell — размер клетки листа, м (> 0). Возврат 0/не-0 (память, аргументы). */
int hz_pyr_build(hz_pyr *py, int32_t nt, const double *tri_min, const double *tri_max,
                 const double *centroid, const int32_t *mtl, const double lo[3], const double hi[3],
                 double cell);

/* НК: скрестить куски с шагом stride (или только кусок 0 при stride == 1).
 * Возвращает число скрещённых. */
int32_t hz_pyr_screw(hz_pyr *py, int32_t stride);

/* Детекторы чистого прогона — все три обязаны дать 0:
 * (а) кусок лежит не в клетке своего центроида (пересчёт + CSR-встречная
 *     проверка «leaf.csr ссылается на куски, чей cell — эта клетка»);
 * (б) bbox-занятость: второй независимый проход по bbox-ам находит клетки,
 *     которых нет в `leaf_id`;
 * (в) кусок в объявленно пустой клетке (id не найден в `leaf_id`). */
typedef struct {
  int64_t d_cell;  /* (а) */
  int64_t d_csr;   /* (а) вторая половина: CSR-встречно */
  int64_t d_bbox;  /* (б) */
  int64_t d_empty; /* (в) */
} hz_pyr_verdict;

void hz_pyr_verify(const hz_pyr *py, int32_t nt, const double *tri_min, const double *tri_max,
                   const double *centroid, hz_pyr_verdict *vd);

/* МАРШ (§834): обход направления omega по трём состояниям. Дети упорядо-
 * чены проекцией центра на omega; АГРЕГАТ — стоп и одно событие; ПУСТ
 * (отсутствует) — прыжок. invert_x — НК: ось x в порядке детей перевёр-
 * нута. visit_bits — [nleaf+63]/64 бит посещений, может быть NULL. */
typedef struct {
  int64_t leaves;     /* посещено листьев */
  int64_t nodes;      /* вся цепь: внутренние + листья */
  int64_t aggr;       /* событий АГРЕГАТ */
  int64_t inversions; /* нарушений неубывания проекции центра по ходу листьев */
} hz_pyr_march_stat;

void hz_pyr_march(const hz_pyr *py, const double omega[3], int invert_x, hz_pyr_march_stat *st,
                  uint64_t *visit_bits, int32_t *visit_index /* [nleaf], NULL можно */);

/* НК-инструмент §834: every == 1 — АГРЕГАТ только корень; otherwise каждый
 * every-й внутренний узел (сквозная нумерация по уровням). hz_pyr_unmark
 * возвращает все узлы в ДРОБЛЁН (§833 агрегатов сама не ставит). */
void hz_pyr_mark_aggr(hz_pyr *py, int32_t every);
void hz_pyr_unmark_aggr(hz_pyr *py);

/* §849: позиция листа по линейному id клетки (двоичный поиск); -1 — пусто. */
int32_t hz_pyr_leaf_pos(const hz_pyr *py, int64_t id);

void hz_pyr_free(hz_pyr *py);

#endif
