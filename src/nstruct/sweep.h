/* sweep.h — СВИП №1 НА НОВЫХ МАССИВАХ (PLAN_ELEMENTS.md §835).
 *
 * Источниковые итерации на массивах §833; порядок листов — марш §834.
 * Модель переноса шага: ПОСЛЕДОВАТЕЛЬНЫЙ СКАЛЯРНЫЙ ЛУЧ на направление —
 * L несётся вдоль цепи листьев, тонкий поверхностный слой клетки (её куски)
 * ослабляет луч с оптической толщиной
 *
 *     τ(ω) = Σ_p area_p·|ω·n_p| / A_⊥(ω),   T = exp(−τ),
 *
 * поглощённый поток распределяется на куски ∝ area·|ω·n| и пишется в E,
 * слой переизлучает (Le + ρ·E_prev/π)·(1−T) обратно в луч. На однородных
 * сценах модель точна, в геометрии — дымовой тест машинерии; граневые
 * потоки — следующий шаг (§835, ОТКРЫТЫЕ МЕСТА).
 *
 * КОНВЕНЦИИ ЭНЕРГИИ (А1471): Le излучается В ОБЕ стороны куска; E —
 * двусторонняя суммарная облучённость, накапливается в double, пишется во
 * float (hz_piece.e). Вес осевого направления w = 2π/3 (изотропия 4π/6).
 */
#ifndef HZ_SWEEP_H
#define HZ_SWEEP_H

#include "pyr.h"

typedef struct {
  double le;  /* эмиссия куска в одну сторону, обе стороны светят */
  double rho; /* albedo; < 0 — брать kd материалов (переданы в kd[]) */
  int iters;  /* итераций (тактов) */
  int tau0;   /* НК: слой не поглощает и не излучает (T ≡ 1) */
  int noprop; /* НК: луч не переносится (L обнуляется на каждом листе) */
} hz_sw_opts;

typedef struct {
  double e_avg;    /* E_avg последней итерации (по площади кусков) */
  double factor;   /* ΔE_{k+1}/ΔE_k на последней паре итераций */
  double emitted;  /* излучено за последнюю итерацию */
  double absorbed; /* поглощено кусками за последнюю итерацию */
  double lost;     /* ушло с лучом за границу домена */
  double recycled; /* рециркуляция ρ·E_prev — внутренний член баланса */
} hz_sw_stat;

/* area/nrm/kd — [nt]; nrm — 3*nt, единичные (ориентация не важна: |ω·n|).
 * E пишется в py->pcs[].e. Возврат 0/не-0 (аргументы, память). */
int hz_sw_run(hz_pyr *py, int32_t nt, const double *area, const double *nrm, const double *kd,
              const hz_sw_opts *o, hz_sw_stat *st, double *e_hist /* [iters] или NULL */);

#endif
