/* sweep.h — свип на новых массивах: §835 (скалярный луч), §836 (колонки),
 * §837 (26 направлений + трафик-счётчик).
 *
 * ЭНЕРГЕТИКА ИТЕРАЦИИ (тождество схемы): на направлении луч входит тёмным,
 * на каждом слое излучённый поток w·Lsurf·(1−T)·A_⊥ равен поглощённому
 * w·L·(1−T)·A_⊥ плюс прирост луча; остаток за последним листом — потери.
 *
 * §836/§837, режим col: занятые листья направления группируются в КОЛОНКИ/
 * ЛИНИИ (поперечные разности индексов; для диагоналей линия = пара
 * поперечных разностей, слэб = знаковая проекция), внутри линии обход по
 * слэбу; L — скаляр линии. Поперечные линии независимы. Связь направлений
 * — через E_prev (источниковые итерации, Жакоби).
 *
 * КОНВЕНЦИИ (А1471/А1475): Le излучается в обе стороны; E — двусторонняя
 * суммарная облучённость, радианс рассеяния на сторону ρE/2π; накопление
 * в double, запись во float (hz_piece.e). Вес направления w = 4π/N.
 */
#ifndef HZ_SWEEP_H
#define HZ_SWEEP_H

#include <stdint.h>

#include "pyr.h"

typedef struct {
  double le;  /* эмиссия куска в одну сторону, обе стороны светят */
  double rho; /* albedo; < 0 — брать kd материалов (переданы в kd[]) */
  int iters;  /* итераций (тактов) */
  int tau0;   /* НК: слой не поглощает и не излучает (T ≡ 1) */
  int mode;   /* 0 — скалярный луч §835 (6 осей, марш), 1 — линии §836/§837,
               * 2 — ОБЪЁМНЫЙ ФРОНТ §845: L на клетку на направление, порядок —
               * марш §834, тёмный вход только на границе домена, линия как
               * понятие устранена; определён на любой таблице dirs.
               * 3 — МАТЕРИАЛЬНЫЙ ФРОНТ НА ПИРАМИДЕ §852: узел ПУСТ — прыжок
               * по tmax узла, МАТЕРИАЛЬНЫЙ — локальное взаимодействие §846
               * на своём LOD-уровне, ПРОМЕЖУТОЧНЫЙ — спуск (продолжение
               * DDA; А1563: Φ = w·L·csec инвариантен, слияния нет). */
  int ndirs;  /* 6|26 — легаси (целые векторы); N_φ*100+N_μ — продуктовая
               * квадратура §843 (Чебышёв по φ × Гаусс по μ, nd = N_φ·N_μ);
               * режим col. mode 0 определён только для 6/26. */
  int noprop; /* НК: луч не переносится (L обнуляется на каждом листе) */
  /* §845-в: строитель похода mode 2. 0 (умолчание) — марш §834 по пирамиде;
   * 1 — прямая сортировка кусковых листьев по проекции центра на ω (пирамида
   * не обходится вовсе, двоичных поисков нет; порядок эквивалентен маршёвому
   * по построению — та же величина сортируется). Фальсификатор: неподвижная
   * точка не зависит от строителя. */
  int build;
  /* §851: КОМПОНЕНТЫ ПУСТОТЫ. 1 — BFS-разметка пустоты сетки; L несётся
   * по (направление, компонента), вход в новую — физически тёмный вход.
   * 0 (memset-умолчание) — старая однокомпонентная логика для сличения;
   * А1551: она пересвечивает тонкие оболочки в void ×3. Вызыватели
   * (swee3/pgather/pref) ставят 1 по умолчанию, ключ vc=0 — сличение. */
  int vc;
  /* §852: вершины треугольников [9·nt] в порядке ИСХОДНЫХ треугольников
   * (кусок p смотрит треугольник py->pcs[p].tri). Обязателен для
   * mode 2 + vc: лучевой свип делает ТОЧНОЕ пересечение линии с
   * треугольником — непрозрачность тоньше/толще клетки выражается
   * геометрией, а не клеточными коэффициентами (А1557). */
  const double *trivert;
  /* §852: LOD-уровни кусков [nt] (ℓ_p, сдвиг от листа). Обязателен для
   * mode 3; перед вызовом hz_sw_run вызывающий обязан прогнать
   * hz_pyr_set_lp. */
  const uint8_t *lp;
  /* §852/G1(a): 1 — ВСЕГДА точное пересечение (предикат «bbox ⊆ клетка»
   * обходится, клеточный перехват не применяется ни в каком окне);
   * 0 (умолчание) — клеточный перехват T только под предикатом,
   * иначе точное пересечение — fail closed (А1566). */
  int xint;
  /* §852: bbox треугольников [6*nt] (xmin,ymin,zmin,xmax,ymax,zmax) в
   * порядке ИСХОДНЫХ треугольников. Обязателен для mode 3 — предикат
   * А1566 вычисляется по нему. */
  const double *tribox;
  /* §852: верх сцены (меш-габарит); сетка листа шире меша на клетку
   * (hz_pyr_build: +1), и без зажима в меш куски граничных стенок — ровно
   * на плоскостях сетки — выпадают из марша. Обязателен для mode 3. */
  const double *domhi;
  /* А1576-фальсификатор: per-piece эмиссия [nt] (порядок кусков, как area);
   * NULL (умолчание) — глобальный le. Смысл: piece le = lep[p] + le, т.е.
   * при lep[p]=0 поведение побитово прежнее. Нужен сценам «источник —
   * заданная пластина» (Ke материала), где глобальный le освещает всё. */
  const double *lep;
  /* А1576: 1 — точный МНОГОПОПАДНЫЙ проход сегмента (все пересечения по
   * ходу трубки, сортировка по t — и на листе, и на узле); 0 (умолчание) —
   * схема §852 (ближайшее пересечение + клеточный перехват под предикатом).
   * Прибор выбора модели: у walk лестница ℓ_p плоская по построению,
   * у перехвата — дрейф (blocked-beam, §854). */
  int walk;
} hz_sw_opts;

/* §843: направление и вес квадратуры. Σw = 4π по построению. */
typedef struct {
  double om[3]; /* единичное направление */
  double w;     /* вес, ср/сфера */
} hz_sw_dir;

/* §843: таблица направлений по коду ndirs (см. hz_sw_opts.ndirs).
 * Таблицу освобождает вызывающий (free). Возврат 0/не-0. */
int hz_sw_dir_table(int ndirs, hz_sw_dir **tab, int *nd);

typedef struct {
  double e_avg;    /* E_avg последней итерации (по площади кусков) */
  double factor;   /* ΔE_{k+1}/ΔE_k на последней паре итераций */
  double emitted;  /* излучено за последнюю итерацию (внешний вход Le) */
  double absorbed; /* поглощено кусками за последнюю итерацию */
  double lost;     /* ушло с лучом за границу домена */
  double recycled; /* рециркуляция ρ·E_prev — внутренний член баланса */
  int64_t traffic; /* модель §5 (§841): походный лист 32 Б + визит куска
                    * 36 Б (wcn 8 + wn 8 + kd 8 + p 4 + E r/w 8), на направление */
  int64_t nvisit;  /* §843: визитов кусковых листьев с cntot>0 (все направления) */
  int64_t ndep;    /* §843: вкладов Ed с L>0 — доставки света; отношение
                    * ndep/nvisit показывает, какая доля визитов несла свет */
  int64_t nline;   /* §843: линий с визитами */
  int64_t nline1;  /* §843: линий из ОДНОГО визита (тёмный вход и выход —
                    * доставки нет вовсе) */
  int64_t nline2;  /* §843: линий из двух визитов */
  /* §845/А1525: хеш последовательности листьев похода (FNV-1a по li, все
   * направления). Прибор против no-op-патча §844-первого: прогон обязан
   * показать, что порядок mode 2 отличается от mode 1 — иначе G1 ничего
   * не измеряет. */
  /* §845-бис: СУММА инверсий марша по всем направлениям строителя похода
   * (нарушений неубывания проекции центра по ходу листьев). На целочисленных
   * направлениях обязан быть 0; на произвольных — прибор «насколько порядок
   * марша не есть ход луча», фальсификатор свипа mode 2 на ND-лестнице. */
  int64_t ninv;
  uint64_t order_hash;
  /* §852 приборы (mode 3): */
  int64_t g6viol;     /* нарушений G6 (parent_flux = Σchild_flux на спуске) —
                       * 0 обязательно на чистом прогоне */
  int64_t njump;      /* ПУСТ-прыжков по tmax узла (А1569) */
  int64_t nmat;       /* материальных взаимодействий узлов */
  int64_t ndesc;      /* спусков (промежуточных узлов) */
  int64_t ncellbase;  /* базовых клеток трубок ПОЛНЫМ DDA (мера «до») */
  int64_t ncellfront; /* базовых клеток, реально посещённых фронтом («после») */
  int64_t nlpclamp;   /* кусков с ℓ_p выше доступного уровня — обработаны на
                       * листе (А1568: отказ с печатаемым счётчиком) */
  int64_t nstamp;     /* срабатываний штампа (кусок × направление): повторных
                       * депозитов, пресечённых кратностью 1 (А1564) */
  int64_t nlostseg;   /* сегментов, ушедших за границу домена (нечётные сетки,
                       * А1567: в lost, не исчезают) */
} hz_sw_stat;

/* §842: Σ_d w·|ω_d·n| по набору направлений (для точного решения модели
 * фикстуры). ndirs — код таблицы (см. hz_sw_dir_table). Кэширует таблицу:
 * НЕ потокобезопасно, инструмент однопоточный. */
double hz_sw_dirsum(const double n[3], int ndirs);

/* §842: Σ по ВЫХОДНЫМ направлениям (n·ω > 0) w·|ω·n| — освещённая половина
 * направлений куска при тёмном окружении; точное решение модели фикстуры.
 * Тот же кэш таблиц, что у hz_sw_dirsum. */
double hz_sw_exitwsum(const double n[3], int ndirs);

/* area/nrm/kd — [nt]; nrm — 3*nt, единичные (ориентация не важна: |ω·n|).
 * E пишется в py->pcs[].e. Возврат 0/не-0 (аргументы, память). */
int hz_sw_run(hz_pyr *py, int32_t nt, const double *area, const double *nrm, const double *kd,
              const hz_sw_opts *o, hz_sw_stat *st, double *e_hist /* [iters] или NULL */);

#endif
