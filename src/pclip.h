/* pclip.h — ОТСЕЧЕНИЕ ТРЕУГОЛЬНИКА КОРОБКОЙ ЯЧЕЙКИ (§241.2, §244, шаг О70).
 *
 * ЗАЧЕМ. Укладка «влезает целиком» оставляет 71…79 % геометрии у ВНУТРЕННИХ
 * узлов (§193), а дублирование ссылок дало избыточность 1193.36 и сборку 361 с
 * (§95.1). Третий ход — РЕЗАТЬ входной треугольник по коробке ячейки — не
 * пробован ни разу (§217). Инвариант укладки: на каждом уровне каждый кусок
 * ЦЕЛИКОМ лежит в своей ячейке; состояния «не влезло» не существует.
 *
 * КУСКИ НЕ ХРАНЯТСЯ (А472). Словарь `new-structure.md` §0 говорит прямо:
 * «ЭЛЕМЕНТ — выпуклый политоп… Выводится отсечением, НЕ ХРАНИТСЯ». 9 вершин ×
 * 3 double = 216 Б на кусок; у Сан-Мигеля 9.96 млн треугольников, и даже при
 * инфляции 3 это 6.5 ГБ. Поэтому функция ОТДАЁТ многоугольник вызывающему, а
 * тот его тут же и потребляет.
 *
 * ФОРМА КУСКА И ПОЧЕМУ ДЕВЯТЬ (§241.3). Плоскость через куб даёт не более
 * шестиугольника; каждая дополнительная полуплоскость добавляет не более одной
 * вершины (отсечение выпуклого k-угольника полуплоскостью даёт максимум k+1).
 * Сквозная ячейка — ≤ 6, кромочная (внутрь попало ребро входного) — ≤ 6+3 = 9.
 * Отсюда ФИКСИРОВАННЫЙ буфер и `assert`, А НЕ ОБРЕЗАНИЕ: обрезание спрятало бы
 * ошибку отсечения, а она проявилась бы потерянным заслоном, то есть молча
 * неверной тенью.
 *
 * ГЛАВНОЕ СВОЙСТВО — ВЕРШИНА НЕ ЗАВИСИТ ОТ ЯЧЕЙКИ (Г50, А474). Наивный
 * Сазерленд—Ходжман считает новую вершину интерполяцией по ТЕКУЩЕМУ ребру
 * многоугольника, то есть по вершине, полученной на предыдущей плоскости. Тогда
 * у крупного и мелкого соседа один и тот же геометрический стык считается по
 * РАЗНЫМ данным и расходится — ровно класс Г50 (замерено 3.6e-13 на отсечённых
 * телах). Здесь вершина считается ПО ПРОИСХОЖДЕНИЮ, и происхождений ровно два:
 *
 *   РОД 1  ребро треугольника ∩ осевая плоскость — берутся ИСХОДНЫЕ концы
 *          ребра (номер ребра канонический: ребро e соединяет вершины e и
 *          (e+1) mod 3), а не концы текущего звена;
 *   РОД 2  плоскость треугольника ∩ ДВЕ осевые (§241.1) — прямое решение,
 *          оси упорядочены по номеру, чтобы порядок слагаемых не зависел от
 *          порядка отсечения.
 *
 * Обе формулы зависят ТОЛЬКО от треугольника и от координат секущих
 * плоскостей — а те у соседей общие побитово, потому что координата грани
 * октодерева вычисляется РОВНО ОДИН РАЗ (в узле, чьё дробление её порождает) и
 * дальше копируется. Значит совпадение побитовое ПО ПОСТРОЕНИЮ, и это
 * проверяемо: ключ `naive` в `hz_pclip_tri_ex` возвращает наивную схему и
 * обязан дать расхождения — без него ноль расхождений непроверяем.
 *
 * ПОЛУОТКРЫТОЕ СОГЛАШЕНИЕ `[lo, hi)` РАСПРОСТРАНЕНО НА ВЕРШИНЫ (А475): внутри
 * значит `>= lo` и `< hi`. Треугольник, легший в плоскость общей грани,
 * принадлежит РОВНО ОДНОЙ из двух ячеек: у той, для которой это `hi`, все его
 * вершины отсекаются, у той, для которой `lo`, — сохраняются. Без соглашения
 * луч вдоль грани проверил бы его дважды либо НОЛЬ раз, а второе есть
 * потерянный заслон.
 */
#ifndef HZ_PCLIP_H
#define HZ_PCLIP_H

/* Постусловие §241.3. Девять — не запас, а доказанный максимум. */
#define HZ_PCLIP_MAXV 9

/* ПРОИСХОЖДЕНИЕ ВЕРШИНЫ — ключ, по которому сверяются соседи разных уровней.
 * Две вершины ОБЯЗАНЫ совпасть побитово тогда и только тогда, когда у них
 * совпал этот ключ (при одном и том же треугольнике). */
typedef struct {
  unsigned char kind;   /* 0 — вершина треугольника; 1 — ребро ∩ плоскость; 2 — две плоскости */
  unsigned char e;      /* род 0: номер вершины 0..2; род 1: номер ребра 0..2 */
  unsigned char a1, a2; /* оси секущих плоскостей; род 2: a1 < a2 */
  double c1, c2;        /* их координаты */
} hz_pclip_prov;

typedef struct {
  double v[HZ_PCLIP_MAXV][3];
  hz_pclip_prov p[HZ_PCLIP_MAXV];
  int nv;    /* 0 — куска нет вовсе */
  int nfall; /* сколько раз каноническая формула была невозможна (вырождение) */
} hz_pclip_poly;

/* Отсечь треугольник (A,B,C) коробкой [lo, hi). Возврат — число вершин куска
 * (0, если куска нет). Порядок обхода вершин сохраняет ориентацию входа. */
int hz_pclip_tri(const double *A, const double *B, const double *C, const double *lo,
                 const double *hi, hz_pclip_poly *out);
/* То же с выбором схемы: `naive = 0` — в точности `hz_pclip_tri`; `naive = 1` —
 * НАИВНАЯ интерполяция по текущему звену. Второе есть НЕГАТИВНЫЙ КОНТРОЛЬ над
 * счётчиком побитовых расхождений и в рабочем пути не применяется. */
int hz_pclip_tri_ex(const double *A, const double *B, const double *C, const double *lo,
                    const double *hi, hz_pclip_poly *out, int naive);
/* Площадь куска, м². Нужна двум вещам: отбраковке вырожденных (А475) и
 * ИНВАРИАНТУ ПЛОЩАДИ — сумма кусков обязана сойтись с площадью сцены (правило
 * §193: у всякого дробления представления обязан быть сохраняющийся инвариант). */
double hz_pclip_area(const hz_pclip_poly *P);

#endif
