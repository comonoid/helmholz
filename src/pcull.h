/* pcull.h — ПОМЕТКИ НЕВИДИМОСТИ, ОДНОСТОРОННИЕ ПО ПОСТРОЕНИЮ (§278).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МЕХАНИЗМ, А НЕ ПРАВКА ФРОНТА. Приёмка этой линии односторонняя
 * (указание пользователя 08-06): среди помеченных не должно быть НИ ОДНОЙ
 * ячейки, видимой от глаза; пропущенные невидимые — не ошибка. Пометки же
 * ставились ТЕМ ЖЕ фронтом `pfront.c`, а он считает ДОЛЮ ОТКРЫТОГО ДИСКА —
 * величину приближённую с ОБЕИХ сторон. Приближений там три, и ни одно не
 * является границей:
 *   `tri_cover`  — подгоняет ЛИНЕЙНОЙ функцией ПОКАЗАТЕЛЬ (0 или 1) проекции
 *                  треугольника. Треугольник, закрывший 90 % грани, читается как
 *                  «всюду 0.9 закрыто», а не «здесь 1, там 0»;
 *   `face_block` — произведение двух линейных функций квадратично, и оно
 *                  ПРОЕЦИРУЕТСЯ обратно на линейный базис (L²), а не
 *                  ограничивается;
 *   `face_join`  — четыре детские грани СКЛАДЫВАЮТСЯ моментами, то есть светлая
 *                  четверть усредняется с тремя тёмными.
 * Отсюда прямое следствие, и оно наблюдалось: щель, сквозь которую свет
 * проходит целиком, размазывается в равномерное затемнение, затемнения
 * перемножаются вдоль пути (`0.1³ < 1/512`), и ячейка объявляется тёмной, будучи
 * видимой насквозь. Порог `1/512` тут ни при чём — размазанная величина просто
 * не та, о которой спрашивает приёмка.
 *
 * ЧТО ИЗМЕРЕНО ПЕРЕД ТЕМ, КАК ЭТО ПИСАТЬ (08-06, зал, `psun mark=2 ref=600`).
 * Прежняя гипотеза винила ПАРАЛЛЕЛЬНОЕ приближение камеры в проходе пометок.
 * Проверка распределением нарушений по углу от оси взгляда её ОТВЕРГЛА:
 *     доля полуполя   1/4     2/4     3/4     4/4
 *     нарушений       11/90   46/215  20/104  5/44
 *     то есть         12.2 %  21.4 %  19.2 %  11.4 %
 * У самой оси, где параллельное приближение точно, нарушений столько же, сколько
 * у края. Скан по полю зрения (§277) вводил в заблуждение: сужение кадра меняет
 * НАБОР проверяемых ячеек, а не только величину ошибки.
 *
 * ЧЕМ ЗАМЕНЕНО. Буфером дальности от глаза с ДВУСТОРОННЕЙ ОСТОРОЖНОСТЬЮ —
 * иерархический z-буфер (Greene—Kass—Miller, 1993) с обеими границами,
 * повёрнутыми в сторону «пометок меньше»:
 *   ЗАСЛОНИТЕЛЬ пишется только в пиксель, накрытый треугольником ЦЕЛИКОМ, и
 *     записывается ДАЛЬНЯЯ его точка в этом пикселе. Тогда утверждение «всё, что
 *     дальше записанного, в этом пикселе заслонено» верно для КАЖДОГО луча
 *     пикселя, а не для его середины;
 *   ЯЧЕЙКА проверяется БЛИЖНЕЙ своей точкой против МАКСИМУМА буфера по ВСЕМ
 *     пикселям, которых касается её проекция. Пиксель без заслонителя несёт
 *     `+∞`, поэтому ячейка, задевшая хоть один открытый пиксель, не помечается.
 * Обе величины — дальность ВДОЛЬ ОСИ ВЗГЛЯДА, а вдоль одного луча она растёт
 * монотонно, поэтому сравнение законно.
 *
 * ПОЧЕМУ ЭТО ТОЧНО В ПЕРСПЕКТИВЕ. Буфер строится ОТ ГЛАЗА КАК ОТ ТОЧКИ:
 * параллельного приближения здесь нет вовсе, и лечение §277 («направление на
 * каждый узел своё») входит сюда даром, а не отдельной правкой.
 *
 * ГДЕ ЭТОТ МЕХАНИЗМ ТЕРЯЕТ, И ЭТО ДОПУСТИМО ПО УСЛОВИЮ ЗАДАЧИ:
 *   - ячейка, закрытая МНОЖЕСТВОМ мелких треугольников, ни один из которых не
 *     накрывает пикселя целиком (листва, решётка), не помечается;
 *   - ячейка, свисающая за край кадра, не помечается: её проекция выходит за
 *     буфер, а вне буфера мы ничего не знаем;
 *   - ячейка ближе первого пикселя разрешения не помечается.
 * Всё это — недобор пометок, то есть потеря скорости, а не правильности.
 */
#ifndef HZ_PCULL_H
#define HZ_PCULL_H

#include "ptree.h"
#include "scene_obj.h"
#include <stdint.h>

/* СТОРОНА БУФЕРА РАВНА СТОРОНЕ КАДРА, и это не выбор, а тождество: пометка
 * служит кадру, поэтому «заслонитель, накрывающий пиксель» обязан значить тот же
 * пиксель, что и в картинке. Число берётся из `scene_cfg.h` вызывающим. */

/* ЗАПАС НА ОКРУГЛЕНИЕ, В ЕДИНИЦАХ ПОСЛЕДНЕГО РАЗРЯДА. Все три места, где
 * односторонность может быть съедена арифметикой, сдвигаются на этот запас в
 * сторону «пометок меньше»: накрытие пикселя требуется С ЗАПАСОМ, записанная
 * дальность округляется ВВЕРХ, ближняя дальность ячейки — ВНИЗ. Шестнадцать —
 * не измеренная величина, а заведомый перебор: ошибка вычисления рёберной
 * функции есть единицы ULP, и запас на порядок выше её. */
#define HZ_PCULL_ULP 16.0

typedef struct {
  double eye[3], rt[3], up[3], fw[3]; /* рама камеры, ортонормированная */
  double tanh_;                       /* тангенс половины поля */
  int side;                           /* сторона буфера в пикселях */
  int nlev;                           /* уровней пирамиды максимумов */
  float **lvl;                        /* пирамида: lvl[0] — сам буфер */
  int *lw;                            /* сторона уровня */
  double zmin;                        /* ближе этого треугольники не пишутся */
  /* НЕГАТИВНЫЕ КОНТРОЛИ С ПРЕДСКАЗАННЫМ ПРОВАЛОМ (§4). Каждый ломает РОВНО ОДНО
   * из двух правил осторожности, чтобы было видно, которое из них работает:
   *   `1` — обычный z-буфер: пиксель пишется по СЕРЕДИНЕ. Ломает правило
   *         «накрыт целиком»; ошибка при этом подпиксельная, поэтому при мелком
   *         пикселе она может и не выйти наружу — контроль осмыслен лишь вместе
   *         со СКАНОМ ПО РАЗРЕШЕНИЮ (замерено: при `1024²` не ломается, при
   *         грубом буфере обязан);
   *   `2` — накрытие проверяется полностью, но пишется БЛИЖНЯЯ точка пикселя
   *         вместо дальней. Ломает второе правило и бьёт по наклонным
   *         поверхностям (пол, потолок), где разброс дальности внутри пикселя
   *         велик. Это ОСТРЫЙ контроль: он не зависит от разрешения. */
  int loose;
  /* --- замеры, часть выхода --- */
  int64_t ntri_near, ntri_off, npix;
  int64_t ntest, nhidden, noff, nnear;
} hz_pcull;

/* Завести буфер. `at` — точка взгляда, `fovdeg` — полное поле, `side` — сторона.
 * `diag` — диагональ сцены: от неё берётся ближняя плоскость (см. `zmin`). */
int hz_pcull_init(hz_pcull *C, const double eye[3], const double at[3], const double up[3],
                  double fovdeg, int side, double diag);
void hz_pcull_free(hz_pcull *C);

/* Нарисовать заслонители. Зовётся один раз по всей сетке. */
void hz_pcull_draw(hz_pcull *C, const hz_objmesh *m);

/* Построить пирамиду МАКСИМУМОВ. Обязательно после `draw` и до `hidden`. */
void hz_pcull_pyramid(hz_pcull *C);

/* Заслонена ли коробка ЦЕЛИКОМ. `1` — да, и это утверждение строгое. */
int hz_pcull_hidden(hz_pcull *C, const double lo[3], const double hi[3]);

/* Разложить пометки по дереву: спуск до `maxlev`, помечается САМЫЙ КРУПНЫЙ
 * заслонённый узел (ниже пометка наследуется обходом). `mark` длиной `T->nnd`,
 * заполнен `255` (пометки нет); заслонённым пишется `1`. */
void hz_pcull_marks(hz_pcull *C, const hz_ptree *T, int maxlev, unsigned char *mark);

#endif
