/* pcut.h — ТЕНЕВЫЕ РАЗРЕЗЫ: discontinuity meshing по правилам §1.8.
 *
 * PLAN_ELEMENTS.md, Ш6. Клинья от СИЛУЭТНЫХ РЁБЕР × КОМПАКТНЫЕ ИСТОЧНИКИ.
 * Видимость для ПОСТРОЕНИЯ не нужна — клин задаётся геометрией ребра и
 * источника, а не тем, что откуда видно.
 *
 * ЗАЧЕМ — И ГДЕ Я ОШИБСЯ, СТАВЯ ЭТОТ ВОПРОС. Ш5 намерил, что хвост ошибки
 * `p99 ≈ 3…4%` не убирается ни ростом `ND` (128 → 1024), ни шагом растра, и я
 * приписал его резкости поля на границе тени. Замер Ш6 это ОПРОВЕРГ: хвост
 * живёт в ПОЛНОСТЬЮ ОСВЕЩЁННЫХ точках (`p99 = 1.33`), а не в полутени
 * (`p99 = 0.53`), то есть главная ошибка — линейная подгонка ПЛАВНОГО `1/r²` по
 * крупному плоскому полигону, а вовсе не разрыв.
 *
 * Разрезы при этом ВСЁ РАВНО окупаются, и это тоже замер: при равном числе
 * полигонов они дают `24.6%` площади хуже 10% против `32.3%` без них. Но
 * работают они не тем, чем предполагалось: они ДРОБЯТ крупные полигоны там, где
 * поле меняется быстро. Контроль это подтверждает — дробление РЕГУЛЯРНОЙ сеткой,
 * не знающей ни про свет, ни про силуэты, даёт `25.7%`, то есть почти столько
 * же. Разрезы выигрывают у сетки только по крайнему хвосту (`p99 = 1.19` против
 * `1.43`), и вот ЭТО — уже вклад собственно теневой геометрии.
 *
 * ПРАВИЛА §1.8, ВСЕ ЧЕТЫРЕ, И НИ ОДНО НЕ ПРИДУМАНО ЗДЕСЬ:
 *   A. РЕЗКОСТЬ. Полутень от источника углового размера `α` на расстоянии `d`
 *      от загораживающего ребра имеет ширину `w = α·d`. Разрез вводится, только
 *      если `w < ε`; иначе переход разрешается самим полигоном, и резать нечего.
 *      Отсюда же ДЛИНА клина: он обрывается там, где `α·d` дорастает до `ε`.
 *   B. КОНТРАСТ. Скачок есть прямой вклад источника, а прямой свет считается
 *      аналитически (`pdirect.h`) ⇒ величина известна ДО построения:
 *      кандидат берётся, только если `ΔΦ/Φ > tol`.
 *   C. ПРОТЯЖЁННОСТЬ. Клин ОГРАНИЧЕН: радиус значимости задаёт то же B через
 *      спад `1/r²`. Берётся МЕНЬШИЙ из двух радиусов (A и B).
 *   D. РЕКУРСИИ НЕТ. Вторичный свет приходит от ПРОТЯЖЁННЫХ поверхностей
 *      (`α ≈ 1` ⇒ `w ≈ d`), и правило A их отсекает всегда. Таблица
 *      одноуровневая по построению, а не по потолку.
 *
 * БЮДЖЕТ С ПРИОРИТЕТОМ ПО КОНТРАСТУ (Т2, §1.9). Кандидаты сортируются по
 * `ΔΦ/Φ` и берутся по убыванию, пока бюджет не исчерпан. Качество деградирует
 * предсказуемо: тень переживает всё остальное.
 *
 * КАК РЕЖЕТСЯ. Разрез НЕ трогает плоскость полигона — он делит его НА ДВА
 * КУСКА ТОЙ ЖЕ ПЛОСКОСТИ. Поэтому реализовано это не отсечением края (кода
 * которого пришлось бы писать много и с дырами), а ИЗМЕЛЬЧЕНИЕМ ТРЕУГОЛЬНОГО
 * СУПА: треугольник делится плоскостью на 1…3 части, метка участка получает
 * добавочный бит стороны, и край пересобирается ТЕМ ЖЕ `hz_poly_build`, который
 * уже проверен приёмкой Ш2 и теоремой Грина. Нового кода извлечения края нет.
 */
#ifndef HZ_PCUT_H
#define HZ_PCUT_H

#include "poly_seg.h"
#include "polygon.h"
#include "scene_obj.h"

typedef struct {
  double n[3], off; /* плоскость клина: проходит через ребро и центр источника */
  double c[3], r;   /* область действия: шар вокруг середины ребра */
  double prio;      /* ΔΦ/Φ — приоритет по контрасту (Т2) */
  int32_t src;      /* источник, породивший клин */
} hz_wedge;

typedef struct {
  hz_wedge *w;
  int32_t n, cap;
  /* доклад */
  int64_t nsil;      /* силуэтных рёбер найдено */
  int64_t nreject_a; /* отсеяно правилом A (полутень шире ε) */
  int64_t nreject_b; /* отсеяно правилом B (контраст мал) */
} hz_wedges;

typedef struct {
  double eps;     /* ε — разрешение, м. Правило A. */
  double tol;     /* порог контраста. Правило B. */
  int32_t budget; /* сколько клиньев взять (Т2). <0 — все прошедшие A и B */
} hz_cutcfg;

/* Строит клинья от силуэтных рёбер × источники. `src`/`nsrc` — полигоны-
 * источники (их `Le` берётся из `Le[]`). Сортирует по приоритету. */
int hz_wedges_build(hz_wedges *ws, const hz_objmesh *m, const hz_polyset *ps, const int32_t *src,
                    int nsrc, const double *Le, const hz_cutcfg *cfg);
void hz_wedges_free(hz_wedges *ws);

/* Применяет первые `ncut` клиньев: измельчает суп треугольников и заводит
 * НОВУЮ разметку. `mo`/`so` заполняются и принадлежат вызывающему.
 * Плоскости участков не меняются — разрез делит участок, а не гнёт его. */
int hz_cut_apply(hz_objmesh *mo, hz_pseglist *so, const hz_objmesh *mi, const hz_pseglist *si,
                 const hz_wedges *ws, int32_t ncut);

#endif
