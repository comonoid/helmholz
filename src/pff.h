/* pff.h — ТОЧНЫЙ ФОРМ-ФАКТОР ТОЧКА–МНОГОУГОЛЬНИК, контурный интеграл Ламберта.
 *
 * ЛИНИЯ ПЕРЕНОСА, PLAN_ELEMENTS.md. Вынесено из `src/plink.c` (шаг О55) по
 * тому же доводу, по которому оттуда же вынесен луч: О55 требует считать порог
 * `η` от ПРЯМОЙ облучённости замкнутой формой, а не приближением «источник как
 * точка» (§172, пункт 5; А391), и стенду фронта эта формула нужна целиком.
 * Копировать её нельзя: знак обхода в ней установлен САМОПРОВЕРКОЙ (см. ниже), и
 * вторая копия — это второе место, где знак может разъехаться незаметно.
 *
 *     F = (1/2π) · Σ_рёбра  β_k · (n_i · e_k),
 *     β_k = ∠(R_k, R_{k+1}),   e_k = (R_k × R_{k+1}) / |R_k × R_{k+1}|,
 *
 * где `R_k` — вершины края излучателя ОТНОСИТЕЛЬНО приёмной точки. Замкнутая
 * форма, точная при любой близости; квадратуры нет.
 *
 * ОТСЕЧЕНИЕ ПОЛУПЛОСКОСТЬЮ ПРИЁМНИКА ОБЯЗАТЕЛЬНО: формула точна лишь для части
 * излучателя НАД касательной плоскостью, а пересекающий её полигон даёт вклад
 * частично отрицательный. Рёбра, легшие в саму плоскость, вклад дают и он
 * законен — это дуга горизонта, входящая в проектированный телесный угол
 * (А209).
 *
 * ПРИЁМНИК ОСТАЁТСЯ ТОЧКОЙ. Ошибка приёмной стороны этим не лечится.
 *
 * ЗНАК. Внешняя петля полигона обходится против часовой стрелки В ЕГО
 * СОБСТВЕННОЙ раме (`polygon.h`, `eu × ev = n`), а приёмник смотрит на лицевую
 * сторону, то есть видит ту же петлю ПО часовой. Классическая запись формулы
 * ждёт обход против часовой ИЗ ПРИЁМНИКА, отсюда минус. Установлено
 * самопроверкой: без него оба аналитических случая выходили с точностью до
 * 15-й цифры, но ОТРИЦАТЕЛЬНЫМИ — то есть ошибка знака сценой не ловится, и
 * потому самопроверка обязательна перед всяким счётом.
 */
#ifndef HZ_PFF_H
#define HZ_PFF_H

/* Вклад ОДНОЙ петли, вершины `R` уже ОТНОСИТЕЛЬНО приёмника (3·n чисел),
 * `nv` — нормаль приёмника. Отсечения НЕ делает: звать после `hz_pff_clip_half`
 * либо там, где излучатель заведомо над касательной плоскостью. */
double hz_pff_loop(const double *R, int n, const double nv[3]);

/* Отсечение петли полуплоскостью `nv·R > 0` по Сазерленду–Ходжмену. Возвращает
 * число вершин на выходе; `out` обязан вмещать `n + 1` вершин (3·(n+1) чисел). */
int hz_pff_clip_half(const double *R, int n, const double nv[3], double *out);

/* Точка `x` с нормалью `nrec` против МИРОВОГО многоугольника `P` (3·n чисел):
 * перенос в раму приёмника, отсечение, контурная сумма. Рабочий буфер `w`
 * обязан вмещать 3·(n+1) чисел. Отрицательный итог («отвёрнут») не срезается —
 * это решает потребитель. */
double hz_pff_point_poly(const double x[3], const double nrec[3], const double *P, int n,
                         double *w);

/* САМОПРОВЕРКА НА АНАЛИТИКЕ (А205). Проверять контурный интеграл СЦЕНОЙ нельзя:
 * ошибка в `2π`, потерянный косинус или перевёрнутый обход дали бы такое же
 * правдоподобное число, и отличить их было бы нечем. Два случая с известным
 * ответом — квадрат полуширины `a` на оси приёмника, на высоте `h`:
 *
 *     F = (4/π) · X/√(1+X²) · atan(X/√(1+X²)),   X = a/h
 *
 * (четыре угловых прямоугольника Хауэлла B-1). При `X → ∞` это ровно `1` —
 * излучатель закрывает всю полусферу. Возвращает ХУДШУЮ невязку; замерено
 * `1.110e-16`, и это то самое число, на которое ссылается §151. */
double hz_pff_selftest(double *f_big, double *f_unit, double *ref_unit);

#endif
