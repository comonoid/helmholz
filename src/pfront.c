/* pfront.c — обход фронта с переносом состояния. Разбор — в `pfront.h`. */
#include "pfront.h"
#include "pclip.h"
#include <math.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

/* УСТРОЙСТВО РЕКУРСИИ (§241.7: один визит на узел, порядок октантов).
 *
 * У ячейки три ВХОДЯЩИЕ грани — по одной на ось, с той стороны, откуда идёт свет
 * (`lo`, если `d[c] > 0`, иначе `hi`), и три ИСХОДЯЩИЕ. При дроблении ребёнок
 * берёт входящую грань либо У РОДИТЕЛЯ (тогда это ЧЕТВЕРТЬ родительской грани, и
 * состояние получается вычислением полинома — Р3), либо У СОСЕДА-РЕБЁНКА,
 * посчитанного раньше. Порядок «раньше» задаётся числом осей, по которым ребёнок
 * стоит с ДАЛЬНЕЙ стороны: сперва ближний угол, потом три соседних, потом три,
 * потом дальний. Это и есть октантный порядок, и он же даёт зависимости без
 * циклов.
 *
 * Исходящие грани родителя собираются из детских: на каждую приходится четыре
 * детские грани, и они складываются СЛОЖЕНИЕМ МОМЕНТОВ (Р2, точная L²-проекция).
 */

/* Индексы осей грани: для оси `a` местные оси грани — две другие, по возрастанию. */
static void face_axes(int a, int *p, int *q) {
  *p = (a + 1) % 3;
  *q = (a + 2) % 3;
}

/* Р3: ЧЕТВЕРТЬ грани. `su`, `sv` — знаки смещения четверти (−1 или +1). Центр
 * четверти лежит в `±1/2` местных координат, полуразмер вдвое меньше — отсюда
 * наклоны делятся пополам, а центр смещается на половину наклона. */
static hz_pfront_face face_quarter(const hz_pfront_face *F, double su, double sv) {
  /* Р3 НА СЕТКЕ: четверть грани есть блок `N/2 × N/2`, размноженный обратно до
   * `N × N`. Это точное «вычисление полинома» для кусочно-постоянного поля: у
   * ребёнка клетки вдвое мельче родительских, и каждая родительская клетка
   * покрывает ровно четыре детских. */
  hz_pfront_face R;
  const int H = HZ_PFRONT_COVN / 2;
  int i0 = (su > 0.0) ? H : 0, j0 = (sv > 0.0) ? H : 0;
  for (int j = 0; j < HZ_PFRONT_COVN; j++)
    for (int i = 0; i < HZ_PFRONT_COVN; i++)
      R.g[j * HZ_PFRONT_COVN + i] = F->g[(j0 + j / 2) * HZ_PFRONT_COVN + (i0 + i / 2)];
  return R;
}

/* Р2: сборка грани из четырёх четвертей — сложение моментов. Точная L²-проекция
 * линейной функции с четырёх подквадратов на один: среднее даёт `c0`, а наклон
 * складывается из наклонов четвертей и из разности их средних. */
static hz_pfront_face face_join(const hz_pfront_face *Q) {
  /* Р2 НА СЕТКЕ: грань родителя вдвое крупнее детской, поэтому каждая её клетка
   * есть среднее блока `2×2` соответствующего ребёнка. Точная L²-проекция для
   * кусочно-постоянного поля — и, в отличие от сложения моментов, она не может
   * дать отрицательного значения (§307). */
  hz_pfront_face R;
  const int H = HZ_PFRONT_COVN / 2;
  for (int j = 0; j < HZ_PFRONT_COVN; j++)
    for (int i = 0; i < HZ_PFRONT_COVN; i++) {
      int qi = (i >= H) ? 1 : 0, qj = (j >= H) ? 1 : 0;
      const hz_pfront_face *C = &Q[qj * 2 + qi];
      int bi = 2 * (i - qi * H), bj = 2 * (j - qj * H);
      double v = 0.0;
      for (int dj = 0; dj < 2; dj++)
        for (int di = 0; di < 2; di++)
          v += (double)C->g[(bj + dj) * HZ_PFRONT_COVN + (bi + di)];
      R.g[j * HZ_PFRONT_COVN + i] = (float)(0.25 * v);
    }
  return R;
}

/* ОПЕРАТОР ПУСТОГО УЗЛА (§241.7). Доля открытого диска постоянна ВДОЛЬ ЛУЧА,
 * поэтому исходящая грань несёт то же, что входящая, — НО В СВОИХ МЕСТНЫХ
 * КООРДИНАТАХ, а они сдвинуты: луч, вошедший в `(u, v)`, выходит в
 * `(u + Δu, v + Δv)`.
 *
 * ЗДЕСЬ ДОЛГО СТОЯЛО ТОЖДЕСТВО, а комментарий утверждал, что «пересчёт этот
 * аффинный». Утверждение было верным, код его не делал, и цена измерена (§308):
 * при КОСОМ солнце доля вдоль одного луча в ПУСТЫХ ячейках скакала
 * `0.109 → 0.012 → 0.014 → 0.033 → 0.058`, тогда как при солнце ВДОЛЬ ОСИ, где
 * сноса нет, она держалась `0.257 → 0.239 → 0.262 → 0.262`. В вакууме состояние
 * обязано сохраняться — не сохранялось.
 *
 * ЧЕГО СНОС ВСЁ ЕЩЁ НЕ ДЕЛАЕТ: при `|Δ| > 2` луч покидает ячейку через БОКОВУЮ
 * грань, и это перераспределение между гранями здесь не выражено — снос
 * обрезается. То есть починка неполная, и граница названа. */
int hz_pfront_shift = 2; /* оставлен для совместимости ключа; перенос всегда полный */

/* Прежний точный вариант через `hz_pclip_tri` убран: он строил вершину ПО
 * ПРОИСХОЖДЕНИЮ ради побитового совпадения у соседей (Г50), а тени это не нужно
 * ни на что, и стоило 56 нс на кандидата. См. `tri_cover` ниже. */

/* ПЕРЕКРЫТИЕ БЕЗ ТОЧНОГО ОТСЕКАТЕЛЯ (указание пользователя 08-05: «это простая
 * операция, она не должна занимать много времени, и её можно делать
 * приблизительно»). Замер, который к этому привёл: вывод кусков занимал 86 %
 * шага, 56 нс на кандидата — потому что звался `hz_pclip_tri`, строящий вершину
 * ПО ПРОИСХОЖДЕНИЮ ради побитового совпадения у соседей разных уровней (Г50).
 * Тени эта точность не нужна ни на что: доля перекрытия есть площадь, а не
 * стык. Здесь треугольник СНОСИТСЯ вдоль направления на грань и отсекается
 * КВАДРАТОМ в двумерии — четыре полуплоскости, не более семи вершин, ни одного
 * трёхмерного отсечения и ни одной записи о происхождении. */
/* ОСЛАБИТЬ ГРАНЬ ПЕРЕКРЫТИЕМ — ПОЭЛЕМЕНТНО (О76). Раньше здесь перемножались две
 * линейные функции и результат проецировался обратно на линейный базис, отчего
 * щель размазывалась в равномерное затемнение по всей грани; затемнения потом
 * перемножались вдоль пути, и ячейка, видимая насквозь, объявлялась тёмной
 * (§278 — именно это сломало односторонность пометок). На сетке умножение
 * поклеточное и точное: где клетка закрыта — там ноль, где открыта — там
 * исходное значение. */
static hz_pfront_face face_block(const hz_pfront_face *F, uint64_t mask) {
  hz_pfront_face R;
  for (int k = 0; k < HZ_PFRONT_NCELL; k++)
    R.g[k] = (mask & ((uint64_t)1 << k)) ? 0.0f : F->g[k];
  return R;
}

/* ОБЪЕДИНЕНИЕ ПРОЕКЦИЙ — БИТОВОЙ МАСКОЙ 8x8 (§292).
 *
 * ЗАЧЕМ. Замер §290 показал, что ОБЕ прежние оценки перекрытия суть ГРАНИЦЫ и
 * обе неверны с разных сторон: максимум по кускам занижает тень в глубине
 * (кусков много, берётся один), сумма завышает её на краю (проекции кусков
 * пересекаются именно там). Нужна ПЛОЩАДЬ ОБЪЕДИНЕНИЯ, а её нельзя получить
 * выбором между двумя приближениями.
 *
 * ПОЧЕМУ МАСКА, А НЕ ГЕОМЕТРИЧЕСКОЕ ОБЪЕДИНЕНИЕ МНОГОУГОЛЬНИКОВ. Точное
 * объединение N многоугольников стоит `O(N log N)` со списком пересечений и
 * живёт в самой горячей точке обхода. Сетка 8x8 на грань даёт объединение
 * ОДНОЙ БИТОВОЙ ОПЕРАЦИЕЙ: у каждого куска своя маска в `uint64_t`, объединение
 * — `|`, площадь — `popcount`. Ошибка при этом есть КВАНТОВАНИЕ (шаг 1/8
 * грани), а не смещение в одну сторону, и она измеряется тем же эталоном.
 *
 * МОМЕНТЫ БЕРУТСЯ ИЗ ТОЙ ЖЕ МАСКИ, а не считаются отдельно: `c0 = popcount/64`,
 * `cu = (3/64)·Σu_k`, `cv = (3/64)·Σv_k` по установленным битам — это ровно
 * L²-проекция показателя на `{1, u, v}`, та же нормировка, что у `tri_cover`.
 *
 * СЕТКА 8x8, А НЕ ДРУГАЯ: `64` бита есть ровно один регистр, и объединение
 * становится одной инструкцией. Шаг сетки `1/8` грани — та же величина, что
 * `HZ_PFRONT_FRAC_TOL`, умноженная на `64`; мельче даёт `16x16` в четырёх
 * словах, и это следующая ступень скана, а не переделка. */

/* Маска проекции треугольника на грань `a`. Возврат `0`, если проекции нет. */
static uint64_t tri_mask(const double *A, const double *B, const double *C, const double *lo,
                         const double *hi, const double *dir, int a) {
  int p, q;
  face_axes(a, &p, &q);
  if (dir[a] < 1e-300 && dir[a] > -1e-300) return 0;
  double du = hi[p] - lo[p], dv = hi[q] - lo[q];
  if (!(du > 0.0) || !(dv > 0.0)) return 0;
  double fa = (dir[a] > 0.0) ? hi[a] : lo[a];
  const double *V[3] = {A, B, C};
  double x[3], y[3];
  for (int i = 0; i < 3; i++) {
    double t = (fa - V[i][a]) / dir[a];
    /* Координаты сразу в СЕТКЕ: `[0, N]` вместо `[-1, 1]`. */
    x[i] = (double)HZ_PFRONT_COVN * (V[i][p] + t * dir[p] - lo[p]) / du;
    y[i] = (double)HZ_PFRONT_COVN * (V[i][q] + t * dir[q] - lo[q]) / dv;
  }
  double xmin = x[0], xmax = x[0], ymin = y[0], ymax = y[0];
  for (int i = 1; i < 3; i++) {
    if (x[i] < xmin) xmin = x[i];
    if (x[i] > xmax) xmax = x[i];
    if (y[i] < ymin) ymin = y[i];
    if (y[i] > ymax) ymax = y[i];
  }
  if (!(xmax > 0.0) || !(ymax > 0.0)) return 0;
  if (!(xmin < (double)HZ_PFRONT_COVN) || !(ymin < (double)HZ_PFRONT_COVN)) return 0;
  int i0 = (int)xmin, i1 = (int)xmax, j0 = (int)ymin, j1 = (int)ymax;
  if (i0 < 0) i0 = 0;
  if (j0 < 0) j0 = 0;
  if (i1 > HZ_PFRONT_COVN - 1) i1 = HZ_PFRONT_COVN - 1;
  if (j1 > HZ_PFRONT_COVN - 1) j1 = HZ_PFRONT_COVN - 1;
  double ar = (x[1] - x[0]) * (y[2] - y[0]) - (y[1] - y[0]) * (x[2] - x[0]);
  if (!(ar > 0.0) && !(ar < 0.0)) return 0;
  double sg = (ar > 0.0) ? 1.0 : -1.0;
  uint64_t mk = 0;
  for (int j = j0; j <= j1; j++)
    for (int i = i0; i <= i1; i++) {
      /* Клетка засчитывается по СЕРЕДИНЕ: односторонности здесь не требуется —
       * это оценка ПЛОЩАДИ, и середина не смещает её ни в одну сторону
       * (в отличие от буфера пометок, где сторона ошибки решает всё). */
      double cx = (double)i + 0.5, cy = (double)j + 0.5;
      int in = 1;
      for (int k = 0; k < 3 && in; k++) {
        int k2 = (k + 1) % 3;
        double ex = x[k2] - x[k], ey = y[k2] - y[k];
        double ev = (cx - x[k]) * ey - (cy - y[k]) * ex;
        if (!(sg * ev <= 0.0)) in = 0;
      }
      if (in) mk |= (uint64_t)1 << (j * HZ_PFRONT_COVN + i);
    }
  return mk;
}

int hz_pfront_cover_sum = 0; /* 1 — перекрытие СУММОЙ (верхняя оценка); опыт §274 */

/* ПОЛНЫЙ ПЕРЕНОС ЧЕРЕЗ ЯЧЕЙКУ, НА СЕТКЕ (§310 + О76).
 *
 * §308 намерил, что состояние НЕ СОХРАНЯЕТСЯ в пустоте при косом направлении;
 * §309 — что снос ВНУТРИ грани делает хуже, потому что при большом сносе луч
 * покидает ячейку через БОКОВУЮ грань, а это не выражено вовсе.
 *
 * Здесь выражено без остатка: для каждой КЛЕТКИ исходящей грани луч
 * прослеживается назад до первой встреченной ВХОДЯЩЕЙ грани — какой бы из трёх
 * она ни была, — и значение берётся оттуда. На сетке результат пишется ПРЯМО В
 * КЛЕТКУ; проекции на линейный базис, бывшей последним приближением §310,
 * больше нет. */
static void face_transport(const hz_pfront_face *in, hz_pfront_face *out, const double *lo,
                           const double *hi, const double *dir) {
  for (int a = 0; a < 3; a++) {
    int p, q;
    face_axes(a, &p, &q);
    double fa = (dir[a] > 0.0) ? hi[a] : lo[a]; /* ИСХОДЯЩАЯ грань по оси a */
    double hp = hi[p] - lo[p], hq = hi[q] - lo[q];
    if (!(hp > 0.0) || !(hq > 0.0)) {
      out[a] = in[a];
      continue;
    }
    for (int j = 0; j < HZ_PFRONT_COVN; j++)
      for (int i = 0; i < HZ_PFRONT_COVN; i++) {
        double u = 2.0 * ((double)i + 0.5) / (double)HZ_PFRONT_COVN - 1.0;
        double v = 2.0 * ((double)j + 0.5) / (double)HZ_PFRONT_COVN - 1.0;
        double P[3];
        P[a] = fa;
        P[p] = 0.5 * (lo[p] + hi[p]) + 0.5 * u * hp;
        P[q] = 0.5 * (lo[q] + hi[q]) + 0.5 * v * hq;
        double tb = 1e300;
        int bax = a;
        for (int c = 0; c < 3; c++) {
          double dc = dir[c];
          if (dc > -1e-300 && dc < 1e-300) continue;
          double pin = (dc > 0.0) ? lo[c] : hi[c]; /* ВХОДЯЩАЯ грань по оси c */
          double t = (P[c] - pin) / dc;
          if (t > 1e-12 && t < tb) {
            tb = t;
            bax = c;
          }
        }
        if (!(tb < 1e299)) tb = 0.0;
        double Q[3];
        for (int c = 0; c < 3; c++)
          Q[c] = P[c] - tb * dir[c];
        int bp, bq;
        face_axes(bax, &bp, &bq);
        double hbp = hi[bp] - lo[bp], hbq = hi[bq] - lo[bq];
        double uu = (hbp > 0.0) ? (2.0 * (Q[bp] - lo[bp]) / hbp - 1.0) : 0.0;
        double vv = (hbq > 0.0) ? (2.0 * (Q[bq] - lo[bq]) / hbq - 1.0) : 0.0;
        out[a].g[j * HZ_PFRONT_COVN + i] = (float)hz_pfront_at(&in[bax], uu, vv);
      }
  }
}

int hz_pfront_shade(const hz_pfront_face *in, hz_pfront_face *out, const hz_objmesh *m,
                    const int32_t *list, int32_t n, const double *lo, const double *hi,
                    const double *dir) {
  /* ШАГ ОПЕРАТОРА НА СЕТКЕ (О76). Две части, и обе теперь точные поклеточно:
   *   ПЕРЕНОС    — обратная прослежка до входящей грани (§310), пишет прямо в
   *                клетку, без проекции на линейный базис;
   *   ПЕРЕКРЫТИЕ — объединение масок кусков (§292) и поэлементное гашение.
   * Выбора между «максимумом» и «суммой» (А517) больше НЕ СУЩЕСТВУЕТ: маска
   * есть объединение по построению, и она же применяется без усреднения. */
  int any = 0;
  hz_pfront_face tr[3];
  face_transport(in, tr, lo, hi, dir);
  for (int a = 0; a < 3; a++) {
    uint64_t umask = 0;
    for (int32_t i = 0; i < n; i++) {
      int32_t t = list[i];
      const double *A = m->v + 3 * (size_t)m->f[3 * (size_t)t + 0];
      const double *B = m->v + 3 * (size_t)m->f[3 * (size_t)t + 1];
      const double *C = m->v + 3 * (size_t)m->f[3 * (size_t)t + 2];
      umask |= tri_mask(A, B, C, lo, hi, dir, a);
    }
    if (umask != 0) any = 1;
    out[a] = face_block(&tr[a], umask);
  }
  return any;
}

