/* ---- ОБХОД С ПЕРЕНОСОМ СОСТОЯНИЯ ------------------------------------------ */
/* Три причины остановить спуск, и третья — ради чего шаг затевался:
 *   ЛИСТ      дерево кончилось;
 *   ПОЛ       угловой размер ячейки упал ниже пола прохода;
 *   ТЕМНОЕ    все три входящие грани ниже допуска по доле открытого диска —
 *             это и есть ОГРУБЛЕНИЕ ЗАСЛОНЁННОГО (и освещённого) вместо
 *             отсечения. Ограничено потолком `HZ_PFRONT_COARSEN_MAX`, и
 *             срабатывание потолка считается отдельно. */
/* ТЕМНО ЛИ ВХОДЯЩЕЕ, СЧИТАЯ ПО ПОТОКУ. Грани взвешиваются `|dir[a]|`: у
 * параллельного фронта грань, перпендикулярная которой составляющая направления
 * равна нулю, потока НЕ НЕСЁТ ВОВСЕ, и требовать на ней темноты бессмысленно.
 * Поймано прогоном с солнцем строго вниз: там осей с потоком одна из трёх, и
 * невзвешенный предикат не срабатывал никогда. */
static int pf_dark3(const hz_pfront_face *in, const double *dir) {
  /* Взвешивание по потоку остаётся: грань, перпендикулярная которой составляющая
   * направления нулевая, потока не несёт. Внутри грани критерий теперь ТОЧНЫЙ —
   * наибольшая клетка, а не оценка сверху по линейной функции. */
  double fl = 0.0, w = 0.0;
  for (int a = 0; a < 3; a++) {
    double wa = (dir[a] < 0.0) ? -dir[a] : dir[a];
    double mx = 0.0;
    for (int k = 0; k < HZ_PFRONT_NCELL; k++)
      if ((double)in[a].g[k] > mx) mx = (double)in[a].g[k];
    w += wa;
    fl += wa * mx;
  }
  return w > 0.0 && fl <= w * HZ_PFRONT_FRAC_TOL;
}

/* Темно ли по ВСЕМ выборкам диска: у протяжённого источника ячейка в тени лишь
 * тогда, когда закрыт весь диск, а не одна его точка. */
static int pf_darkK(const hz_pfront_ctx *X, const hz_pfront_face *in) {
  for (int s = 0; s < X->nk; s++) {
    hz_pfront_face f[3];
    for (int a = 0; a < 3; a++)
      f[a] = in[a * X->nk + s];
    if (!pf_dark3(f, X->sdir[s])) return 0;
  }
  return 1;
}

static int box_hits3(const double *bl, const double *bh, const double *clo, const double *chi) {
  for (int c = 0; c < 3; c++)
    if (!(bl[c] < chi[c]) || !(bh[c] >= clo[c])) return 0;
  return 1;
}

void hz_pfront_walk(hz_pfront_ctx *X, int32_t nid, const double *lo, const double *hi,
                    const hz_pfront_face *in, hz_pfront_face *out, const int32_t *list, int32_t n,
                    int coarsened, int extra) {
  const hz_ptnode *N = &X->T->nd[nid];
  if (X->visit != NULL) X->visit[nid]++;
  /* ПОМЕТКА НЕСЁТ ЧИСЛО СТУПЕНЕЙ ПОСЛАБЛЕНИЯ, А НЕ ПРЕДЕЛЬНЫЙ УРОВЕНЬ. Сперва
   * было наоборот, и скан вышел обратный: чем грубее просили, тем БОЛЬШЕ выходило
   * ячеек, а при шести ступенях пометка не срабатывала вовсе. Причина в том, что
   * «уровень узла + ступени» отодвигает предел ВНИЗ, то есть разрешает спускаться
   * глубже. Правильно — отпускать ПОЛ, ровно как это делает пирамида: фронт
   * впитывается либо согласно LOD, либо на столько-то ступеней грубее. */
  /* Предел уровня, унаследованный сверху либо поставленный здесь. `-1` — нет. */
  int save_on = X->markon;
  if (X->mark != NULL && X->mark[nid] != 255) X->markon = 1;
  int stop = 0, why = 0, refined = 0;
  /* ПИРАМИДА КАМЕРЫ. Ячейка целиком снаружи хотя бы одной плоскости — невидима
   * камере, и её собственная подробность этому проходу не нужна. Берётся целиком
   * (огрубление), а не отбрасывается: свет в ней есть, и другим проходам она
   * нужна. */
  /* ВНЕ ПИРАМИДЫ — ПОДНЯТЬСЯ НА ПАРУ УРОВНЕЙ, А НЕ ОСТАНОВИТЬСЯ СОВСЕМ
   * (уточнение пользователя 08-05). Разница существенная: остановка совсем
   * означала бы, что ячейка вне кадра не рассматривается вовсе, а она ЗАСЛОНЯЕТ
   * — её тень падает ВНУТРЬ кадра (§241.5, §259 граница 1). Поэтому вне
   * пирамиды пол лишь ОТПУСКАЕТСЯ: при подъёме на `N` уровней допустимый размер
   * ячейки растёт вдвое на уровень, а критерий `4·r² ≤ (px·ε)²·d²` — вчетверо.
   * `frustfull = 1` даёт прежнее поведение (остановка совсем) — оно есть ВЕРХНЯЯ
   * ГРАНИЦА выигрыша, и держать её рядом полезно. */
  double pxe2 = X->pxeps2;
  if (X->usefrustum) {
    int outside = 0;
    for (int k = 0; k < 6 && !outside; k++) {
      const double *P = X->fr[k];
      double s = P[3];
      for (int c = 0; c < 3; c++)
        s += (P[c] > 0.0 ? hi[c] : lo[c]) * P[c];
      if (s < 0.0) outside = 1;
    }
    if (outside) {
      if (X->frustfull) {
        X->ncell++;
        X->stop_flat++;
        X->nshadow++;
        for (int a = 0; a < 3; a++) {
          hz_pfront_set(&out[a], 0.0);
        }
        return;
      }
      for (int k = 0; k < HZ_PFRONT_COARSEN_MAX; k++)
        pxe2 *= 4.0;
      X->noutside++;
    }
  }
  /* §241.4: ПУСТОЙ УЗЕЛ БЕРЁТСЯ ЦЕЛИКОМ, каков бы ни был его размер. Оператор
   * пустого — тождество, и спускаться незачем: линейное состояние проходит
   * сквозь пустоту ТОЧНО. Правило измерено негативным контролем §263: без него
   * спуск в пустоте упирается в потолок 150 млн ячеек. */
  if (X->occ != NULL && !X->occ[nid]) {
    stop = 1;
    why = 3;
  } else if (N->child < 0) {
    stop = 1;
    why = 0;
  } else {
    double r2 = 0.0, t = 0.0;
    for (int c = 0; c < 3; c++) {
      double h = 0.5 * (hi[c] - lo[c]);
      r2 += h * h;
      t += 0.5 * (lo[c] + hi[c]) * X->dir[c];
    }
    double dep = t - X->t_entry, d2 = dep * dep;
    /* ПОМЕТКА ОГРУБЛЯЕТ ОТНОСИТЕЛЬНО ТОГО, ГДЕ ФРОНТ ОСТАНОВИЛСЯ БЫ ИНАЧЕ, а
     * «иначе» есть `min(LOD, лист)`. Поэтому веток две, и нужны обе:
     *   ОТ ЛИСТА — остановиться, когда до дна поддерева осталось `N` уровней
     *     (там, где связывает лист, а это 58.9 %% спусков, §257);
     *   ОТ LOD  — отпустить пол на `N` ступеней, вчетверо на ступень
     *     (там, где связывает пол: у Сан-Мигеля 20 %%, при грубом поле 27.7 %%).
     * Одна ветка без другой покрывает лишь свою половину случаев, что и было
     * измерено 08-06 порознь. */
    if (X->markon && X->markrelax > 0) {
      /* ПОЛ ОЧЕРКА: послабление отменяется, если ячейка НЕСЁТ ГЕОМЕТРИЮ и при
       * этом крупнее полутени, которую она отбрасывает. Пустая ячейка тени не
       * даёт — её послабление не трогается. */
      int silh = 0;
      if (X->silh_a > 0.0 && n > 0) {
        double h = hi[0] - lo[0];
        double dd = X->silh_d;
        if (X->silh_local) {
          double tc = 0.0;
          for (int c = 0; c < 3; c++)
            tc += 0.5 * (lo[c] + hi[c]) * X->dir[c];
          dd = X->t_exit - tc;
          if (dd < 0.0) dd = 0.0;
          if (dd > X->silh_d) dd = X->silh_d;
        }
        if (h > X->silh_a * dd) {
          silh = 1;
          X->nsilh++;
        }
      }
      if (!silh)
        for (int k = 0; k < X->markrelax && k < 16; k++)
          pxe2 *= 4.0;
    }
    if (d2 > r2 && 4.0 * r2 <= pxe2 * d2) {
      /* Р3 §241.9 — УТОЧНЕНИЕ ТАМ, ГДЕ СОСТОЯНИЕ НЕ ПРЕДСТАВИМО. Зеркало правила
       * огрубления: ровное и тёмное берём крупным, а НЕРОВНОЕ — мельчим НИЖЕ
       * пола. Нужно оно потому, что эталон поймал расхождение `0.203` именно на
       * КРАЮ тени, где доля открытого диска меняется от 0 до 1 на одной-двух
       * ячейках, и линейная функция такого не несёт. Глубина уточнения
       * ограничена: без предела край тени утянул бы спуск до листьев везде. */
      double var = 0.0;
      for (int a = 0; a < 3; a++) {
        double wa = (X->dir[a] < 0.0) ? -X->dir[a] : X->dir[a];
        /* Р3 НА СЕТКЕ: «неровно» есть разброс по клеткам грани, а не наклон
         * линейной функции. Уточнять стоит там, где грань не однородна. */
        double mn = 1e300, mx = -1e300;
        for (int k = 0; k < HZ_PFRONT_NCELL; k++) {
          double g = (double)in[a].g[k];
          if (g < mn) mn = g;
          if (g > mx) mx = g;
        }
        var += wa * (mx - mn);
      }
      if (var > HZ_PFRONT_REFINE_TOL && extra < X->refinemax) {
        stop = 0;
        refined = 1;
        X->nrefine++;
      } else {
        stop = 1;
        why = 1;
      }
    } else if (X->markon && X->depth != NULL && X->depth[nid] <= X->markrelax &&
               !(X->silh_a > 0.0 && n > 0 && (hi[0] - lo[0]) > X->silh_a * X->silh_d)) {
      /* Здесь оценка остаётся общей: ветвь «за N уровней до дна» срабатывает у
       * мелких узлов, где локальное уточнение ничего не меняет. */
      /* ОГРУБЛЕНИЕ НА `markrelax` УРОВНЕЙ ОТ ТОГО МЕСТА, ГДЕ ОСТАНОВИЛИСЬ БЫ
       * ИНАЧЕ. Дно поддерева отсюда — `depth`; значит «на два уровня грубее»
       * есть «остановиться, когда до дна осталось два». Так формулировал
       * пользователь, и только так работает: пол бессилен там, где спуск
       * упирается в лист, а предел по уровню узла не относителен ни к чему. */
      stop = 1;
      why = 4;
      X->nmarkstop++;
    } else if (!X->noshadow && pf_darkK(X, in)) {
      if (coarsened < HZ_PFRONT_COARSEN_MAX) {
        stop = 1;
        why = 2;
      } else {
        X->ncap++;
      }
    }
  }
  if (stop) {
    X->markon = save_on;
    X->ncell++;
    if (why == 0) X->stop_leaf++;
    if (why == 1) X->stop_floor++;
    if (why == 2) X->stop_flat++;
    if (why == 3) X->stop_void++;
    /* Куски для ЭТОГО прохода больше не выводятся: перекрытие считается прямо по
     * треугольникам-кандидатам дешёвой двумерной проекцией (см. `tri_cover`). */
    /* КУСКИ ВЫВОДЯТСЯ ТОЛЬКО ТАМ, ГДЕ ОНИ НУЖНЫ, и это не оптимизация, а
     * устранение заведомо напрасной работы. Отсечение стоит ~2300 нс на ячейку
     * против 12…19 нс у обхода без света (§255), то есть почти вся цена шага
     * сидит здесь. Два случая, где оно НЕ нужно и это ТОЧНО, а не приближённо:
     *   ПУСТАЯ ЯЧЕЙКА — `occ` уже говорит, что куска с ненулевой площадью нет;
     *     кандидаты по ГАБАРИТУ при этом есть, и на зале их 97 % против 13 %
     *     настоящих (А511) — вот эта разница и резалась впустую;
     *   ТЁМНАЯ ЯЧЕЙКА — заслонять нечего: исходящее есть входящее, умноженное
     *     на (1 − перекрытие), а входящее уже ноль. */
    /* ОТСЕЧЕНИЕ ВЕДЁТСЯ ТОЛЬКО ПО КРУПНЫМ ЭЛЕМЕНТАМ (указание пользователя 08-05).
     * Замер: вывод кусков есть 86 %% времени шага (2329 нс на ячейку против 314 нс
     * без него), и почти вся эта работа повторяет уже сделанное — тень
     * устанавливается КРУПНОЙ ячейкой, а мелкие лишь пересчитывают ту же
     * поверхность заново. Глубже `cliplev` куски не выводятся: перекрытие там
     * берётся нулевым, то есть тень остаётся такой, какой её установил крупный
     * элемент. Это НИЖНЯЯ оценка заслонения, как и всё в А517. */
    int has = 0;
    if (X->noshadow || !(n > 0) || why == 3 || pf_darkK(X, in) ||
        (X->cliplev >= 0 && (int)X->T->lev[nid] > X->cliplev)) {
      for (int a = 0; a < 3 * X->nk; a++)
        out[a] = in[a];
      has = (why != 3);
    } else {
      /* ОДИН ТРАВЕРС, `K` СОСТОЯНИЙ (Ф4, §275). Выборки по диску отличаются
       * только направлением, и знаки его у всех одни (А530), поэтому порядок
       * октантов общий и обход делается однажды — множится лишь оператор. */
      for (int s = 0; s < X->nk; s++) {
        hz_pfront_face si[3], so[3];
        for (int a = 0; a < 3; a++)
          si[a] = in[a * X->nk + s];
        if (hz_pfront_shade(si, so, X->m, list, n, lo, hi, X->sdir[s])) has = 1;
        for (int a = 0; a < 3; a++)
          out[a * X->nk + s] = so[a];
      }
    }
    /* ДИАГНОСТИКА «СОБСТВЕННОЙ МЕЛКОСТИ» УЗЛА (разбор с пользователем 08-05:
     * сейчас тон задаёт общий уровень фронта, а менее детальный объект ничего не
     * экономит). Гипотеза: у большинства ячеек вся геометрия лежит в ОДНОЙ
     * плоскости, и такую ячейку дробить незачем при любом поле. Считается
     * сравнением нормалей и смещений с первым кандидатом; допуск — тот же
     * относительный, что у слияния компланарных в О70 (шестнадцатая доля ребра). */
    if (has && n > 0) {
      X->nflatgeo++;
      double h0 = hi[0] - lo[0];
      double tol = 0.0625 * h0;
      const double *v0 = X->m->v;
      const int32_t *f0 = X->m->f;
      double n0[3] = {0.0, 0.0, 0.0}, d0 = 0.0;
      int one = 1, first = 1;
      for (int32_t i = 0; i < n && one; i++) {
        int32_t t = list[i];
        const double *A = v0 + 3 * (size_t)f0[3 * (size_t)t + 0];
        const double *B = v0 + 3 * (size_t)f0[3 * (size_t)t + 1];
        const double *C = v0 + 3 * (size_t)f0[3 * (size_t)t + 2];
        double e1[3], e2[3], nr[3];
        for (int c = 0; c < 3; c++) {
          e1[c] = B[c] - A[c];
          e2[c] = C[c] - A[c];
        }
        nr[0] = e1[1] * e2[2] - e1[2] * e2[1];
        nr[1] = e1[2] * e2[0] - e1[0] * e2[2];
        nr[2] = e1[0] * e2[1] - e1[1] * e2[0];
        double ln = nr[0] * nr[0] + nr[1] * nr[1] + nr[2] * nr[2];
        if (!(ln > 0.0)) continue;
        ln = 1.0 / sqrt(ln);
        for (int c = 0; c < 3; c++)
          nr[c] *= ln;
        double dd = nr[0] * A[0] + nr[1] * A[1] + nr[2] * A[2];
        if (first) {
          for (int c = 0; c < 3; c++)
            n0[c] = nr[c];
          d0 = dd;
          first = 0;
          continue;
        }
        double dot = n0[0] * nr[0] + n0[1] * nr[1] + n0[2] * nr[2];
        double sg = (dot < 0.0) ? -1.0 : 1.0;
        double gap = 0.0;
        for (int c = 0; c < 3; c++) {
          double dn = n0[c] - sg * nr[c];
          gap += (dn < 0.0 ? -dn : dn) * 0.5 * h0;
        }
        double dd2 = d0 - sg * dd;
        gap += (dd2 < 0.0 ? -dd2 : dd2);
        if (gap > tol) one = 0;
      }
      if (one) X->nflat1++;
    }
    if (has)
      X->ncell_geo++;
    else
      X->ncell_void++;
    /* ЗАПИСЬ ПОМЕТКИ (разбор 08-05/08-06): этот же проход, пущенный ОТ КАМЕРЫ,
     * ищет НЕВИДИМОЕ напрямую — то, что за стеной, — и кладёт ему предел
     * детализации. Насколько огрублять, задаёт диффузность: у полностью
     * диффузной поверхности подробность дальше не передаётся вовсе (§259), и
     * берётся `markrelax` ступеней. Пометка пишется ТОЛЬКО на крупных уровнях:
     * ниже она и не нужна, и стоила бы полного второго обхода. */
    if (X->markout != NULL && (int)X->T->lev[nid] <= X->markoutlev) {
      /* ПОМЕТКА СТАВИТСЯ ПО ХУДШЕЙ ТОЧКЕ ГРАНИ, А НЕ ПО СРЕДНЕЙ. Сперва бралось
       * среднее (`c0`), и приёмка это поймала: среди помеченных оказалось
       * `18.7 %` ячеек, ВИДИМЫХ от камеры (зал) и `11.6 %` (Сан-Мигель). Причина
       * прямая: у крупного узла часть в тени, часть на свету, среднее темно — а
       * светлая часть видна. Критерий обязан быть таким же, как у остановки по
       * темноте: `c0 + |cu| + |cv|` ниже допуска, то есть темно ВЕЗДЕ на грани.
       * Ошибка при этом смещается в безопасную сторону: не пометим часть
       * невидимого — это по указанию пользователя 08-06 допустимо, а огрубить
       * видимое — нет. */
      if (pf_darkK(X, in)) {
        X->markout[nid] = 1;
        X->nmarkset++;
      }
    }
    /* ГЛУБИНА ЗАСЛОНИТЕЛЯ ПО СТОЛБИКАМ (§296). Считается там же, где перекрытие,
     * и по той же сетке: для каждой клетки 8x8 входной грани — наименьшая
     * глубина, на которой столбик встречает геометрию ячейки. */
    if (X->cellslot != NULL && n > 0 && X->nslot < X->capslot) {
      int a = 0;
      double ma = 0.0;
      for (int c = 0; c < 3; c++) {
        double v = (X->dir[c] < 0.0) ? -X->dir[c] : X->dir[c];
        if (v > ma) {
          ma = v;
          a = c;
        }
      }
      X->celldepax = a;
      int p2, q2;
      face_axes(a, &p2, &q2);
      double fa = (X->dir[a] > 0.0) ? lo[a] : hi[a]; /* ВХОДНАЯ грань */
      float *dep = X->celldep + HZ_PFRONT_NCELL * (size_t)X->nslot;
      for (int k = 0; k < HZ_PFRONT_NCELL; k++)
        dep[k] = INFINITY;
      double du = hi[p2] - lo[p2], dv = hi[q2] - lo[q2];
      for (int32_t i = 0; i < n; i++) {
        int32_t t = list[i];
        const double *A = X->m->v + 3 * (size_t)X->m->f[3 * (size_t)t + 0];
        const double *B = X->m->v + 3 * (size_t)X->m->f[3 * (size_t)t + 1];
        const double *C = X->m->v + 3 * (size_t)X->m->f[3 * (size_t)t + 2];
        double e1[3] = {B[0] - A[0], B[1] - A[1], B[2] - A[2]};
        double e2[3] = {C[0] - A[0], C[1] - A[1], C[2] - A[2]};
        double nw[3];
        nw[0] = e1[1] * e2[2] - e1[2] * e2[1];
        nw[1] = e1[2] * e2[0] - e1[0] * e2[2];
        nw[2] = e1[0] * e2[1] - e1[1] * e2[0];
        double nd = nw[0] * X->dir[0] + nw[1] * X->dir[1] + nw[2] * X->dir[2];
        if (nd > -1e-300 && nd < 1e-300) continue; /* параллелен свету */
        double dpl = nw[0] * A[0] + nw[1] * A[1] + nw[2] * A[2];
        uint64_t mk = tri_mask(A, B, C, lo, hi, X->dir, a);
        while (mk != 0) {
          int b = 0;
          uint64_t lsb = mk & (~mk + 1);
          while ((lsb >> b) != 1)
            b++;
          mk &= mk - 1;
          int gi = b % HZ_PFRONT_COVN, gj = b / HZ_PFRONT_COVN;
          double X0[3];
          X0[a] = fa;
          X0[p2] = lo[p2] + du * ((double)gi + 0.5) / (double)HZ_PFRONT_COVN;
          X0[q2] = lo[q2] + dv * ((double)gj + 0.5) / (double)HZ_PFRONT_COVN;
          double num = dpl - (nw[0] * X0[0] + nw[1] * X0[1] + nw[2] * X0[2]);
          double tt = num / nd;
          if (tt > 0.0 && (float)tt < dep[b]) dep[b] = (float)tt;
        }
      }
      /* Заодно кладётся и само состояние входящей грани — картинка читает
       * КЛЕТКУ под точкой, а не среднее по грани. */
      if (X->cellval != NULL) {
        float *cv2 = X->cellval + HZ_PFRONT_NCELL * (size_t)X->nslot;
        for (int k = 0; k < HZ_PFRONT_NCELL; k++)
          cv2[k] = in[a * X->nk].g[k];
      }
      X->cellslot[nid] = X->nslot;
      X->nslot++;
    }
    /* ОТВЕТ ФРОНТА, ОСТАВЛЕННЫЙ СНАРУЖИ (см. `cellf` в заголовке). Берётся
     * ВХОДЯЩЕЕ состояние по потоку — «сколько диска видно этой ячейке», то есть
     * та же величина, что уходит в выборку эталона. */
    if (X->cellf != NULL) {
      double fi = 0.0, wi = 0.0;
      for (int s = 0; s < X->nk; s++)
        for (int a = 0; a < 3; a++) {
          double wa = (X->sdir[s][a] < 0.0) ? -X->sdir[s][a] : X->sdir[s][a];
          wi += wa;
          fi += wa * hz_pfront_mean(&in[a * X->nk + s]);
        }
      X->cellf[nid] = (float)((wi > 0.0) ? fi / wi : 0.0);
    }
    /* Освещённость ячейки — тоже по ПОТОКУ, а не среднее по трём граням. */
    double fl = 0.0, w = 0.0;
    for (int a = 0; a < 3; a++) {
      double wa = (X->dir[a] < 0.0) ? -X->dir[a] : X->dir[a];
      w += wa;
      fl += wa * hz_pfront_mean(&out[a]);
    }
    if (w > 0.0) {
      if (fl <= w * HZ_PFRONT_FRAC_TOL)
        X->nshadow++;
      else if (fl >= w * (1.0 - HZ_PFRONT_FRAC_TOL))
        X->nlit++;
    }
    /* Запись в выборку эталона. Берётся ВХОДЯЩЕЕ состояние, взвешенное потоком:
     * именно оно есть «сколько диска видно этой ячейке». */
    if (X->refpt != NULL && X->refn < X->refcap && X->refstride > 0 &&
        (X->ncell % X->refstride) == 0 && w > 0.0) {
      /* СРЕДНЕЕ ПО ДИСКУ, а не нулевая выборка: у протяжённого источника доля
       * открытого диска и есть среднее по выборкам, и сверять с эталоном надо
       * именно её. Брал нулевую — и потому `K` не был виден в замере вовсе. */
      double fi = 0.0, wi = 0.0;
      for (int s = 0; s < X->nk; s++)
        for (int a = 0; a < 3; a++) {
          double wa = (X->sdir[s][a] < 0.0) ? -X->sdir[s][a] : X->sdir[s][a];
          wi += wa;
          fi += wa * hz_pfront_mean(&in[a * X->nk + s]);
        }
      if (wi > 0.0) {
        fi /= wi;
        wi = 1.0;
      }
      for (int c = 0; c < 3; c++)
        X->refpt[3 * (size_t)X->refn + (size_t)c] = 0.5 * (lo[c] + hi[c]);
      if (X->refh != NULL) X->refh[X->refn] = 0.5 * (hi[0] - lo[0]);
      X->refvis[X->refn] = fi;
      X->refn++;
    }
    return;
  }

  /* Если спускаемся ВОПРЕКИ полу (Р3), уровень уточнения растёт. */
  int nextra = refined ? extra + 1 : extra;
  int32_t c0 = N->child;
  double mid[3];
  for (int c = 0; c < 3; c++)
    mid[c] = 0.5 * (lo[c] + hi[c]);
  int e[3];
  for (int c = 0; c < 3; c++)
    e[c] = (X->dir[c] > 0.0) ? 0 : 1;
  int32_t *sub = malloc(((size_t)(n > 0 ? n : 1) + 1) * sizeof *sub);
  if (sub == NULL) {
    X->fail = 1;
    return;
  }
  /* Инициализация по построению: порядок «ближние раньше дальних» гарантирует,
   * что сосед посчитан до чтения, но анализатору этот довод недоступен, и он
   * прав в том, что доказательства у него нет. Двадцать четыре записи на узел —
   * цена никакая. */
  /* На каждую выборку по диску — своя тройка граней: `[ось · nk + выборка]`. */
  /* СОСТОЯНИЕ ДЕТЕЙ — В КУЧЕ (А540). На сетке оно есть `8 × 3 × K` граней по
   * `N²` чисел: при `N = 8, K = 16` это `98` КБ НА УРОВЕНЬ и `1.2` МБ на глубину
   * `12`. На стеке такому не место, и аудит потребовал вынести это ДО кода, а не
   * после первого падения. Выделяется столько, сколько нужно при этом `K`. */
  hz_pfront_face *cout = calloc((size_t)8 * 3 * (size_t)X->nk, sizeof *cout);
  if (cout == NULL) {
    X->fail = 1;
    free(sub);
    return;
  }
  /* Порядок «ближние раньше дальних»: по числу осей, где ребёнок с дальней
   * стороны. Он делает зависимости ациклическими (§241.7). */
  for (int far = 0; far <= 3; far++) {
    for (int k = 0; k < 8; k++) {
      int b[3], nf = 0;
      for (int c = 0; c < 3; c++) {
        b[c] = (k >> c) & 1;
        if (b[c] != e[c]) nf++;
      }
      if (nf != far) continue;
      double clo[3], chi[3];
      for (int c = 0; c < 3; c++) {
        clo[c] = b[c] ? mid[c] : lo[c];
        chi[c] = b[c] ? hi[c] : mid[c];
      }
      /* Обнуление явное: при  цикл ниже не заполнил бы её вовсе, и
       * cppcheck прав, что доказательства обратного у него нет. */
      hz_pfront_face cin[3 * HZ_PFRONT_MAXK] = {{{0}}};
      for (int a = 0; a < 3; a++) {
        int p, q;
        face_axes(a, &p, &q);
        for (int s = 0; s < X->nk; s++) {
          if (b[a] == e[a]) {
            double su = b[p] ? 1.0 : -1.0, sv = b[q] ? 1.0 : -1.0;
            cin[a * X->nk + s] = face_quarter(&in[a * X->nk + s], su, sv);
          } else {
            cin[a * X->nk + s] =
                cout[(size_t)(k ^ (1 << a)) * 3 * (size_t)X->nk + (size_t)(a * X->nk + s)];
          }
        }
      }
      int32_t ns = 0;
      for (int32_t i = 0; i < n; i++) {
        const double *bl = X->tlo + 3 * (size_t)list[i], *bh = X->thi + 3 * (size_t)list[i];
        if (box_hits3(bl, bh, clo, chi)) sub[ns++] = list[i];
      }
      hz_pfront_walk(X, c0 + k, clo, chi, cin, cout + (size_t)k * 3 * (size_t)X->nk, sub, ns,
                     coarsened, nextra);
      if (X->fail) {
        free(sub);
        free(cout);
        return;
      }
    }
  }
  X->markon = save_on;
  free(sub);
  /* Исходящие грани родителя — сложение моментов по четырём детским (Р2). */
  for (int a = 0; a < 3; a++) {
    int p, q;
    face_axes(a, &p, &q);
    for (int s = 0; s < X->nk; s++) {
      hz_pfront_face Q[4];
      for (int j = 0; j < 4; j++) {
        int b[3];
        b[a] = 1 - e[a];
        b[p] = j & 1;
        b[q] = (j >> 1) & 1;
        Q[j] = cout[(size_t)((b[0]) | (b[1] << 1) | (b[2] << 2)) * 3 * (size_t)X->nk +
                    (size_t)(a * X->nk + s)];
      }
      out[a * X->nk + s] = face_join(Q);
    }
  }
  free(cout);
}
