/* pfront.h — ФРОНТ ОТ ПРОТЯЖЁННОГО ИСТОЧНИКА: СОСТОЯНИЕ НА ГРАНЯХ И ОПЕРАТОР
 * УЗЛА (Ф3, план §266, аудит §267 и поправки к ним от 08-05).
 *
 * ЧТО ЭТО. Обход О72 ходил по ячейкам, но света не нёс. Здесь у ячейки
 * появляется СОСТОЯНИЕ, и вместе с ним три вещи, ради которых Ф3 и затевался:
 * заслонение (свет не проходит сквозь стену), полутень (край тени не резкий) и
 * ОГРУБЛЕНИЕ ЗАСЛОНЁННОГО — главный рычаг шага.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ — ОТСЕЧЕНИЯ. Указание пользователя 08-05: «не
 * отсечение по телесному углу, а уменьшение детальности; отсечение нельзя».
 * Заслонённая ячейка НЕ выбрасывается: у неё отпускается пол, она берётся одной
 * крупной ячейкой и несёт состояние «прямого света нет». Три довода, каждый
 * самостоятельный: (1) косвенный свет в ней есть, и камера её видит — отсечённую
 * нечем осветить на следующем проходе; (2) полутень непрерывна, двоичное решение
 * рвёт градиент там, где Р1 требует линейной доли; (3) ошибка отсечения
 * несимметрична и картинкой не ловится — класс А475, уже пойманный однажды.
 *
 * СОСТОЯНИЕ — ДОЛЯ ОТКРЫТОГО ДИСКА ИСТОЧНИКА, ЛИНЕЙНАЯ ПО ГРАНИ (Р1 §241.9).
 * Три коэффициента на грань: `c0` в центре и два наклона по осям грани. Почему
 * не одно число: линейная доля даёт ПОДЪЯЧЕЕЧНОЕ положение края тени
 * (пересечение уровня 0.5) — по той же причине, по которой работает сглаживание.
 * Почему не больше трёх: огрубление `4 → 1` тогда есть СЛОЖЕНИЕ МОМЕНТОВ, то
 * есть точная L²-проекция (Р2), а уточнение `1 → 4` — вычисление полинома (Р3).
 *
 * ОГРУБЛЕНИЕ РЕШАЕТСЯ СОСТОЯНИЕМ, А НЕ ПОМЕТКОЙ. Спуск прекращается, когда доля
 * представима на грани ЭТОГО уровня в пределах допуска: в глубокой тени она
 * тождественно ноль, на открытом свету — тождественно единица, у края тени
 * меняется быстро и спуск продолжается. Ни копии геометрии, ни поля в узле не
 * нужно (§6 запрещает второе представление, А133 — проходозависимость дерева):
 * УРОВЕНЬ ОСТАНОВКИ И ЕСТЬ ПОМЕТКА, и живёт он в обходе.
 *
 * ПОТОЛОК ОГРУБЛЕНИЯ `N` — НАСТРОЙКА, А ВЕЛИЧИНА — ВЫВОД. Критерий `Δn < β/2`
 * (разброс нормалей против ширины лепестка) при полной диффузности разрешает
 * много; `N = 2` взято как сознательная осторожность (решение пользователя
 * 08-05) и печатается как умолчание. Предсказание под него записано ДО кода:
 * `431 725` ячеек против `8 730 408`, выигрыш `20.2` раза.
 */
#ifndef HZ_PFRONT_H
#define HZ_PFRONT_H

#include "pclip.h"
#include "ptree.h"

/* ПОТОЛОК ОГРУБЛЕНИЯ ЗАСЛОНЁННОГО, В УРОВНЯХ. Не выведенная величина, а
 * страховка: настоящий предел даёт `Δn < β/2`, и при диффузной поверхности он
 * много слабее. Срабатывание потолка СЧИТАЕТСЯ и печатается — иначе «выигрыш
 * 20 раз» неотличим от «упёрлись в потолок». */
#define HZ_PFRONT_COARSEN_MAX 2

/* ДОПУСК НА ПРЕДСТАВИМОСТЬ ДОЛИ НА ГРУБОЙ ГРАНИ. Задан ВКЛАДОМ В ПИКСЕЛЬ, а не
 * абсолютной освещённостью (А522): доля меняется от 0 до 1, и различимой её
 * делает та же величина, что различает яркость соседних пикселей. Восьмибитный
 * вывод даёт 1/256; берётся половина ступени, потому что ошибка складывается из
 * двух проходов (прямого и косвенного). */
#define HZ_PFRONT_FRAC_TOL (1.0 / 512.0)

/* СОСТОЯНИЕ НА ГРАНИ: доля открытого диска источника как линейная функция.
 * `c0` — значение в ЦЕНТРЕ грани, `cu`/`cv` — наклоны по двум осям грани в
 * долях ПОЛУРАЗМЕРА (то есть на краю грани вклад равен самому наклону). Такая
 * нормировка выбрана затем, чтобы огрубление 4 → 1 складывало моменты без
 * пересчёта масштабов. */
typedef struct {
  double c0, cu, cv;
} hz_pfront_face;

/* Доля в точке грани, заданной местными координатами `u`, `v` из [-1, 1]. */
static inline double hz_pfront_at(const hz_pfront_face *F, double u, double v) {
  double f = F->c0 + F->cu * u + F->cv * v;
  return f < 0.0 ? 0.0 : (f > 1.0 ? 1.0 : f);
}

/* МОЖНО ЛИ ОГРУБЛЯТЬ ЗДЕСЬ. Критерий — не «ровно», а ТЕМНО: доля открытого диска
 * по всей грани ниже допуска. Тогда содержимое ячейки на исход не влияет вовсе
 * (исходящее = входящее × (1 − перекрытие), а входящее уже ноль), и спускаться
 * незачем — это и есть огрубление заслонённого ВМЕСТО отсечения.
 *
 * ПОЧЕМУ НЕ ПРОСТО «РОВНО», хотя так и было написано сперва: ровным состояние
 * бывает и на ОТКРЫТОМ СВЕТУ (на входе в сцену оно тождественно единица), а там
 * огрублять нельзя — именно в освещённых ячейках и рождаются тени. Поймано
 * первым же прогоном: обход остановился на КОРНЕ, выдав одну ячейку. */
static inline int hz_pfront_dark(const hz_pfront_face *F) {
  double a = (F->cu < 0.0 ? -F->cu : F->cu) + (F->cv < 0.0 ? -F->cv : F->cv);
  return F->c0 + a <= HZ_PFRONT_FRAC_TOL;
}

/* ШАГ ОПЕРАТОРА: по входящим граням, кускам ячейки и направлению даёт исходящие.
 * Пустая ячейка (`npiece == 0`) — тождество, шаг во весь узел. */
int hz_pfront_shade(const hz_pfront_face in[3], hz_pfront_face out[3], const hz_objmesh *m,
                    const int32_t *list, int32_t n, const double *lo, const double *hi,
                    const double *dir);
/* ПРЕДЕЛ ЧИСЛА КУСКОВ, РАЗБИРАЕМЫХ В ЯЧЕЙКЕ. Остаток на дне может быть толстым
 * (§241.6: куст — сотни кусков), и разбирать его поштучно незачем: перекрытие
 * берётся максимумом, а не суммой. Срабатывание считается и печатается. */
#define HZ_PFRONT_MAXPIECE 64

#include "scene_obj.h"
typedef struct {
  const hz_ptree *T;
  const hz_objmesh *m;
  const double *tlo, *thi;
  double dir[3], pxeps2, t_entry;
  int fail;
  int64_t ncell, ncell_geo, ncell_void, ncap, npclip;
  int64_t stop_leaf, stop_floor, stop_flat, stop_void, nlit, nshadow;
  /* УСЕЧЁННАЯ ПИРАМИДА КАМЕРЫ как источник (поправка 08-05: камера — источник в
   * том же списке, пирамида — его диаграмма излучения). Шесть плоскостей,
   * внутрь положительны. Ячейка ЦЕЛИКОМ снаружи невидима, и по тому же правилу,
   * что заслонённая, БЕРЁТСЯ ЦЕЛИКОМ — не выбрасывается. */
  /* ВЫБОРКА ДЛЯ ЭТАЛОНА (А519): каждая `refstride`-я остановившаяся ячейка
   * записывается вместе со своим состоянием, чтобы сверить её с трассировкой
   * теневых лучей. Выборка ДЕТЕРМИНИРОВАНА — повтор даёт те же ячейки. */
  int32_t refstride, refcap, refn;
  double *refpt;  /* 3·refcap: центры ячеек */
  double *refvis; /* refcap: доля открытого диска по нашему состоянию */
  int cliplev;    /* глубже этого уровня куски НЕ выводятся; −1 — без предела */
  int usefrustum;
  int frustfull; /* 1 — прежнее поведение: вне пирамиды останавливаться совсем (верхняя граница) */
  const unsigned char *mark;   /* пометки от камеры: предельный уровень; NULL — не применять */
  unsigned char *markout;      /* КУДА писать пометки: проход от камеры заполняет их сам */
  int markoutlev;              /* глубже этого уровня проход пометок не идёт */
  int markrelax;               /* на сколько уровней огрублять невидимое */
  const unsigned char *depth;  /* высота поддерева: сколько уровней ниже узла */
  int markon;                  /* внутри помеченного (невидимого) поддерева */
  int64_t nmarkstop, nmarkset; /* остановок ПО ПОМЕТКЕ; поставленных пометок */
  int markcur;                 /* унаследованная пометка на текущем пути */
  int64_t nflat1;              /* ячеек, где вся геометрия лежит В ОДНОЙ плоскости (стена) */
  int64_t nflatgeo;            /* ячеек с геометрией, по которым считалось nflat1 */
  int64_t noutside;            /* ячеек, попавших под отпущенный пол из-за пирамиды */
  double fr[6][4];
  int noshadow;             /* негативный контроль: ни заслонения, ни огрубления по ровности */
  const unsigned char *occ; /* §241.4: пустой узел берётся целиком; NULL — правило выключено */
} hz_pfront_ctx;

void hz_pfront_walk(hz_pfront_ctx *X, int32_t nid, const double *lo, const double *hi,
                    const hz_pfront_face in[3], hz_pfront_face out[3], const int32_t *list,
                    int32_t n, int coarsened);

/* Оговорка о том, что в операторе приближено, — печатается в докладе. */
const char *hz_pfront_note(void);

#endif
