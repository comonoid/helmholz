/* pgrid.h — РАВНОМЕРНАЯ СЕТКА ПО ТРЕУГОЛЬНИКАМ СЦЕНЫ И ЛУЧ ПО НЕЙ.
 *
 * ЛИНИЯ ПЕРЕНОСА, PLAN_ELEMENTS.md. Вынесено из `tools/psil.c` (шаг О55,
 * §172, пункт 0 порядка работ) ПО ОДНОЙ ПРИЧИНЕ: стенду фронта `tools/pfront.c`
 * нужен тот же луч по тем же треугольникам, а третья копия трассировщика в
 * репозитории — это три места, где «видно/не видно» может разойтись, и ни
 * одного, где расхождение поймается.
 *
 * ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ И ПОЧЕМУ НЕ `hz_pray`. `src/pray.h` ищет попадание по
 * ПОЛИГОНАМ сегментации, а они отстоят от треугольников на `δ`. Там, где
 * решается видимость силуэта, порождённого РЕБРОМ ТРЕУГОЛЬНИКА, заслон обязан
 * считаться по той же поверхности, что породила силуэт, иначе «видно» и
 * «породило» относятся к разным телам (довод §153, пункт 2). Обе сетки живут
 * рядом СОЗНАТЕЛЬНО: у них разный источник истины, а не разная реализация.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Ни материалов, ни нормалей, ни попадания с барицентрикой —
 * только «есть ли заслон» и «где ближайший». Всё, что сверх этого, считает
 * потребитель по индексу треугольника.
 *
 * ЛУЧ ДВУСТОРОННИЙ: стена заслоняет независимо от того, какой стороной
 * повёрнута. Для теней это единственное верное поведение — у воксельной сцены
 * (Rungholt) ориентация части граней произвольна.
 */
#ifndef HZ_PGRID_H
#define HZ_PGRID_H

#include "scene_obj.h"
#include <stdint.h>

/* РАЗМЕР ЯЧЕЙКИ выводится из СРЕДНЕЙ площади треугольника: ячейка не должна
 * быть мельче треугольника (иначе один треугольник растекается по многим
 * ячейкам) и не крупнее нескольких его размеров (иначе в ячейке очередь).
 * `cs = 2·sqrt(2·A_ср)`; у города `A = 0.5015` м² даёт `2.0` м. */
#define HZ_PGRID_CELL_MUL 2.0
/* Потолок числа ячеек: `start[]` есть `8` байт на ячейку, `64` млн ячеек —
 * `512` МБ. При превышении ячейка укрупняется. */
#define HZ_PGRID_CELL_MAX 67108864LL
/* Определитель Мёллера — Трумбора ниже этого считается вырожденным: у
 * метровых треугольников он порядка единицы, `1e-12` есть луч, лежащий в
 * плоскости с точностью до `1e-12` радиана. */
#define HZ_PGRID_DET_TINY 1.0e-12
/* Ноль направления: `1e-300` — не допуск задачи, а защита от деления. */
#define HZ_PGRID_DTINY 1.0e-300
/* ЭПСИЛОН ЛУЧА — ОТНОСИТЕЛЬНЫЙ, и он не новый: ровно то соглашение, что стоит
 * в `prender.c:599` (`len * (1.0 - 1e-6)`). Нужен для СКОЛЬЗЯЩИХ лучей вдоль
 * пола, где исключение по индексу не помогает (§153, А345). Живёт здесь, а не
 * у потребителя: соглашение об отступе есть часть договора о видимости, и
 * разъехаться ему у двух стендов нельзя. */
#define HZ_PGRID_EPSREL 1.0e-6

typedef struct {
  int32_t nc[3];       /* ячеек по осям */
  double lo[3], hi[3]; /* коробка сетки: габарит меша, расширенный на ячейку */
  double cs;           /* ребро ячейки, метры */
  int64_t *start;      /* ncell+1, CSR-начала списков треугольников */
  int32_t *idx;        /* nref, индексы треугольников */
  int64_t ncell, nref;
} hz_pgrid;

/* Построить сетку по мешу. Возврат: 0 — успех, 2 — нет памяти.
 * При ненулевом возврате звать `hz_pgrid_free` всё равно можно и нужно. */
int hz_pgrid_build(hz_pgrid *g, const hz_objmesh *m);
void hz_pgrid_free(hz_pgrid *g);

/* Пересечение луча с ОДНИМ треугольником (Мёллер — Трумбор, двусторонний).
 * Возврат 1 и `*tout` — параметр вдоль `d` (НЕ нормированный на длину `d`). */
int hz_pgrid_tri_hit(const hz_objmesh *m, int32_t t, const double o[3], const double d[3],
                     double *tout);

/* Обход DDA. `anyhit` — вопрос «есть ли заслон» (для тени), иначе ищется
 * БЛИЖАЙШЕЕ попадание. `skip`/`nskip` — треугольники, которые не считаются
 * заслоном (обычно те, на которых сидит начало луча).
 * Возврат: 1 — попадание, `*thit` — параметр; 0 — ничего. */
int hz_pgrid_trace(const hz_pgrid *g, const hz_objmesh *m, const double o[3], const double dir[3],
                   double tmin, double tmax, const int32_t *skip, int nskip, int anyhit,
                   double *thit);

/* То же самое, но с индексом попавшего треугольника (`tri` может быть NULL).
 * Заведено отдельной функцией, а не лишним параметром у `hz_pgrid_trace`,
 * СОЗНАТЕЛЬНО: у той есть работающий потребитель (`tools/psil.c`), чьи числа
 * сверяются побитово, и трогать её подпись значит пересверять их ради удобства.
 * Треугольник нужен затенению — по нему берутся нормаль и материал. */
int hz_pgrid_trace_tri(const hz_pgrid *g, const hz_objmesh *m, const double o[3],
                       const double dir[3], double tmin, double tmax, const int32_t *skip,
                       int nskip, int anyhit, double *thit, int32_t *tri);

#endif
