/* phcube.h — ПОЛУКУБ: ВИДИМОСТЬ И ФОРМ-ФАКТОР ОДНОЙ РАСТЕРИЗАЦИЕЙ (§94).
 *
 * ЗАЧЕМ. Сборка оператора связями считала видимость ПОПАРНО: для каждой пары
 * элементов `nvis²` лучей, и замер дал 14 314 328 лучей за 65 с на зале.
 * Довод пользователя 08-01: это видимость ПОЛИГОНА ИЗ ПОЛИГОНА, а такую задачу
 * рисование полигонами решает на порядки быстрее. Полукуб (Cohen–Greenberg,
 * 1985) ставится в опорной точке элемента, сцена рисуется в него ОДИН раз с
 * буфером номеров полигонов, и из этого кадра читаются СРАЗУ и видимость, и
 * форм-факторы ко всем видимым элементам. Пары не перебираются вовсе.
 *
 * ЭТО И ЕСТЬ ТРЕБОВАНИЕ §6, записанное с начала проекта: «видимость нужна как
 * ВЫЧИСЛЕНИЕ, не как таблица пар: O(n²) погубило классическую радиосити».
 *
 * ЧЕГО ПОЛУКУБ НЕ ДЕЛАЕТ, И ЭТО СКАЗАНО ДО ЗАМЕРА (§94.1, А239, А240):
 *   - АСИМПТОТИКУ НЕ МЕНЯЕТ. Растеризация сцены стоит `O(треугольников)` на
 *     элемент, то есть `O(n²)` на сцену. Выигрывает КОНСТАНТА: проекция трёх
 *     вершин против форм-фактора и четырёх лучей сквозь сетку. Ниже `O(n²)`
 *     уводит только отсев заведомо невидимого — отдельный шаг;
 *   - ФОРМ-ФАКТОР КВАНТУЕТ пикселями. Точная контурная форма §87 (проверенная
 *     до `1e-16`) при этом теряется: полукуб даёт видимость и коэффициент ОДНИМ
 *     числом на пиксель, и разделить их нельзя. Размен сознательный, цену мерит
 *     негативный контроль с разрешением `R = 4`;
 *   - ПРИЁМНИК ОСТАЁТСЯ ТОЧКОЙ, значит перебор `Σf` у близких пар никуда не
 *     денется — он держится приёмной стороной, а не излучающей.
 *
 * УСТРОЙСТВО. Пять граней куба над касательной плоскостью: верхняя `R×R` в
 * `[-1,1]²` и четыре боковых `R×R/2` в `[-1,1]×[0,1]`. Каждый пиксель несёт
 * ДЕЛЬТА-ФОРМ-ФАКТОР — телесный угол с косинусом, отнесённый к `π`; таблица
 * считается замкнутой формой один раз на разрешение. Сумма по всем пикселям
 * равна единице ТОЧНО в пределе, и это самопроверка, а не пожелание.
 */
#ifndef HZ_PHCUBE_H
#define HZ_PHCUBE_H

#include "polygon.h"
#include "scene_obj.h"

typedef struct {
  int R;         /* разрешение верхней грани, пикселей по стороне */
  int npix;      /* всего пикселей во всех пяти гранях */
  float *dff;    /* дельта-форм-фактор пикселя, npix */
  double *dir;   /* 3*npix: единичное направление пикселя в раме полукуба */
  double *depth; /* npix: текущая ближайшая дальность */
  int32_t *id;   /* npix: номер полигона или -1 */
  double sum;    /* Σ dff — подпись: обязана быть близка к 1 */
} hz_hcube;

/* Завести полукуб разрешения `R` (верхняя грань `R×R`). Таблица направлений и
 * дельта-форм-факторов считается здесь один раз и переиспользуется. */
int hz_hcube_init(hz_hcube *h, int R);
void hz_hcube_free(hz_hcube *h);

/* Нарисовать сцену в полукуб, поставленный в точку `x` с нормалью `n`.
 * Растеризуются ИСХОДНЫЕ ТРЕУГОЛЬНИКИ (у них край из трёх рёбер, поэтому
 * `O(периметра)` из §90.1 здесь не возникает), а номер пишется ПОЛИГОНА, к
 * которому треугольник принадлежит: `tri2poly` длиной `m->nt`.
 * `skip` — полигон, который не рисуется вовсе (сам приёмник: плоский элемент не
 * затеняет себя, §88); `-1`, если пропускать нечего. */
void hz_hcube_draw(hz_hcube *h, const hz_objmesh *m, const int32_t *tri2poly, const double x[3],
                   const double n[3], int32_t skip);

#endif
