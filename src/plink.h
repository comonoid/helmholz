/* plink.h — ОПЕРАТОР ПЕРЕНОСА СВЯЗЯМИ ПО ЛЕСТНИЦЕ (PLAN_ELEMENTS.md, §84, §85).
 *
 * ЗАЧЕМ ЭТО ВМЕСТО СВИПА. Разбор 08-01 (§85): взаимодействие происходит только на
 * ПОВЕРХНОСТЯХ — отражение и преломление при постоянном показателе суть события
 * геометрической оптики на границе, и интерполяция нормали этого не меняет. Значит
 * направление СВЯЗАННОЕ: оно задано парой точек и нормалью, а не является
 * независимой переменной. Представлять его набором ординат нечего, переносить
 * свипом нечего. Свип и ординаты нужны ровно при объёмном рассеянии, которого в
 * цели нет.
 *
 * ЧТО ХРАНИТСЯ. Связь `(i, j)` с коэффициентом переноса. Оператор НЕ ЗАВИСИТ ни от
 * света, ни от камеры (это записано в основаниях проекта), поэтому собирается один
 * раз, а смена освещения есть умножение на вектор. Многократные отражения выходят
 * рядом Неймана сами, без всякой отдельной машинерии: каждая итерация добавляет
 * один порядок.
 *
 * ИЕРАРХИЯ — ТА ЖЕ ЛЕСТНИЦА LOD. Близкие пары держатся на мелких узлах, дальние на
 * грубых: одна связь вместо всех пар потомков. Уровень выбирается ТЕМ ЖЕ критерием,
 * что срез камеры, и это не совпадение: связь `i → j` допустима там, где `j` виден
 * из `i` под углом меньше допуска. Формула та же `размер / расстояние < ε`, только
 * вместо глаза стоит другой элемент. Никакого нового порога на всю схему.
 *
 * ПРЯМОЙ СВЕТ ОТДЕЛЬНЫМ МЕХАНИЗМОМ НЕ НУЖЕН. Лампа — элемент с ненулевым `Le`, и её
 * вклад идёт обычной связью, коэффициент которой считается ЗАМКНУТОЙ ФОРМОЙ. Отсюда
 * исчезает разом всё, чем мы мучились: лучевой эффект (его неоткуда взять — нет
 * квадратуры по направлению), «первый порядок» как особый случай, пробы видимости
 * как отдельный механизм и классификация источников по угловому размеру.
 *
 * ВИДИМОСТЬ — ЕДИНСТВЕННОЕ, ЧТО ТРЕБУЕТ ВЫБОРКИ, и она берётся ПРИ СБОРКЕ, а не в
 * решении: доля незаслонённых проб между парой. Это законные лучи: их число не
 * зависит ни от кадра, ни от числа отскоков, и при статичной геометрии они
 * считаются один раз навсегда.
 */
#ifndef HZ_PLINK_H
#define HZ_PLINK_H

#include "plod.h"
#include "polygon.h"
#include "pray.h"

typedef struct {
  int32_t i, j; /* приёмник и излучатель: узлы лестницы */
  /* ФОРМ-ФАКТОР, безразмерный: доля потока `j`, приходящая на `i`, с учётом
   * заслонения. Прежняя редакция называла его «облучённостью при единичном
   * радиансе», и это расходилось с кодом ровно на `π` (А195): облучённость есть
   * `π·f`. Величина выбрана форм-фактором СОЗНАТЕЛЬНО — у неё есть проверяемая
   * подпись, `Σ_j f_ij = 1` в замкнутой сцене, и она печатается каждым прогоном. */
  double f;
} hz_link;

typedef struct {
  hz_link *l;
  int64_t n, cap;
  /* ЗАМЕРЫ СБОРКИ — часть выхода, а не отладка. Судьба всей архитектуры решается
   * числом связей: `O(n log n)` — работает, ближе к `n²` — не работает, и узнать
   * это надо было ДО решателя (§84). */
  int64_t nvisit;    /* пар, рассмотренных при дроблении */
  int64_t nrefine;   /* раз, когда пара дробилась */
  int64_t nzero;     /* связей отброшено: нулевой коэффициент либо полное заслонение */
  int64_t nray;      /* проб видимости */
  int64_t nmax_node; /* наибольшее число связей у одного узла */
  /* Отброшенных НА ГРУБОМ уровне: такая отбраковка рубит целое поддерево, потому
   * что усреднённая нормаль узла — плохая замена нормалям его потомков. Замерено
   * (§86.3): отложить её до листьев стоит втрое больше связей и даёт `Σf`
   * `0.607 → 0.653`, то есть не там потеря. Счётчик оставлен как показатель. */
  int64_t nzero_coarse;
  /* ДОЛЯ СВЯЗЕЙ С ИЗЛУЧАТЕЛЕМ-ЛИСТОМ (А207). Точный форм-фактор ставится только
   * там, где у излучателя есть край, то есть на уровне 0; у внутренних узлов
   * остаётся диск. Без этого числа промах предсказания списался бы на формулу,
   * тогда как формула могла просто не применяться. Вторая доля взвешена
   * коэффициентом: важно не сколько связей, а сколько энергии они несут. */
  int64_t nlink_leaf;
  double wleaf; /* доля Σf, пришедшая связями с излучателем уровня 0 */
  double t_build;
  /* ПОДПИСЬ ЗАМКНУТОСТИ. `Σ_j f_ij` по листу С УЧЁТОМ ПРЕДКОВ (грубая связь
   * приносит энергию всем потомкам, значит и в сумму листа входит) обязана быть
   * единицей в замкнутой сцене. Хвост, а не среднее: §4 требует мерить хвост, и
   * `min`/`max` хвостом не являются — это по одному узлу (А194). Проценты взяты
   * по ПЛОЩАДИ, потому что вклад в картинку идёт площадью. */
  double sf_mean, sf_min, sf_max;
  double sf_p10, sf_p50, sf_p90;
  double sf_lowfrac; /* доля площади листьев, где `Σf < 0.9` */
} hz_linkset;

/* ЭЛЕМЕНТЫ, НА КОТОРЫХ ЖИВЁТ ЗАДАЧА. Узел лестницы сам по себе геометрии не несёт
 * (у него плоскость, площадь и опорная точка), а для коэффициента нужен полигон.
 * Поэтому связи строятся по СРЕЗУ: набор узлов, покрывающий сцену без пересечений,
 * плюс его полигоны. Для иерархии при этом используется вся лестница — дробление
 * идёт вниз от корней. */
typedef struct {
  const hz_lod *L;
  const hz_pray *g; /* сетка лучей по геометрии сцены — только для видимости */
  /* ПОЛИГОНЫ — ради ТОЧНОГО форм-фактора (§87). Узел уровня 0 есть участок
   * сегментации, и у него ЕСТЬ край; у внутренних узлов края нет, там остаётся
   * диск. `NULL` — считать всё диском. */
  const hz_polyset *ps;
} hz_scene;

/* Настройки сборки. Три последних поля — ЗАМЕРЫ И КОНТРОЛИ, а не режимы работы:
 * ими снимаются числа §86–§87, и в рабочем прогоне все три нулевые. */
typedef struct {
  double eps; /* тот же угловой допуск, что у среза */
  int nvis;   /* проб видимости на связь по каждой оси (`nvis²`); `0` = `2` */
  int noself; /* без самопар `(a,a)` */
  int disk;   /* НК3: точечно-дисковый коэффициент вместо точного */
  int noclip; /* НК4: точный форм-фактор БЕЗ отсечения полуплоскостью */
} hz_linkcfg;

/* Собрать связи. `eps` — тот же угловой допуск, что у среза; `nvis` — проб
 * видимости на связь по каждой оси (`nvis²`). `0` для `nvis` читается как `2`.
 *
 * `noself = 1` ВЫКЛЮЧАЕТ САМОПАРЫ — это замер, а не режим. Самопара `(a, a)`
 * есть обмен светом ВНУТРИ одного узла, то есть между его потомками. Без неё
 * потомки общего корня не видят друг друга совсем: на зале это 22 корня по ~45
 * листьев, и `Σf` падало до `0.596` при обязательной единице. Выключатель нужен,
 * чтобы это число было измерено, а не выведено (А195).
 *
 * Самопара дробится ОСОБО — раскрывается во ВСЕ пары детей, включая их
 * собственные самопары, — а не по общему правилу «дробить того, кто больше»: при
 * тождественном продвижении у предка и единственного ребёнка ОДНА опорная точка,
 * `r² = 0`, коэффициент нулевой, и пара умерла бы, не дойдя до настоящих детей. */
int hz_links_build(hz_linkset *S, const hz_scene *sc, const hz_linkcfg *cfg);

/* САМОПРОВЕРКА ТОЧНОГО ФОРМ-ФАКТОРА НА АНАЛИТИКЕ — гоняется ПЕРВОЙ, до всякой
 * сцены (А205). Возвращает худшую невязку против замкнутой формы; через
 * указатели отдаёт сами числа: `f_big` — огромный квадрат над приёмником
 * (обязан быть `1`), `f_unit` и `ref_unit` — квадрат `a = h` против точного
 * `(4/π)·X/√(1+X²)·atan(X/√(1+X²))`. */
double hz_links_ff_selftest(double *f_big, double *f_unit, double *ref_unit);

/* `Σ_j f_ij` ПОУЗЛОВО, с учётом предков; `sf` — на `L->nnd`. Нужно потребителю,
 * чтобы сверить подпись замкнутости с НЕЗАВИСИМОЙ ссылкой лучами: пока сверялись
 * только ручки внутри одной формулы, величина не двигалась вовсе (А204). */
void hz_links_sf(const hz_linkset *S, const hz_lod *L, double *sf);

/* ЭТАЛОН ПОЛНЫМ ПЕРЕБОРОМ. Для каждого `stride`-го листа `Σf` считается по ВСЕМ
 * листьям сцены, без иерархии, тем же точным форм-фактором. Различает две
 * причины, которые ни `Σf`, ни ссылка лучами по отдельности не различают:
 * теряет ли энергию ДРОБЛЕНИЕ или сам КОЭФФИЦИЕНТ. `sf_novis` — без видимости,
 * `sf_vis` — с ней; порознь, потому что заслонение есть законная причина
 * недобора, а пропущенная пара — нет. Возвращает число заполненных мест. */
int hz_links_sf_brute(const hz_scene *sc, int stride, int nvis, double *sf_novis, double *sf_vis,
                      int32_t *node, int cap);
void hz_links_free(hz_linkset *S);

/* Решить `E = E₀ + F·(ρE)` итерациями. `Le`, `rho` — по полигонам среза; `E` —
 * выход, облучённость на полигон. Возвращает число итераций; `tol` — по
 * относительному изменению. Многократные отражения суть эти самые итерации. */
/* ОБМЕН МЕЖДУ УРОВНЯМИ ОБЯЗАТЕЛЕН, И ЭТО НЕ ОПТИМИЗАЦИЯ. Узлы разных уровней
 * описывают ОДНУ И ТУ ЖЕ поверхность: связь, заведённая на грубом узле, приносит
 * энергию всем его потомкам, а излучение потомков обязано подниматься к предку,
 * иначе грубая связь несёт неверный радианс.
 *
 * ПОПРАВКА 08-01, ЗАМЕРЕНО: «без обмена картинка выходит чёрной» БОЛЬШЕ НЕ
 * ВОСПРОИЗВОДИТСЯ и цитироваться не может. Негативный контроль НК1 (§86,
 * `prad nopull`) даёт `flux0` `4.28e+01` против `5.13e+01` — падение на 16 %, а
 * не почернение. Чёрная картинка была у РЕДАКЦИИ ДО ПРАВКИ, где ещё делили на
 * `π` и источник сидел на всех уровнях сразу. Подъём остаётся обоснованным
 * (16 % — не ноль), но обоснование теперь слабее заявленного.
 *
 *   ВНИЗ (push): облучённость наследуется — она на единицу площади, значит
 *   передаётся потомку как есть.
 *   ВВЕРХ (pull): радианс предка есть средневзвешенное по ПЛОЩАДИ радиансов детей.
 *
 * Решается по-прежнему итерациями, и каждая по-прежнему добавляет один порядок
 * отражения.
 *
 * НЕВЯЗКА МЕРИТ ИЗМЕНЕНИЕ `B` ЗА ПОЛНУЮ ИТЕРАЦИЮ — снимок начала против снимка
 * конца, — и на неподвижной точке она ноль ПО ПОСТРОЕНИЮ. Прежняя редакция
 * сравнивала `Le + ρ·acc` с `B`, а у внутренних узлов `B` тут же перезаписывается
 * подъёмом: две разные величины, и разность между ними на неподвижной точке не
 * ноль. Отсюда и был потолок в 200 итераций при решении, замершем на четвёртой.
 * Мера — МАКСИМУМ относительного изменения, а не среднеквадратичное: подмена
 * `L∞` на `L2` в этом проекте ловилась трижды (Г40/Г44, А20).
 *
 * ЧЕГО ЭТА НЕВЯЗКА НЕ ЗНАЧИТ (А193): она мерит СТАЦИОНАРНОСТЬ, а не верность.
 * Неподвижная точка с потерянной энергией даст ноль и будет объявлена сходимостью.
 * Верность свидетельствуют `Σf` в `hz_linkset` и сверка с независимым решателем.
 *
 * `reshist` — если не `NULL`, туда пишутся невязки по итерациям (не более
 * `maxit`); нужны, чтобы видеть ОТНОШЕНИЕ соседних, то есть измеренное сжатие.
 * `nopull = 1` выключает подъём — негативный контроль НК1, а не режим. */
int hz_links_solve(const hz_linkset *S, const hz_lod *L, const double *Le, const double *rho,
                   double *B, double tol, int maxit, double *reshist, int nopull);

#endif
