/* plod.h — ИЕРАРХИЧЕСКОЕ ОГРУБЛЕНИЕ И СРЕЗ LOD (PLAN_ELEMENTS.md, §54…§57, О16).
 *
 * ЗАЧЕМ. До сих пор уровни огрубления считались НЕЗАВИСИМО: каждый прогон с
 * нуля, разбиение у соседних уровней разное. Поэтому камера не могла ВЫБИРАТЬ
 * уровень — только пересчитывать всё, — а на стыке уровней появлялись щели (А31).
 * Это стояло главным незакрытым пунктом в каждом докладе с §15.
 *
 * КОНСТРУКЦИЯ (предложена пользователем 07-30, §54): уровень `L+1` строится ИЗ
 * ЭЛЕМЕНТОВ уровня `L` — примерно по четыре смежных, — поэтому вложенность
 * получается по построению, а с ней и право брать срез.
 *   - смежность по ОБЩИМ РЁБРАМ, не по общим вершинам (А130: точечное касание
 *     дало бы неманифолдный элемент с защемлённым контуром);
 *   - приоритет пары — косинус угла между нормалями (плоское сливается первым,
 *     углы откладываются на грубые уровни; лицо и изнанка тонкой ножки дают
 *     `−1` и уходят в самый конец САМИ);
 *   - при равном угле — форма объединения по обезразмеренному `P/√A`
 *     (минимум `2√π ≈ 3.545` у круга): §55, «близость к правильному
 *     многоугольнику». Сырое `P/A` для сравнения уровней не годится — оно мерит
 *     размер, — но печатается как плотность края, то есть показатель ЦЕНЫ (А52);
 *   - ворота — ДОПУСК уровня. Четвёрка есть СТРУКТУРА, допуск есть КРИТЕРИЙ, и
 *     сокращение «до четырёх раз» выходит следствием, а не целью (§54.2, §46).
 *     Отклонение от четырёх само есть замер: оно показывает, где сцена перестаёт
 *     быть гладкой на этом масштабе.
 *
 * `dmax` УЗЛА СЧИТАЕТСЯ ОТ ИСХОДНЫХ ТРЕУГОЛЬНИКОВ, А НЕ ОТ ДЕТЕЙ (А134). Иначе
 * полная ошибка против входа стала бы суммой по лестнице — на шести уровнях до
 * шести допусков, — и «`dmax ≤ δ_L`» перестало бы что-либо значить. Это тот же
 * класс, что А8: занижающий промах, накапливающийся по уровням.
 *
 * УРОВЕНЬ — ВСЕГДА РАЗБИЕНИЕ ВСЕЙ СЦЕНЫ. Элемент, который слить не удалось,
 * переходит на следующий уровень БЕЗ ИЗМЕНЕНИЙ (тождественное продвижение).
 * Тогда срез определён просто: для каждого исходного полигона берётся САМЫЙ
 * ГРУБЫЙ предок, удовлетворяющий `dmax < ε·R`. Лестница при этом остаётся
 * неоднородной по глубине — ради чего дерево и нужно.
 *
 * КАМЕРА В ДЕРЕВЕ НЕ ХРАНИТСЯ (А133): в узле только `dmax` (геометрия),
 * расстояние `R` вычисляется при СРЕЗЕ. `ε` хранится рядом с деревом и сверяется
 * при срезе (А131), иначе ступени не совпадут со срезом.
 */
#ifndef HZ_PLOD_H
#define HZ_PLOD_H

#include "poly_seg.h"
#include "polygon.h"
#include "scene_obj.h"

typedef struct {
  int32_t level;  /* 0 — исходные полигоны сегментации */
  int32_t parent; /* −1 у корня своего уровня */
  double n[3], off;
  double dmax;       /* ТОЧНО, по опорным точкам ИСХОДНЫХ полигонов узла (А134) */
  double area_surf;  /* сумма площадей исходных треугольников */
  double area_elem;  /* площадь элемента в его плоскости (`mom[0]`), А128 */
  double perim;      /* периметр границы узла, м */
  double cx, cy, cz; /* опорная точка (центр площади) — для среза */
  int32_t nmemb;     /* исходных полигонов в узле */
} hz_lodnode;

typedef struct {
  hz_lodnode *nd;
  int32_t nnd, ndcap;
  int32_t *lab;  /* nlev × np: номер узла для каждого исходного полигона */
  int32_t nlev;  /* уровней всего, включая нулевой */
  int32_t np;    /* исходных полигонов */
  double eps;    /* угловой размер пикселя, под который строилась лестница (А131) */
  double delta0; /* допуск нулевого уровня */
  /* ЗАМЕРЫ ПОСТРОЙКИ — печатаются, а не отлаживаются. */
  int64_t npair_edge;  /* пар, смежных по РЕБРУ */
  int64_t npair_point; /* пар, смежных лишь ПО ТОЧКЕ — отвергнуто (А130) */
  int64_t ngate_rej;   /* групп, отвергнутых воротами по допуску */
  int64_t nident;      /* тождественных продвижений (слить не удалось) */
  int64_t nlow_rej;    /* групп, отсеянных НИЖНЕЙ оценкой без подгонки */
  double area_grow;    /* худшее отношение площади элемента к площади поверхности */
  int bands;           /* тактика полос по двугранному углу (§59) в слиянии уровня */
  int bycount;         /* ВТОРАЯ ТАКТИКА (§60): критерий уровня — ЧИСЛО, а не допуск */
  /* ДВУГРАННЫЙ УГОЛ ПО ВСЕЙ ЛЕСТНИЦЕ (§59): сумма по уровням, корзины по 30°. */
  int64_t dih_hist[12];
  int64_t ndih_conv, ndih_conc, ndih_flat;
} hz_lod;

/* Построить лестницу от `sg` (сегментация) вверх, пока сливается либо пока
 * уровней меньше `maxlev`. Допуск уровня `L` есть `delta0 · 2^L`. */
int hz_lod_build(hz_lod *L, const hz_objmesh *m, const hz_pseglist *sg, const hz_polyset *ps,
                 double delta0, int maxlev, double eps);
void hz_lod_free(hz_lod *L);

/* Срез камеры: для каждого исходного полигона выбирается самый грубый предок с
 * `dmax < eps·R`. В `out` пишется номер выбранного узла на полигон; возвращается
 * число РАЗЛИЧНЫХ узлов среза. */
int32_t hz_lod_cut(const hz_lod *L, const double eye[3], double eps, int32_t *out);

/* Разметка треугольников по срезу — вход для `hz_poly_build`, то есть срез
 * становится обычным набором полигонов и всё, что ниже, работает без правок. */
int hz_lod_seglist(const hz_lod *L, const hz_objmesh *m, const hz_pseglist *sg, const int32_t *cut,
                   hz_pseglist *so);

/* ВТОРОЙ ПОСТРОИТЕЛЬ: УРОВЕНЬ СТРОИТСЯ УЖЕ ПРОВЕРЕННЫМ `hz_merge`.
 *
 * ПОЧЕМУ ОН ПОНАДОБИЛСЯ. Первый построитель (выше) берёт кандидатов по СМЕЖНОСТИ
 * ПО РЕБРУ, и замер 07-30 на городе показал, что этого мало: сокращение
 * `1.00…1.27×` на уровень вместо четырёх, итог `301 430 → 124 912` при δ = 6.4 м,
 * тогда как плоское слияние даёт `24 320` уже при δ = 2 м. Причина названа
 * замером: у осепараллельных блоков соседи ПО РЕБРУ почти всегда перпендикулярны,
 * поэтому смежность запрещает почти все слияния — а `hz_merge` берёт кандидатов
 * ПО БЛИЗОСТИ и сливает компланарные куски РАЗНЫХ блоков.
 *
 * ЧТО ЭТО ДАЁТ. Уровень `L+1` есть `hz_merge` над разбиением уровня `L` с
 * допуском `2^{L+1}·δ₀` и БЕЗ цели по числу (§46). Вложенность сохраняется по
 * построению — слияние работает над группами предыдущего уровня, — а качество
 * равно измеренному у плоского слияния, потому что это тот же код: минимакс,
 * конус, неперекрытие, все замеры О7…О21 в силе.
 * `dmax` узла при этом приходит из `so->seg[g].dmax`, а он считается по ВСЕМ
 * треугольникам от плоскости группы, то есть от ИСХОДНОЙ геометрии (А134).
 */
/* ДВЕ ТАКТИКИ ЛЕСТНИЦЫ (§60, решение пользователя 07-30). `bycount = 0` —
 * критерием служит ДОПУСК `2^L·δ₀`, и число элементов выходит следствием: сцены
 * получаются простые и непростые, как и должно быть. `bycount = 1` — критерием
 * служит ЧИСЛО (цель `1/4` от предыдущего уровня), допуск снят с габарита сцены
 * и не ограничивает, а достигнутый `dmax` становится ЗАМЕРОМ. Так делают почти
 * все, и ход обоснован: замер на городе показал, что уровни 0…3 по допуску
 * сокращают лишь `1.03…1.21x` — ступени стоят там, где сливать нечего. */
int hz_lod_build_merge(hz_lod *L, const hz_objmesh *m, const hz_pseglist *sg, const hz_polyset *ps0,
                       double delta0, int maxlev, double eps, int bands, int bycount);

#endif
