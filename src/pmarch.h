/* pmarch.h — МАРШ ЛУЧА ПО ЯЧЕЙКАМ СРЕЗА (§242 Ф2, план §247, шаг О71).
 *
 * ЗАЧЕМ. Структура О70 самоценности не имеет: она сделана ради быстрого
 * прохождения фронта. Ф2 меряет два её свойства, и оба проверяются ЗНАКОМ:
 * касания как функция расстояния (на октаву обязано быть постоянно) и
 * распределение длины шага (обязано быть двугорбым — длинные прыжки по пустоте,
 * короткие у геометрии).
 *
 * ДВА ЧИСЛА, А НЕ ОДНО (А495). «Касания» есть произведение двух разных вещей:
 * числа ШАГОВ (сколько ячеек пересёк луч — свойство ДЕРЕВА) и числа ПОСЕЩЕНИЙ
 * УЗЛОВ (сколько узлов пришлось потрогать, чтобы ячейку найти, — свойство
 * ПОИСКА). Здесь считаются оба порознь; логарифм предсказывается для ШАГОВ.
 * Поиск сделан спуском ОТ КОРНЯ сознательно: он стоит глубину дерева на шаг и
 * потому даёт ВЕРХНЮЮ оценку работы поиска. Связи между соседями стоили бы
 * O(1), но их нет в структуре, а заводить их — правка ПРЕДСТАВЛЕНИЯ, которая
 * этому шагу запрещена прямым указанием (§247).
 *
 * ПОЛУОТКРЫТОЕ СОГЛАШЕНИЕ БЕРЁТСЯ ВДОЛЬ ЛУЧА, И ЭТО НЕ ПРОИЗВОЛ. У О70 ячейка
 * есть `[lo, hi)` (А475). Для марша такого правила НЕ ХВАТАЕТ: при `d < 0` точка
 * выхода лежит ровно на `lo` текущей ячейки, по правилу `>= lo` принадлежит ЕЙ
 * ЖЕ, и марш зацикливается. Поэтому при спуске равенство разрешается ПО ЗНАКУ
 * НАПРАВЛЕНИЯ: `[lo, hi)` при `d >= 0` и `(lo, hi]` при `d < 0`. Тогда точка
 * выхода принадлежит РОВНО следующей ячейке, покрытие луча точное — без щелей и
 * без перекрытий, — и подпорка «сдвинуть на ulp» не нужна вовсе. При `d > 0`
 * правило совпадает с правилом О70 дословно.
 *
 * ПАРАМЕТР ЛУЧА — ПЕРВИЧНОЕ СОСТОЯНИЕ, А ТОЧКА ПРОИЗВОДНА. Точка выхода
 * считается как `o + t·d`, но координата ПО ОСИ ВЫХОДА ставится РАВНОЙ границе
 * точно, а не получается счётом (тот же приём, что `pc_lerp` в `pclip.c`): иначе
 * округление вернуло бы точку внутрь покинутой ячейки. Накопления ошибки нет —
 * `t` считается от начала луча, а не приращениями.
 */
#ifndef HZ_PMARCH_H
#define HZ_PMARCH_H

#include "ptree.h"

/* ПРЕДЕЛ ЧИСЛА ШАГОВ НА ЛУЧ. Не «сколько не жалко»: у дерева глубины 12 луч
 * поперёк сцены пересекает не более 3·2¹² ≈ 12 288 ячеек самого мелкого уровня
 * (по одной на грань каждой оси), и запас вчетверо покрывает любой законный
 * случай. Срабатывание СЧИТАЕТСЯ и печатается: молчаливый обрыв читался бы как
 * «луч столько и прошёл». */
#define HZ_PMARCH_MAXSTEP 49152

/* ПРАВИЛО СРЕЗА. Или пол в пикселях от `eye` (как в О70), или ФИКСИРОВАННЫЙ
 * уровень. Второе нужно потому, что пол `εR` камерозависим и длинные шаги вдали
 * получились бы САМИ СОБОЙ — ячейка при нём растёт с расстоянием по построению
 * (А496). Двугорбость обязана пережить и фиксированный уровень. */
typedef struct {
  double eye[3];
  double eps;   /* радиан на пиксель */
  double pxcut; /* пол в пикселях; `<= 0` — срез ДО ЛИСТЬЕВ */
  int fixlev;   /* `>= 0` — срез по этому уровню; `-1` — по полу */
} hz_pmarch_cut;

typedef struct {
  const hz_ptree *T;
  hz_pmarch_cut cut;
  double o[3], d[3]; /* начало и направление; `d` нормировано вызывающим */
  double tin, tout;  /* отрезок луча внутри корня */
  /* --- текущая ячейка --- */
  int32_t nid;
  int lev;
  /* ЧЕМ ОСТАНОВЛЕН СПУСК: `1` — ЛИСТОМ дерева, `0` — ПОЛОМ среза. Без этого
   * различия скан по полу читается как «параметр ни на что не влияет», тогда
   * как на деле он может просто НЕ ДОХОДИТЬ до дела — лист кончается раньше,
   * чем пол начинает работать (урок О67: пустой скан требует диагностики, а не
   * толкования). */
  int byleaf;
  double t0, t1;  /* её отрезок вдоль луча: `t0` включительно, `t1` нет */
  int64_t visits; /* узлов пройдено при поиске ИМЕННО ЭТОЙ ячейки */
  /* --- итоги луча --- */
  int64_t nstep, nvisit;
  int64_t ncap;   /* сколько раз сработал предел шагов */
  int64_t nbreak; /* разрывов покрытия: начало шага не совпало с концом прошлого */
} hz_pmarch;

/* Начать марш. Возврат `0`, если луч коробки корня не задевает. */
int hz_pmarch_begin(hz_pmarch *M, const hz_ptree *T, const hz_pmarch_cut *cut, const double *o,
                    const double *d);
/* Перейти к следующей ячейке. Возврат `0`, когда луч вышел из корня. */
int hz_pmarch_next(hz_pmarch *M);

#endif
