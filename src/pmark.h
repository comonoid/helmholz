/* pmark.h — ПОМЕТКИ ОТ КАМЕРЫ: до какого уровня стоит спускаться в этом объёме.
 *
 * ЗАЧЕМ (разбор с пользователем 08-05). Замерено, что разы даёт только то, что
 * меняет УРОВЕНЬ, по которому идёт фронт: пол прохода (21× между 3 и 64
 * пикселями) и пирамида камеры (3.6×). Всё, что меняет содержимое ячейки, а не
 * её размер, давало доли процента: огрубление тени 1.001×, одноплоскостные
 * ячейки ≤1.5×. Значит нужен ТРЕТИЙ ограничитель уровня — и он не выводится на
 * ходу, потому что уровень выбирается ДО того, как посмотрели, что внутри.
 *
 * ОТКУДА ОН БЕРЁТСЯ. Из дешёвого предварительного прохода ОТ КАМЕРЫ ПО КРУПНЫМ
 * УЗЛАМ: он один раз обходит верхние уровни и кладёт каждому узлу предельный
 * уровень детализации. Дёшев он по построению — крупных узлов проценты от всех
 * (у Rungholt уровни 0…8 это сотни тысяч из тридцати миллионов).
 *
 * ПОЧЕМУ ЭТО НЕ ПОЛЕ В УЗЛЕ, А БОКОВАЯ ТАБЛИЦА. Пометка зависит от КАМЕРЫ, то
 * есть от прохода, а А133 запрещает хранить проходозависимое в дереве («камера в
 * дереве не хранится, R вычисляется при СРЕЗЕ»). Приём для этого случая в
 * проекте уже выбран: боковая таблица с ключом-ячейкой (`PLAN_CUT.md` Г3/Г4),
 * живущая кадр. Дерево остаётся переиспользуемым.
 *
 * ЧТО ЭТО ОДНОВРЕМЕННО ПРО ОБЪЁМ И ПРО ДЕТАЛИЗАЦИЮ: величина лежит в УЗЛЕ, то
 * есть в объёме, а говорит про УРОВЕНЬ, то есть про детализацию. Одна и та же
 * запись отвечает на оба вопроса, потому её и хватает одной.
 */
#ifndef HZ_PMARK_H
#define HZ_PMARK_H

#include "ptree.h"

/* ДО КАКОГО УРОВНЯ ИДЁТ САМ ПРОХОД ПОМЕТОК. Глубже он не спускается — иначе
 * перестанет быть дешёвым и превратится во второй полный обход. Восьмой уровень
 * у Rungholt (655 м) есть ячейка 2.6 м: крупнее любого решения, которое пометка
 * принимает, и мельче любого, которое ей поручено. */
#define HZ_PMARK_LEVEL 8

/* НА СКОЛЬКО УРОВНЕЙ ОТПУСКАЕТСЯ ПОЛ ВНЕ КОНУСА. Не «остановиться совсем»:
 * ячейка вне кадра ЗАСЛОНЯЕТ, её тень падает внутрь кадра (§241.5), и выбросить
 * её нельзя. Двойка — то же сознательно осторожное число, что у огрубления
 * заслонённого; замерено, что полное схлопывание дало бы 7.5× против 3.6×, и
 * разница есть цена этой осторожности. */
#define HZ_PMARK_OUT_LEVELS 2

/* `255` — предела нет. Иначе: предельный уровень, глубже которого спускаться не
 * надо ни фронту, ни кому-либо ещё в этом кадре. */
#define HZ_PMARK_NONE 255

typedef struct {
  double eye[3];   /* глаз */
  double fwd[3];   /* направление взгляда, нормировано */
  double fr[6][4]; /* шесть плоскостей пирамиды, нормали ВНУТРЬ */
  double eps;      /* радиан на пиксель */
  double px;       /* пол в пикселях */
  int level;       /* до какого уровня идёт проход пометок */
  int outlevels;   /* на сколько уровней отпускать вне конуса */
  /* --- счётчики, часть выхода --- */
  int64_t nnode, nout, nin;
} hz_pmark_cfg;

/* Построить таблицу пометок. `mark` — массив на `T->nnd` байт. */
void hz_pmark_build(const hz_ptree *T, hz_pmark_cfg *C, unsigned char *mark);

#endif
