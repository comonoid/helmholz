/* Проб на полигон ПО КАЖДОЙ ОСИ при проверке НЕПЕРЕКРЫТИЯ.
 *
 * ОБОСНОВАНИЕ ИСПРАВЛЕНО 07-29 ПО АУДИТУ: прежнее говорило «16 проб по каждой
 * оси обнаруживают такое перекрытие заведомо», тогда как в коде стоит ВОСЕМЬ.
 * Обоснование относилось к другому числу, чем сама константа, и держать такое
 * рядом нельзя: оно читается как вывод, а является опиской.
 *
 * ЧТО ВЕРНО СЕЙЧАС. Порог перекрытия — доля `1/16` (см. `overlaps`), сетка
 * `8×8 = 64` пробы, то есть на долю `1/16` приходится в среднем 4 пробы.
 * Обнаружение поэтому не «заведомо», а ВЕРОЯТНОСТНОЕ, и односторонность его не
 * доказана — доказать её обязан О13 сравнением с ТОЧНЫМ пересечением
 * многоугольников на подвыборке пар. До этого замера число проб не менять: оно
 * входит в критерий, а не в скорость. */
#define PM_OVSAMP 8

typedef struct {
  int32_t a, b;
  double err;
} pm_pair;

/* Порядок ПОЛНЫЙ: сперва ошибка, потом номера. Сравнение по одной ошибке
 * оставляло равные пары на произвол `qsort`, а от их порядка зависит, какие
 * группы срастутся первыми. Тогда сеточный набор кандидатов и переборный,
 * СОВПАДАЯ как множества, давали бы разный выход, и проверку «сетка равна
 * перебору» нельзя было бы поставить вовсе.
 *
 * ЭТО ЖЕ И ЕСТЬ ДОВОД ПОБИТОВОСТИ ПРИ ПОТОКАХ (А12): раз порядок полный, а пары
 * попарно различны, отсортированный массив однозначно определён МНОЖЕСТВОМ пар,
 * и порядок, в котором потоки их выдали, безразличен. Нестабильность `qsort`
 * при полном порядке ничего не меняет.
 *
 * ФЛАГ `pm_notie` — НЕГАТИВНЫЙ КОНТРОЛЬ, а не режим. Он снимает доопределение,
 * и тогда выход ОБЯЗАН зависеть от порядка эмиссии, то есть от числа потоков.
 * Переменная файловая, потому что `qsort` не передаёт контекста; ставится один
 * раз в начале `hz_merge`, из одного потока, до всякой сортировки. */
static int pm_notie = 0;

static int cmp_pair(const void *x, const void *y) {
  const pm_pair *p = x, *q = y;
  if (p->err < q->err) return -1;
  if (p->err > q->err) return 1;
  if (pm_notie) return 0;
  if (p->a != q->a) return (p->a < q->a) ? -1 : 1;
  if (p->b != q->b) return (p->b < q->b) ? -1 : 1;
  return 0;
}

/* ПЕРЕМЕШИВАНИЕ ДЛЯ НЕГАТИВНОГО КОНТРОЛЯ `random` — ФУНКЦИЯ ПАРЫ, А НЕ ПОРЯДКА
 * ЭМИССИИ (А13). Был ЛЦГ, продвигаемый по мере выдачи пар: при потоках он
 * рассыпается, а на этом контроле стоят Ш7, приёмка О12 и приёмка О20. Хеш от
 * `(a, b)` делает величину воспроизводимой лучше, чем прежде, и от обхода
 * независимой вовсе. Ступени те же, что у `mix64` в `src/polygon.c`, — качество
 * перемешивания здесь не роскошь: пространственно связная «случайность»
 * ослабила бы контроль, оставшись с виду тем же (А61). */
static uint64_t pm_mix64(uint64_t k) {
  k ^= k >> 33;
  k *= 0xFF51AFD7ED558CCDULL;
  k ^= k >> 33;
  k *= 0xC4CEB9FE1A85EC53ULL;
  k ^= k >> 33;
  return k;
}

static int32_t uf_find(int32_t *p, int32_t x) {
  while (p[x] != x) {
    p[x] = p[p[x]];
    x = p[x];
  }
  return x;
}

/* Мировая коробка полигона.
 *
 * КРАЙ ЕСТЬ ПРОЕКЦИЯ, И КОРОБКА ПО НЕМУ ПОЛИГОН НЕ НАКРЫВАЕТ. Найдено аудитом
 * плана 07-29. Край хранится в местных `(u,v)` (`polygon.h`), а
 * `hz_poly_world` возвращает `org + u·eu + v·ev` — точку СТРОГО в плоскости
 * полигона. Треугольники же отходят от неё до `P->dmax`, и у зала при δ = 45 мм
 * это `0.9997 δ` (Ш1), то есть почти весь допуск сегментации. Коробка по краю
 * получалась ЗАНИЖЕННОЙ, а по ней работают оба отбора — и раскладка по ячейкам
 * сетки, и точная проверка `near` в `pm_emit`. Значит терялись законные пары:
 * треугольники сходились ближе `δ`, а проекции краёв — нет.
 * Проверка «сетка = перебор» этого поймать не могла: оба пути берут одну и ту
 * же коробку, и совпадали они друг с другом, а не с геометрией.
 * ДОБАВКА ТОЧНАЯ, А НЕ ЗАПАС: смещение вдоль нормали на `d` меняет координату
 * `c` ровно на `d·n_c`, поэтому раздутие на `dmax·|n_c|` по каждой оси и
 * необходимо, и достаточно.
 *
 * ЗАПАСНОЙ ПУТЬ ПО ТРЕУГОЛЬНИКАМ — ЯВНЫЙ. Полигон без края (все петли короче
 * трёх вершин отброшены в `hz_poly_build`) давал коробку ВЫВЕРНУТУЮ
 * (`lo = 1e300`), а такая коробка отвергает любую пару в `pm_emit`: полигон
 * молча выпадал из огрубления целиком. На обеих сценах таких ноль (измерено), но
 * «ноль сегодня» — не свойство схемы, и именно на подразумеваемом запасном пути
 * села первая редакция критерия. */
static void pbox(const hz_polyset *ps, const hz_objmesh *m, int32_t k, double lo[3], double hi[3],
                 int64_t *nbox_tri) {
  const hz_poly *P = &ps->p[k];
  for (int a = 0; a < 3; a++) {
    lo[a] = 1e300;
    hi[a] = -1e300;
  }
  for (int32_t l = P->l0; l < P->l0 + P->nloop; l++)
    for (int32_t b = ps->loop[l]; b < ps->loop[l + 1]; b++) {
      double x[3];
      hz_poly_world(P, ps->bv[(size_t)b * 2], ps->bv[(size_t)b * 2 + 1], x);
      for (int a = 0; a < 3; a++) {
        if (x[a] < lo[a]) lo[a] = x[a];
        if (x[a] > hi[a]) hi[a] = x[a];
      }
    }
  if (lo[0] <= hi[0]) {
    for (int a = 0; a < 3; a++) {
      double e = P->dmax * fabs(P->n[a]);
      lo[a] -= e;
      hi[a] += e;
    }
    return;
  }
  (*nbox_tri)++;
  for (int32_t q = 0; q < P->ntri; q++) {
    double p[3][3];
    hz_obj_tri(m, ps->tri[P->t0 + q], p);
    for (int j = 0; j < 3; j++)
      for (int a = 0; a < 3; a++) {
        if (p[j][a] < lo[a]) lo[a] = p[j][a];
        if (p[j][a] > hi[a]) hi[a] = p[j][a];
      }
  }
  if (!(lo[0] <= hi[0]))
    for (int a = 0; a < 3; a++) {
      lo[a] = 0.0;
      hi[a] = 0.0;
    }
}

/* Общая плоскость СПИСКА полигонов и МАКСИМАЛЬНОЕ отклонение их вершин от неё —
 * то есть `dmax`, а не среднеквадратичное (Г40/Г44).
 *
 * ПРОВЕРЯЕТСЯ ОБЪЕДИНЕНИЕ ГРУПП, А НЕ ПАРА, и это исправление настоящей ошибки.
 * Первая редакция проверяла пару и сливала транзитивно: `A~B` и `B~C` проходили
 * по отдельности, а у `A∪B∪C` отклонение не ограничивалось ничем. Замер поймал
 * это сразу — `dmax` дорастал до `44 δ` при допуске `1 δ`, — и поймал его
 * ИМЕННО тот пересчёт `dmax`, которого требует Ш7 («ложный ноль опаснее
 * UNKNOWN»). Метрика картинки к этому слепа: при уехавшей на два метра
 * плоскости она даже УЛУЧШАЛАСЬ, потому что сравнивает поле с точным светом в
 * той же уехавшей точке (узор К13/К40/К94). */
/* ОТКЛОНЕНИЕ МЕРЯЕТСЯ ПО ТРЕУГОЛЬНИКАМ, А НЕ ПО КРАЮ, И ЭТО ИСПРАВЛЕНИЕ ПО
 * ЗАМЕРУ. Первая редакция брала вершины КРАЯ, и на городе это дало `dmax = 4.18`
 * м при допуске огрубления `0.5` м — то есть критерий, обязанный держать `dmax`
 * под допуском, его не держал. Причина: `hz_poly_build` отбрасывает петли короче
 * трёх вершин (`nvloop < 3`), и полигон может остаться БЕЗ КРАЯ ВОВСЕ, сохранив
 * свои треугольники. По краю такой полигон не даёт НИ ОДНОЙ пробы — его
 * отклонение не проверяется ничем, а в группу он входит целиком. На зале не
 * срабатывало: там полигонов без петли единицы.
 * Треугольники — это и есть поверхность; край есть её проекция. Заодно критерий
 * и докладываемый `dmax` становятся ОДНОЙ величиной, а не двумя похожими, и
 * тогда «`dmax_worst < δ`» — проверяемый инвариант, а не пожелание. */
/* ПРЕДЕЛ ЧИСЛА ОБМЕНОВ В МИНИМАКСНОМ РЕШАТЕЛЕ.
 *
 * ОТКУДА ЧИСЛО. Обмен строго увеличивает `t` (нижнюю оценку оптимума по текущей
 * четвёрке), а четвёрок конечное число, поэтому зацикливания нет и предел —
 * страховка, а не механизм останова. Шестьдесят четыре выбрано как заведомо
 * больше наблюдаемого: замер §26 на тех же данных показывал сходимость за
 * единицы шагов. Срабатывания СЧИТАЮТСЯ и печатаются: если счётчик не ноль,
 * предел стал рабочей частью, и это надо чинить, а не терпеть. */
#define PM_MMEXCH 64

/* ПРЕДЕЛ ПОВОРОТОВ ОСИ КОНУСА (О21). Персептрон на сфере сходится при СТРОГОЙ
 * отделимости; при касании (нормаль ровно перпендикулярна любой допустимой оси)
 * он будет крутиться, и предел это ловит. Тридцать два — заведомо больше
 * ожидаемого: старт берётся из `Σ A·n`, и предсказание §31 — ноль-один поворот.
 * Упёрлись — ОТКАЗ и счётчик; в докладе это «вырожденный конус» (А101). */
#define PM_CONEIT 32

/* Состояние минимаксного решателя — замер, а не отладка (А89: сходимость этой
 * формы обмена НЕ доказана, значит её надо мерить). */
static int pm_solve4(double A[4][4], double rhs[4], double x[4]) {
  for (int c = 0; c < 4; c++) {
    int piv = c;
    for (int r = c + 1; r < 4; r++)
      if (fabs(A[r][c]) > fabs(A[piv][c])) piv = r;
    if (!(fabs(A[piv][c]) > 0.0)) return 1;
    if (piv != c) {
      for (int k = 0; k < 4; k++) {
        double tt = A[c][k];
        A[c][k] = A[piv][k];
        A[piv][k] = tt;
      }
      double tt = rhs[c];
      rhs[c] = rhs[piv];
      rhs[piv] = tt;
    }
    for (int r = 0; r < 4; r++) {
      if (r == c) continue;
      double f = A[r][c] / A[c][c];
      for (int k = 0; k < 4; k++)
        A[r][k] -= f * A[c][k];
      rhs[r] -= f * rhs[c];
    }
  }
  for (int c = 0; c < 4; c++)
    x[c] = rhs[c] / A[c][c];
  return 0;
}

/* РЕШЕНИЕ ПО ЧЕТВЁРКЕ: ЗНАКИ БЕРУТСЯ ИЗ АФФИННОЙ ЗАВИСИМОСТИ, А НЕ ПЕРЕБОРОМ.
 *
 * ПЕРВАЯ РЕДАКЦИЯ ПЕРЕБИРАЛА ВОСЕМЬ ЗНАКОВЫХ КОМБИНАЦИЙ И БРАЛА НАИБОЛЬШЕЕ `t`
 * — И ЭТО НЕВЕРНО (А94). У почти вырожденной системы решение уходит в
 * бесконечность, «наибольшее `t`» выбирает именно её, и замер показал это сразу:
 * наклон `√(1+a²+b²)` дорастал до `2.4e31`, а `dmax_worst` — до `3.994` м при
 * допуске `0.3`.
 *
 * ПРАВИЛЬНОЕ ПОСТРОЕНИЕ. Четыре точки в плоскости всегда аффинно зависимы:
 * существует `λ ≠ 0` с `Σ λ_k = 0`, `Σ λ_k u_k = 0`, `Σ λ_k v_k = 0`. Он
 * находится ровно как в правиле Крамера — минорами `3×3`. Знаки опорных невязок
 * задаются им: `σ_k = sign(λ_k)`, а сама величина — двойственная оценка
 *   `t = |Σ λ_k w_k| / Σ |λ_k|`,
 * то есть нижняя оценка минимакса (де ла Валле Пуссен) для ЛЮБОЙ плоскости. Она
 * ограничена по построению и в бесконечность уйти не может.
 * Плоскость затем берётся из трёх уравнений `a u + b v + c = w − σ t`. */
static double pm_det3(double a1, double a2, double a3, double b1, double b2, double b3, double c1,
                      double c2, double c3) {
  return a1 * (b2 * c3 - b3 * c2) - a2 * (b1 * c3 - b3 * c1) + a3 * (b1 * c2 - b2 * c1);
}

static int pm_ref4(const double ref[4][3], double *pa, double *pb, double *pc, double *pt) {
  double lam[4];
  const double *p0 = ref[0], *p1 = ref[1], *p2 = ref[2], *p3 = ref[3];
  lam[0] = +pm_det3(1.0, 1.0, 1.0, p1[0], p2[0], p3[0], p1[1], p2[1], p3[1]);
  lam[1] = -pm_det3(1.0, 1.0, 1.0, p0[0], p2[0], p3[0], p0[1], p2[1], p3[1]);
  lam[2] = +pm_det3(1.0, 1.0, 1.0, p0[0], p1[0], p3[0], p0[1], p1[1], p3[1]);
  lam[3] = -pm_det3(1.0, 1.0, 1.0, p0[0], p1[0], p2[0], p0[1], p1[1], p2[1]);
  double sabs = 0.0, sw = 0.0;
  for (int k = 0; k < 4; k++) {
    sabs += fabs(lam[k]);
    sw += lam[k] * ref[k][2];
  }
  /* Вырожденная четвёрка (совпавшие точки, три на одной прямой при нулевом
   * четвёртом миноре) — отказ, а не подстановка нуля: ложный ноль здесь дал бы
   * «идеальную плоскость» на пустом месте. */
  if (!(sabs > 0.0)) return 1;
  double t = fabs(sw) / sabs;
  double sgn = (sw >= 0.0) ? 1.0 : -1.0;
  /* Три уравнения из четырёх: берутся точки с наибольшими `|λ|` — у них система
   * заведомо не вырождена, потому что именно они и определяют зависимость. */
  int id[4] = {0, 1, 2, 3};
  for (int i = 0; i < 4; i++)
    for (int j = i + 1; j < 4; j++)
      if (fabs(lam[id[j]]) > fabs(lam[id[i]])) {
        int tmp = id[i];
        id[i] = id[j];
        id[j] = tmp;
      }
  double A[4][4], rhs[4], x[4];
  for (int r = 0; r < 3; r++) {
    int k = id[r];
    double sk = (lam[k] >= 0.0) ? sgn : -sgn;
    A[r][0] = ref[k][0];
    A[r][1] = ref[k][1];
    A[r][2] = 1.0;
    A[r][3] = 0.0;
    rhs[r] = ref[k][2] - sk * t;
  }
  A[3][0] = 0.0;
  A[3][1] = 0.0;
  A[3][2] = 0.0;
  A[3][3] = 1.0;
  rhs[3] = 0.0;
  if (pm_solve4(A, rhs, x) != 0) return 1;
  *pa = x[0];
  *pb = x[1];
  *pc = x[2];
  *pt = t;
  return 0;
}

/* МИНИМАКСНАЯ (ЧЕБЫШЕВСКАЯ) ПЛОСКОСТЬ ПО ОПОРНЫМ ТОЧКАМ — ОБМЕННЫЙ РЕШАТЕЛЬ.
 *
 * Задача решается в ГРАФОВОЙ форме `w ≈ a·u + b·v + c` в раме `(eu, ev, n)`, где
 * `n` — уже найденная ориентация группы. Мировая плоскость восстанавливается как
 * `N = n − a·eu − b·ev`, и ортогональное отклонение равно графовому, делённому
 * на `|N| = √(1+a²+b²)`.
 *
 * ЧТО ЭТО ЗА ВЕЛИЧИНА, БЕЗ ПРИКРАС (А92): это минимакс ГРАФОВОЙ задачи,
 * приведённый к ортогональной мере, а не минимакс ортогональной. Он даёт оценку
 * СВЕРХУ для ортогонального оптимума, то есть ошибается в сторону ОТКАЗА:
 * приняли — значит влезло точно. Обратного (принять невлезающее) быть не может.
 *
 * СХОДИМОСТЬ ЭТОЙ ФОРМЫ ОБМЕНА НЕ ДОКАЗАНА (А89). `t` строго растёт, четвёрок
 * конечное число — зацикливания нет; но выход на оптимум не гарантирован, и
 * процесс может встать. Поэтому «недосход» СЧИТАЕТСЯ, а на зале результат
 * сверяется с ПЕРЕБОРОМ (`pfit`). На городе перебор вырожден (А88).
 *
 * `quarter` — негативный контроль (§28): плоскость подгоняется по ЧЕТВЕРТИ
 * точек, отобранной хешем от номеров, то есть детерминированно и как функция
 * пары (А93), а проверяется потом по ВСЕМ. */
static int pm_minimax(const hz_polyset *ps, const int32_t *mem, int32_t nm, double n[3],
                      const double org[3], double *off, int64_t *nwork, hz_mergestat *ms,
                      int quarter) {
  double eu[3], ev[3];
  {
    int ax = 0;
    for (int a = 1; a < 3; a++)
      if (fabs(n[a]) < fabs(n[ax])) ax = a;
    double e0[3] = {0.0, 0.0, 0.0};
    e0[ax] = 1.0;
    double d = e0[0] * n[0] + e0[1] * n[1] + e0[2] * n[2];
    for (int a = 0; a < 3; a++)
      eu[a] = e0[a] - d * n[a];
    double en = sqrt(eu[0] * eu[0] + eu[1] * eu[1] + eu[2] * eu[2]);
    if (!(en > 0.0)) return 1;
    for (int a = 0; a < 3; a++)
      eu[a] /= en;
    ev[0] = n[1] * eu[2] - n[2] * eu[1];
    ev[1] = n[2] * eu[0] - n[0] * eu[2];
    ev[2] = n[0] * eu[1] - n[1] * eu[0];
  }
/* Один проход по опорным точкам группы: `(u, v, w)` считаются на лету, а не
 * материализуются — проходов будет несколько, а памяти на группу нет. */
#define PM_MM_FOREACH(BODY)                                                                        \
  do {                                                                                             \
    for (int32_t i_ = 0; i_ < nm; i_++) {                                                          \
      const hz_poly *P_ = &ps->p[mem[i_]];                                                         \
      const double *S_ = ps->sup + (size_t)P_->s0 * 3;                                             \
      for (int32_t q_ = 0; q_ < P_->nsup; q_++) {                                                  \
        if (quarter &&                                                                             \
            (pm_mix64(((uint64_t)(uint32_t)mem[i_] << 32) | (uint64_t)(uint32_t)q_) & 3u) != 0u)   \
          continue;                                                                                \
        double dx_ = S_[(size_t)q_ * 3] - org[0], dy_ = S_[(size_t)q_ * 3 + 1] - org[1],           \
               dz_ = S_[(size_t)q_ * 3 + 2] - org[2];                                              \
        double pu = dx_ * eu[0] + dy_ * eu[1] + dz_ * eu[2];                                       \
        double pv = dx_ * ev[0] + dy_ * ev[1] + dz_ * ev[2];                                       \
        double pw = dx_ * n[0] + dy_ * n[1] + dz_ * n[2];                                          \
        BODY                                                                                       \
      }                                                                                            \
    }                                                                                              \
  } while (0)

  /* Начальная четвёрка — крайние точки по `w` и по `u`: они почти наверняка
   * опорные, и вырожденность такой четвёрки ловится отказом системы. */
  double ref[4][3];
  int have = 0;
  {
    double wlo = 1e300, whi = -1e300, ulo = 1e300, uhi = -1e300;
    double rw0[3] = {0, 0, 0}, rw1[3] = {0, 0, 0}, ru0[3] = {0, 0, 0}, ru1[3] = {0, 0, 0};
    PM_MM_FOREACH({
      if (pw < wlo) {
        wlo = pw;
        rw0[0] = pu;
        rw0[1] = pv;
        rw0[2] = pw;
      }
      if (pw > whi) {
        whi = pw;
        rw1[0] = pu;
        rw1[1] = pv;
        rw1[2] = pw;
      }
      if (pu < ulo) {
        ulo = pu;
        ru0[0] = pu;
        ru0[1] = pv;
        ru0[2] = pw;
      }
      if (pu > uhi) {
        uhi = pu;
        ru1[0] = pu;
        ru1[1] = pv;
        ru1[2] = pw;
      }
      have++;
    });
    if (have < 4) return 1;
    for (int c = 0; c < 3; c++) {
      ref[0][c] = rw0[c];
      ref[1][c] = rw1[c];
      ref[2][c] = ru0[c];
      ref[3][c] = ru1[c];
    }
  }
  double a = 0.0, b = 0.0, cc = 0.0, t = 0.0;
  if (pm_ref4(ref, &a, &b, &cc, &t) != 0) {
    a = 0.0;
    b = 0.0;
    cc = 0.0;
    t = 0.0;
  }
  int it = 0;
  for (; it < PM_MMEXCH; it++) {
    double worst = -1.0, wp[3] = {0, 0, 0};
    PM_MM_FOREACH({
      double r = fabs(pw - a * pu - b * pv - cc);
      if (r > worst) {
        worst = r;
        wp[0] = pu;
        wp[1] = pv;
        wp[2] = pw;
      }
    });
    if (nwork != NULL) *nwork += have;
    if (!(worst > t)) break; /* ни одна точка не хуже опорных — оптимум */
    /* ОБМЕН: нарушитель заменяет одну из четырёх, берётся замена с наибольшим
     * `t`. Монотонность `t` и конечность множества четвёрок дают конечность
     * процесса; оптимальность — нет (А89), поэтому останов без улучшения
     * считается НЕДОСХОДОМ и печатается. */
    double ba = a, bb2 = b, bc = cc, bt = t;
    int best = -1;
    for (int k = 0; k < 4; k++) {
      double cand[4][3];
      memcpy(cand, ref, sizeof cand);
      for (int c = 0; c < 3; c++)
        cand[k][c] = wp[c];
      double a2, b2, c2, t2;
      if (pm_ref4(cand, &a2, &b2, &c2, &t2) != 0) continue;
      if (t2 > bt) {
        bt = t2;
        ba = a2;
        bb2 = b2;
        bc = c2;
        best = k;
      }
    }
    if (best < 0) {
      if (ms != NULL) ms->nmm_under++;
      break;
    }
    for (int c = 0; c < 3; c++)
      ref[best][c] = wp[c];
    a = ba;
    b = bb2;
    cc = bc;
    t = bt;
  }
  if (ms != NULL) {
    ms->nmm_call++;
    ms->nmm_exch += it;
    if (it > ms->nmm_exch_max) ms->nmm_exch_max = it;
    if (it >= PM_MMEXCH) ms->nmm_cap++;
  }
#undef PM_MM_FOREACH
  /* Мировая плоскость: `N = n − a·eu − b·ev`, нормируется. */
  double N[3];
  for (int c = 0; c < 3; c++)
    N[c] = n[c] - a * eu[c] - b * ev[c];
  double nl = sqrt(N[0] * N[0] + N[1] * N[1] + N[2] * N[2]);
  if (!(nl > 0.0)) return 1;
  if (ms != NULL && nl > ms->mm_gmax) ms->mm_gmax = nl;
  for (int c = 0; c < 3; c++)
    n[c] = N[c] / nl;
  *off = (N[0] * org[0] + N[1] * org[1] + N[2] * org[2] + cc) / nl;
  return 0;
}

/* О7: ХОДИМ ПО ОПОРНОМУ МНОЖЕСТВУ, А НЕ ПО ВСЕМ ТРЕУГОЛЬНИКАМ. Величина ТА ЖЕ —
 * максимум аффинной функции достигается на вершине выпуклой оболочки, — а работа
 * падает на столько, во сколько оболочка мельче набора (`polygon.h`, поле `sup`).
 * Мажорантой это НЕ становится: подмены максимума чем-то другим здесь нет, в
 * отличие от Г40/Г44. Треугольники сюда больше не приходят вовсе, поэтому и
 * сетка (`m`) функции не нужна. */
/* ВЫТЯНУТОСТЬ ГРУППЫ И ПОТЕРЯ ПЛОЩАДИ ПРИ УПЛОЩЕНИИ (§38) — ЗАМЕР.
 *
 * Обе величины считаются из УЖЕ ИМЕЮЩИХСЯ и не требуют ни персептрона, ни
 * итераций.
 *
 * ВЫТЯНУТОСТЬ. Вторые моменты полигона `mom[3..5]` = `∫u²`, `∫uv`, `∫v²` в его
 * СОБСТВЕННОЙ раме, точные и взвешенные площадью. Точка `x = org + u·eu + v·ev`
 * в раме группы даёт `U = a0 + a1·u + a2·v`, `V = b0 + b1·u + b2·v`, поэтому
 * `∫U²`, `∫UV`, `∫V²` объединения собираются из моментов членов сложением — то
 * есть за `O(1)` на член (перенос Штейнера сидит в членах с `a0`, `b0`).
 * Вытянутость — корень отношения собственных чисел центральной ковариации,
 * замкнутая форма для `2×2`.
 *
 * ПОТЕРЯ ПЛОЩАДИ. Грань, стоящая под углом к общей плоскости, проецируется с
 * множителем `|n_i·N|`, то есть теряет площадь в `1/|n_i·N|` раз. Берётся
 * МАКСИМУМ по членам, а не среднее (§38): среднее прячет одну перпендикулярную
 * грань в сотне компланарных — подмена того же класса, что Г40/Г44.
 */
static void pm_shape(const hz_polyset *ps, const int32_t *mem, int32_t nm, const double N[3],
                     hz_mergestat *st, double *pasp, double *ploss) {
  double eu[3], ev[3];
  {
    int ax = 0;
    for (int a = 1; a < 3; a++)
      if (fabs(N[a]) < fabs(N[ax])) ax = a;
    double e0[3] = {0.0, 0.0, 0.0};
    e0[ax] = 1.0;
    double d = e0[0] * N[0] + e0[1] * N[1] + e0[2] * N[2];
    for (int a = 0; a < 3; a++)
      eu[a] = e0[a] - d * N[a];
    double en = sqrt(eu[0] * eu[0] + eu[1] * eu[1] + eu[2] * eu[2]);
    if (!(en > 0.0)) return;
    for (int a = 0; a < 3; a++)
      eu[a] /= en;
    ev[0] = N[1] * eu[2] - N[2] * eu[1];
    ev[1] = N[2] * eu[0] - N[0] * eu[2];
    ev[2] = N[0] * eu[1] - N[1] * eu[0];
  }
  double M0 = 0.0, MU = 0.0, MV = 0.0, MUU = 0.0, MUV = 0.0, MVV = 0.0, worst = 1.0;
  for (int32_t i = 0; i < nm; i++) {
    const hz_poly *P = &ps->p[mem[i]];
    double c = fabs(P->n[0] * N[0] + P->n[1] * N[1] + P->n[2] * N[2]);
    double loss = (c > 0.0) ? 1.0 / c : 1e300;
    if (loss > worst) worst = loss;
    double o[3];
    for (int a = 0; a < 3; a++)
      o[a] = P->org[a];
    double a0 = o[0] * eu[0] + o[1] * eu[1] + o[2] * eu[2];
    double b0 = o[0] * ev[0] + o[1] * ev[1] + o[2] * ev[2];
    double a1 = P->eu[0] * eu[0] + P->eu[1] * eu[1] + P->eu[2] * eu[2];
    double a2 = P->ev[0] * eu[0] + P->ev[1] * eu[1] + P->ev[2] * eu[2];
    double b1 = P->eu[0] * ev[0] + P->eu[1] * ev[1] + P->eu[2] * ev[2];
    double b2 = P->ev[0] * ev[0] + P->ev[1] * ev[1] + P->ev[2] * ev[2];
    double m0 = P->mom[0], m1 = P->mom[1], m2 = P->mom[2];
    double m3 = P->mom[3], m4 = P->mom[4], m5 = P->mom[5];
    M0 += m0;
    MU += a0 * m0 + a1 * m1 + a2 * m2;
    MV += b0 * m0 + b1 * m1 + b2 * m2;
    MUU += a0 * a0 * m0 + 2.0 * a0 * a1 * m1 + 2.0 * a0 * a2 * m2 + a1 * a1 * m3 +
           2.0 * a1 * a2 * m4 + a2 * a2 * m5;
    MVV += b0 * b0 * m0 + 2.0 * b0 * b1 * m1 + 2.0 * b0 * b2 * m2 + b1 * b1 * m3 +
           2.0 * b1 * b2 * m4 + b2 * b2 * m5;
    MUV += a0 * b0 * m0 + (a0 * b1 + a1 * b0) * m1 + (a0 * b2 + a2 * b0) * m2 + a1 * b1 * m3 +
           (a1 * b2 + a2 * b1) * m4 + a2 * b2 * m5;
  }
  if (!(M0 > 0.0)) return;
  double cuu = MUU / M0 - (MU / M0) * (MU / M0);
  double cvv = MVV / M0 - (MV / M0) * (MV / M0);
  double cuv = MUV / M0 - (MU / M0) * (MV / M0);
  double tr = cuu + cvv, det = cuu * cvv - cuv * cuv;
  double disc = tr * tr * 0.25 - det;
  if (disc < 0.0) disc = 0.0;
  double l1 = tr * 0.5 + sqrt(disc), l2 = tr * 0.5 - sqrt(disc);
  /* Вырожденная ковариация (все точки на прямой) — вытянутость бесконечна;
   * в последнюю корзину, а не в ноль: ложный ноль здесь означал бы «идеально
   * круглая группа» ровно там, где она хуже всего. */
  double asp = (l2 > 0.0 && l1 > 0.0) ? sqrt(l1 / l2) : 1e300;
  int ab = (asp < 1e299) ? (int)(log(asp) / log(2.0)) : 11;
  if (ab < 0) ab = 0;
  if (ab > 11) ab = 11;
  if (pasp != NULL) *pasp = asp;
  if (ploss != NULL) *ploss = worst;
  if (st == NULL) return;
  st->asp_hist[ab]++;
  if (asp < 1e299 && asp > st->asp_max) st->asp_max = asp;
  int lb = (worst < 1e299) ? (int)((worst - 1.0) / 0.25) : 11;
  if (lb < 0) lb = 0;
  if (lb > 11) lb = 11;
  st->loss_hist[lb]++;
  if (worst < 1e299 && worst > st->loss_max) st->loss_max = worst;
}

static double group_plane(const hz_polyset *ps, const int32_t *mem, int32_t nm, double n[3],
                          double *off, int64_t *nwork, hz_mergestat *mmst, int quarter,
                          double conemax, double *pcone) {
  double s = 0.0, ns[3] = {0, 0, 0}, org[3] = {0, 0, 0};
  for (int32_t i = 0; i < nm; i++) {
    const hz_poly *P = &ps->p[mem[i]];
    double w = P->area;
    s += w;
    for (int c = 0; c < 3; c++) {
      ns[c] += w * P->n[c];
      org[c] += w * P->org[c];
    }
  }
  if (!(s > 0.0)) return 1e300;
  double nn = sqrt(ns[0] * ns[0] + ns[1] * ns[1] + ns[2] * ns[2]);
  if (!(nn > 0.0)) return 1e300;
  for (int c = 0; c < 3; c++) {
    n[c] = ns[c] / nn;
    org[c] /= s;
  }
  /* ВСЕ НОРМАЛИ ОБЯЗАНЫ СМОТРЕТЬ В ОДНУ СТОРОНУ С ГРУППОВОЙ. Найдено замером на
   * ГОРОДЕ: группа из 12 участков дала `dmax = 4.18` м при допуске `0.5` м, и
   * улики показали, чем именно — `|Σ A·n| = 0` при `Σ A = 15.4`. Это шесть пар
   * ВСТРЕЧНЫХ граней (лицо и изнанка одной диагональной стены, `n` и `−n`,
   * площади равны). Взвешенная нормаль у них гасится ТОЧНО, и «плоскость
   * группы» получается направлением ОСТАТКА ОКРУГЛЕНИЯ — то есть произволом
   * порядка `1e−17`, усиленным до единичного вектора. Проверка `dmax` при этом
   * не спасает: если случайное направление легло поперёк разброса, отклонение
   * выходит малым и слияние ПРИНИМАЕТСЯ; а в конце плоскость пересчитывается в
   * ДРУГОМ порядке суммирования, даёт другое случайное направление — и `dmax`
   * оказывается метрами.
   * Порога здесь нет и не нужно: требуется строгая положительность `n_i·n`.
   * Встречные грани — это ДВЕ поверхности, а не одна, и сливать их нельзя ни
   * при каком допуске; кривая же поверхность, которую огрубление и должно
   * сливать, держит нормали в одной полусфере, и её ограничивает `dmax`. */
  /* О21: КОНУС НОРМАЛЕЙ, А НЕ ПОЛУСФЕРА С ОСЬЮ ИЗ `Σ A·n`. Две причины, обе
   * замеренные. (1) А77: при взаимно гасящихся нормалях `Σ A·n` есть ОСТАТОК
   * ОКРУГЛЕНИЯ, и проверка держалась на удаче — город при δ = 8 м дал тогда
   * `dmax_worst = 9.236` м. (2) А97: после О11 полусфера оказалась слишком
   * слабым условием — сливались куски с нормалями `(0,−1,0)`, `(−1,0,0)`,
   * `(0,0,−1)`, потому что оптимальная плоскость к ним подбирается.
   * Ось ищется персептроном на сфере: старт — `Σ A·n`, затем поворот к худшему
   * нарушителю, пока такие есть. Сходимость — при отделимости множества;
   * упёрлись в предел — ОТКАЗ (fail closed, А101: это «вырожденный конус», а не
   * «конуса нет»). Полураствор `θ = arccos(min n_i·ось)` — ОЦЕНКА СВЕРХУ
   * наименьшего конуса, значит ограничение сверху ошибается в сторону отказа. */
  {
    double ax[3] = {n[0], n[1], n[2]};
    int it = 0;
    double mn = 0.0;
    for (; it <= PM_CONEIT; it++) {
      mn = 2.0;
      int32_t iw = -1;
      for (int32_t i = 0; i < nm; i++) {
        const hz_poly *P = &ps->p[mem[i]];
        double d = P->n[0] * ax[0] + P->n[1] * ax[1] + P->n[2] * ax[2];
        if (d < mn) {
          mn = d;
          iw = i;
        }
      }
      if (mn > 0.0 || iw < 0) break;
      const hz_poly *W = &ps->p[mem[iw]];
      for (int c = 0; c < 3; c++)
        ax[c] += W->n[c];
      double al = sqrt(ax[0] * ax[0] + ax[1] * ax[1] + ax[2] * ax[2]);
      if (!(al > 0.0)) return 1e300;
      for (int c = 0; c < 3; c++)
        ax[c] /= al;
      if (mmst != NULL) mmst->ncone_turn++;
    }
    if (!(mn > 0.0)) {
      if (mmst != NULL) mmst->ncone_fail++;
      return 1e300;
    }
    /* ПОЛУРАСТВОР ВОЗВРАЩАЕТСЯ НАРУЖУ, А В ГИСТОГРАММУ ПОПАДАЕТ ТОЛЬКО У
     * ПРИНЯТЫХ СЛИЯНИЙ (А99). Первая редакция писала его прямо здесь — и
     * histogram оказывалась по ВСЕМ проверяемым парам, включая отвергаемые
     * воротами: на зале в корзину `85-90°` попало `36.8%`, что говорит о
     * кандидатах, а не о том, что сливается. */
    if (pcone != NULL)
      *pcone = acos(mn < -1.0 ? -1.0 : (mn > 1.0 ? 1.0 : mn)) * 180.0 / 3.14159265358979323846;
    /* ОГРАНИЧЕНИЕ ПОЛУРАСТВОРА — ПАРАМЕТР, а не константа в коде: значение
     * выбирается ПОСЛЕ замера гистограммы и метрики О20, а не в этом шаге. */
    if (conemax > 0.0) {
      double th = acos(mn < -1.0 ? -1.0 : (mn > 1.0 ? 1.0 : mn)) * 180.0 / 3.14159265358979323846;
      if (th > conemax) {
        if (mmst != NULL) mmst->ncone_rej++;
        return 1e300;
      }
    }
    /* Ось конуса становится ориентацией группы: она отделима от всех нормалей
     * членов по построению, тогда как `Σ A·n` этого не гарантирует. */
    for (int c = 0; c < 3; c++)
      n[c] = ax[c];
  }
  *off = n[0] * org[0] + n[1] * org[1] + n[2] * org[2];

  /* О11: ПЛОСКОСТЬ МИНИМАКСНАЯ, А НЕ СРЕДНЕВЗВЕШЕННАЯ. Средневзвешенная —
   * не подгонка вовсе, а среднее нормалей и центров; критерий же есть МАКСИМУМ,
   * и подгонять надо в той же норме, в какой меряют (А20, §22). Замер §26:
   * минимакс даёт отклонение `0.83` от средневзвешенного по медиане на городе и
   * `0.64` на зале, а пул допустимых объединений растёт в `6.4` и `1.5` раза.
   * Ориентация при этом остаётся ОТДЕЛЬНОЙ величиной (А22) и берётся выше из
   * `Σ A·n`: собственный вектор минимакса знака не имеет, и встречные грани дали
   * бы ему идеальную плоскость. */
  /* ОТКАТ К СРЕДНЕВЗВЕШЕННОЙ, ЕСЛИ МИНИМАКС НАКЛОНИЛ ПЛОСКОСТЬ ЗА ПРЕДЕЛЫ КОНУСА
   * НОРМАЛЕЙ (А95). Графовая задача наклон не ограничивает: если опорные точки
   * почти коллинеарны в проекции, плоскость можно повернуть почти «на ребро», и
   * отклонение формально упадёт — но такая плоскость поверхность уже не
   * представляет, а проверка ориентации выше сделана по СТАРОЙ нормали и этого
   * не видит. Замер на зале: `√(1+a²+b²)` доходил до `10.5`, то есть нормаль
   * уезжала на 84°. Поэтому после решателя ориентация проверяется ЗАНОВО, и при
   * отказе берётся прежняя плоскость — с ней слияние просто останется тем, чем
   * было до О11. */
  double nav[3] = {n[0], n[1], n[2]}, offav = *off;
  if (pm_minimax(ps, mem, nm, n, org, off, nwork, mmst, quarter) != 0) return 1e300;
  {
    int okc = 1;
    for (int32_t i = 0; i < nm && okc; i++) {
      const hz_poly *P = &ps->p[mem[i]];
      if (!(P->n[0] * n[0] + P->n[1] * n[1] + P->n[2] * n[2] > 0.0)) okc = 0;
    }
    if (!okc) {
      for (int c = 0; c < 3; c++)
        n[c] = nav[c];
      *off = offav;
      if (mmst != NULL) mmst->nmm_revert++;
    }
  }

  double dmax = 0.0;
  for (int32_t i = 0; i < nm; i++) {
    const hz_poly *P = &ps->p[mem[i]];
    if (nwork != NULL) *nwork += P->nsup;
    const double *S = ps->sup + (size_t)P->s0 * 3;
    for (int32_t q = 0; q < P->nsup; q++) {
      double d = fabs(S[(size_t)q * 3] * n[0] + S[(size_t)q * 3 + 1] * n[1] +
                      S[(size_t)q * 3 + 2] * n[2] - *off);
      if (d > dmax) dmax = d;
    }
  }
  return dmax;
}

/* ВОРОТА — ОЦЕНКА СВЕРХУ ЗА `O(1)`, А НЕ ПОДГОНКА. Переписано 07-29 по замеру
 * и по замечанию пользователя, и замечание было верным дословно: «фиттингом
 * добиваемся, чтобы полигоны в одной плоскости слить — это как, это что?».
 *
 * ЧТО БЫЛО. На каждую пару-кандидата собиралась квадрика по ВСЕМ вершинам края
 * обоих полигонов с их нормалями и решалась система 3×3 (`src/cut/qef.c`, она
 * писалась для дуального контурирования). Цена — `1.45` мкс на пару, измерено.
 * За эти деньги работает настоящая ПОДГОНКА, а вопрос был «лежат ли два куска в
 * общей плоскости с точностью δ», то есть да/нет.
 *
 * ЧТО СТАЛО. Мажоранта за `O(1)` по коробке края (`dev_box`), и ТОЧНЫЙ расчёт
 * только если мажоранта не пропустила. Точный — тот же `group_plane`, что решает
 * при слиянии, на группе из двух; значит ворота и решение стали ОДНОЙ величиной.
 * Одной мажоранты мало: она строже точного критерия, и замер это показал сразу —
 * цель 150 полигонов переставала достигаться (246 вместо 150).
 *
 * ЗАОДНО СНЯТА ОГОВОРКА Г40/Г44. Невязка QEF есть СРЕДНЕКВАДРАТИЧНОЕ, и
 * подменять ею максимум запрещено прямым текстом; здесь и мажоранта, и точный
 * расчёт — величины той же природы, что критерий, то есть МАКСИМУМ. */
/* Худшее отклонение края `B` от плоскости `A`, оценённое по КОРОБКЕ края в
 * местной раме `B`. Точка `B` есть `org_b + u·eu_b + v·ev_b`, поэтому её
 * отклонение от плоскости `A` — линейная функция `(u, v)`, и максимум модуля
 * достигается В УГЛУ коробки. Четыре вычисления вместо описанного радиуса: та
 * же `O(1)`, но мажоранта много туже, а от туготы зависит, как часто придётся
 * считать точно. Добавляется `dmax` самого `B` — на столько его треугольники
 * отходят от собственной плоскости. */
static double dev_box(const hz_poly *A, const hz_poly *B) {
  double d0 = A->n[0] * B->org[0] + A->n[1] * B->org[1] + A->n[2] * B->org[2] - A->off;
  double pu = A->n[0] * B->eu[0] + A->n[1] * B->eu[1] + A->n[2] * B->eu[2];
  double pv = A->n[0] * B->ev[0] + A->n[1] * B->ev[1] + A->n[2] * B->ev[2];
  double best = 0.0;
  for (int i = 0; i < 4; i++) {
    double u = (i & 1) ? B->uvhi[0] : B->uvlo[0];
    double v = (i & 2) ? B->uvhi[1] : B->uvlo[1];
    double d = fabs(d0 + u * pu + v * pv);
    if (d > best) best = d;
  }
  return best + B->dmax;
}

static double pair_gate(const hz_polyset *ps, int32_t a, int32_t b) {
  const hz_poly *A = &ps->p[a], *B = &ps->p[b];
  double c = A->n[0] * B->n[0] + A->n[1] * B->n[1] + A->n[2] * B->n[2];
  /* Встречные грани — две поверхности, а не одна (см. `group_plane`). */
  if (!(c > 0.0)) return 1e300;
  double ea = dev_box(A, B), eb = dev_box(B, A);
  return (ea > eb) ? ea : eb;
}

/* ПЕРЕКРЫВАЮТСЯ ЛИ ПРОЕКЦИИ. Добавлено по замеру Ш3: критерий «все точки в
 * пределах δ от общей плоскости» разрешает слить две ОДИНАКОВО СМОТРЯЩИЕ
 * поверхности ближе δ, и на грубом δ это съедает до 10.6% площади сцены, чего
 * баланс энергии не ловит вовсе. */
/* НЕСИММЕТРИЧНОСТЬ, НАЙДЕННАЯ АУДИТОМ 07-29 И ОСТАВЛЕННАЯ ДО ЗАМЕРА О13.
 * Пробы ставятся по коробке `B`, а доля считается от числа проб, попавших в
 * `B`, — то есть нормировка идёт на площадь `B`. Дешёвый же отсев ниже
 * нормирует на `amin`, МЕНЬШУЮ из двух коробок. Это две разные величины под
 * одним именем «1/16», и слабее из них та, что решает.
 * Следствие проверяемое: если `A` мал и лежит ЦЕЛИКОМ внутри `B`, доля проб
 * равна отношению площадей, и при разнице в 20 раз она ниже `1/16` ⇒
 * перекрытие объявляется отсутствующим ⇒ листы слипаются, а площадь теряется
 * физически (Ш3, до 10.6%). Промах управляется ОТНОШЕНИЕМ РАЗМЕРОВ, а не
 * тонкостью перекрытия.
 * ПОЧЕМУ НЕ ИСПРАВЛЕНО ЗДЕСЬ И СЕЙЧАС: это правка КРИТЕРИЯ, а не скорости, и
 * О13 заведён ровно затем, чтобы сперва измерить величину промаха точным
 * пересечением многоугольников. Чинить до замера значит менять критерий
 * вслепую и потерять точку отсчёта. */
static int overlaps(const hz_polyset *ps, int32_t a, int32_t b, hz_mergestat *st) {
  const hz_poly *A = &ps->p[a], *B = &ps->p[b];
  st->ngate_ov++;
  /* ДЕШЁВЫЙ ОТСЕВ ПЕРЕД ПРОБАМИ, и он снимает девять десятых цены огрубления.
   * Измерено 07-29: с проверкой перекрытия ворота стоили `14.19` мкс на пару,
   * без неё — `1.45`, то есть 90% времени уходило сюда. Причина простая:
   * `PM_OVSAMP²  = 64` пробы, каждая — обход ВСЕГО края (57 вершин у зала), и
   * так на каждую пару-кандидата.
   * Отсев точный, а не эвристический: проекция `B` на раму `A` целиком лежит в
   * коробке `[uvlo, uvhi]` каждого, и если коробки не пересекаются, то не
   * пересекаются и сами полигоны — пробовать нечего. Считается за десяток
   * сравнений по величинам, посчитанным при импорте. Соседние по ребру
   * полигоны (а их большинство среди кандидатов) отсеиваются здесь же. */
  {
    /* Коробка `B`, перенесённая в раму `A` через четыре УГЛА (не через радиус:
     * радиус раздувает её вчетверо и отсев перестаёт срабатывать). Перенос
     * через габарит углов — оценка СВЕРХУ, поэтому настоящее перекрытие отсев
     * выбросить не может. */
    double lo[2] = {1e300, 1e300}, hi[2] = {-1e300, -1e300};
    for (int i = 0; i < 4; i++) {
      double u = (i & 1) ? B->uvhi[0] : B->uvlo[0];
      double v = (i & 2) ? B->uvhi[1] : B->uvlo[1];
      double x[3], q[3];
      hz_poly_world(B, u, v, x);
      for (int c = 0; c < 3; c++)
        q[c] = x[c] - A->org[c];
      double ua = q[0] * A->eu[0] + q[1] * A->eu[1] + q[2] * A->eu[2];
      double va = q[0] * A->ev[0] + q[1] * A->ev[1] + q[2] * A->ev[2];
      if (ua < lo[0]) lo[0] = ua;
      if (ua > hi[0]) hi[0] = ua;
      if (va < lo[1]) lo[1] = va;
      if (va > hi[1]) hi[1] = va;
    }
    double w0 =
        (hi[0] < A->uvhi[0] ? hi[0] : A->uvhi[0]) - (lo[0] > A->uvlo[0] ? lo[0] : A->uvlo[0]);
    double w1 =
        (hi[1] < A->uvhi[1] ? hi[1] : A->uvhi[1]) - (lo[1] > A->uvlo[1] ? lo[1] : A->uvlo[1]);
    /* ОТСЕВ ПО ПЛОЩАДИ, А НЕ ПО ФАКТУ КАСАНИЯ, и в этом всё дело. Соседние по
     * ребру полигоны — а их среди кандидатов большинство — коробками ВСЕГДА
     * соприкасаются, поэтому проверка «пересекаются ли коробки» не отсеивает
     * почти ничего. Но перекрытием считается ДОЛЯ больше 1/16 (см. ниже), а
     * площадь пересечения коробок эту долю ограничивает сверху: если она сама
     * меньше 1/16 меньшей коробки, настоящее перекрытие тем более меньше, и
     * шестьдесят четыре пробы можно не ставить. */
    if (!(w0 > 0.0) || !(w1 > 0.0)) {
      st->ngate_ovbox++;
      return 0;
    }
    double ab = (hi[0] - lo[0]) * (hi[1] - lo[1]);
    double aa = (A->uvhi[0] - A->uvlo[0]) * (A->uvhi[1] - A->uvlo[1]);
    double amin = (aa < ab) ? aa : ab;
    if (w0 * w1 * 16.0 < amin) {
      st->ngate_ovbox++;
      return 0;
    }
  }
  /* РАБОТА, А НЕ ВЫЗОВЫ. `hz_poly_inside` обходит ВЕСЬ край, поэтому цена этой
   * проверки линейна по его длине, и О6 намерил это прямо: сжатие края втрое
   * уронило ворота втрое. Число вызовов такой цены не выражает — считаются
   * тронутые вершины. */
  {
    const hz_poly *P = B;
    int32_t nb2 = (P->nloop > 0) ? ps->loop[P->l0 + P->nloop] - ps->loop[P->l0] : 0;
    st->nwork_bv += (int64_t)PM_OVSAMP * PM_OVSAMP * nb2;
  }
  int inside = 0, tried = 0;
  for (int i = 0; i < PM_OVSAMP; i++)
    for (int j = 0; j < PM_OVSAMP; j++) {
      double u = B->uvlo[0] + ((double)i + 0.5) / PM_OVSAMP * (B->uvhi[0] - B->uvlo[0]);
      double v = B->uvlo[1] + ((double)j + 0.5) / PM_OVSAMP * (B->uvhi[1] - B->uvlo[1]);
      if (!hz_poly_inside(ps, B, u, v)) continue;
      tried++;
      double x[3], q[3];
      hz_poly_world(B, u, v, x);
      for (int c = 0; c < 3; c++)
        q[c] = x[c] - A->org[c];
      double ua = q[0] * A->eu[0] + q[1] * A->eu[1] + q[2] * A->eu[2];
      double va = q[0] * A->ev[0] + q[1] * A->ev[1] + q[2] * A->ev[2];
      if (ua < A->uvlo[0] || ua > A->uvhi[0] || va < A->uvlo[1] || va > A->uvhi[1]) continue;
      st->nwork_bv += (A->nloop > 0) ? ps->loop[A->l0 + A->nloop] - ps->loop[A->l0] : 0;
      if (hz_poly_inside(ps, A, ua, va)) inside++;
    }
  /* Соседние по ребру полигоны дают единичные попадания на самой кромке;
   * перекрытием считается заметная ДОЛЯ, а не факт попадания. */
  return (tried > 0) && (inside * 16 > tried);
}

static double pm_now(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (double)ts.tv_sec + 1e-9 * (double)ts.tv_nsec;
}

/* ПРОЦЕССОРНОЕ ВРЕМЯ ВСЕГО ПРОЦЕССА — второй часовой механизм к стенному (К79).
 * Отношение `CPU/стена` показывает, заняты потоки или ждут; сама по себе
 * величина при активном ожидании OpenMP включает и простой (А57), поэтому
 * читать её надо только в паре со стенным временем и с перекосом по потокам. */
static double pm_cpu(void) {
  struct timespec ts;
  clock_gettime(CLOCK_PROCESS_CPUTIME_ID, &ts);
  return (double)ts.tv_sec + 1e-9 * (double)ts.tv_nsec;
}

/* --- отбор кандидатов ---------------------------------------------------------
 * `pm_emit` — единственное место, где пара проверяется и попадает в список.
 * Едино для сетки и для переборного эталона: иначе «совпадение выходов» ничего
 * бы не доказывало, потому что различаться могли бы сами проверки. */

typedef struct {
  pm_pair *pl;
  int64_t pn, pcap;
} pm_plist;

/* ПАМЯТЬ СПИСКОВ ПАР — ОБЩАЯ НА ВСЕ ПОТОКИ, И ПИК МЕРИТСЯ, А НЕ ОЦЕНИВАЕТСЯ.
 * После О8 списков столько же, сколько потоков, и «сумма пиков по потокам» была
 * бы МАЖОРАНТОЙ: удваиваются они не одновременно. Поэтому ведётся текущий объём
 * (сумма ёмкостей) и его максимум; момент удвоения учитывается как «старый плюс
 * новый», момент сцепки — как «все списки плюс итоговый массив». Величина
 * измеренная, а не выведенная. */
static int64_t pm_bytes_cur = 0, pm_bytes_max = 0;

static void pm_bytes_add(int64_t d, int64_t transient) {
  int64_t cur;
#pragma omp atomic capture
  {
    pm_bytes_cur += d;
    cur = pm_bytes_cur;
  }
#pragma omp critical(pm_bytes)
  {
    if (cur + transient > pm_bytes_max) pm_bytes_max = cur + transient;
  }
}

static int pm_emit(pm_plist *L, const hz_polyset *ps, const double *bb, int32_t a, int32_t b,
                   const hz_mergecfg *cfg, hz_mergestat *st) {
  st->ncand++;
  const double *A = bb + (size_t)a * 6, *B = bb + (size_t)b * 6;
  for (int c = 0; c < 3; c++) {
    if (A[c] - B[3 + c] > cfg->delta) return 0;
    if (B[c] - A[3 + c] > cfg->delta) return 0;
  }
  st->npair++;

  double err = 0.0;
  /* ГЕОМЕТРИЯ ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ — она проверяется при СЛИЯНИИ, по
   * объединению групп (см. `group_plane`). Здесь только законно парные
   * члены: ворота по оценке сверху и перекрытие. */
  if (cfg->random) {
    /* НЕГАТИВНЫЙ КОНТРОЛЬ: метрика СЛУЧАЙНАЯ. Ошибка обязана стать O(1);
     * если не стала — критерий ничего не решает и мерили не его.
     * Величина есть функция ПАРЫ (А13), см. `pm_mix64`. */
    uint64_t h = pm_mix64(((uint64_t)(uint32_t)a << 32) | (uint64_t)(uint32_t)b);
    err = (double)(h >> 11) / 9007199254740992.0;
  } else {
    /* ВОРОТА — `dgate`, РАДИУС — `delta` (А144). Нормировка приоритета ниже
     * остаётся на `delta` сознательно (А145). */
    const double dgate = (cfg->dgate > 0.0) ? cfg->dgate : cfg->delta;
    if (cfg->use_geom) {
      /* МАЖОРАНТА ЗА O(1), И ТОЧНЫЙ РАСЧЁТ ТОЛЬКО ЕСЛИ ОНА НЕ ПРОПУСТИЛА.
       * Одна мажоранта качество портит: она строже точного критерия, и замер
       * это показал сразу — цель 150 полигонов переставала достигаться (246
       * вместо 150). Точный расчёт — тот же `group_plane`, что решает при
       * слиянии, только на группе из двух; значит ворота и решение стали ОДНОЙ
       * величиной, а не двумя похожими. Дорогой путь берётся лишь там, где
       * дешёвый сомневается. */
      double qg = pair_gate(ps, a, b);
      if (qg > dgate) {
        int32_t mm[2] = {a, b};
        double gn[3], goff;
        st->ngate_exact++;
        qg =
            group_plane(ps, mm, 2, gn, &goff, &st->nwork_tri, st, cfg->quarter, cfg->conemax, NULL);
        if (qg > dgate) {
          st->nrej_geom++;
          return 0;
        }
      } else {
        st->ngate_major++;
      }
      err += qg / cfg->delta;
    }
    if (cfg->use_overlap && overlaps(ps, a, b, st)) {
      st->nrej_overlap++;
      return 0;
    }
  }
  if (L->pn >= L->pcap) {
    int64_t nc = L->pcap * 2;
    /* ПИК ПАМЯТИ СИДИТ В САМОМ УДВОЕНИИ: `realloc` в худшем случае держит
     * СТАРЫЙ и НОВЫЙ массивы одновременно, то есть полтора итоговых размера.
     * Мерить надо этот момент, а не конечную длину списка (О10). */
    pm_bytes_add((nc - L->pcap) * (int64_t)sizeof *L->pl, nc * (int64_t)sizeof *L->pl);
    pm_pair *q = realloc(L->pl, (size_t)nc * sizeof *q);
    if (q == NULL) return 2;
    L->pl = q;
    L->pcap = nc;
  }
  L->pl[L->pn].a = a;
  L->pl[L->pn].b = b;
  L->pl[L->pn].err = err;
  L->pn++;
  return 0;
}

int hz_merge(hz_pseglist *so, const hz_objmesh *m, const hz_pseglist *si, const hz_polyset *ps,
             const hz_mergecfg *cfg, hz_mergestat *st) {
  memset(so, 0, sizeof *so);
  memset(st, 0, sizeof *st);
  st->side_min = 1.0; /* худшее из ни одного есть единица, а не ложный ноль */
  st->nseg_in = si->nseg;
  /* ТОЛЬКО ПОЛИГОНЫ ИЗ УЧАСТКОВ. В наборе за ними идут ИСТОЧНИКИ, добавленные
   * `hz_poly_add_quad`: у них нет треугольников в сетке, сливать их не с чем и
   * незачем, а группа без треугольников даёт пустой участок на выходе. */
  const int32_t np = (ps->np < si->nseg) ? ps->np : si->nseg;

  double *bb = malloc((size_t)np * 6 * sizeof *bb);
  int32_t *par = malloc((size_t)np * sizeof *par);
  if (bb == NULL || par == NULL) {
    free(bb);
    free(par);
    return 2;
  }
  double glo[3] = {1e300, 1e300, 1e300}, ghi[3] = {-1e300, -1e300, -1e300};
  for (int32_t k = 0; k < np; k++) {
    pbox(ps, m, k, bb + (size_t)k * 6, bb + (size_t)k * 6 + 3, &st->nbox_tri);
    par[k] = k;
    for (int c = 0; c < 3; c++) {
      if (bb[(size_t)k * 6 + (size_t)c] < glo[c]) glo[c] = bb[(size_t)k * 6 + (size_t)c];
      if (bb[(size_t)k * 6 + 3 + (size_t)c] > ghi[c]) ghi[c] = bb[(size_t)k * 6 + 3 + (size_t)c];
    }
  }

  /* --- кандидаты ---
   * СПИСОК У КАЖДОГО ПОТОКА СВОЙ, сцепка — в порядке номеров потоков (О8).
   * Порядок сцепки на выход не влияет (А12): `cmp_pair` — полный порядок, пары
   * попарно различны, значит отсортированный массив определён МНОЖЕСТВОМ пар.
   * Проверяется это не рассуждением, а негативным контролем `cfg.notie`. */
  const int nthr = (cfg->brute) ? 1 : omp_get_max_threads();
  pm_plist *TL = calloc((size_t)(nthr > 0 ? nthr : 1), sizeof *TL);
  hz_mergestat *TS = calloc((size_t)(nthr > 0 ? nthr : 1), sizeof *TS);
  if (TL == NULL || TS == NULL) {
    free(TL);
    free(TS);
    free(bb);
    free(par);
    return 2;
  }
  pm_bytes_cur = 0;
  pm_bytes_max = 0;
  pm_notie = cfg->notie;
  int oom = 0;
  for (int t = 0; t < nthr; t++) {
    TL[t].pcap = 4096;
    TL[t].pn = 0;
    TL[t].pl = malloc((size_t)TL[t].pcap * sizeof *TL[t].pl);
    if (TL[t].pl == NULL) oom = 1;
    pm_bytes_add(TL[t].pcap * (int64_t)sizeof *TL[t].pl, 0);
  }
  st->nthreads = (int32_t)nthr;
  double tphase = pm_now();
  double tcpu0 = pm_cpu();
  if (oom) {
    for (int t = 0; t < nthr; t++)
      free(TL[t].pl);
    free(TL);
    free(TS);
    free(bb);
    free(par);
    return 2;
  }
  if (cfg->brute) {
    for (int32_t a = 0; a < np && !oom; a++)
      for (int32_t b = a + 1; b < np && !oom; b++)
        if (pm_emit(&TL[0], ps, bb, a, b, cfg, &TS[0]) != 0) oom = 1;
  } else {
    /* СЕТКА КАНДИДАТОВ. Коробка полигона расширяется на `δ/2` с каждой стороны,
     * поэтому две коробки, отстоящие меньше чем на `δ`, заведомо делят ячейку:
     * расширенные пересекаются, а ячейка точки пересечения принадлежит обеим
     * записям. Точная проверка расстояния остаётся в `pm_emit` — сетка только
     * отбрасывает заведомо далёкое. */
    double ext[3], vol = 1.0;
    for (int c = 0; c < 3; c++) {
      ext[c] = ghi[c] - glo[c];
      if (!(ext[c] > 0.0)) ext[c] = 1e-9;
      vol *= ext[c];
    }
    /* Ячеек примерно `np/2` — та же цель, что у сетки лучей: пар внутри ячейки
     * квадратично по числу жильцов, поэтому мельче двух дробить незачем. */
    double want = (double)np / 2.0;
    if (want < 1.0) want = 1.0;
    double s = cbrt(vol / want);
    int32_t nc[3];
    double cs[3];
    int64_t tot = 1;
    for (int c = 0; c < 3; c++) {
      double n = floor(ext[c] / (s > 0.0 ? s : 1e-9)) + 1.0;
      if (n > 512.0) n = 512.0;
      nc[c] = (int32_t)n;
      cs[c] = ext[c] / (double)nc[c];
      tot *= nc[c];
    }
    int32_t *cr = malloc((size_t)np * 6 * sizeof *cr);
    int32_t *start = calloc((size_t)tot + 1, sizeof *start);
    if (cr == NULL || start == NULL) {
      free(cr);
      free(start);
      for (int t = 0; t < nthr; t++)
        free(TL[t].pl);
      free(TL);
      free(TS);
      free(bb);
      free(par);
      return 2;
    }
    double half = 0.5 * cfg->delta;
    for (int32_t k = 0; k < np; k++)
      for (int c = 0; c < 3; c++) {
        double t0 = (bb[(size_t)k * 6 + (size_t)c] - half - glo[c]) / cs[c];
        double t1 = (bb[(size_t)k * 6 + 3 + (size_t)c] + half - glo[c]) / cs[c];
        int32_t i0 = (int32_t)floor(t0), i1 = (int32_t)floor(t1);
        if (i0 < 0) i0 = 0;
        if (i0 > nc[c] - 1) i0 = nc[c] - 1;
        if (i1 < 0) i1 = 0;
        if (i1 > nc[c] - 1) i1 = nc[c] - 1;
        if (i1 < i0) i1 = i0;
        cr[(size_t)k * 6 + (size_t)c] = i0;
        cr[(size_t)k * 6 + 3 + (size_t)c] = i1;
      }
    /* Два прохода развёрнуты ЯВНО, а не циклом по `pass`: у выделения внутри
     * цикла gcc-analyzer теряет связь «после прохода 0 указатель заведён» и
     * докладывает разыменование NULL. Развёрнутая форма и человеку читается
     * прямее. */
    for (int32_t k = 0; k < np; k++)
      for (int32_t z = cr[(size_t)k * 6 + 2]; z <= cr[(size_t)k * 6 + 5]; z++)
        for (int32_t y = cr[(size_t)k * 6 + 1]; y <= cr[(size_t)k * 6 + 4]; y++)
          for (int32_t x = cr[(size_t)k * 6 + 0]; x <= cr[(size_t)k * 6 + 3]; x++)
            start[((int64_t)z * nc[1] + y) * nc[0] + x + 1]++;
    for (int64_t c = 0; c < tot; c++)
      start[c + 1] += start[c];
    int32_t *idx = calloc((size_t)(start[tot] > 0 ? start[tot] : 1), sizeof *idx);
    if (idx == NULL) {
      free(cr);
      free(start);
      for (int t = 0; t < nthr; t++)
        free(TL[t].pl);
      free(TL);
      free(TS);
      free(bb);
      free(par);
      return 2;
    }
    for (int32_t k = 0; k < np; k++)
      for (int32_t z = cr[(size_t)k * 6 + 2]; z <= cr[(size_t)k * 6 + 5]; z++)
        for (int32_t y = cr[(size_t)k * 6 + 1]; y <= cr[(size_t)k * 6 + 4]; y++)
          for (int32_t x = cr[(size_t)k * 6 + 0]; x <= cr[(size_t)k * 6 + 3]; x++)
            idx[start[((int64_t)z * nc[1] + y) * nc[0] + x]++] = k;
    for (int64_t c = tot; c > 0; c--)
      start[c] = start[c - 1];
    st->ngridcell = tot;
    st->ngrident = start[tot];
    st->bytes_grid = (int64_t)np * 6 * (int64_t)sizeof *cr + (tot + 1) * (int64_t)sizeof *start +
                     (int64_t)start[tot] * (int64_t)sizeof *idx;
    start[0] = 0;

    st->t_grid = pm_now() - tphase;
    tphase = pm_now();
    tcpu0 = pm_cpu();
    /* ЦИКЛ ПО ЯЧЕЙКАМ — ПАРАЛЛЕЛЬНЫЙ, `dynamic`: цена ячейки различается на
     * порядки (у города медиана 4 треугольника при максимуме 695 364), и
     * статическое деление дало бы перекос вместо ускорения. Гонок нет:
     * пишет каждый поток только в СВОЙ список и СВОИ счётчики, а правило
     * «пара выдаётся из ПЕРВОЙ общей ячейки» есть функция ПАРЫ, а не обхода
     * (А59: ячейка-эмитент — покоординатный максимум нижних углов коробок).
     * НЕХВАТКА ПАМЯТИ — ОТКАЗ ВСЕЙ ФУНКЦИИ, а не усечённый список (А60): из
     * `omp for` не выйти по `break`, поэтому флаг проверяется в начале тела, а
     * усечённый список означал бы ложно малое число слияний. */
#pragma omp parallel for schedule(dynamic, 8)
    for (int64_t c = 0; c < tot; c++) {
      int oomlocal;
#pragma omp atomic read
      oomlocal = oom;
      if (oomlocal) continue;
      int th = omp_get_thread_num();
      int64_t x = c % nc[0], y = (c / nc[0]) % nc[1], z = c / ((int64_t)nc[0] * nc[1]);
      for (int32_t i = start[c]; i < start[c + 1]; i++)
        for (int32_t j = i + 1; j < start[c + 1]; j++) {
          int32_t a = idx[i], b = idx[j];
          if (a > b) {
            int32_t t = a;
            a = b;
            b = t;
          }
          /* ПАРА ВЫДАЁТСЯ ОДИН РАЗ — из ПЕРВОЙ общей ячейки. Иначе крупный
           * полигон, лежащий в сотне ячеек, дал бы сотню одинаковых пар, и
           * они прошли бы дорогие ворота по сто раз. */
          int first = 1;
          for (int cc = 0; cc < 3 && first; cc++) {
            int32_t lo = cr[(size_t)a * 6 + (size_t)cc];
            if (cr[(size_t)b * 6 + (size_t)cc] > lo) lo = cr[(size_t)b * 6 + (size_t)cc];
            int64_t me = (cc == 0) ? x : ((cc == 1) ? y : z);
            if (me != lo) first = 0;
          }
          if (!first) continue;
          if (pm_emit(&TL[th], ps, bb, a, b, cfg, &TS[th]) != 0) {
#pragma omp atomic write
            oom = 1;
          }
        }
    }
    free(cr);
    free(start);
    free(idx);
  }
  st->t_gate = pm_now() - tphase;
  st->t_gate_cpu = pm_cpu() - tcpu0;
  tphase = pm_now();
  /* --- сцепка списков в порядке номеров потоков и редукция счётчиков --- */
  int64_t pn = 0;
  for (int t = 0; t < nthr; t++) {
    pn += TL[t].pn;
    if (TL[t].pn > st->npair_thr_max) st->npair_thr_max = TL[t].pn;
    st->ncand += TS[t].ncand;
    st->npair += TS[t].npair;
    st->nrej_geom += TS[t].nrej_geom;
    st->nrej_overlap += TS[t].nrej_overlap;
    st->ngate_major += TS[t].ngate_major;
    st->ngate_exact += TS[t].ngate_exact;
    st->ngate_ov += TS[t].ngate_ov;
    st->ngate_ovbox += TS[t].ngate_ovbox;
    st->nwork_tri += TS[t].nwork_tri;
    st->nwork_bv += TS[t].nwork_bv;
  }
  pm_pair *pl = malloc((size_t)(pn > 0 ? pn : 1) * sizeof *pl);
  if (pl == NULL) oom = 1;
  if (oom) {
    free(pl);
    for (int t = 0; t < nthr; t++)
      free(TL[t].pl);
    free(TL);
    free(TS);
    free(bb);
    free(par);
    return 2;
  }
  /* Сцепка — момент наибольшей памяти: живы и все списки потоков, и итоговый
   * массив. Учитывается именно так, а не суммой пиков (та была бы мажорантой). */
  pm_bytes_add(0, pn * (int64_t)sizeof *pl);
  {
    int64_t at = 0;
    for (int t = 0; t < nthr; t++) {
      memcpy(pl + at, TL[t].pl, (size_t)TL[t].pn * sizeof *pl);
      at += TL[t].pn;
      free(TL[t].pl);
      TL[t].pl = NULL;
    }
  }
  free(TL);
  free(TS);
  st->bytes_pairs_peak = pm_bytes_max;
  st->npair_list = pn;

  /* --- слияние по возрастанию ошибки (Т2: приоритет — качество) ---
   * ГЕОМЕТРИЯ ПРОВЕРЯЕТСЯ ЗДЕСЬ, ПО ОБЪЕДИНЕНИЮ ГРУПП. Списки членов ведутся
   * односвязно: `head[корень] -> nxt`. Слияние принимается, только если у
   * ОБЪЕДИНЁННОЙ группы `dmax < δ`; иначе пара отбрасывается, а группы живут
   * дальше и могут слиться с другими. */
  /* ТАКТИКА ПОЛОС ПО ДВУГРАННОМУ УГЛУ (§59, уточнено пользователем 07-30).
   *
   * СЧИТАЕТСЯ ИМЕННО ДВУГРАННЫЙ УГОЛ, А НЕ УГОЛ МЕЖДУ НОРМАЛЯМИ, и это не
   * переименование. Две лицевые компланарные грани дают `180°`, слабый излом —
   * `170°`, прямой угол коробки — `90°`, лицо и изнанка тонкой ножки — `0°`.
   * Угол между нормалями путает ВЫПУКЛЫЙ излом с ВОГНУТЫМ: у обоих он `10°`, а
   * двугранные при этом `170°` и `190°` — разные объекты. Знак берётся
   * симметричным признаком `D = (n_A − n_B)·(c_B − c_A)`: `D < 0` — выпуклый
   * (сосед ЗА плоскостью, внешний угол коробки), `D > 0` — вогнутый (угол
   * комнаты). Проверено на сцене: зал вогнутый, город выпуклый, см. доклад.
   *
   * Приоритет — |180° − φ|, то есть отклонение от плоского в любую сторону;
   * порядок по величине совпадает с прежним, а знак теперь ЗАПИСАН, и потому
   * выпуклое от вогнутого можно будет разделить замером, а не догадкой. */
  {
    const double PI = 3.14159265358979323846;
    for (int64_t i = 0; i < pn; i++) {
      const hz_poly *A = &ps->p[pl[i].a], *B = &ps->p[pl[i].b];
      double cs = A->n[0] * B->n[0] + A->n[1] * B->n[1] + A->n[2] * B->n[2];
      if (cs > 1.0) cs = 1.0;
      if (cs < -1.0) cs = -1.0;
      double th = acos(cs) * 180.0 / PI; /* отклонение от плоского, `0…180` */
      double dd = 0.0;
      for (int c = 0; c < 3; c++)
        dd += (A->n[c] - B->n[c]) * (B->org[c] - A->org[c]);
      /* Двугранный угол через МАТЕРИАЛ: выпуклый режет его ниже `180`, вогнутый
       * поднимает выше. Гистограмма — двенадцать корзин по `30°` от `0` до
       * `360`, то есть плоское садится на границу корзин 5|6 и видно сразу. */
      double phi = (dd < 0.0) ? 180.0 - th : 180.0 + th;
      int hb = (int)(phi / 30.0);
      if (hb < 0) hb = 0;
      if (hb > 11) hb = 11;
      st->dih_hist[hb]++;
      if (th > 1e-9) {
        if (dd < 0.0)
          st->ndih_conv++;
        else
          st->ndih_conc++;
      } else {
        st->ndih_flat++;
      }
      if (cfg->bands) {
        /* Полосы в НАЗВАНИИ ПОЛЬЗОВАТЕЛЯ: сперва `180°` (ровно плоское), затем
         * до `179`, `178`, `175`, `170`, `160`, `135`, дальше всё. Числа не
         * подобраны под результат — это та же двоично-десятичная шкала,
         * записанная от `180` вниз, и её выбор есть параметр замера. */
        const double band[7] = {180.0, 179.0, 178.0, 175.0, 170.0, 160.0, 135.0};
        int bk = 7;
        /* Полоса берётся по ОТКЛОНЕНИЮ, поэтому выпуклый `170` и вогнутый `190`
         * попадают в одну — разделять их пока нечем, кроме замера, и он
         * впереди. */
        for (int q = 0; q < 7; q++)
          if (th <= 180.0 - band[q] + 1e-9) {
            bk = q;
            break;
          }
        /* Ошибка сдвигается на номер полосы: сортировка по ней даёт полосы
         * подряд, а внутри полосы — прежний порядок по ошибке. */
        pl[i].err += (double)bk * 1024.0;
      }
    }
  }
  qsort(pl, (size_t)pn, sizeof *pl, cmp_pair);
  st->bytes_pairs = pn * (int64_t)sizeof *pl;
  /* СОВПАДАЮЩИЕ ОШИБКИ — мера силы негативного контроля О8, а не статистика.
   * Порядок доопределён номерами именно на этот случай; если совпадений нет,
   * снятие доопределения ничего не изменит, и контроль окажется слепым, не
   * будучи от этого пройденным. */
  for (int64_t i = 1; i < pn; i++)
    if (pl[i].err >= pl[i - 1].err && pl[i].err <= pl[i - 1].err) st->ntie++;
  int32_t *head = malloc((size_t)np * sizeof *head);
  int32_t *nxt = malloc((size_t)np * sizeof *nxt);
  int32_t *mem = malloc((size_t)np * sizeof *mem);
  /* ХВОСТ СПИСКА У КОРНЯ — ЭТО ВСЁ, ЧТО ОТ О9 УЦЕЛЕЛО (§21). Накопители
   * `Σ A`, `Σ A·n`, `Σ A·org` были написаны и измерены: плоскость объединения
   * они дают за `O(1)`, но их порядок суммирования — ДРУГОЙ, и на городе при
   * δ = 8 м это сломало инвариант (`dmax_worst = 9.236` при допуске `8`),
   * потому что при взаимно гасящихся нормалях направление групповой нормали
   * есть направление остатка округления (А76, А77). Хвост же ни одного числа не
   * меняет — он снимает только проход до конца списка. */
  int32_t *tail = malloc((size_t)np * sizeof *tail);
  /* РЕШАЮЩАЯ ПЛОСКОСТЬ ХРАНИТСЯ У КОРНЯ, А НЕ ПЕРЕСЧИТЫВАЕТСЯ В РАЗМЕТКЕ (А96).
   * Минимаксный решатель зависит от ПОРЯДКА членов (обмен идёт от начальной
   * четвёрки), а разметка обходит полигоны по номерам, а не по списку группы, —
   * и получает ДРУГУЮ плоскость. Замер на зале: группа из пяти кусков прошла по
   * наклонной плоскости при δ = 0.3, а разметка пересчитала по средневзвешенной
   * и дала `dmax = 1.602` м. Инвариант ломался ровно на этом. Плоскость, по
   * которой принято решение, — единственная законная для доклада. */
  double *gpl = malloc((size_t)np * 4 * sizeof *gpl);
  if (head == NULL || nxt == NULL || mem == NULL || tail == NULL || gpl == NULL) {
    free(gpl);
    free(head);
    free(nxt);
    free(mem);
    free(tail);
    free(pl);
    free(bb);
    free(par);
    return 2;
  }
  for (int32_t k = 0; k < np; k++) {
    head[k] = k;
    nxt[k] = -1;
    tail[k] = k;
    /* Одиночная группа: плоскость — собственная плоскость полигона. */
    for (int c = 0; c < 3; c++)
      gpl[(size_t)k * 4 + (size_t)c] = ps->p[k].n[c];
    gpl[(size_t)k * 4 + 3] = ps->p[k].off;
  }
  int32_t nleft = np;
  for (int64_t i = 0; i < pn; i++) {
    if (cfg->target > 0 && nleft <= cfg->target) break;
    int32_t ra = uf_find(par, pl[i].a), rb = uf_find(par, pl[i].b);
    if (ra == rb) continue;
    st->nmerge_try++;
    /* ГРУППА НЕ ПОМЕСТИЛАСЬ — ОТКАЗ, А НЕ ОБРЕЗАНИЕ. Прежняя форма
     * (`nm < np` в условии цикла) молча останавливала сбор членов, и `dmax`
     * считался по УСЕЧЁННОЙ группе, то есть выходил ложно малым, а слияние
     * принималось. Случиться этого не может (группы суть разбиение `np`
     * полигонов), но «не может» — это то самое место, где ложный ноль и
     * заводится: он опаснее UNKNOWN, потому что не останавливает потребителя
     * (Ш7). Поэтому счётчик и отказ от слияния — fail closed. */
    /* ПЛОСКОСТЬ ОБЪЕДИНЕНИЯ — СЛОЖЕНИЕМ НАКОПИТЕЛЕЙ, `O(1)`. Это и есть то, что
     * от О9 УЦЕЛЕЛО (§21): прежняя форма пересматривала все члены объединения
     * ради той же плоскости, то есть тратила `O(k)` на каждую попытку.
     *
     * ГРАНИЦЫ ЗДЕСЬ БОЛЬШЕ НЕТ, И ЭТО РЕЗУЛЬТАТ ЗАМЕРА, А НЕ УПРОЩЕНИЕ.
     * Замысел был: держать у корня `dmax`, радиус `R` и `mincos`, оценивать
     * прирост сверху как `|n'−n|·R + |n'·(c−c')|` и считать точно лишь тогда,
     * когда оценка вылезает за допуск. Измерено на городе при δ = 2 м: точный
     * пересчёт всё равно требовался в `94.3%` попыток, а поддержание `R` стоило
     * ТРЁХ лишних действий на каждую опорную точку и подняло фазу слияния
     * `8.13 → 22.6` с. Причина не в реализации: огрубитель ведёт группу до
     * упора в допуск, поэтому `dmax` группы у самой границы `δ` — обычное
     * состояние, а не исключение, и всякая оценка вида «`dmax` плюс запас» в
     * этом режиме бесполезна по существу. Сработало условие УБИВАЕТ из §19. */
    /* ПЛОСКОСТЬ ГРУППЫ СЧИТАЕТСЯ ПО ЧЛЕНАМ ЗАНОВО, А НАКОПИТЕЛЕЙ ЗДЕСЬ НЕТ, И
     * ЭТО ИТОГ ЗАМЕРА, А НЕ ОСТОРОЖНОСТЬ (§21, А76).
     *
     * Замысел О9 был: держать у корня `Σ A`, `Σ A·n`, `Σ A·org` и брать
     * плоскость объединения сложением за `O(1)`. Реализовано и измерено — и
     * СЛОМАЛО ИНВАРИАНТ: город при δ = 8 м дал `dmax_worst = 9.236` м при
     * допуске `8`. Улики: у виновной группы `|Σ A·n| = 0.000000` при
     * `Σ A = 35.88` — это встречные грани (`+0.7071, 0, +0.7071` и
     * `−0.7071, 0, −0.7071`), то есть ровно случай А17/А22. Проверка
     * `n_i·n > 0` их не поймала, потому что при почти полном взаимном гашении
     * направление групповой нормали есть направление ОСТАТКА ОКРУГЛЕНИЯ, а
     * остаток у накопленной суммы ДРУГОЙ, чем у свежей: он может лечь так, что
     * все `n_i·n` окажутся положительными. Старый порядок суммирования на этих
     * данных давал остаток, при котором проверка срабатывала, — то есть она
     * держалась на удаче, и это записано находкой отдельно (А77).
     *
     * ЧТО ОТ О9 УЦЕЛЕЛО: `O(1)`-сцепка списков по хвосту. Она значений не
     * трогает вовсе, поэтому выход остаётся ПОБИТОВО прежним. */
    int32_t nm = 0;
    int trunc = 0;
    for (int32_t x = head[ra]; x >= 0; x = nxt[x]) {
      if (nm >= np) {
        trunc = 1;
        break;
      }
      mem[nm++] = x;
    }
    for (int32_t x = head[rb]; x >= 0 && !trunc; x = nxt[x]) {
      if (nm >= np) {
        trunc = 1;
        break;
      }
      mem[nm++] = x;
    }
    /* ГРУППА НЕ ПОМЕСТИЛАСЬ — ОТКАЗ, А НЕ ОБРЕЗАНИЕ. Случиться этого не может
     * (группы суть разбиение `np` полигонов), но «не может» — то самое место,
     * где заводится ложный ноль: усечённая группа дала бы ложно малый `dmax`,
     * и слияние приняли бы (Ш7). Поэтому счётчик и отказ. */
    if (trunc) {
      st->ntrunc++;
      continue;
    }
    st->nmerge_exact++;
    st->nwork_merge_mem += nm;
    {
      double n[3], off, cone = 0.0;
      double q = group_plane(ps, mem, nm, n, &off, &st->nwork_merge_sup, st, cfg->quarter,
                             cfg->conemax, &cone);
      const double dgate = (cfg->dgate > 0.0) ? cfg->dgate : cfg->delta;
      if (cfg->use_geom && !cfg->random && !cfg->noexact && !(q < dgate)) {
        st->nrej_geom++;
        continue;
      }
      /* §38: ФОРМА КАК КРИТЕРИЙ. Потеря площади худшим членом (`1/|n_i·N|`) —
       * МАКСИМУМ, а не среднее: среднее прячет одну перпендикулярную грань в
       * сотне компланарных. Вытянутость — против вырожденной подгонки (А95). */
      if (q < 1e299 && (cfg->lossmax > 0.0 || cfg->aspmax > 0.0)) {
        double asp = 1.0, loss = 1.0;
        pm_shape(ps, mem, nm, n, NULL, &asp, &loss);
        if ((cfg->lossmax > 0.0 && loss > cfg->lossmax) ||
            (cfg->aspmax > 0.0 && asp > cfg->aspmax)) {
          st->nrej_shape++;
          continue;
        }
      }
      /* Полураствор — в гистограмму ТОЛЬКО у принятого слияния (А99). */
      if (q < 1e299) {
        int bk = (int)(cone / 5.0);
        if (bk < 0) bk = 0;
        if (bk > 17) bk = 17;
        st->cone_hist[bk]++;
        if (cone > st->cone_max) st->cone_max = cone;
        /* §61: СТОРОНА ЧЛЕНА ОТНОСИТЕЛЬНО ЭЛЕМЕНТА. Замер, а не ворота: ставить
         * порог до того, как известно, случается ли это вовсе, значило бы
         * подобрать его под догадку. */
        {
          double smin = 1.0;
          for (int32_t mi = 0; mi < nm; mi++) {
            const hz_poly *P = &ps->p[mem[mi]];
            double d = P->n[0] * n[0] + P->n[1] * n[1] + P->n[2] * n[2];
            if (d < smin) smin = d;
          }
          if (smin < st->side_min) st->side_min = smin;
          if (smin < 0.0) st->nside_mix++;
          if (smin < -0.9) st->nside_anti++;
        }
        /* §38: ВЫТЯНУТОСТЬ И ПОТЕРЯ ПЛОЩАДИ — замер по принятым слияниям. Обе
         * величины считаются из уже имеющегося: вторые моменты `mom[6]` точны,
         * взвешены площадью и аддитивны (А21), потеря площади есть `1/|n_i·N|`.
         * Пока ТОЛЬКО замер: порогов нет, критерий не тронут. */
        pm_shape(ps, mem, nm, n, st, NULL, NULL);
      }
      /* Плоскость объединения запоминается у БУДУЩЕГО корня (`ra`). */
      if (q < 1e299) {
        for (int c = 0; c < 3; c++)
          gpl[(size_t)ra * 4 + (size_t)c] = n[c];
        gpl[(size_t)ra * 4 + 3] = off;
      }
    }
    /* СЦЕПКА ЗА `O(1)`: корнем объединения всегда становится `ra`, поэтому
     * достаточно перенести хвост (А70: сжатие путей в `uf_find` корней не
     * меняет). Прежняя форма шла до хвоста проходом, то есть тратила ещё одно
     * `O(k)` на каждую принятую пару. */
    nxt[tail[ra]] = head[rb];
    tail[ra] = tail[rb];
    par[rb] = ra;
    nleft--;
    st->nmerged++;
  }
  free(tail);
  free(head);
  free(nxt);
  free(mem);
  free(pl);
  free(bb);

  st->t_merge = pm_now() - tphase;
  tphase = pm_now();
  /* --- новая разметка: треугольник наследует корень своего полигона --- */
  int32_t *rank = malloc((size_t)np * sizeof *rank);
  so->label = malloc((size_t)m->nt * sizeof *so->label);
  so->seg = calloc((size_t)np, sizeof *so->seg);
  if (rank == NULL || so->label == NULL || so->seg == NULL) {
    free(rank);
    free(par);
    hz_seg_free(so);
    return 2;
  }
  for (int32_t k = 0; k < np; k++)
    rank[k] = -1;
  int32_t nn = 0;
  for (int32_t k = 0; k < np; k++) {
    int32_t r = uf_find(par, k);
    if (rank[r] < 0) {
      rank[r] = nn;
      so->seg[nn] = si->seg[si->label[ps->tri[ps->p[r].t0]]];
      so->seg[nn].area = 0.0;
      so->seg[nn].ntri = 0;
      so->seg[nn].dmax = 0.0;
      nn++;
    }
  }
  /* ПЛОСКОСТЬ ВЫХОДНОЙ ГРУППЫ — ТА ЖЕ МИНИМАКСНАЯ, ЧТО РЕШАЛА ПРИ СЛИЯНИИ, И
   * ИНАЧЕ НЕЛЬЗЯ (§28, п. 4). Если критерий принимает по одной плоскости, а
   * разметка считает `dmax` по другой (средневзвешенной), инвариант ломается
   * ровно так, как сломался в О9: город при δ = 8 м дал тогда `9.236` м при
   * допуске `8` (А76). Поэтому здесь собираются члены каждой группы и
   * вызывается тот же `group_plane`. Цена — один проход по опорным точкам всей
   * сцены, то есть меньше одной попытки слияния на группу. */
  for (int32_t k = 0; k < np; k++) {
    int32_t r = uf_find(par, k);
    if (r != k) continue;
    int32_t g = rank[r];
    for (int c = 0; c < 3; c++)
      so->seg[g].n[c] = gpl[(size_t)r * 4 + (size_t)c];
    so->seg[g].off = gpl[(size_t)r * 4 + 3];
  }
  free(gpl);

  /* Треугольник знает свой ИСХОДНЫЙ участок; полигон — тот же индекс, потому
   * что `hz_poly_build` нумерует полигоны участками один к одному. */
  for (int32_t t = 0; t < m->nt; t++) {
    int32_t k = si->label[t];
    int32_t g = rank[uf_find(par, k)];
    so->label[t] = g;
    so->seg[g].ntri++;
    so->seg[g].area += hz_obj_tri_area(m, t);
    double p[3][3];
    hz_obj_tri(m, t, p);
    for (int i = 0; i < 3; i++) {
      double d = fabs(p[i][0] * so->seg[g].n[0] + p[i][1] * so->seg[g].n[1] +
                      p[i][2] * so->seg[g].n[2] - so->seg[g].off);
      if (d > so->seg[g].dmax) so->seg[g].dmax = d;
    }
  }
  for (int32_t g = 0; g < nn; g++)
    if (so->seg[g].dmax > st->dmax_worst) st->dmax_worst = so->seg[g].dmax;
  /* СЛЕПОК РАЗМЕТКИ (FNV-1a). Сквозное требование фазы I — «выход не меняется
   * ПОБИТОВО» — было записано, а сличать его было нечем: ни один стенд не
   * печатал величины, по которой два прогона сравниваются. Сравнение «по числу
   * полигонов и dmax» этого не заменяет: те же 700 участков можно получить
   * ДРУГИМ разбиением. */
  {
    uint64_t h = 1469598103934665603ULL;
    for (int32_t t = 0; t < m->nt; t++) {
      uint32_t v = (uint32_t)so->label[t];
      for (int i = 0; i < 4; i++) {
        h ^= (uint64_t)((v >> (8 * i)) & 0xFFu);
        h *= 1099511628211ULL;
      }
    }
    st->digest = h;
  }
  st->t_label = pm_now() - tphase;
  so->nseg = nn;
  so->delta = si->delta;
  st->nseg_out = nn;
  free(rank);
  free(par);
  return 0;
}
