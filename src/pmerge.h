/* pmerge.h — ОГРУБЛЕНИЕ: слияние полигонов по ГЕОМЕТРИИ.
 *
 * PLAN_ELEMENTS.md, Ш7. Огрубление есть СЛИЯНИЕ, а не удаление (§1.10):
 * удаление у тонкого тела разрушает замкнутость.
 *
 * КРИТЕРИЙ ЧИСТО ГЕОМЕТРИЧЕСКИЙ, И ЭТО ИСПРАВЛЕНИЕ ПО ЗАМЕРУ, А НЕ ПЛАН.
 * Плана требовал КОНЪЮНКЦИИ с членом по ПОЛЮ («половинки теневого разреза
 * компланарны, слияние по одной геометрии сольёт их обратно, уничтожив Ш6»).
 * Ш7 (вторая поправка) этот довод опроверг дважды: при РАВНОМ числе полигонов
 * геометрия БЕЗ поля оказалась вчетверо лучше по медиане и вдвое по доле
 * площади, а посылка исчезла вместе с Ш6 — теневые разрезы не нужны, их роль
 * играет детализация, и уничтожать нечего. Члены по полю и по материалу
 * УБРАНЫ из кода вслед за выводом: держать в коде отвергнутый замером критерий
 * значит приглашать его обратно.
 *
 *   1. ГЕОМЕТРИЯ. Невязка QEF по эрмитовым образцам обеих частей ниже `δ` —
 *      дешёвые ворота. Затем ТОЧНЫЙ `dmax` по общей плоскости, потому что
 *      невязка QEF есть СРЕДНЕКВАДРАТИЧНОЕ, а критерий — МАКСИМУМ (Г40/Г44), и
 *      подменять одно другим запрещено прямым текстом.
 *   2. НЕПЕРЕКРЫТИЕ ПРОЕКЦИЙ — ДОБАВЛЕНО ПО ЗАМЕРУ Ш3 и оставлено. Оно не про
 *      точность, а про то, что критерий Ш1 «все точки в пределах δ от общей
 *      плоскости» РАЗРЕШАЕТ слить две одинаково смотрящие поверхности,
 *      оказавшиеся ближе `δ` (две полки, столешница и подставка), а слипшиеся
 *      листы теряют площадь ФИЗИЧЕСКИ — до 10.6% площади сцены на грубом `δ`.
 *      Баланс энергии такого НЕ ЛОВИТ: он сходится на любой площади (узор
 *      К13/К40/К94).
 *
 * СЛЕДСТВИЕ, РАДИ КОТОРОГО ЭТО И ВАЖНО: критерий НЕ ЗАВИСИТ ОТ СВЕТА, значит
 * иерархия строится ОДИН РАЗ при импорте и живёт при любом освещении. Именно
 * так устроен Nanite, и совместимость с ним теперь прямая.
 *
 * `dmax` ПЕРЕСЧИТЫВАЕТСЯ ПРИ КАЖДОМ СЛИЯНИИ. При импорте он честный (Ш2), после
 * слияния — другой, и ЛОЖНЫЙ НОЛЬ ОПАСНЕЕ `UNKNOWN`: тот останавливает
 * потребителя, этот пропускает.
 *
 * КАНДИДАТЫ БЕРУТСЯ СЕТКОЙ, А НЕ ПЕРЕБОРОМ ПАР. Перебор `O(np²)` на зале (993)
 * стоил секунды, а на городе (285 тыс.) означал `4e10` пар — то есть город был
 * недостижим не по существу, а по устройству цикла. Сетка даёт ТОТ ЖЕ набор
 * пар: в ячейку полигон кладётся по коробке, РАСШИРЕННОЙ на `δ/2`, поэтому две
 * коробки ближе `δ` заведомо делят ячейку, а точная проверка `near` остаётся
 * той же. Совпадение выходов проверяется флагом `brute` — прямым прогоном
 * старого перебора, а не рассуждением.
 *
 * ВЫХОД НЕ ОБЯЗАН БЫТЬ РАЗБИЕНИЕМ ВХОДА (§5, урок 3), но подгонка (edge-collapse)
 * с критического пути снята Ш7 (третья поправка): дно по числу полигонов задаёт
 * ТОПОЛОГИЯ поверхности, и слияние его уже достигает.
 */
#ifndef HZ_PMERGE_H
#define HZ_PMERGE_H

#include "poly_seg.h"
#include "polygon.h"
#include "scene_obj.h"

typedef struct {
  double delta;              /* геометрический допуск, м */
  int use_geom, use_overlap; /* включение членов */
  /* НЕГАТИВНЫЙ КОНТРОЛЬ: сливать по СЛУЧАЙНОЙ метрике. Ошибка обязана стать
   * O(1); если не стала — критерий ничего не решает и мерили не его. */
  int random;
  /* ПРОВЕРКА СЕТКИ КАНДИДАТОВ: перебрать пары в лоб, `O(np²)`. Не режим
   * работы, а эталон — набор пар обязан совпасть с сеточным. */
  int brute;
  int32_t target; /* до скольких полигонов огрублять; <=0 — пока сливается */
} hz_mergecfg;

typedef struct {
  int64_t npair, nmerged;
  int64_t nrej_geom, nrej_overlap;
  int64_t ncand;     /* пар, дошедших до проверки `near` (цена сетки) */
  int64_t ngridcell; /* ячеек сетки кандидатов */
  int64_t ngrident;  /* вхождений полигонов в ячейки */
  double dmax_worst; /* худший dmax ПОСЛЕ слияния, м */
  int32_t nseg_in, nseg_out;
  /* ВРЕМЯ ПО ФАЗАМ. Заведено потому, что «огрубление города идёт семь минут» —
   * это не адрес, а жалоба. Фазы разделены так, что каждая отвечает своему
   * подозреваемому: сетка — устройству отбора, ворота — цене ОДНОЙ пары,
   * слияние — скрытой квадратичности по размеру группы (`group_plane`
   * пересматривает объединение на каждой попытке), разметка — выходу. */
  double t_grid, t_gate, t_merge, t_label;
} hz_mergestat;

int hz_merge(hz_pseglist *so, const hz_objmesh *m, const hz_pseglist *si, const hz_polyset *ps,
             const hz_mergecfg *cfg, hz_mergestat *st);

#endif
