/* pmerge.h — ОГРУБЛЕНИЕ: слияние полигонов по КОНЪЮНКЦИИ критериев.
 *
 * PLAN_ELEMENTS.md, Ш7. Огрубление есть СЛИЯНИЕ, а не удаление (§1.10):
 * удаление у тонкого тела разрушает замкнутость.
 *
 * КРИТЕРИЙ — КОНЪЮНКЦИЯ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А НЕОБХОДИМОСТЬ (Ш7 дословно):
 * половинки теневого разреза КОМПЛАНАРНЫ, и слияние по одной геометрии сольёт
 * их обратно с невязкой ноль, уничтожив Ш6 подчистую. Членов ЧЕТЫРЕ, и
 * четвёртый добавлен по замеру Ш3, а не взят из плана:
 *
 *   1. ГЕОМЕТРИЯ. Невязка QEF по эрмитовым образцам обеих частей ниже `δ` —
 *      дешёвые ворота. Затем ТОЧНЫЙ `dmax` по общей плоскости, потому что
 *      невязка QEF есть СРЕДНЕКВАДРАТИЧНОЕ, а критерий — МАКСИМУМ (Г40/Г44), и
 *      подменять одно другим запрещено прямым текстом.
 *   2. ПОЛЕ. Радиансы частей различаются меньше допуска. Без этого сливаются
 *      освещённая и затенённая половины — то самое, что Ш6 разделял.
 *   3. МАТЕРИАЛ. Альбедо совместимы.
 *   4. НЕПЕРЕКРЫТИЕ ПРОЕКЦИЙ — ДОБАВЛЕНО ПО ЗАМЕРУ Ш3. Критерий Ш1 «все точки в
 *      пределах δ от общей плоскости» РАЗРЕШАЕТ слить две одинаково смотрящие
 *      поверхности, оказавшиеся ближе `δ` (две полки, столешница и подставка), и
 *      на грубом `δ` это съедает до 10.6% площади сцены. Баланс энергии такого
 *      НЕ ЛОВИТ — он сходится на любой площади (узор К13/К40/К94). Поэтому
 *      неперекрытие проверяется явно, а не подразумевается.
 *
 * `dmax` ПЕРЕСЧИТЫВАЕТСЯ ПРИ КАЖДОМ СЛИЯНИИ. При импорте он честный (Ш2), после
 * слияния — другой, и ЛОЖНЫЙ НОЛЬ ОПАСНЕЕ `UNKNOWN`: тот останавливает
 * потребителя, этот пропускает.
 *
 * ВЫХОД НЕ ОБЯЗАН БЫТЬ РАЗБИЕНИЕМ ВХОДА (§5, урок 3; замечание пользователя):
 * огрубление — это ПОДГОНКА, и меньшее число полигонов может подгоняться под
 * большее, а не собираться из него. Здесь реализовано слияние (частный случай
 * подгонки, где выход всё же разбиение), и это ОГРАНИЧЕНИЕ РЕАЛИЗАЦИИ, а не
 * модели: подгонка даёт не хуже, и разница уже измерена в §8 — `265` против
 * `4 106` на одном и том же допуске.
 */
#ifndef HZ_PMERGE_H
#define HZ_PMERGE_H

#include "poly_seg.h"
#include "polygon.h"
#include "scene_obj.h"

typedef struct {
  double delta;                                /* геометрический допуск, м */
  double ltol;                                 /* допуск по радиансу, ДОЛЯ от среднего по сцене */
  double rtol;                                 /* допуск по альбедо */
  int use_geom, use_rad, use_mtl, use_overlap; /* включение членов конъюнкции */
  /* НЕГАТИВНЫЙ КОНТРОЛЬ: сливать по СЛУЧАЙНОЙ метрике. Ошибка обязана стать
   * O(1); если не стала — критерий ничего не решает и мерили не его. */
  int random;
  int32_t target; /* до скольких полигонов огрублять; <=0 — пока сливается */
} hz_mergecfg;

typedef struct {
  int64_t npair, nmerged;
  int64_t nrej_geom, nrej_rad, nrej_mtl, nrej_overlap;
  double dmax_worst; /* худший dmax ПОСЛЕ слияния, м */
  int32_t nseg_in, nseg_out;
} hz_mergestat;

/* `E` — 3·np коэффициентов поля (для члена 2), `rho` — np альбедо (член 3).
 * Оба могут быть NULL: тогда соответствующий член конъюнкции выключается, и
 * это докладывается, а не молчится. */
int hz_merge(hz_pseglist *so, const hz_objmesh *m, const hz_pseglist *si, const hz_polyset *ps,
             const double *E, const double *rho, const hz_mergecfg *cfg, hz_mergestat *st);

#endif
