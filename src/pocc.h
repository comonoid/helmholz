/* pocc.h — ЗАНЯТОСТЬ УЗЛОВ ДЕРЕВА: где есть кусок с ненулевой площадью.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Правило §241.4 («пол ограничивает размер ЭЛЕМЕНТА, а
 * НЕ размер пустого узла») стоит ≥17 раз на Rungholt и ≥54 на зале — это
 * измерено негативным контролем §263, где пол, применённый к пустоте, упёрся в
 * потолок 150 млн ячеек. Значит занятость нужна КАЖДОМУ обходу, и держать её
 * копию в каждом стенде — верный способ развести их определения.
 *
 * ОПРЕДЕЛЕНИЕ ОДНО И ТОЧНОЕ: ячейка занята, если её коробку задевает кусок с
 * НЕНУЛЕВОЙ ПЛОЩАДЬЮ (то же, что «ячеек с геометрией» в О70). Габаритный
 * суррогат брать нельзя, и это замерено: на зале он даёт 97.28 % занятых узлов
 * против 12.79 % настоящих — в семь раз, и правило «пустой узел целиком»
 * перестало бы работать почти везде.
 *
 * ГДЕ ЭТОМУ МЕСТО ПО-НАСТОЯЩЕМУ. Внутри ПОСТРОЙКИ дерева (указание пользователя
 * 08-05): она уже держит список кандидатов в каждом узле, и занятость получается
 * там на месте, без повторного обхода и повторной фильтрации — то есть почти
 * даром вместо измеренных 8.7 с. Здесь она пока считается отдельным проходом,
 * потому что О72 добавлял её к готовому дереву; перенос в постройку записан как
 * §264 п. 4.
 */
#ifndef HZ_POCC_H
#define HZ_POCC_H

#include "ptree.h"
#include "scene_obj.h"

/* Посчитать занятость всех узлов. `occ` — массив на `T->nnd` байт, `bocc` —
 * ГАБАРИТНАЯ занятость (верхняя оценка), можно `NULL`. Возврат: `0` — успех.
 * `tlo`/`thi`/`tpl` — коробки и плоскости треугольников, как их готовят стенды. */
int hz_pocc_build(const hz_objmesh *m, const hz_ptree *T, const double *tlo, const double *thi,
                  const double *tpl, unsigned char *occ, unsigned char *bocc);

/* ВЫСОТА ПОДДЕРЕВА: сколько уровней ниже узла ещё есть (`0` у листа). Нужна
 * затем, чтобы «огрубить на два уровня» имело смысл ОТНОСИТЕЛЬНО ТОГО, ГДЕ ФРОНТ
 * ОСТАНОВИЛСЯ БЫ ИНАЧЕ. А останавливается он в 58.9 %% случаев ЛИСТОМ (§257), и
 * значит мерить надо от дна поддерева, а не от пола и не от уровня узла: оба эти
 * способа были пробованы 08-06 и оба бессильны — пол не работает там, где лист
 * кончается раньше. Величина СТАТИЧНА и проходонезависима (свойство дерева), а
 * потому её место в узле законно (А133 её не касается). Считается тем же
 * проходом снизу вверх, что и занятость. */
void hz_pocc_depth(const hz_ptree *T, unsigned char *depth);

#endif
