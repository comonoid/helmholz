/* poly_seg.h — ПЛАНАРНАЯ СЕГМЕНТАЦИЯ: суп треугольников → плоские участки.
 *
 * PLAN_ELEMENTS.md, Ш1. Полигон «выводится сегментацией, не задаётся сеткой»
 * (§1.1), и здесь ровно этот вывод. Геометрию полигона (край, моменты, поле
 * нормалей) собирает Ш2 поверх выданной здесь разметки.
 *
 * КРИТЕРИЙ ОДИН, И ОН СВЯЗЫВАЕТ НОРМАЛЬ СО СМЕЩЕНИЕМ (§5, урок 1): все вершины
 * участка лежат в пределах `δ` от ОБЩЕЙ плоскости. Раздельного допуска по
 * нормали нет — фиксированный допуск по нормали запретил бы слияние кривой
 * поверхности НА ЛЮБОЙ дальности, а это ровно уже сделанная ошибка.
 *
 * СМЕЖНОСТЬ ПРОСТРАНСТВЕННАЯ, А НЕ СЕТОЧНАЯ (§5, урок 2): смежность по общим
 * индексам упирается в число связных компонент входа (3 603 у конференц-зала),
 * то есть меряет нарезку меша, а не сцену. Здесь два куска смежны, если
 * расстояние между их габаритными коробками не больше `δ`.
 *
 * ПОЧЕМУ ЗАЗОР РОВНО `δ`, А НЕ ОТДЕЛЬНОЕ ЧИСЛО. Слить два куска через зазор `g`
 * значит объявить поверхностью то, чего там нет, с геометрической ошибкой
 * порядка `g`; допуск на геометрическую ошибку и есть `δ`. Дальнобойного
 * слияния это НЕ запрещает: два куска пола в двадцати метрах сливаются ЦЕПОЧКОЙ
 * через промежуточные, а не прыжком, — и потому «слияние несмежного» (§5) здесь
 * невозможно по построению.
 *
 * ЗНАК НОРМАЛИ ПРОВЕРЯЕТСЯ, ВЕЛИЧИНА — НЕТ. Кандидат обязан смотреть в ту же
 * сторону, что и плоскость участка (`n_тр · n > 0`). Это НЕ допуск, а знак:
 * иначе передняя и задняя грани тонкой панели толщиной меньше `δ` слились бы в
 * один полигон, и он перестал бы быть односторонним — а односторонность нужна и
 * BRDF, и признаку «замыкает тело» (§1.10).
 *
 * ЗАТРАВКИ ПО ПЛОЩАДИ, А НЕ ПО НОМЕРУ В ФАЙЛЕ. Ш2 требует, чтобы набор
 * полигонов не менялся при перестановке треугольников входа, иначе
 * инкрементность не обоснована. Поэтому порядок затравок и порядок обхода
 * соседей задаются ГЕОМЕТРИЧЕСКИМ ключом (площадь по убыванию, затем центр
 * коробки лексикографически), а номер треугольника в него не входит вовсе.
 *
 * ПЛОСКОСТЬ ПОДГОНЯЕТСЯ ПО ХОДУ, А ИТОГ ПРОВЕРЯЕТСЯ ТОЧНО. Подгонка по
 * взвешенной площади ковариации минимизирует СРЕДНЕКВАДРАТИЧНОЕ, а критерий —
 * МАКСИМУМ (тот же зазор Г40/Г44, что у `dmax`). Поэтому после роста участок
 * ПРОВЕРЯЕТСЯ на итоговой плоскости, нарушители отпускаются обратно и
 * пересеиваются. На выходе `dmax ≤ δ` у каждого участка — не по вере, а по
 * проверке.
 */
#ifndef HZ_POLY_SEG_H
#define HZ_POLY_SEG_H

#include "scene_obj.h"

typedef struct {
  double n[3], off; /* плоскость n·x = off, |n| = 1, n согласована с гранями */
  double area;      /* м² */
  double dmax;      /* макс |n·x − off| по вершинам участка; ≤ δ по проверке */
  int32_t ntri;
} hz_pseg;

typedef struct {
  int32_t *label; /* nt: номер участка, всегда ≥ 0 после успеха */
  hz_pseg *seg;
  int32_t nseg;

  /* Доклад замера — часть выхода, а не отладка. */
  double delta;
  int64_t nrounds;    /* сколько раундов пересева понадобилось */
  int64_t nreleased;  /* сколько треугольников отпущено проверкой */
  int64_t ncross;     /* межуровневых пар смежности */
  int64_t ncand;      /* сколько кандидатов вообще рассмотрено (цена) */
  int32_t nlev;       /* занятых уровней сетки поиска */
} hz_pseglist;

/* delta — метры. Возврат 0 — успех, 2 — нет памяти. */
int hz_seg_planar(hz_pseglist *s, const hz_objmesh *m, double delta);
void hz_seg_free(hz_pseglist *s);

#endif
