/* prast.h — ПАРАЛЛЕЛЬНАЯ ПРОЕКЦИЯ ПОЛИГОНОВ: развёртка по направлению.
 *
 * PLAN_ELEMENTS.md, Ш3 — внутренний цикл всей схемы. На направление `ω` все
 * полигоны проецируются параллельно, перекрытие разрешается ПОРЯДКОМ ПО
 * ГЛУБИНЕ. Один проход обслуживает все полигоны: `O(направления × полигоны)`,
 * форм-факторов нет.
 *
 * ПОЧЕМУ НЕ `src/transport/raster3.c`, НА КОТОРЫЙ ССЫЛАЕТСЯ §1.5. Тот
 * растеризатор существует и работает, но делает две вещи, несовместимые с этой
 * моделью. Во-первых, он ПЕРСПЕКТИВНЫЙ (камера-обскура), а развёртке нужна
 * ПАРАЛЛЕЛЬНАЯ проекция — направление обслуживает всю сцену, а не то, что видно
 * из точки. Во-вторых, он растеризует `tr3_selem` и грани `tr3_mesh`, то есть
 * ОБЪЁМНЫЕ носители поля, а §6 их отвергла прямым текстом: «при σ = 0 радианс
 * постоянен вдоль луча ⇒ в прозрачном объёме независимых неизвестных НЕТ».
 * Общей осталась ИДЕЯ (проекция вместо марша, К52…К59); общего кода нет, и
 * притворяться, что есть, значило бы тащить за собой объёмную сетку.
 *
 * НУЖЕН КАЖДЫЙ ФРАГМЕНТ, А НЕ БЛИЖАЙШИЙ. Z-буфер отвечает на вопрос «что
 * видно»; перенос спрашивает «что чему светит», и поверхность на глубине `i`
 * освещается поверхностью на глубине `i−1`. Список фрагментов пикселя и есть
 * перечень пар «излучатель → приёмник» вдоль направления.
 *
 * ТРИ ШАГА, А НЕ ОДИН, И РАЗДЕЛЕНИЕ ЗДЕСЬ — ПРЕДМЕТ ЗАМЕРА Ш3.
 *   1. ПОЛОСЫ (`hz_prast_spans`) — заливка краёв даёт (строка, i0..i1, полигон)
 *      плюс аффинную глубину. Полос на порядки меньше, чем пикселей.
 *   2. РАСКЛАДКА — полосы разворачиваются в фрагменты. Способов два, и они дают
 *      РАЗНЫЙ доступ в памяти на третьем шаге:
 *        `hz_fbuf` — СПЛОШНЫЕ пробеги на пиксель (счётная сортировка). Чтение
 *                    редукции последовательно по всему буферу;
 *        `hz_abuf` — ОДНОСВЯЗНЫЕ списки. Чтение редукции — гонка по указателям.
 *      Плана требует «менять надо раскладку данных» как ответ на упор не туда,
 *      поэтому обе раскладки существуют одновременно и МЕРЯЮТСЯ, а не
 *      выбираются по вкусу.
 *   3. РЕДУКЦИЯ — не здесь, в `psweep.c`.
 *
 * КОСИНУС СОКРАЩАЕТСЯ САМ, и на этом стоит вся дешевизна. Пиксель площади `h²`
 * отвечает участку полигона площади `h²/|ω·n|`; в облучённость участок входит с
 * множителем `|ω·n|`. Произведение равно `h²` — множитель `cos θ` НЕ
 * ВЫЧИСЛЯЕТСЯ ВОВСЕ, он сокращён аналитически. Заодно снимается вырождение на
 * скользящих углах: полигон, почти параллельный `ω`, проецируется в щепку и
 * вносит мало, а не делится на почти-ноль.
 *
 * ВЫБОРКА ПО ЦЕНТРУ ПИКСЕЛЯ, правило НЕНУЛЕВОГО ОБОРОТА (то же, что у
 * `hz_poly_inside`, и по той же причине). Полосы полуоткрыты, поэтому общая
 * кромка двух полигонов достаётся ровно одному — покрытие не двоится и не
 * дырявится.
 */
#ifndef HZ_PRAST_H
#define HZ_PRAST_H

#include "polygon.h"

typedef struct {
  double w[3];         /* направление РАСПРОСТРАНЕНИЯ света, единичное */
  double ea[3], eb[3]; /* экранные оси, ортонормированные, ea × eb = w */
  double o[3];         /* мир, отвечающий углу пикселя (0,0) */
  double h;            /* шаг растра, м */
  int32_t W, H;
} hz_pview;

/* Габарит сцены задаёт размер экрана. 0 — успех, 1 — вырожденное направление,
 * 2 — экран не помещается. */
int hz_pview_make(hz_pview *v, const double w[3], const double lo[3], const double hi[3], double h);

/* Мировая точка центра пикселя (i, j) на нулевой глубине. */
void hz_pview_origin(const hz_pview *v, int32_t i, int32_t j, double r[3]);

/* Полоса: строка `j`, пиксели `[i0, i1]`, полигон `poly`, глубина `t0 + ti·i`. */
typedef struct {
  int32_t j, i0, i1, poly;
  double t0, ti;
} hz_span;

typedef struct {
  int64_t nspan, nfrag;
  int64_t nedge; /* просмотрено рёбер (цена заливки) */
  int64_t nrow;  /* строк заливки */
  int64_t nskip; /* полигонов пропущено: ω в плоскости полигона */
} hz_rstats;

/* Полосы всего набора для одного направления. `*sp`/`*cap` — растущий буфер
 * вызывающего (переиспользуется между направлениями), `*nsp` — сколько вышло. */
int hz_prast_spans(hz_span **sp, int64_t *nsp, int64_t *cap, const hz_pview *v,
                   const hz_polyset *ps, hz_rstats *st);

/* --- раскладка 1: СПЛОШНЫЕ пробеги --------------------------------------- */

typedef struct {
  int32_t *start; /* W·H + 1 */
  int32_t *poly;  /* nfrag */
  double *depth;  /* nfrag */
  int64_t n, cap;
  int32_t W, H;
} hz_fbuf;

int hz_fbuf_init(hz_fbuf *fb, int64_t npix, int64_t cap);
void hz_fbuf_free(hz_fbuf *fb);
/* 0 — успех, 3 — не хватило ёмкости (ответ был бы НЕПОЛОН, а не «чуть хуже»). */
int hz_fbuf_build(hz_fbuf *fb, const hz_span *sp, int64_t nsp, int32_t W, int32_t H);
void hz_fbuf_sort(hz_fbuf *fb);

/* --- раскладка 2: ОДНОСВЯЗНЫЕ списки --------------------------------------- */

typedef struct {
  int32_t *head; /* W·H, −1 = пусто */
  int32_t *next;
  int32_t *poly;
  double *depth;
  int64_t n, cap;
  int32_t W, H;
} hz_abuf;

int hz_abuf_init(hz_abuf *ab, int64_t npix, int64_t cap);
void hz_abuf_free(hz_abuf *ab);
int hz_abuf_build(hz_abuf *ab, const hz_span *sp, int64_t nsp, int32_t W, int32_t H);
void hz_abuf_sort(hz_abuf *ab);

#endif
