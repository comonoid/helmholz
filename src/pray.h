/* pray.h — ЛУЧ ПО ПОЛИГОНАМ: равномерная сетка, ближайшее попадание и заслон.
 *
 * PLAN_ELEMENTS.md. Луч здесь нужен ровно в двух местах, и оба названы планом
 * явно, а не изобретены:
 *   §7 — КАМЕРА: «на первое время как угодно, годится существующий ray
 *        casting». Кадр строится ОТ ПОЛЯ (§6), то есть луч спрашивает у сцены
 *        только «какой полигон виден», а яркость берёт из `E` этого полигона;
 *   §1.8 — ТЕНЬ: заслонённость от компактного источника. Видимость нужна как
 *        ВЫЧИСЛЕНИЕ, а не как таблица пар (§6, «форм-факторы»), и здесь она
 *        именно вычисление: луч, а не запомненная пара.
 *
 * ПОЧЕМУ ЛУЧ, А НЕ РАСТЕРИЗАТОР, ХОТЯ §6 ОТВЕРГАЕТ ЛУЧ ДЛЯ ПЕРЕНОСА. Отвергнут
 * он для ПЕРЕНОСА — там направлений сотня, а полигонов миллион, и проекция
 * обслуживает всех разом. У тени и камеры задача обратная: направление у
 * каждого луча СВОЁ (на источник, в пиксель), и проекцией это не выражается.
 * §6 это и говорит: «где луч остаётся: немного лучей в ПРОИЗВОЛЬНЫХ
 * направлениях».
 *
 * СЕТКА, А НЕ ИЕРАРХИЯ. Полигоны крупные и их тысячи, а не миллионы; дерево
 * стоило бы дороже в постройке, чем сэкономило бы на обходе. Крупный полигон
 * попадает во многие ячейки — это цена, и она замеряется (`nent/np`).
 */
#ifndef HZ_PRAY_H
#define HZ_PRAY_H

#include "polygon.h"

typedef struct {
  const hz_polyset *ps;
  int32_t *start; /* ncell+1 */
  int32_t *idx;   /* nent */
  int32_t nc[3];
  double lo[3], hi[3], cs[3];
  int64_t ncell, nent;
} hz_pray;

/* `target` — желаемое среднее число полигонов в занятой ячейке. */
int hz_pray_build(hz_pray *g, const hz_polyset *ps, double target);
void hz_pray_free(hz_pray *g);

/* Ближайшее попадание луча (o, d) при `t > tmin`. Возврат — индекс полигона
 * или −1; `*tout` — дальность. */
int32_t hz_pray_hit(const hz_pray *g, const double o[3], const double d[3], double tmin,
                    double *tout);

/* Есть ли ЛЮБОЕ попадание строго между tmin и tmax. Для тени: как только нашли
 * одно — дальше не смотрим, и это не оптимизация, а другой вопрос. */
int hz_pray_occluded(const hz_pray *g, const double o[3], const double d[3], double tmin,
                     double tmax);

#endif
