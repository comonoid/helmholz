/* ptrace.h — ЛУЧ ПО ВОСЬМИДЕРЕВУ `hz_ptree` (шаг О63, план §215).
 *
 * ЗАЧЕМ. §210 измерила доли кадра вычитанием: солнце — `40 %` (`9.72` из
 * `24.13` с), и цену задаёт не число лучей, а ДЛИНА пути в геометрии. §209.2
 * назвала адрес: лучи идут через `hz_pgrid` — равномерную сетку, которая
 * пустоту проходит ячейку за ячейкой. У Сан-Мигеля ребро её ячейки
 * `2·sqrt(2·A_ср) ≈ 0.10` м, то есть солнечный луч через двор в `70` м делает
 * порядка `700` шагов, почти все по пустоте. Дерево в том же стенде уже
 * строится и для лучей не использовалось ни разу.
 *
 * ПЕРЕСЕЧЕНИЕ — ВЫЗОВ `hz_pgrid_tri_hit`, СВОЕЙ КОПИИ МЁЛЛЕРА—ТРУМБОРА ЗДЕСЬ
 * НЕТ. Довод дословно из `pgrid.h`: третья копия трассировщика в репозитории —
 * это три места, где «видно/не видно» может разъехаться, и ни одного, где
 * расхождение поймается. По той же причине дословно взяты семантика
 * `tmin/tmax/skip/nskip/anyhit` и предикат отбора `th <= tmin || th >= best`:
 * сравнение двух трассировщиков имеет смысл, только если они отвечают на ОДИН
 * вопрос, а не на два похожих.
 *
 * ТРЕУГОЛЬНИКИ ПРОВЕРЯЮТСЯ У КАЖДОГО ПОСЕЩЁННОГО УЗЛА, А НЕ ТОЛЬКО У ЛИСТА.
 * При строгом правиле укладки треугольник живёт в самом глубоком узле, который
 * содержит его ЦЕЛИКОМ, и у внутренних узлов повисает `71…79 %` геометрии
 * (замерено по трём сценам, `ptree.c`). `ptree.c:87` требует этого прямым
 * текстом. Это же — главный риск шага (А427): крупные стены висят наверху и
 * проверяются на КАЖДОМ луче, чего равномерная сетка не делает.
 *
 * ПУСТОЙ РЕБЁНОК ОТСЕИВАЕТСЯ ДО СПУСКА, а не после входа в него (§209.2, довод
 * пользователя: «если в самом крупном уровне записано пустое пространство, его
 * очень быстро пропустить»). Глубоких пустых поддеревьев у `hz_ptree` не
 * бывает по построению: узел дробится только при `n > leafmax`, поэтому пустая
 * область — это ОДИН пустой лист, а не лестница из пустых узлов.
 *
 * ОБХОД РЕКУРСИВНЫЙ, И ЭТО НЕ ЛЕНЬ. Явный стек потребовал бы константы на его
 * глубину, а `maxlev` — параметр дерева; переполнение такого стека дало бы
 * ПОТЕРЮ ЗАСЛОНА, то есть молча неверный ответ там, где ошибка не видна.
 * Глубина рекурсии равна глубине дерева (умолчание `12`).
 *
 * ПОРЯДОК ДЕТЕЙ — по знакам направления (`j ^ mask`), то есть спереди назад.
 * На ПРАВИЛЬНОСТЬ он не влияет: узел отсекается по `t_входа >= best`, а любое
 * попадание внутри узла имеет `t >= t_входа`. Он влияет только на то, как рано
 * найдётся ближнее попадание.
 */
#ifndef HZ_PTRACE_H
#define HZ_PTRACE_H

#include "ptree.h"
#include "scene_obj.h"
#include <stdint.h>

/* Обход дерева. Аргументы `tmin/tmax/skip/nskip/anyhit/thit/tri` — дословно
 * как у `hz_pgrid_trace_tri`, так что замена в потребителе есть одна строка.
 * `anyhit` — вопрос «есть ли заслон», иначе ищется БЛИЖАЙШЕЕ попадание.
 * Возврат: 1 — попадание, `*thit` — параметр вдоль `dir`; 0 — ничего.
 *
 * ФУНКЦИЯ ОДНА, А НЕ ТРИ, В ОТЛИЧИЕ ОТ `pgrid`. Там три подписи потому, что у
 * двух старых есть потребители с побитово сверяемыми числами; здесь потребитель
 * один, и обёртки без счётчиков были бы мёртвым кодом — `scripts/lean.sh`
 * назвал их поимённо в первом же прогоне.
 *
 * СЧЁТЧИКИ: `nnode` — посещено узлов, `ntest` — проверено треугольников (оба
 * могут быть NULL). Порознь они нужны потому, что дерево выигрывает у сетки
 * ДВУМЯ разными способами, и смешивать их нельзя (А424): пропуском пустоты
 * (это `nnode`) и отсутствием повторных проверок одного треугольника из разных
 * ячеек (это `ntest`; избыточность дерева `1.000` против сетки). */
int hz_ptrace_cnt(const hz_ptree *t, const hz_objmesh *m, const double o[3], const double dir[3],
                  double tmin, double tmax, const int32_t *skip, int nskip, int anyhit,
                  double *thit, int32_t *tri, int64_t *nnode, int64_t *ntest);

#endif
