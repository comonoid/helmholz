/* ptree.h — ПРОСТРАНСТВЕННОЕ ДЕРЕВО НАД ТРЕУГОЛЬНИКАМИ СЦЕНЫ (§95).
 *
 * ЗАЧЕМ. Лестница LOD построена СЛИЯНИЕМ КОМПЛАНАРНЫХ участков: она хороша для
 * представления поверхности (у узла есть измеренный `dmax`) и пространственной
 * вложенности не даёт вовсе. Поэтому по ней нельзя ни сортировать по видимости,
 * ни отсекать заслонённое. Пространственное дерево даёт ровно обратный набор, и
 * оба нужны — это ДВЕ РАЗНЫЕ иерархии, а не замена одной другой.
 *
 * ПОЧЕМУ ВОСЬМИДЕРЕВО, А НЕ BSP (разбор с пользователем 08-01):
 *   - BSP РЕЖЕТ полигоны плоскостями разбиения, а наши полигоны несут
 *     неизвестные; резать их значит либо резать неизвестные, либо завести
 *     геометрию для рисования отдельно от элементов переноса — то есть ВТОРОЕ
 *     ПРЕДСТАВЛЕНИЕ, которое §6 запрещает прямым текстом;
 *   - восьмидерево ССЫЛАЕТСЯ на треугольник из нескольких ячеек. Избыточность
 *     есть цена, и она ЗАМЕРЯЕТСЯ (`nref / nt`), а не предполагается;
 *   - перестройка дешёвая, а она обязательна: цель §84 — динамическая геометрия;
 *   - порядок обхода спереди назад из ЛЮБОЙ точки — просто порядок октантов по
 *     знакам направления, без расщепления. Это и есть «сортировка по видимости
 *     даром».
 *
 * ЗАЧЕМ ИМЕННО СЕЙЧАС, числом: полукуб рисует ВСЕ 124 635 треугольников в КАЖДЫЙ
 * из 4247 полукубов — 529 324 845 установок, и в них сидит вся сборка (А244).
 */
#ifndef HZ_PTREE_H
#define HZ_PTREE_H

#include "scene_obj.h"
#include <stdint.h>

typedef struct {
  double lo[3], hi[3]; /* коробка узла */
  int32_t child;       /* индекс первого из восьми детей; -1 у листа */
  int32_t t0, ntri;    /* ссылки на треугольники: [t0, t0+ntri) в `ref` */
} hz_ptnode;

typedef struct {
  hz_ptnode *nd;
  int32_t nnd, ndcap;
  int32_t *ref; /* ссылки на треугольники, подряд по листьям */
  int64_t nref, refcap;
  int32_t maxlev, leafmax;
  /* СКОЛЬКО ТРЕУГОЛЬНИКОВ ЗАСТРЯЛО У ВНУТРЕННИХ УЗЛОВ. Это те, что не влезли
   * целиком ни в одного ребёнка; в порядок обхода детей они не встраиваются, и
   * для рисования сзади наперёд их пришлось бы резать. Число решает, годится ли
   * усреднение по покрытию без z-буфера (разговор 08-01). */
  int64_t n_inner, n_leaf_tri;
  /* ЗАМЕРЫ ПОСТРОЙКИ — часть выхода. Избыточность решает, окупается ли дерево. */
  int64_t nleaf;
  double redundancy; /* `nref / nt`: сколько ссылок на треугольник */
  /* РЫХЛАЯ УКЛАДКА (§196): треугольник уходит вниз по октанту ЦЕНТРА, коробка
   * ребёнка расширяется. `0` — прежнее правило «влезает целиком», и оно
   * УМОЛЧАНИЕ: при рыхлом коробки детей перекрываются, и точный обход спереди
   * назад по порядку октантов (несущее свойство `pvis`, §95) теряется. */
  int loose;
  /* --- УКЛАДКА РЕЗКОЙ (§241.2, шаг О70) ---------------------------------- */
  /* `1` — дерево построено `hz_ptree_build_cut`: ссылок не хранит вовсе, а
   * содержимое узла выводится ОТСЕЧЕНИЕМ при обходе (А472). */
  int cut;
  unsigned char *lev; /* nnd: уровень узла; нужен и градуировке, и срезу */
  int32_t depth;      /* достигнутая глубина */
  /* ТРЕУГОЛЬНИКОВ, НЕ ВЛЕЗАЮЩИХ ЦЕЛИКОМ НИ В ОДНОГО РЕБЁНКА, — считается по
   * САМОМУ ГЛУБОКОМУ СОДЕРЖАЩЕМУ узлу, то есть ровно те, что при старой укладке
   * и застревали наверху. При укладке резкой они РЕЖУТСЯ, и `n_inner`
   * остаётся нулём; держать оба числа рядом обязательно, иначе ноль `n_inner`
   * неотличим от неработающего счётчика. */
  int64_t n_nofit;
  int64_t ngrade;          /* узлов, ДОБАВЛЕННЫХ градуировкой 2:1 (А476) */
  int32_t ngpass;          /* НАИБОЛЬШИЙ перепад уровней, встреченный ДО градуировки */
  int64_t nvisited;        /* узлов, пройденных построением (цена укладки) */
  double t_build, t_grade; /* секунды: спуск и градуировка ПОРОЗНЬ (А476) */
} hz_ptree;

/* Построить дерево. `leafmax` — порог дробления по числу треугольников в узле,
 * `maxlev` — предел глубины. Значения `0` читаются как `16` и `12`.
 * `leafmax` больше `m->nt` даёт дерево ИЗ ОДНОГО ЛИСТА — это негативный контроль
 * НК13: ответ обязан совпасть с прогоном без дерева. */
int hz_ptree_build(hz_ptree *t, const hz_objmesh *m, int leafmax, int maxlev);
/* То же с выбором правила укладки: `loose = 0` — в точности `hz_ptree_build`. */
int hz_ptree_build_ex(hz_ptree *t, const hz_objmesh *m, int leafmax, int maxlev, int loose);

/* ДЕРЕВО УКЛАДКИ РЕЗКОЙ (§241.2, §244 п. 2). Отличий от `build_ex` три, и все
 * три вынуждены:
 *   - треугольник спускается в КАЖДОГО ребёнка, чью коробку задевает, потому
 *     что в ячейке он будет РЕЗАТЬСЯ; состояния «не влезло» не существует, и
 *     `n_inner` остаётся нулём ПО ПОСТРОЕНИЮ;
 *   - ССЫЛКИ НЕ ХРАНЯТСЯ ВОВСЕ (А472): при избыточности порядка 10³ массив
 *     ссылок у Сан-Мигеля не поместился бы в память, а куски выводятся
 *     отсечением при обходе. Наружу отдаётся только СТРУКТУРА узлов;
 *   - постройка КАМЕРОНЕЗАВИСИМА (А470): спуск идёт до `maxlev` либо до
 *     `leafmax`, пол камеры применяется на СРЕЗЕ, при чтении.
 * `grade` — строить ли градуированное дерево (перепад не более 2:1 между
 * соседями по грани, §241.3); добавленные узлы считаются в `ngrade`. */
int hz_ptree_build_cut(hz_ptree *t, const hz_objmesh *m, int leafmax, int maxlev, int grade);

/* ВТОРОЙ КРИТЕРИЙ ДРОБЛЕНИЯ (§294): узел, чья геометрия НЕ лежит в одной
 * плоскости, дробится независимо от числа треугольников. Разбор — в `ptree.c`.
 * `0` — прежнее поведение (умолчание): числа §271…§293 обязаны воспроизводиться
 * до единицы. */
extern int hz_ptree_flat_split;
void hz_ptree_free(hz_ptree *t);

#endif
