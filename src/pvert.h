/* pvert.h — НЕИЗВЕСТНЫЕ НА ВЕРШИНАХ ГРАНИЦЫ (PLAN_ELEMENTS.md, §100).
 *
 * ЗАЧЕМ. Решение, кусочно-постоянное по элементам, даёт ЛОСКУТЫ — знаменитый
 * артефакт радиосити, названный в §6 с начала проекта. Восстановление
 * непрерывности при чтении (§98) их уменьшило, но не убрало, и три причины
 * измерены: `15 503` вершины с одним владельцем, `808` элементов (24.8 %) с
 * вырожденной подгонкой, и сдвиг под сохранение среднего, который сам ломает
 * непрерывность (А250).
 *
 * ВСЕ ТРИ СНИМАЕТ ОДНО: неизвестная сидит НА ВЕРШИНЕ, а не на куске. Формулировка
 * пользователя 08-01: «поле у нас только на поверхности, на самой границе».
 * Тогда непрерывность выходит ПО ПОСТРОЕНИЮ — значение в общей вершине одно, —
 * а сохранять среднее не нужно, потому что среднее и ЕСТЬ решение.
 *
 * КРУГ ЗАМЫКАЕТСЯ ТАК: полукуб стоит в ВЕРШИНЕ и собирает с УЗЛОВ лестницы;
 * радианс узла есть средневзвешенное по площади его полигонов; радианс полигона
 * есть среднее его вершин. Приёмник — вершина, излучатель — узел, и связь между
 * ними та же, что была, только приёмная сторона сменила носитель.
 *
 * ЧЕГО ЭТО НЕ ДЕЛАЕТ. Не добавляет разрешения: вершин столько, сколько дал край
 * элементов. Не делает тени резче. Не отменяет коллокацию — полукуб по-прежнему
 * стоит в ТОЧКЕ, просто точка теперь на стыке, а не в середине.
 */
#ifndef HZ_PVERT_H
#define HZ_PVERT_H

#include "plink.h"
#include "polygon.h"

typedef struct {
  int32_t nv;    /* различных вершин */
  int32_t *id;   /* ps->nbv: позиция края → номер вершины */
  double *x;     /* 3*nv: положение */
  double *n;     /* 3*nv: нормаль, средняя по владельцам */
  double *area;  /* nv: суммарная площадь владельцев (вес) */
  int32_t *nown; /* nv: сколько владельцев */
  /* ЗАМЕРЫ — часть выхода. Вершина с ОДНИМ владельцем ничего не соединяет, и
   * шов на ней остаётся законно: это кромка объекта, а не дефект схемы. */
  int64_t n_one, n_many;
} hz_vset;

/* Построить набор вершин по краю полигонов. Сварной номер берётся из `ps->bw`;
 * позиции без номера получают собственный. */
int hz_vset_build(hz_vset *V, const hz_polyset *ps);
void hz_vset_free(hz_vset *V);

/* Сборка оператора ПОЛУКУБОМ С ПРИЁМНИКОМ В ВЕРШИНЕ (§100). Связь есть
 * `(вершина, узел лестницы, форм-фактор)`; хранится в том же `hz_linkset`, где
 * поле `i` читается как номер ВЕРШИНЫ, а не узла. */
int hz_vert_build(hz_linkset *S, const hz_vset *V, const hz_scene *sc, const hz_linkcfg *cfg,
                  int R);

/* Решить `B_v = Le_v + ρ_v · Σ f·B_узла` итерациями. `Bv` — выход на вершинах;
 * `Bp` — рабочий массив на полигоны, `Bn` — на узлы лестницы. */
int hz_vert_solve(const hz_linkset *S, const hz_vset *V, const hz_polyset *ps, const hz_lod *L,
                  const double *Le, const double *rho, double *Bv, double *Bp, double *Bn,
                  double tol, int maxit, double *reshist);

#endif
