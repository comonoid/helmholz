/* pvfit.h — ПОДГОНКА ВЕРШИН КРАЯ В 3D (PLAN_ELEMENTS.md, §40…§43, пункт О17).
 *
 * ЗАЧЕМ. До этого вершины огрублённого полигона не подгонялись ВОВСЕ: это были
 * входные вершины сетки, снесённые на плоскость группы вдоль её нормали. Отсюда
 * весь спор про угловое условие: угол из трёх граней одной плоскостью
 * непредставим, поэтому приходилось либо запрещать такие слияния (`+45%`
 * элементов), либо принимать диагональную плоскость, уезжающую вдоль луча на
 * метры (`20.76` пикселя против `3…5`, замер §39). Если же вершина ставится в 3D,
 * угол представляется двумя-тремя ПЛОСКИМИ элементами с общей вершиной НА изломе,
 * и запрещать ничего не надо.
 *
 * ПРАВИЛО ПОСТАНОВКИ — §41: **L∞ задаёт гарантию, L2 выбирает внутри неё.**
 *   1. минимакс: минимизировать `t` при `|n_i·v − d_i| ≤ t` по плоскостям, которые
 *      вершина обслуживает. Решается ТОЧНО перебором четвёрок знаковых
 *      ограничений — плоскостей у вершины единицы (А122), и оптимум ЛП сидит на
 *      четырёх активных ограничениях;
 *   2. наименьшие квадраты БЕЗ ограничений; принимаются только если попали в
 *      `t*`, иначе берётся минимаксная точка, и это считается (А123).
 * Довод за такую пару записан пользователем: квадратичное обычно работает хорошо,
 * но изредка даёт выбросы, а выброс в геометрии — видимый шип; чебышёвское
 * гарантирует их отсутствие, но недифференцируемо и грозит дребезгом между
 * уровнями. Лексикографическая пара берёт оба свойства.
 *
 * ДВИГАЮТСЯ ТОЛЬКО ВЕРШИНЫ С ТРЕМЯ И БОЛЕЕ ПЛОСКОСТЯМИ (А121). При одной
 * плоскости свободны ДВА направления, при двух — одно вдоль линии пересечения;
 * ограничение «не дальше `t*` от прежнего места» оставило бы вершине круг или
 * отрезок, и край поехал бы ВДОЛЬ поверхности, растащив площади и стыки.
 * Замер, оправдывающий шаг (А122): у города `73.24%` краевых вершин имеют три и
 * более групп, у зала — `20.36%`.
 *
 * ЧТО ОСТАЁТСЯ НЕРЕШЁННЫМ, И ЭТО СКАЗАНО ЗАРАНЕЕ:
 *   - ХРАНЕНИЕ ПЛОСКОЕ. Новая вершина лежит в каждой плоскости лишь с точностью
 *     `t*`, а край хранится в двумерных `(u, v)`, поэтому в полигон она кладётся
 *     ПРОЕКЦИЕЙ, и щель между двумя полигонами в этой вершине не больше `2 t*`.
 *     Сегодня она ограничена допуском `δ`, то есть шаг меняет `δ` на `t*` —
 *     и `t*` обязан печататься распределением, иначе замена ничем не подтверждена;
 *   - ОДИН ПРОХОД (А119). Плоскости групп подогнаны по СПРОЕЦИРОВАННЫМ вершинам,
 *     а вершины ставятся по плоскостям; после сдвига вершин та же группа получила
 *     бы другую оптимальную плоскость. Это первое приближение, а не оптимум.
 */
#ifndef HZ_PVFIT_H
#define HZ_PVFIT_H

#include "polygon.h"

typedef struct {
  int64_t nvert;       /* вершин края со сварным номером */
  int64_t nvert_moved; /* из них передвинуто (три и более плоскостей) */
  int64_t nvert_fixed; /* оставлено на месте: меньше трёх плоскостей (А121) */
  int64_t nvert_fail;  /* минимакс не решился ни на одной четвёрке */
  int64_t nvert_l2out; /* L2 вышел за гарантию `t*`, взята минимаксная точка */
  int64_t nvert_many;  /* плоскостей больше буфера — часть отброшена */
  int64_t nvert_far;   /* отказ: вершина уехала бы дальше предела (А124) */
  int64_t nvert_noimp; /* отказ: в новой точке худшая невязка не меньше (А125) */
  double dmax_move;    /* худшее принятое смещение, м */
  double dmax_area;    /* худшее `|mom0/area − 1|`: расхождение площади элемента и
                        * представляемой поверхности (А127, А128) */
  double tmax;         /* худшее `t*` по сцене, м */
  int64_t t_hist[12];  /* гистограмма `t*`: логарифмические корзины от 1e−6 м */
} hz_vfitstat;

/* Переставляет вершины края НА МЕСТЕ. Полигоны остаются плоскими: в каждый
 * вершина кладётся своей проекцией. Габариты `uvlo/uvhi` пересчитываются. */
/* `dmove` — предел смещения вершины от исходного места. Он НУЖЕН, и это замер:
 * `t*` ограничивает расстояние до плоскостей, а НЕ перемещение. У трёх почти
 * параллельных плоскостей точка пересечения может лежать за километр при
 * крошечной невязке, и вершина уезжает туда, разрывая край. Замерено на зале:
 * без предела метрика О20 портилась с `1.36` до `253` пикселя по p90 (А124).
 * Естественная величина здесь — допуск огрубления: дальше него поверхность
 * двигать нельзя по определению самого огрубления. */
int hz_poly_vfit(hz_polyset *ps, double dmove, hz_vfitstat *st);

#endif
