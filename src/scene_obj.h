/* scene_obj.h — ВХОД СЦЕНЫ: суп треугольников из OBJ.
 *
 * ЛИНИЯ ПЕРЕНОСА, PLAN_ELEMENTS.md, Ш2. Разбор недоверенного входа — значит
 * гейт качества целиком, включая CBMC (`scripts/cverify.sh`).
 *
 * ЧТО ЭТО ЗА СЛОЙ И ЧЕГО В НЁМ НЕТ. Здесь ТОЛЬКО чтение файла: вершины,
 * нормали, треугольники, материалы. Ни плоскостей, ни полигонов, ни сегментации
 * — они в `poly_seg.h`, и разделение не косметическое: разборщик обязан
 * проходить CBMC, а сегментатор — это счёт по плавающей арифметике, который
 * CBMC не осилит и в котором его нечего искать.
 *
 * ДВА ПРОХОДА ПО ФАЙЛУ, А НЕ РАСТУЩИЕ МАССИВЫ. Первый проход считает `v`, `vn` и
 * ТРЕУГОЛЬНИКИ (грань из `k` вершин даёт `k−2`), второй заполняет. Так больших
 * `realloc` нет вовсе, а значит нет и известного класса ложных срабатываний
 * gcc-analyzer на связке ёмкость↔счётчик (CLAUDE.md, аудит diam 07-24).
 *
 * ОТНОСИТЕЛЬНЫЕ ИНДЕКСЫ ОБЯЗАТЕЛЬНЫ, А НЕ ЖЕЛАТЕЛЬНЫ: Rungholt записан
 * Mineways целиком в отрицательных индексах (`f -2444194/-656/-18`), и разборщик
 * без них прочтёт ровно ноль граней. Отрицательный индекс отсчитывается от числа
 * вершин, ВИДЕННЫХ К ЭТОМУ МОМЕНТУ, поэтому второй проход ведёт СВОЙ бегущий
 * счётчик, а не берёт итоговый.
 *
 * ГРАНИ БЫВАЮТ ЧЕТЫРЁХУГОЛЬНЫМИ (тот же Rungholt) — веер `(0, i, i+1)`.
 * Веер законен, потому что вход — плоские выпуклые грани блоков; для
 * произвольного невыпуклого многоугольника он неверен, и это записано здесь,
 * чтобы не искать потом причину вывернутых треугольников.
 *
 * ОДИН СПЕКТРАЛЬНЫЙ КАНАЛ (PLAN_ELEMENTS.md §2: цвет — отдельная веха).
 * `Kd` сворачивается СРЕДНИМ по трём числам, а не яркостью: альбедо есть ДОЛЯ
 * ОТРАЖЁННОЙ ЭНЕРГИИ, и при плоском спектре среднее сохраняет её точно, тогда
 * как весовая яркость сохраняла бы видимое впечатление ценой энергии. В печи
 * (Ш4) сверяется именно энергия.
 *
 * ВЫРОЖДЕННЫЕ ТРЕУГОЛЬНИКИ ОТБРАСЫВАЮТСЯ ПРИ ЗАГРУЗКЕ и считаются. У нулевой
 * площади нет плоскости, то есть нет и нормали; протащить такой дальше значит
 * получить NaN в сегментации и искать его там, где его не порождали.
 */
#ifndef HZ_SCENE_OBJ_H
#define HZ_SCENE_OBJ_H

#include <stdint.h>

#define HZ_OBJ_MTLNAME 64

typedef struct {
  char name[HZ_OBJ_MTLNAME];
  double kd; /* альбедо, ОДИН канал: среднее по Kd из .mtl — перенос считает им */
  /* ЦВЕТ ДЛЯ КАРТИНКИ (§78). Перенос одноканален сознательно: он считает энергию,
   * и три канала утроили бы стоимость решения ни за чем. Но КАРТИНКА без цвета
   * выглядит заливкой, а цвет достаётся даром — по правилу Т1 альбедо
   * применяется при ЧТЕНИИ поля, то есть три канала стоят три умножения на
   * пиксель и ноль в решателе. */
  double kd3[3];
  /* ЗЕРКАЛЬНОСТЬ И ПРЕЛОМЛЕНИЕ (§89). Читаются из `.mtl`; перенос ими НЕ
   * пользуется — они нужны проходу камеры, где §85.2 держит строку «зеркало и
   * стекло, ВИДНО». */
  double ks3[3]; /* `Ks`: доля зеркального, три канала */
  double ns;     /* `Ns`: показатель блеска; `0` — не задан */
  double ior;    /* `Ni`: показатель преломления */
  double alpha;  /* `d`: непрозрачность, `1` — непрозрачно */
  /* ИНТЕРПОЛИРОВАТЬ ЛИ НОРМАЛЬ. Пользователь 08-01: «горы-камни всякие лучше НЕ
   * интерполировать». По умолчанию решает ВХОД: без вершинных нормалей подгонка
   * даёт `nu = nv = 0` точно, и интерполяция ничего не меняет сама. Флаг нужен
   * для обратного случая — `vn` есть, а гладкости не надо; читается из
   * необязательной строки `hz_flat 1`, потому что в стандартном `.mtl` таких
   * данных нет, а выдумывать эвристику по `Ns` или по имени запрещено. */
  int flat;
} hz_obj_mtl;

typedef struct {
  double *v;  /* 3*nv, МЕТРЫ: масштаб применён при разборе */
  double *vn; /* 3*nvn, единичные; NULL, если в файле нормалей нет */
  int32_t nv, nvn;

  int32_t *f;  /* 3*nt, индексы в v */
  int32_t *fn; /* 3*nt, индексы в vn; -1 = у этого угла нормали нет */
  int32_t *fm; /* nt, индекс материала; 0 — материал по умолчанию */
  int32_t nt;

  hz_obj_mtl *mtl; /* [0] всегда «__default», чтобы fm был валиден всегда */
  int32_t nmtl;

  double lo[3], hi[3]; /* габарит по вершинам, метры */

  /* Замеренное при разборе — доклад, а не отладка. */
  int64_t ndegen; /* отброшено треугольников нулевой площади */
  int64_t nquad;  /* граней с более чем тремя вершинами */
} hz_objmesh;

/* scale — множитель координат (PLAN_ELEMENTS.md §2: зал ×0.003, город ×1.0).
 * Возврат: 0 — успех; 1 — файл не открыть/не прочесть; 2 — нет памяти;
 * 3 — файл не разобран (битые индексы). */
/* ДОБАВИТЬ ИЗЛУЧАЮЩИЙ ПРЯМОУГОЛЬНИК В МЕШ — ДО СЕГМЕНТАЦИИ (§91).
 *
 * ЗАЧЕМ ИМЕННО В МЕШ, А НЕ В ПОЛИГОНЫ. `plod.c:329` берёт `min(ps->np,
 * sg->nseg)`, поэтому полигон, добавленный только в `ps` (как делает `prender`
 * через `hz_poly_add_quad`), ЛЕСТНИЦЕЙ НЕ ВИДЕН и в перенос не войдёт. Лампа,
 * заведённая двумя треугольниками в меше, проходит сегментацию, полигоны,
 * лестницу и связи как обычная геометрия — без единого особого случая.
 *
 * Возвращает индекс материала лампы (общий для всех вызовов с тем же именем)
 * либо `-1`. Нормаль задаёт, куда лампа смотрит; `eu` — первая ось в плоскости. */
/* Разбить треугольники, у которых самая длинная сторона больше `smax` метров
 * (§97). Условие для теней: сегментация треугольники не режет, и поверхность,
 * смоделированная одним треугольником, остаётся одним элементом при любом
 * ограничении размера. `smax <= 0` — ничего не делать. */
/* Сшить вершины, отличающиеся меньше чем на `eps` (§104.2). Возвращает через
 * указатели, сколько вершин слито и сколько треугольников выродилось —
 * последнее есть мера того, не срастили ли раздельные тела. */
int hz_obj_weld(hz_objmesh *m, double eps, int64_t *nmerged, int64_t *ndegen);

int hz_obj_subdivide(hz_objmesh *m, double smax);

int hz_obj_add_quad(hz_objmesh *m, const char *mtlname, const double c[3], const double n[3],
                    const double eu[3], double hu, double hv);

int hz_obj_load(hz_objmesh *m, const char *path, double scale);
void hz_obj_free(hz_objmesh *m);

/* РАЗБОР ОТДЕЛЁН ОТ ЧТЕНИЯ ФАЙЛА, и это не удобство, а условие проверяемости.
 * У CBMC нет тела ни для `fread`, ни для `FILE*`, поэтому «CBMC на
 * hz_obj_load» недостижимо как задача (тот же довод, что в
 * `tests/cbmc_octree.c`). Здесь вход — NUL-терминированный буфер в памяти, и
 * ровно эту половину гоняет `tests/cbmc_sceneobj.c`.
 * `objpath` может быть NULL: тогда строки `mtllib` пропускаются, и разбор не
 * трогает файловую систему вовсе. */
int hz_obj_parse(hz_objmesh *m, const char *buf, double scale, const char *objpath);

/* Площадь треугольника t и его вершины. Отдельно, потому что нужны всем
 * потребителям, а раскладка `f`/`v` — здесь. */
void hz_obj_tri(const hz_objmesh *m, int32_t t, double p[3][3]);
double hz_obj_tri_area(const hz_objmesh *m, int32_t t);

#endif
