/* cam3.h — T5а: камера-обскура, прямой свет и сбор по пикселю.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md), проходы 1 и 3 из трёх.
 *
 * ЧТО ЛЕЖИТ В ИСХОДЯЩЕМ РАДИАНСЕ — ДОГОВОРЁННОСТЬ, ЗАПИСАННАЯ СЕЙЧАС (К17).
 * Аудит К9 требует явно условиться, включён ли прямой свет в хранимое на
 * поверхности, иначе проход 3 добавит его ВТОРОЙ раз и картинка выйдет
 * правдоподобной, но вдвое пересвеченной. В T5а хранимого поля нет, значит
 * двойного учёта быть не может — и ровно поэтому договорённость надо записать
 * СЕЙЧАС, пока она ничего не стоит:
 *
 *     L_out = L_e + ПРЯМОЙ + КОСВЕННЫЙ
 *     T5а даёт L_e и ПРЯМОЙ; КОСВЕННЫЙ тождественно ноль.
 *     Хранимое на поверхности (аудит Р3) будет содержать ТОЛЬКО КОСВЕННЫЙ.
 *
 * Поэтому в T5б проход 3 складывает хранимое с заново посчитанным прямым, и
 * двойного учёта не возникает по построению.
 *
 * ИСТОЧНИК — СТРОГО ПАРАЛЛЕЛЬНЫЙ ПУЧОК (К18). Аналитический эталон (ламбертова
 * сфера, косинусная затенённость) верен только для удалённого источника. У
 * точечного на расстоянии R от сферы радиуса r формула другая, и расхождение
 * порядка r/R — при R = 10r это 10%, которые я принял бы за ошибку схемы и
 * полез бы чинить исправное. Точечный источник — отдельный тип со своей
 * формулой, а не «тот же с большим R».
 *
 * ПИКСЕЛЬ — НЕ ТОЧКА (К20). Луч идёт через ЦЕНТР пикселя, то есть это выборка, а
 * не интеграл по телесному углу. На силуэте это ошибка O(1), и метрика обязана
 * брать пиксели ВНЕ силуэта.
 */
#ifndef TR_CAM3_H
#define TR_CAM3_H

#include "transport/ray3.h"

typedef struct {
  double eye[3];
  double fwd[3], right[3], up[3]; /* ортонормированный кадр */
  double tanx, tany;              /* полутангенсы поля зрения */
  int w, h;
} tr3_camera;

/* fov — ПОЛНЫЙ горизонтальный угол в радианах. Вертикальный выводится из
 * соотношения сторон, поэтому пиксель квадратный, и след пикселя один по обеим
 * осям — иначе «ошибка вне силуэта» зависела бы от направления. */
int tr3_camera_look(tr3_camera *c, const double eye[3], const double at[3], const double up[3],
                    double fov, int w, int h);

/* Луч через ЦЕНТР пикселя (px, py). Направление единичное. */
void tr3_camera_ray(const tr3_camera *c, int px, int py, double o[3], double d[3]);

/* Удалённый источник: параллельный пучок. dir — направление НА источник. */
typedef struct {
  double dir[3]; /* единичное */
  double e;      /* облучённость площадки, перпендикулярной пучку */
} tr3_sun;

/* Ламбертова поверхность: одна на сцену, пока материалов нет. */
typedef struct {
  double albedo;
} tr3_material;

/* Радианс, приходящий по лучу (o, d) в камеру. Это ровно
 *     L = exp(−τ_камеры) · (albedo/π) · E · max(0, n·l) · exp(−τ_тени),
 * где обе толщины НАКОПЛЕНЫ маршем, а не заменены булевой видимостью (К16).
 * shadow = 0 выключает теневой марш — это негативный контроль, а не режим. */
double tr3_shade(const tr3_scene *sc, const tr3_sun *sun, const tr3_material *mat,
                 const double o[3], const double d[3], int shadow);

/* Кадр в буфер РАДИАНСА (w·h). Метрика берётся здесь; PPM пишется отдельно и в
 * метрику не входит — тон-маппинг её съедает (К19). */
int tr3_render(const tr3_scene *sc, const tr3_camera *cam, const tr3_sun *sun,
               const tr3_material *mat, int shadow, double *buf);

#endif
