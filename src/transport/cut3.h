/* cut3.h — СТЫК развёртки с геометрией разреза: поверхности ВНУТРИ области.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md, T4). До этого файла развёртка знала только
 * коробки и стенки куба, а разрез жил отдельно; здесь они соединяются.
 *
 * ЧТО СЧИТАЕТСЯ. Для каждой ячейки, которую режет поверхность:
 *
 *   ФЛЮИДНАЯ ОБЛАСТЬ = коробка МИНУС материал. Она НЕ ВЫПУКЛА, и это не помеха:
 *   hz_poly3_complement даёт её ТОЧНОЕ разбиение на непересекающиеся выпуклые
 *   куски (пункт 4 общего слоя), а моменты аддитивны, поэтому матрица масс
 *   области есть сумма матриц кусков. Приближения здесь нет нигде.
 *
 *   ПОВЕРХНОСТНЫЕ ЭЛЕМЕНТЫ — грани кусков, лежащие на ПЕРЕВЁРНУТОЙ полуплоскости.
 *   Каждый есть кусок фасета внутри этой ячейки, и на нём хранится ОДНО число:
 *   исходящий радианс (аудит Р3 — у диффузной поверхности он от направления не
 *   зависит).
 *
 *   ГРАНИ КУСКОВ НА НЕПЕРЕВЁРНУТЫХ полуплоскостях ВНУТРЕННИЕ: по ту сторону
 *   лежит другой кусок ТОЙ ЖЕ флюидной области, а разложение DG у ячейки одно.
 *   Они не дают ни потока, ни поверхности, и отбрасываются.
 *
 * ОГРАНИЧЕНИЕ, ЗАПИСАННОЕ ЯВНО: разрезанная ячейка обязана быть на самом мелком
 * уровне вместе с соседями (стык 1:1). Иначе грань сетки была бы МЕНЬШЕ грани
 * коробки, и флюидную часть пришлось бы ещё и обрезать прямоугольником. Условие
 * ПРОВЕРЯЕТСЯ и при нарушении возвращается ошибка, а не молчаливое приближение.
 */
#ifndef TR_CUT3_H
#define TR_CUT3_H

#include "cut/surf.h"
#include <stdint.h>
#include "transport/mesh3.h"

typedef struct {
  int32_t cell, facet;
  double n[3];    /* нормаль В ФЛЮИД (наружу материала), МИР, единичная */
  double area;    /* мир */
  double m[4][4]; /* ∫ b_i b_j dA в базисе ячейки */
  double hsum;    /* Σ_{ω·n>0} w(ω·n) — К29 для произвольной нормали */
  /* НУЛЕВОЙ ВЕКТОР МАТРИЦЫ МАСС, АНАЛИТИЧЕСКИЙ (К39). Элемент ПЛОСКИЙ, а базис
   * ячейки {1, ξ, η, ζ} на плоскости линейно ЗАВИСИМ: подстановка
   * x_ед = clo + s(½ + b) в уравнение плоскости n·x_ед = off даёт тождество
   *
   *     s·Σ_a n_a·b_{a+1} − (off − Σ_a n_a(clo_a + s/2))·b_0 ≡ 0.
   *
   * Значит m[4][4] вырождена ТОЧНО и её ранг равен ТРЁМ — не «почти», а по
   * построению (измерено |m·nul|/(|m||nul|) = 1.4e-16 на всех элементах сцены).
   * Хранится вектор, а не флаг: решать надо В ДОПОЛНЕНИИ к нему, и для этого
   * нужен он сам. */
  double nul[4];
} tr3_selem;

typedef struct {
  const tr3_mesh *m;
  double (*mvol)[4][4]; /* [ncell] матрица масс ФЛЮИДНОЙ части, мир */
  double (*ffm)[4][4];  /* [nf] ∫b^ca b^ca по ФЛЮИДНОЙ части грани */
  double (*ffmb)[4][4]; /* [nf] то же в базисе cb */
  double (*ffmx)[4][4]; /* [nf] смешанная ca×cb */
  double *farea;        /* [nf] флюидная площадь грани */
  uint8_t *solid;       /* [ncell] 1 — ячейка целиком в материале */
  tr3_selem *se;
  int32_t nse, secap;
  int32_t *sestart, *selist; /* CSR: элементы по ячейке */
  int32_t nbad;              /* ячеек, нарушивших условие 1:1 */
} tr3_cut;

/* ft/cm могут быть NULL — тогда всё вырождается в коробки, и развёртка работает
 * ровно как до стыка. */
/* solid_in — [ncell] маска «ячейка ЦЕЛИКОМ в материале», ОБЯЗАТЕЛЬНАЯ, если тело
 * есть. Сама боковая таблица её не несёт: hz_facets_for_box отвечает НОЛЬ и для
 * полной ячейки, и режущих плоскостей у неё нет, поэтому в cutmap она не
 * попадает вовсе (Г38 как раз про то, что «ноль отобранных» у полной и у пустой
 * ячейки выглядит одинаково). Пропустить её значит пустить свет НАСКВОЗЬ ТЕЛА —
 * измерено: объём материала вышел 29.4 вместо 164.6. */
int tr3_cut_build(tr3_cut *cu, const tr3_mesh *m, const hz_facettab *ft, const hz_cutmap *cm,
                  const uint8_t *solid_in);
void tr3_cut_free(tr3_cut *cu);

#endif
