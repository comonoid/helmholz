/* dirs3.h — шаг A: ординаты на СФЕРЕ для трёхмерной развёртки.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Произведение двух квадратур, и обе взяты
 * не по вкусу:
 *
 *   по μ — ДВОЙНОЙ Гаусс, узлы раздельно на [−1,0] и [0,1] (К10). В T3 это
 *   ИЗМЕРЕНО: одинарный Гаусс по [−1,1] даёт ошибку в 15, 26 и 49 раз больше при
 *   ND = 16, 32, 64, и разрыв РАСТЁТ с ND, то есть он сходится медленнее;
 *
 *   по азимуту — Гаусс ПО КВАДРАНТАМ, узлы строго внутри. Тогда направлений,
 *   параллельных осям, в наборе НЕТ вовсе, а такое направление дало бы грань с
 *   ω·n = 0, то есть ячейку без вытока и вырожденный порядок обхода (тот же
 *   довод, что в tr2_dirs_quadrant_gauss).
 *
 * СКОЛЬКО БРАТЬ — ОТВЕТ T3: при альбедо 0.9 для 1e-3 по радиансу довольно
 * ND = 16, для 1e-4 — ND = 32. Здесь ND = 2·nmu · 4·nphi.
 */
#ifndef TR_DIRS3_H
#define TR_DIRS3_H

typedef struct {
  int n;
  double *ox, *oy, *oz; /* единичные направления */
  double *w;            /* веса, Σ = 4π */
} tr3_dirs;

/* nmu узлов на ПОЛУСФЕРУ по μ, nphi узлов на КВАДРАНТ по азимуту.
 * Итого n = 2·nmu · 4·nphi. 0 — успех. */
int tr3_dirs_product(tr3_dirs *d, int nmu, int nphi);
void tr3_dirs_free(tr3_dirs *d);

#endif
