/* mesh3.h — шаг B: сетка ГРАНЕЙ над октодеревом для трёхмерной развёртки.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Трёхмерный аналог `tr2_mesh`, и главное в
 * нём то же самое:
 *
 *     ГРАНЬ ЕСТЬ ПЕРЕСЕЧЕНИЕ ГРАНЕЙ ДВУХ СОСЕДЕЙ, А НЕ ГРАНЬ ЯЧЕЙКИ.
 *
 * Поэтому висячего узла как особого случая не существует: у крупной ячейки вдоль
 * одной стороны просто НЕСКОЛЬКО граней, и обе стороны интегрируют по ОДНОЙ И
 * ТОЙ ЖЕ геометрии. Отсюда консервативность передачи потока на смене уровня —
 * конструктивно, а не проверкой.
 *
 * И ЭТО ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ОНА ОБЕСПЕЧИВАЕТСЯ (К13). Печная задача
 * неконсервативную передачу НЕ ЛОВИТ: константу воспроизводит любой разумный
 * оператор, включая небрежное усреднение по всему ребру крупной ячейки. Ловит её
 * баланс энергии при НЕОДНОРОДНОЙ подсветке — и здесь, на этапе построения,
 * ловит ещё и целочисленное тождество «сумма площадей подграней равна площади
 * стороны», которое проверяется ТОЧНО, потому что все координаты целые.
 *
 * ЯЧЕЙКИ — ЛИСТЬЯ ОКТОДЕРЕВА, КОРОБКИ. Разрезанных ячеек здесь нет, и это не
 * упрощение на бегу: T2 в двумерии ровно так и сделана (прямоугольники), а
 * поверхность входит ГРАНИЧНЫМ УСЛОВИЕМ, то есть шагом D, а не объёмом.
 */
#ifndef TR_MESH3_H
#define TR_MESH3_H

#include "cut/poly3.h"
#include "octree.h"

/* Грань: прямоугольник на плоскости axis = pos, между ячейками ca (со стороны
 * МЕНЬШИХ координат) и cb (со стороны больших). cb < 0 — внешняя граница куба,
 * номер стенки = ~cb (0..5: −x,+x,−y,+y,−z,+z). ca < 0 быть не может. */
typedef struct {
  int32_t ca, cb;
  int32_t axis;
  int32_t pos;
  int32_t lo[2], hi[2]; /* по двум поперечным осям, в порядке возрастания номера */
} tr3_face;

typedef struct {
  const hz_octree *tree;
  hz_frame fr;
  int32_t ncell;
  int32_t *node;   /* [ncell] индекс узла дерева */
  int32_t *cellof; /* [tree->n] узел -> ячейка, иначе −1 */
  int32_t (*clo)[3];
  int32_t *csize;
  tr3_face *f;
  int32_t nf, fcap;
  int32_t *fstart, *flist; /* CSR: грани, инцидентные ячейке */
} tr3_mesh;

int tr3_mesh_build(tr3_mesh *m, const hz_octree *t, const hz_frame *fr);
void tr3_mesh_free(tr3_mesh *m);

/* Четыре вершины грани в МИРОВЫХ координатах, обходом ПРОТИВ ЧАСОВОЙ, если
 * смотреть с ПЛЮС стороны оси. Нужно потоковым членам DG. */
void tr3_face_corners(const tr3_mesh *m, int32_t fi, double v[4][3]);

/* Площадь грани в мире. */
double tr3_face_area(const tr3_mesh *m, int32_t fi);

#endif
