/* raster3.h — ЭТАП A, ШАГ 2: ПРОЕКЦИОННЫЙ СБОР вместо марша по лучу.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md, план перехода, этап A).
 *
 * ЗАЧЕМ. Марш по лучу спрашивает у геометрии «что видно в этом направлении» и
 * платит спуском по дереву, поиском в боковой таблице и разворачиванием
 * полуплоскостей НА КАЖДУЮ ЯЧЕЙКУ вдоль луча. Измерено: `1082` нс на луч, из них
 * марш 37%, разворачивание 31%, спуск 17%, поиск 15%. Проекция задаёт обратный
 * вопрос — «куда проецируется этот элемент» — и потому стоит
 * `O(элементы + покрытые пиксели)`, а дерева не касается вовсе.
 *
 * ПОЛОВИНЫ ЭТАПА A РАЗДЕЛЕНЫ, И ЭТО ИЗМЕРЕНИЕ, А НЕ УДОБСТВО. План связывал их
 * доводом «LOD без проекции превращает марш из 23 ячеек в 7500»; К52 закрыта
 * замером — при схлопнутой пустоте ячеек вдоль луча `18 → 21 → 22` при
 * учетверении `ε`, то есть довод принадлежал ОБЪЁМНОМУ закону. Поэтому шаг 1
 * (LOD) уже закрыт при СТАРОМ сборе, а здесь меняется ровно одна вещь — сбор, —
 * и сверяется он с маршем НА ТОЙ ЖЕ СЕТКЕ (К53).
 *
 * ТОЧКА В МНОГОУГОЛЬНИКЕ БЕРЁТСЯ ПЕРЕСЕЧЕНИЕМ ЛУЧА ПИКСЕЛЯ С ПЛОСКОСТЬЮ
 * ЭЛЕМЕНТА, а не интерполяцией по экрану. Так не нужен отдельный отсекатель,
 * геометрия остаётся точной, а стоимость — та же `O(покрытые пиксели)`:
 * перебираются только пиксели экранной коробки элемента. Порога нигде нет —
 * принадлежность решается знаком, а глубина сравнивается как есть.
 *
 * ЧЕГО ЭТОТ СБОР НЕ ДЕЛАЕТ И НЕ БУДЕТ (К56). Зеркал он не считает: отражённый
 * луч уходит в направление, которое проекцией не выражается вовсе, и образ в
 * зеркале по-прежнему берётся ПРОСЛЕЖИВАНИЕМ. Проекция закрывает диффузную
 * часть, то есть ту, ради которой поле и хранится.
 *
 * И ЧТО ОН МЕНЯЕТ В ОТВЕТЕ (К59). Растеризуются ЭЛЕМЕНТЫ, то есть куски ФАСЕТОВ:
 * силуэт тела становится многогранным, тогда как марш брал его у ПРИМИТИВА и
 * давал `0.0` побитово. Это НЕ дефект реализации, а выбор тела, и он обязан быть
 * ВИДЕН в замере: ошибка силуэта должна ПАДАТЬ с уровнем фасетизации `k`. Если
 * не падает — растеризуется не то, что думаем.
 */
#ifndef TR_RASTER3_H
#define TR_RASTER3_H

#include "transport/cam3.h"
#include "transport/cut3.h"
#include "transport/gather3.h"

typedef struct {
  const tr3_mesh *m;
  const tr3_cut *cut;
  /* Хранимое по каналам, раскладка та же, что у сбора: [nch][4·nf], [nch][4·nse] */
  const double *bout;
  const double *sout;
  int nch;
} tr3_raster;

typedef struct {
  long nelem;  /* сколько элементов и граней вообще нарисовано */
  long nskip;  /* пропущено: многоугольник не поместился (`nv = 0`) либо за камерой */
  long npix;   /* сколько пикселей записано (с учётом перезаписи по глубине) */
  long nempty; /* пикселей без единого элемента — ДЫРЫ, и их надо видеть */
} tr3_rstats;

/* `buf` — [nch][W·H] радианс; `zbuf` — [W·H] глубина (может быть NULL внутри).
 * Возврат 0 — успех, иначе нехватка памяти. */
int tr3_raster_render(const tr3_raster *r, const tr3_camera *cam, double *buf, tr3_rstats *st);

#endif
