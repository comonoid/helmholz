/* ray3.h — T5а, проход 1 и проход 3: марш по лучу сквозь октодерево.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Фазы нет.
 *
 * ЧТО ЭТО ЗАКРЫВАЕТ. Проход 1 (прямой свет) требует НАКОПЛЕНИЯ оптической
 * толщины вдоль пути от источника, а не булева «видно/не видно» (аудит С4):
 * один запрос стоит O(ячеек вдоль луча), и в мутной среде булев ответ ещё и
 * физически неверен. Проход 3 (сбор по пикселю) требует того же марша до первого
 * попадания. Поэтому интерфейс здесь ОДИН и булевой видимости в нём НЕТ (К16):
 * толщина возвращается всегда, попадание — отдельным полем.
 *
 * ε НЕТ НИГДЕ (К16 и общее правило проекта). Обычный обход октодерева лучом
 * сдвигает точку за грань на малую величину — магический порог в чистом виде.
 * Здесь следующая ячейка определяется ЦЕЛОЧИСЛЕННЫМ ШАГОМ через грань выхода:
 * у коробки считается параметр выхода и ОСЬ выхода, вдоль неё целая координата
 * шагает на lo+size (при d>0) или lo−1 (при d<0), остальные берутся из точки
 * выхода с зажимом в текущую коробку. Зажим делает угловой случай (луч ровно в
 * ребро) детерминированным: обход входит в соседа через шаг, не теряя ячеек и
 * не создавая щели.
 *
 * НАЧАЛО РОВНО НА ПОВЕРХНОСТИ ТОЖЕ БЕЗ ε. Теневой луч выходит из точки, где
 * s = n·x − off РОВНО ноль. Самопопадания не будет, потому что вход в
 * полупространство требует ds/dt < 0 СТРОГО: при взгляде наружу производная
 * положительна, и полупространство ПОКИДАЕТСЯ, а не входится. Смещать точку по
 * нормали не нужно.
 *
 * ОКТОДЕРЕВО ЗДЕСЬ — ПРОСТРАНСТВЕННЫЙ ИНДЕКС, А НЕ НОСИТЕЛЬ СВОЙСТВ. hz_onode
 * несёт double complex k2 — это волновая физика, и перенос её не читает. σ_t
 * приходит массивом по ИНДЕКСУ УЗЛА, то есть тем самым абстрактным ключом,
 * который PLAN_CUT.md Г20 и заводил.
 */
#ifndef TR_RAY3_H
#define TR_RAY3_H

#include "cut/poly3.h"
#include "cut/surf.h"
#include "octree.h"

typedef struct {
  const hz_octree *tree; /* топология и ячейки; k2 НЕ читается */
  hz_frame fr;           /* единицы дерева -> мир */
  const double *sigma;   /* [nsigma] σ_t по индексу узла; NULL = вакуум */
  /* ДЛИНА `sigma`, И ОНА СВЕРЯЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ (К28).
   * `sigma` читается как `sigma[ni]`, где `ni` — индекс УЗЛА, то есть его
   * законная граница есть `tree->n`. Если дерево дорастёт ПОСЛЕ выделения
   * массива (`hz_oct_set_box` умеет добавлять узлы), чтение уедет за границу
   * МОЛЧА. Прежде это держалось на порядке вызовов в каждом строителе сцены —
   * то есть на соглашении, а `CLAUDE.md` велит ловить такой класс проверкой.
   * Сверка стоит одно сравнение на весь марш, а не на ячейку. */
  int32_t nsigma;
  const hz_surftab *st;  /* примитивы: источник истины для попадания (К15) */
  const hz_facettab *ft; /* плоскости, которыми режут */
  const hz_cutmap *cm;   /* ячейка -> веер полуплоскостей */
  /* ТЕЛО КАК МНОГОГРАННИК, А НЕ КАК ПРИМИТИВ. По умолчанию 0, и тогда действует
   * К15: где веер ссылается на примитив, ему принадлежат и решение «попал / не
   * попал», и точка, и нормаль, а фасеты работают только пространственным
   * признаком. Единица выключает примитив совсем — тело становится тем
   * многогранником, которым его видит объёмный интегратор.
   *
   * ЭТО НЕ ТОЛЬКО НЕГАТИВНЫЙ КОНТРОЛЬ, НО И ЗАКОННЫЙ РЕЖИМ. Огранённое тело —
   * не ошибка, а другая геометрия, и у зеркала она даёт осмысленную картинку:
   * каждый фасет отражает свой кусок комнаты. Прежде этот путь existed только
   * внутри теста, что неверно: режим, которым пользуются, обязан быть в коде, а
   * не воспроизводиться в проверке.
   *
   * ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ОШИБКИ, ИЗМЕРЕНО: у зеркала ошибка нормали входит в
   * отражённое направление С УДВОЕНИЕМ, и подмена примитива фасетом даёт
   * расхождение 1.5 при яркости порядка единицы, падающее в 1.82 раза с ростом
   * уровня фасетизации. Поэтому включать это надо СОЗНАТЕЛЬНО. */
  int facet_only;
} tr3_scene;

typedef struct {
  double tau;     /* НАКОПЛЕННАЯ оптическая толщина до точки останова */
  int hit;        /* 1 — попали в границу материала */
  double t;       /* параметр луча в точке попадания, МИРОВАЯ длина */
  double p[3];    /* точка попадания, МИР */
  double n[3];    /* нормаль наружу материала, МИР, единичная */
  int32_t facet;  /* фасет, породивший попадание, или -1 */
  int32_t surf;   /* примитив-родитель или -1 */
  int32_t cell;   /* узел, в котором произошло попадание */
  int32_t nsteps; /* пройдено ячеек — цена запроса по С4, а не догадка */
  int refined;    /* 1 — точка уточнена по ПРИМИТИВУ, 0 — осталась фасетной */
} tr3_hit;

/* К45: СЕГМЕНТЫ СРЕДЫ ВДОЛЬ ЛУЧА. march умеет только НАКОПЛЕННУЮ τ, а сбору с
 * вкладом среды нужно ∫ T(s)·(σ_s/4π)·φ(s) ds — то есть ЗНАТЬ СЕГМЕНТЫ
 * (ячейка, [ta, tb]) по отдельности. Лезть в накопленную τ нельзя: она
 * суммарна, и распределить её по ячейкам задним числом негде. Поэтому марш
 * умеет ЗВАТЬ НАБЛЮДАТЕЛЯ на каждый средовый отрезок; суммарная τ при этом не
 * меняется, и вызов с seg_fn = NULL даёт прежний мир побитово.
 * `ta`/`tb` — параметры ЛУЧА (мировая длина от точки старта марша), `ni` —
 * индекс УЗЛА дерева, в котором отрезок лежит. */
typedef void (*tr3_seg_fn)(void *ctx, int32_t ni, double ta, double tb);

/* Луч задаётся в МИРЕ: o + t·d, |d| = 1 (параметр есть длина, и на этом стоит
 * то, что τ считается той же замкнутой формой, что в T1). tmax < 0 — идти до
 * выхода из куба. Возврат 0 — марш выполнен (в том числе без попадания).
 * Возврат TR3_MARCH_ESIGMA — `sigma` короче дерева (К28); марш НЕ выполняется. */
#define TR3_MARCH_ESIGMA 2
int tr3_march(const tr3_scene *sc, const double o[3], const double d[3], double tmax, tr3_hit *h);
/* То же с наблюдателем сегментов среды (К45); остальное — как у tr3_march. */
int tr3_march_sink(const tr3_scene *sc, const double o[3], const double d[3], double tmax,
                   tr3_hit *h, tr3_seg_fn seg_fn, void *seg_ctx);

/* §829: прибор доли марша — счётчик вызовов и Σ шагов по ячейкам. Пассивные
 * атомики; долю ВРЕМЕНИ даёт perf по символу tr3_march (план §829). */
void hz_ray3_stats_get(long long *calls, long long *steps);
void hz_ray3_stats_print(const char *tag);

#endif
