/* rte2d.h — T2: рассеяние, разрывный Галёркин степени 1, ограничитель.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Фазы нет.
 *
 *     (ω·∇)L = −σ_t(x,ω)·L + σ_s(x)∫p·L dω' + ε(x,ω)
 *
 * ПОЧЕМУ ДВА ИЗМЕРЕНИЯ, А НЕ СЛОЙ КАК В T1. Аудит К8 требует гонять печь на
 * ГРАДУИРОВАННОЙ и АНИЗОТРОПНОЙ сетке, потому что на равномерной ошибка
 * передачи потока между уровнями не проявится ВОВСЕ. Но в одномерном слое
 * разбитой грани не существует (у каждой грани ровно один сосед с каждой
 * стороны), а «анизотропная ячейка» не определена. То есть T2 обязана быть
 * минимум двумерной — иначе главное требование К8 проверить нечем.
 *
 * УГЛОВАЯ ОСЬ — НАПРАВЛЕНИЯ В ПЛОСКОСТИ, L(x,y,θ), мера dθ на [0,2π). Это
 * двумерная модельная задача переноса, а не срез трёхмерной: настоящий
 * трёхмерный набор (двойной Гаусс по μ × азимут) приезжает вместе с трёхмерной
 * развёрткой. Для T2 это неважно — печь, линейное решение и баланс энергии
 * точны при ЛЮБОМ нормированном наборе направлений, а проверяется здесь
 * ПРОСТРАНСТВЕННАЯ схема.
 *
 * ЧТО ХРАНИТСЯ (аудит Р1). Угловое поле транзиентно: коэффициенты DG живут
 * только внутри прохода по одной ординате, 3·ncell чисел, и умирают вместе с
 * ним. НАРУЖУ выходит скалярный поток φ = ∫L dω — тоже DG1, 3 числа на ячейку.
 * При изотропном рассеянии этого моменты и достаточно; анизотропная фазовая
 * функция потребует больше моментов и НЕ реализована (см. ниже).
 *
 * ЧТО В T2 НЕ ДЕЛАЕТСЯ И ПОЧЕМУ:
 *  - σ_t, σ_s, ε КОНСТАНТНЫ в ячейке (ε — DG1, среда — нет). Линейная по узлу
 *    среда стоит в плане, но она сцеплена с линейной функцией границы материала
 *    и уезжает в T4 вместе с ней. В T1 линейная σ_t уже проверена — в замкнутой
 *    форме свободного пролёта.
 *  - Фазовая функция ТОЛЬКО ИЗОТРОПНАЯ. Причина не лень: анизотропную матрицу
 *    p[m'][m] недостаточно нормировать по СТРОКАМ (Σ_m w_m p = 1 сохраняет
 *    источник рассеяния), нужна ДВАЖДЫ стохастическая нормировка, иначе
 *    рассеяние перестаёт сохранять энергию по столбцам и баланс уезжает.
 *    Здесь p = p0 = const, и p0 берётся как 1/Σw — тогда рассеяние сохраняет
 *    энергию ТОЧНО, даже если Σw отличается от 2π на округление.
 */
#ifndef TR_RTE2D_H
#define TR_RTE2D_H

/* ------------------------------------------------------- направления */

/* Направления в плоскости: ω = (ox, oy), |ω| = 1, веса Σw = 2π. */
typedef struct {
  int n;
  double *ox, *oy, *w;
} tr2_dirs;

/* nper узлов Гаусса на КАЖДЫЙ квадрант азимута (n = 4·nper). Раздельные
 * квадранты — та же мысль, что двойной Гаусс в T1 (К10): узлы строго внутри,
 * поэтому направлений, параллельных осям, в наборе НЕТ. А они бы дали грань с
 * ω·n = 0, то есть ячейку без вытока и вырожденную развёртку. */
int tr2_dirs_quadrant_gauss(tr2_dirs *d, int nper);
void tr2_dirs_free(tr2_dirs *d);

/* -------------------------------------------------- фазовая функция */

/* Изотропное рассеяние: p ≡ p0. p0 = 1/Σw, а НЕ 1/(2π) — тогда
 * Σ_m w_m·(σ_s·p0·φ) = σ_s·φ побитово, и рассеяние сохраняет энергию точно
 * независимо от округления в весах. */
typedef struct {
  double p0;
} tr2_phase;
void tr2_phase_isotropic(tr2_phase *ph, const tr2_dirs *d);

/* ------------------------------------------------------------ сетка */

/* Прямоугольники на ЦЕЛОЧИСЛЕННОЙ виртуальной сетке nx×ny единиц; физический
 * размер единицы — ux×uy. Целые координаты не украшение: сопоставление граней
 * требует ТОЧНОГО равенства положений, а на double его пришлось бы сравнивать
 * с порогом. Анизотропия бывает двух родов и обе поддержаны: ux ≠ uy (единица
 * не квадратная) и ячейка в несколько единиц по одной оси. */
typedef struct {
  int ix0, iy0, ix1, iy1;
} tr2_cell;

/* Грань = ПЕРЕСЕЧЕНИЕ рёбер двух соседних ячеек, а не ребро ячейки. Поэтому
 * висячего узла как особого случая не существует: у крупной ячейки вдоль одного
 * ребра просто несколько граней. Отсюда же консервативность передачи потока
 * (К8): обе стороны интегрируют по ОДНОЙ И ТОЙ ЖЕ геометрии.
 * axis 0 — нормаль вдоль x, axis 1 — вдоль y. lo/hi — ячейки с − и + стороны,
 * −1 = граница области. it0..it1 — тангенциальный отрезок в единицах. */
typedef struct {
  int axis, ipos, it0, it1, lo, hi;
} tr2_face;

typedef struct {
  double ux, uy;
  int nx, ny;
  int ncell, ccap;
  tr2_cell *cell;
  int nface;
  tr2_face *face;
  int *coff, *cfac; /* CSR: грани ячейки c — cfac[coff[c]..coff[c+1]) */
} tr2_mesh;

int tr2_mesh_init(tr2_mesh *m, int nx, int ny, double ux, double uy, int ccap);
int tr2_mesh_add(tr2_mesh *m, int ix0, int iy0, int ix1, int iy1);
/* Строит грани и CSR. ПРОВЕРЯЕТ, что ячейки покрывают nx×ny ровно один раз
 * (целочисленно, без порогов) — дырка или наложение здесь дешевле, чем
 * загадочный перенос потом. −1 при незамощении. */
int tr2_mesh_finish(tr2_mesh *m);
void tr2_mesh_free(tr2_mesh *m);

int tr2_mesh_uniform(tr2_mesh *m, int nx, int ny, double ux, double uy);
/* Градуированная: квадродерево, мельче к центру области, БЕЗ балансировки
 * уровней — перепад 4:1 законен и для граней он тяжелее, чем 2:1. */
int tr2_mesh_graded(tr2_mesh *m, int nunit, double ux, double uy);
/* Анизотропная: слева ячейки w×1 единиц, справа 1×w. Вытянуты в
 * ПЕРПЕНДИКУЛЯРНЫЕ стороны, и на стыке половин грани разбиты. */
int tr2_mesh_aniso(tr2_mesh *m, int nunit, double ux, double uy, int w);

/* Сколько граней КОРОЧЕ полного ребра ячейки, к которой они принадлежат, —
 * то есть сколько раз передача потока идёт через смену уровня. Нужно как
 * страховка от первой подписи артефакта: если это число ноль, «печь на
 * градуированной сетке» ничего про К8 не проверяет. */
int tr2_mesh_nsplit(const tr2_mesh *m);

/* ------------------------------------------------------- ограничитель */

/* OFF          — чистый DG1, около границы тени радианс уходит в минус (T5);
 * SLOPE        — наклон срезается, среднее НЕ пересчитывается: ограничитель
 *                меняет выточный след, и баланс ячейки (уравнение при v=1)
 *                перестаёт выполняться ⇒ энергия ТЕЧЁТ. Оставлен как
 *                негативный контроль к следующему режиму, а не как вариант;
 * CONSERVATIVE — наклон срезается, затем среднее ПЕРЕСЧИТЫВАЕТСЯ из уравнения
 *                баланса при уже срезанном наклоне. Баланс точен, константа
 *                сохраняется (у константы наклон нулевой, срезать нечего —
 *                поэтому печь по К6 этот ограничитель пройти обязана). */
typedef enum { TR2_LIM_OFF = 0, TR2_LIM_SLOPE = 1, TR2_LIM_CONSERVATIVE = 2 } tr2_limiter;

/* ---------------------------------------------------------- задача */

typedef struct {
  const tr2_mesh *mesh;
  const tr2_dirs *dirs;
  const tr2_phase *phase;
  const double *sig_t; /* [ncell] */
  const double *sig_s; /* [ncell] */
  /* σ_t(x,ω) = gdir[m]·sig_t[c]. NULL ⇒ скалярное σ_t (gdir ≡ 1). Форма
   * разделяется, поэтому направленность стоит один скаляр на ординату — как
   * и в T1. ВНИМАНИЕ (К1): при gdir ≠ const однородный радианс есть решение
   * ТОЛЬКО если ε тоже направленное, ε(ω) = (σ_t(ω) − σ_s)·L. Печь с
   * направленным σ_t и изотропным ε ОБЯЗАНА поехать у исправного кода. */
  const double *gdir;
  /* ε(x,ω), DG1: emit[(c·n + m)·3 + k], k = 0,1,2 ↔ 1,ξ,η. NULL ⇒ ε = 0. */
  const double *emit;
  /* Влёт на границе: L = lb[side] + lbt[side]·t, t — ФИЗИЧЕСКАЯ тангенциальная
   * координата. Сторона: 0=xlo, 1=xhi, 2=ylo, 3=yhi. Линейная часть нужна не
   * для красоты: без неё нельзя поставить задачу с ЛИНЕЙНЫМ точным решением, а
   * это единственный тест, который проверяет НАКЛОННЫЕ степени свободы. Печь
   * их не проверяет вовсе — у неё наклон нулевой. */
  double lb[4], lbt[4];
  tr2_limiter lim;
  int maxit;          /* 0 ⇒ TR2_MAXIT */
  double tol;         /* 0 ⇒ TR2_TOL */
  int one_pass;       /* 1 ⇒ ровно один проход от phi0 (для невязки точного решения) */
  const double *phi0; /* начальный φ (3·ncell) или NULL ⇒ нули */
} tr2_problem;

typedef struct {
  int iters;
  double resid; /* относительное изменение φ на последней итерации */
  /* Энергетика. balance = pin + pemit − pout − pabs, где pabs берёт σ_t от
   * НОВОГО прохода, а σ_s·φ — от ТОГО ЖЕ φ, что породил источник. В такой
   * комбинации это ТОЧНОЕ дискретное тождество (сумма уравнений при v=1 по
   * всем ячейкам и ординатам), и оно обязано выполняться до округления на
   * ЛЮБОЙ итерации, а не только после сходимости. Именно оно ловит утечку на
   * смене уровня — печь её не ловит, см. заголовок tr2_solve. */
  double pin, pout, pabs, pemit, balance;
  double lmin, lmax; /* min/max среднего DG1 по всем ячейкам И ординатам */
  double cmin;       /* минимум по углам ячеек: где радианс ушёл в минус */
  long nneg;         /* сколько (ячейка,ординат) имели отрицательный угол */
  long nlimited;     /* сколько раз ограничитель срезал наклон */
  double *phi;       /* 3·ncell, ВЛАДЕНИЕ у вызывающего: tr2_stats_free */
} tr2_stats;

/* ПЕЧЬ ПРОВЕРЯЕТ ТОЛЬКО СРЕДНЕЕ. Однородный радианс есть решение с нулевым
 * наклоном, поэтому ошибка в уравнениях для наклонных степеней свободы печь
 * проходит незамеченной; и передачу потока через разбитую грань она тоже не
 * ловит, потому что ЛЮБОЙ разумный оператор передачи воспроизводит константу.
 * Отсюда два теста рядом с печью: линейное точное решение (наклоны) и баланс
 * энергии при НЕОДНОРОДНОЙ подсветке (передача потока). */
int tr2_solve(const tr2_problem *pr, tr2_stats *st);
void tr2_stats_free(tr2_stats *st);

#endif /* TR_RTE2D_H */
