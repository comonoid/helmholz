/* sweep.h — T1: ядро развёртки по дискретным ординатам, ЧИСТОЕ ПОГЛОЩЕНИЕ.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md), не волновая. Фазы нет, комплексных
 * чисел нет, потенциалов φ нет: базис оператора первого порядка — полиномы.
 *
 * Решается    (ω·∇)L = −σ_t(x,ω)·L,    σ_s = 0,  ε = 0.
 *
 * ε = 0 — НЕ упрощение ради первого шага, а условие корректности эталона
 * (аудит К2): при линейной σ_t и q ≠ 0 уравнение dL/ds = −σ_t·L + q в
 * элементарных функциях не берётся, и exp(−τ) перестаёт быть эталоном.
 * Подсветка поэтому только через границу.
 *
 * НАПРАВЛЕННОЕ σ_t. Плановая форма σ_t(x,ω) = G(ω)·u_L(x) РАЗДЕЛЯЕТСЯ, поэтому
 * в ядро она входит одним скаляром g = G(ω) на ординату, умножающим запасённое
 * поле u_L. g = 1 — изотропное (скалярное) σ_t.
 *
 * ЗАМКНУТАЯ ФОРМА, А НЕ КВАДРАТУРА. Внутри ячейки σ_t линейна, а трапеция для
 * линейной функции ТОЧНА, поэтому τ = (σ_вход + σ_выход)/2 · длина есть
 * аналитический интеграл, и обновление ячейки L_out = L_in·exp(−τ) верно до
 * округления. Полиномиальное (DG) обновление дало бы рациональное приближение
 * к exp(−τ) с ошибкой O(τ³) на ячейку — то есть 1e-8, а не 1e-14. Форма
 * L_out = L_in·e^{−τ} + (q/σ)(1 − e^{−τ}) — та же характеристическая схема, и
 * второе слагаемое приезжает вместе с рассеянием в T2.
 *
 * ГЕОМЕТРИЯ T1 — плоский слой: ячейки по z, направление задаётся косинусом μ,
 * длина хорды в ячейке = Δz/|μ|. Сетка НЕРАВНОМЕРНАЯ с самого начала: точность
 * замкнутой формы не должна зависеть от разбиения, а на равномерной сетке
 * ошибка накопления не проявится (та же логика, что в аудите К8).
 */
#ifndef TR_SWEEP_H
#define TR_SWEEP_H

/* ---------------------------------------------------------------- ординаты */

/* Набор ординат для плоского слоя. Азимутальная симметрия уже свёрнута:
 * ∫_{S²} f(μ) dω = 2π ∫_{−1}^{1} f(μ) dμ, поэтому веса нормированы на
 *
 *     Σ_m w_m = 2            (полная сфера)
 *     Σ_{μ>0} w_m       = 1        Σ_{μ>0} w_m·μ_m = 1/2
 *
 * Узлы ДВОЙНОЙ гауссовой квадратуры: [−1,0] и [0,1] набираются раздельно
 * (аудит К10 — на границе полубесконечной среды радианс разрывен при μ = 0, и
 * обычный Гаусс по [−1,1] этот разрыв перешагивает). В T1 разрыва нет, но
 * квадратура заводится сразу правильная, чтобы T3 не ловил ложную тревогу.
 * μ_m строго внутри полуинтервалов, поэтому μ = 0 в наборе не бывает.
 */
typedef struct {
  int n;      /* число ординат, = 2·nhalf */
  double *mu; /* косинусы, по возрастанию: [−1,0) затем (0,1] */
  double *w;  /* веса, Σ = 2 */
} tr_ordinates;

/* nhalf узлов на каждую полусферу. 0 — успех, −1 — плохой аргумент/память. */
int tr_ordinates_double_gauss(tr_ordinates *o, int nhalf);
void tr_ordinates_free(tr_ordinates *o);

/* ------------------------------------------------------------------- среда */

/* Слой: ncell ячеек по z, в каждой u_L ЛИНЕЙНА. Значения на входной и
 * выходной гранях хранятся раздельно (sig_lo/sig_hi), поэтому u_L может
 * РАЗРЫВАТЬСЯ между ячейками — граница материала не требует непрерывности. */
typedef struct {
  int ncell;
  double *z;      /* ncell+1 границ ячеек, по возрастанию */
  double *sig_lo; /* ncell: u_L на грани z[i]   */
  double *sig_hi; /* ncell: u_L на грани z[i+1] */
} tr_slab;

int tr_slab_alloc(tr_slab *s, int ncell);
void tr_slab_free(tr_slab *s);

/* Границы ячеек от z=0 до z=zmax, геометрическая градуировка.
 * stretch = Δz_первой / Δz_последней — отношение НА ВЕСЬ СЛОЙ, не на ячейку.
 * stretch = 1 даёт равномерную сетку, stretch > 1 — сгущение к z=zmax.
 * Требует stretch > 0.
 *
 * ПОЧЕМУ НА СЛОЙ, А НЕ НА ЯЧЕЙКУ. При шаге-на-ячейку (Δz_i ∝ q^{−i}) мелкие
 * ячейки при большом n уходят ниже разрешения double рядом с z ≈ zmax, там
 * z[i+1] == z[i], и «измельчение сетки» перестаёт измельчать — ошибка схемы
 * замирает не потому, что схема точна, а потому, что параметр не действует.
 * Первая подпись артефакта, поймана на самом этом тесте. */
void tr_slab_grade(tr_slab *s, double zmax, double stretch);

/* u_L(z) = a + b·z, сэмплированное на грани ячеек: непрерывная линейная
 * среда, для которой ∫u_L dz известен аналитически. */
void tr_slab_set_linear(tr_slab *s, double a, double b);

/* ----------------------------------------------------------------- ядро */

/* Одна ячейка вдоль характеристики, чистое поглощение.
 * len — длина ХОРДЫ (уже поделена на |μ|), sig_* — σ_t на входе/выходе. */
double tr_cell_absorb(double sig_in, double sig_out, double len, double l_in);

/* Развёртка через весь слой для одной ординаты. Порядок обхода задаёт знак μ:
 * μ > 0 — вток на z[0], μ < 0 — вток на z[ncell]. Возвращает радианс на
 * выходной грани. Если l_face != NULL, туда пишутся ncell+1 значений на гранях
 * (индекс i ↔ z[i], НЕ порядок обхода). Требует μ ≠ 0. */
double tr_sweep_absorb(const tr_slab *s, double mu, double g, double l_in, double *l_face);

/* --------------------------------------------------------- угловые моменты */

/* Моменты по всему набору ординат; l[] — по одному значению на ординату.
 * Чтобы взять полусферу, обнулите противоположную половину l[].
 *   moment0 = ∫L dω   = 2π Σ w_m l_m         (скалярный поток φ)
 *   moment1 = ∫L μ dω = 2π Σ w_m μ_m l_m     (нормальный поток F_z)
 * Изотропный радианс L₀ по одной полусфере даёт φ = 2π·L₀ и F_z = π·L₀ ТОЧНО:
 * это и есть место, где нормировка весов входит в измеряемое число. */
double tr_moment0(const tr_ordinates *o, const double *l);
double tr_moment1(const tr_ordinates *o, const double *l);

#endif /* TR_SWEEP_H */
