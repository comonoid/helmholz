/* sweep3.h — шаги C и D: ТРЁХМЕРНАЯ РАЗВЁРТКА по дискретным ординатам.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md). Разрывный Галёркин степени 1 по коробкам
 * октодерева, противопоток по граням, изотропное рассеяние, итерация по
 * рассеянию. Трёхмерный аналог T2, и вся его оснастка переносится сюда дословно
 * вместе с находками:
 *
 *   К12  печь проверяет только СРЕДНЕЕ — нужен ещё тест с ЛИНЕЙНЫМ точным
 *        решением, иначе две трети неизвестных (наклоны) не проверены;
 *   К13  печь НЕ ловит неконсервативную передачу потока — ловит её баланс
 *        энергии при НЕОДНОРОДНОЙ подсветке;
 *   К14  ограничитель монотонности несовместим с Р1 (границы нужны со ВСЕХ
 *        соседей, а в развёртке доступны только верхние по потоку), поэтому
 *        здесь остаётся ПОЛОЖИТЕЛЬНОСТЬ — ровно то, чего требуют К6 и T5;
 *   Р1   угловое поле ТРАНЗИЕНТНО: наружу выходит только скалярный поток φ,
 *        4 числа на ячейку, а полные ND ординат живут внутри одного прохода.
 *
 * ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Разрезанных ячеек нет — ячейка есть коробка листа, а
 * поверхность входит ГРАНИЧНЫМ УСЛОВИЕМ (шаг D). Ровно так же устроена T2 в
 * двумерии, и это не упрощение на бегу, а тот же порядок вех.
 */
#ifndef TR_SWEEP3_H
#define TR_SWEEP3_H

/* Сколько итераций подряд без улучшения лучшей невязки считать ПОЛОМ (К81).
 * Выведено, а не подобрано: ряд по рассеянию идёт как `ρⁿ`, и даже при `ρ = 0.9`
 * десять итераций дают множитель 0.35. Ноль улучшения за десять итераций
 * медленной сходимостью быть не может. */
#define HZ_SWEEP_STALL 10

#include "transport/cut3.h"
#include "transport/dirs3.h"
#include "transport/mesh3.h"

typedef struct {
  const tr3_mesh *m;
  const tr3_dirs *d;
  /* Геометрия разреза. NULL — развёртка по коробкам, как до стыка. */
  const tr3_cut *cut;
  /* Поверхности ВНУТРИ области: отражение и собственное излучение по ФАСЕТУ. */
  const double *facet_rho;
  const double *facet_emit;
  int32_t nfacet;
  const double *sig_t; /* [ncell] */
  const double *sig_s; /* [ncell] */
  const double *eps;   /* [4·ncell] объёмное излучение, DG1, или NULL */
  /* НАПРАВЛЕННАЯ ЧАСТЬ ИЗЛУЧЕНИЯ: ε += eps_dir·ω. Без неё К12 в 3D не поставить
   * вовсе: у точного решения L = A + B·x подстановка в (ω·∇)L + σ_t L = ε даёт
   * ε = B·ω + σ_t(A + B·x), и первый член ЗАВИСИТ ОТ НАПРАВЛЕНИЯ. Изотропным ε
   * линейное решение недостижимо, а без него проверены только средние, то есть
   * треть неизвестных. */
  double eps_dir[3];
  /* ВЛЁТ НА ГРАНИЦЕ: L = binc0 + binc·(x − x0), одинаково для всех направлений.
   * Линейная часть нужна тесту К12: без линейного по касательной влёта задачу с
   * точным решением A + Bx + Cy + Dz не поставить вовсе. */
  double binc0, binc[3], binx0[3];
  /* ШАГ D: СТЕНКИ КАК ГРАНИЧНОЕ УСЛОВИЕ. Если wall_rho != NULL, предписанный
   * влёт заменяется ЛАМБЕРТОВЫМ отражением: на каждой граничной грани хранится
   * ИСХОДЯЩИЙ радианс (аудит Р3 — у диффузной поверхности он от направления не
   * зависит, то есть ОДНО число вместо ND), и он же служит влётом.
   *
   *     L_out = L_emit + (ρ/π)·E,   E = ∫_{вход} L |ω·n| dω
   *
   * ДОГОВОРЁННОСТЬ К9/К17: в хранимом лежит ПОЛНЫЙ исходящий радианс стенки,
   * включая её собственное излучение. Прямой свет здесь не выделен отдельно,
   * потому что источник в этой постановке И ЕСТЬ стенка. */
  const double *wall_rho;  /* [6] отражательная способность стенок */
  const double *wall_emit; /* [6] собственный радианс стенок */
  int limiter;             /* 1 — включить ограничитель положительности */
  /* НЕ ОБНУЛЯТЬ `phi` НА ВХОДЕ. Нужно ровно для одного: чтобы ОДИН проход
   * развёртки можно было применить как ОПЕРАТОР к заданному полю, а не только
   * прогнать итерацию от нуля.
   *
   * Зачем это. Итерация по рассеянию есть ряд Неймана `φ = Σ Tⁿ b` — самый
   * медленный из возможных способов решить `(I − T)φ = b`. Крыловский метод на
   * той же системе сходится по `√κ` вместо `κ`, но ему нужно уметь умножать на
   * `A = I − T`, то есть применять ОДИН проход к произвольному вектору.
   * `tr3_sweep_solve(p, 1, 0, φ, ...)` при `warm_start = 1` делает ровно это:
   * возвращает `S(φ)`.
   *
   * ОГРАНИЧЕНИЕ, КОТОРОЕ НАДО ЗНАТЬ: между отдельными вызовами НЕ сохраняются
   * `bout` и `sout`. Значит применять развёртку как оператор законно только там,
   * где отражающих границ нет (влёт предписан, поверхностных элементов нет) —
   * иначе часть состояния итерации теряется между вызовами. Для задач с
   * отражением нужен вынос состояния наружу, и это отдельная работа. */
  int warm_start;
  /* ПЕЧАТАТЬ ИСТОРИЮ НЕВЯЗКИ КАЖДЫЕ `trace` ИТЕРАЦИЙ; 0 — молчать.
   * Не отладочный хлам, а прибор (К38): «не сошлось за N» и «сходится медленно»
   * различаются ТОЛЬКО историей, и один раз эта разница уже стоила целого
   * пункта плана. Вместе с невязкой печатаются `nclip` и `nfallback` — если
   * невязка стоит, а они меняются, это нелинейный переключатель, а не скорость. */
  int trace;
} tr3_problem;

typedef struct {
  int iters;
  double resid;
  /* [4·nf] исходящий радианс граничных граней, DG1 ПО ПОЛОЖЕНИЮ.
   * ОДНО число на грань давало видимые квадраты на картинке: Р3 говорит, что у
   * диффузной поверхности радианс не зависит от НАПРАВЛЕНИЯ, и это про угловую
   * ось, а не про пространственную. По положению он меняется, и DG1 у нас уже
   * есть — хранить его константой значило бы выбрасывать то, что посчитано. */
  double *bout;
  /* [4·nse] то же на поверхностных элементах внутри области */
  double *sout;
  double pin, pout, pabs, balance; /* энергетический баланс: втекло/вытекло/поглощено */
  /* ПОВЕРХНОСТИ ВНУТРИ ОБЛАСТИ — ОТДЕЛЬНАЯ СТАТЬЯ БАЛАНСА (К40). psin —
   * мощность, ушедшая из объёма В поверхности; psout — отданная ими обратно
   * (отражение плюс собственное излучение). Тождество:
   *
   *     pin + psout = pout + pabs + psin
   *
   * Без этих двух членов баланс в РАЗРЕЗАННОЙ сцене показывал законную невязку
   * в полтора процента (сфера с ρ = 0.78 поглощает 22% падающего), и отличить
   * от неё ошибку схемы в полтора процента было нечем. То есть главный инвариант
   * метода там не проверял ничего. */
  double psin, psout;
  int nclip; /* сколько раз сработал ограничитель */
  /* СКОЛЬКО РАЗ ПРОЕКЦИЯ ХРАНИМОГО ОТСТУПИЛА К КОНСТАНТЕ, на ПОСЛЕДНЕЙ итерации.
   * Число не украшение: пока проекция решалась вырожденной системой 4×4 (К39),
   * откат срабатывал на 1536 гранях из 1536 и его исход МЕНЯЛСЯ между итерациями,
   * отчего развёртка не сходилась вовсе. Тест обязан видеть это число, иначе
   * возврат той же ошибки заметить не по чему. */
  int nfallback;
  /* 1 — остановлено по ЗАСТОЮ невязки, а не по допуску (К81). Два исхода
   * РАЗЛИЧАЮТСЯ: «сошлось» и «упёрлось в пол» — это разные ответы, и сливать
   * их значит повторить Г38 («ноль отобранных» у полной и у пустой ячейки
   * выглядят одинаково). */
  int stalled;
} tr3_stats;

/* phi — [4·ncell] коэффициенты DG1 скалярного потока φ = ∫L dω. */
int tr3_sweep_solve(const tr3_problem *p, int maxit, double tol, double *phi, tr3_stats *st);

/* ПРОЕКЦИЯ НА ЛИНЕЙНЫЕ ФУНКЦИИ НА ПЛОСКОСТИ (К39) — наружу ради фальсификатора.
 * Матрица масс плоского элемента в базисе ячейки вырождена ТОЧНО, и проверять
 * это надо прямо, а не через картинку: печь и полость его не ловят вовсе, потому
 * что у однородного равновесия все наклоны нули. Возврат 1 — настоящее
 * вырождение элемента (отрезок либо точка). */
int tr3_project_plane(const double M[4][4], const double rr[4], const double nul[4], double ee[4]);

/* Нулевой вектор матрицы масс ГРАНИ СЕТКИ в базисе ячейки c. */
void tr3_face_null(const tr3_mesh *m, int32_t f, int32_t c, double nul[4]);

#endif
