/* tet3.h — T4, шаг первый: ИНТЕГРАТОР ПЕРЕНОСА над разрезанной ячейкой.
 *
 * ЛИНИЯ ПЕРЕНОСА (PLAN_TRANSPORT.md T4, PLAN_CUT.md пункт 6 порядка работ:
 * «перенос тетраэдризует — открывает T4»). Общий слой доводит геометрию до
 * выпуклого многогранника с топологией (`hz_poly3`) и на этом СОЗНАТЕЛЬНО
 * останавливается: у двух линий подынтегральные разной природы, и интегратор у
 * каждой свой (Г1, Г6). Здесь — переносный.
 *
 * ПОЧЕМУ ТЕТРАЭДРЫ ЗДЕСЬ ЗАКОННЫ, А В ВОЛНОВОЙ ЛИНИИ ЗАПРЕЩЕНЫ. У переноса
 * подынтегральное — ДЕЙСТВИТЕЛЬНЫЙ ПОЛИНОМ НИЗКОЙ СТЕПЕНИ (произведение двух
 * функций DG1), и для него на тетраэдре существует ЗАМКНУТАЯ ФОРМА по значениям
 * в вершинах. У волновой оно осциллирует как e^{i(k_i+k_j)·x} с 1e6 периодами на
 * носителе, и любая узловая формула там есть sampling (Г2).
 *
 * КВАДРАТУРНЫХ УЗЛОВ ЗДЕСЬ НЕТ ВОВСЕ. Матрица масс линейного базиса на тетраэдре
 * есть V/20·(1 + δ_ij) в барицентрических координатах — это ТОЖДЕСТВО, следствие
 * ∫λ1^a λ2^b λ3^c λ4^d = 6V·a!b!c!d!/(a+b+c+d+3)!, а не правило с подобранными
 * точками. Поэтому «магических порогов нет» соблюдается буквально: подбирать
 * нечего.
 */
#ifndef TR_TET3_H
#define TR_TET3_H

#include "cut/poly3.h"

/* Тетраэдр: четыре вершины в ЕДИНИЦАХ дерева (как и hz_poly3). */
typedef struct {
  double v[4][3];
} tr3_tet;

/* Ёмкость: у выпуклого многогранника с F гранями сумма длин петель ≤ 6F−12,
 * веер из одной вершины даёт по (длина петли − 2) треугольников на грань. */
#define TR3_MAXTET (6 * HZ_P3_MAXF)

/* Веер от вершины v0 по треугольникам граней, ЭТУ ВЕРШИНУ НЕ СОДЕРЖАЩИХ. Грани,
 * содержащие v0, дают вырожденные (нулевого объёма) тетраэдры и пропускаются —
 * это не оптимизация, а условие невырожденности разбиения.
 * Возврат: число тетраэдров, или −1 при переполнении. */
int tr3_tet_from_poly(const hz_poly3 *p, tr3_tet *out, int max);

/* Объём тетраэдра со знаком, в ЕДИНИЦАХ. Знак сохраняется намеренно: сумма со
 * знаком есть проверка ориентации разбиения, а модуль её бы скрыл. */
double tr3_tet_volume(const tr3_tet *t);

/* Матрица масс ЛИНЕЙНОГО базиса {1, ξ, η, ζ} над многогранником, где
 * ξ = (x − c)/h — координаты, отнесённые к центру ячейки c и её размеру h.
 * m[4][4] в МИРОВЫХ объёмах (умножено на u0·u1·u2, см. Г21: объём — единственная
 * величина, переносящаяся в мир умножением).
 * Считается ТОЧНО: по тетраэдрам, замкнутой формой, без узлов. */
int tr3_mass_matrix(const hz_poly3 *p, const hz_frame *fr, const double c[3], double h,
                    double m[4][4]);

/* Интеграл полинома степени ≤ 1 по многограннику: ∫(a0 + a·(x−c)/h) dV, мир. */
double tr3_int_linear(const hz_poly3 *p, const hz_frame *fr, const double c[3], double h,
                      const double a[4]);

#endif
