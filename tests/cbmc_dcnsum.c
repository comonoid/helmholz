/* CBMC-стенд для ПОБОЧНОГО МАССИВА СУММ НОРМАЛЕЙ (`src/cut/dc.c`, шаг Ш9; долг
 * А846).
 *
 * ЗАЧЕМ ИМЕННО ЭТО. Ш9 завёл ВТОРУЮ структуру рядом с деревом, и адресуется она
 * не индексом узла, а `(child0 − 1)/8` — то есть ПРОИЗВОДНЫМ от поля, которое
 * читается из памяти. Класс отказа тут ровно один и он тихий: узел, у которого
 * `child0` не таков, каким его сделал распределитель (порча, чужое дерево,
 * знаковый путь, где массив вовсе не заводился), — и тогда индекс уезжает за
 * массив, а величина возвращается как настоящая. А833 назвал это ДО кода.
 *
 * ЧТО ДОКАЗЫВАЕТСЯ. При ЛЮБОМ содержимом `child0`, `n`, `nsumcap` и при
 * `nsum == NULL` в том числе:
 *   (1) `hz_dc_nsum` не читает за пределами массива;
 *   (2) она возвращает 0 (нет величины) ВСЯКИЙ раз, когда индекс негоден, —
 *       различие «нет величины» и «величина ноль» и есть fail closed (Г25);
 *   (3) при возврате 0 выход обнулён, то есть мусор не выдаётся никогда.
 *
 * ЧЕГО СТЕНД НЕ ПОКРЫВАЕТ: сложение сумм по дереву (`masks_occ_rec`) —
 * рекурсия по дереву, CBMC её в разумном бюджете не берёт; она проверяется
 * прогоном и сверкой Г49 (починка против полной пересборки).
 *
 * КОНТРОЛЬ НАД САМИМ СТЕНДОМ: `-DHZ_CHECK_FALSE` требует заведомо ложного
 * «величина есть всегда», и CBMC ОБЯЗАН выдать контрпример.
 *
 * Прогон:
 *   scripts/cverify.sh tests/cbmc_dcnsum.c --function harness --unwind 4 src/cut/dc.c
 *   ... -DHZ_CHECK_FALSE   (ОБЯЗАН дать контрпример)
 */
#include "cut/dc.h"

int nondet_i(void);

#if !defined(__CPROVER) && !defined(__CPROVER__)
#define __CPROVER_assume(x) ((void)(x))
#define __CPROVER_assert(x, s) ((void)(x))
int nondet_i(void) {
  return 0;
}
#endif

void harness(void);

#define HZ_NB 3 /* узлов в стенде: корень плюс блок — больше CBMC не нужно */

void harness(void) {
  hz_dcnode nd[HZ_NB];
  double sums[HZ_NB][3];
  hz_dctree t;

  int ni = nondet_i();
  __CPROVER_assume(ni >= 0 && ni < HZ_NB);
  for (int i = 0; i < HZ_NB; i++) {
    nd[i].child0 = nondet_i(); /* ЛЮБОЕ, включая порченое и отрицательное */
    for (int a = 0; a < 3; a++)
      sums[i][a] = 1.0;
  }
  t.nd = nd;
  t.n = HZ_NB;
  t.cap = HZ_NB;
  t.nsum = sums;
  t.nsumcap = nondet_i();
  __CPROVER_assume(t.nsumcap >= 0 && t.nsumcap <= HZ_NB);

  double s[3];
  int got = hz_dc_nsum(&t, ni, s);

  /* (2) и (3): «нет величины» обязано быть нулём на выходе. */
  if (!got) {
    /* Сравнение с нулём здесь ТОЧНОЕ и обязано быть точным: доказывается, что
     * выход обнулён, а не «мал». Записано через отрицание неравенств, чтобы не
     * будить -Wfloat-equal, — смысл тот же. */
    int zero = !(s[0] < 0.0) && !(s[0] > 0.0) && !(s[1] < 0.0) && !(s[1] > 0.0) && !(s[2] < 0.0) &&
               !(s[2] > 0.0);
    __CPROVER_assert(zero, "нет величины => выход обнулён, а не мусор");
  }
#ifdef HZ_CHECK_FALSE
  /* КОНТРОЛЬ НАД СТЕНДОМ: заведомо ложно — величина есть не всегда. */
  __CPROVER_assert(got == 1, "заведомо ложное: величина есть всегда");
#endif

  /* Узел без детей величины иметь не может — иначе индекс взят из мусора. */
  if (nd[ni].child0 < 1) {
    __CPROVER_assert(got == 0, "у узла без блока детей величины нет");
  }
}
