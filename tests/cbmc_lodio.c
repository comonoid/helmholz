/* Оснастка CBMC для проверки лестницы LOD (PLAN_ELEMENTS.md, §62; гейт CLAUDE.md
 * требует формального слоя на «разборщиках файлов сцены и всём, что ходит по
 * недоверенному входу»).
 *
 * ПОЧЕМУ ОСНАСТКА, А НЕ `cverify.sh src/lodio.c`. У CBMC нет тела ни для `fread`,
 * ни для `FILE*`, поэтому «CBMC на hz_lod_read» недостижимо как задача — по той же
 * причине, что и у разборщика OBJ (`tests/cbmc_sceneobj.c`). Чтение поэтому
 * разделено: `hz_lod_read` вытаскивает байты и зовёт `hz_lod_check`, а вся
 * ЦЕЛОЧИСЛЕННАЯ работа над недоверенными данными сидит в `hz_lod_check`. Здесь
 * недетерминированы именно её входы: уровни, родители и МЕТКИ.
 *
 * ЧТО ДОКАЗЫВАЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО.
 *
 *   1. `hz_lod_check` НЕ ВЫХОДИТ ЗА ПРЕДЕЛЫ САМА. Она индексирует `L->nd[id]` по
 *      метке из файла, то есть по величине, подконтрольной тому, кто файл
 *      подсунул. Проверка диапазона стоит ДО индексации — но «стоит» надо
 *      доказать, а не прочитать глазами.
 *
 *   2. ГЛАВНОЕ: `OK` ОЗНАЧАЕТ, ЧТО ПОТРЕБИТЕЛЮ ИНДЕКСИРОВАТЬ БЕЗОПАСНО. Срез
 *      (`hz_lod_cut`) и разметка (`hz_lod_seglist`) берут `L->nd[lab[...]]` без
 *      всяких проверок — они полагаются на то, что чтение уже проверило. Здесь это
 *      утверждение: при `HZ_LODIO_OK` каждая метка лежит в `[0, nnd)` И уровень
 *      узла равен номеру слоя. Если проверка когда-нибудь ослабнет, падёт ЭТО
 *      утверждение, а не картинка через неделю.
 *
 *   3. ВЛОЖЕННОСТЬ ПРИ `OK` ВЫПОЛНЕНА ПОТОЧЕЧНО: два полигона, лежащие в одном
 *      узле уровня `L`, лежат в одном узле уровня `L+1`. Это то самое свойство, из
 *      которого следует право брать срез, и проверяется оно перебором пар — то
 *      есть НЕ тем же способом, каким считается (там таблица «первый увиденный
 *      родитель»). Совпадение двух разных способов и есть доказательство.
 *
 * РАЗМЕР ЗАДАЧИ — ЛЕСТНИЦА КОМПИЛИРУЕМЫМИ КОНСТАНТАМИ, как в `cbmc_octree.c` и
 * `cbmc_sceneobj.c`: каждая ступень — отдельный дешёвый прогон.
 *
 * Запуск (ступени, выполненные в докладе О22):
 *   scripts/cverify.sh tests/cbmc_lodio.c --function harness --unwind 30 \
 *       -DHZ_NLEV=2 -DHZ_NP=2 -DHZ_NND=3 --drop-unused-functions
 */

/* NOLINTBEGIN */
#include "../src/lodio.c"
/* NOLINTEND */
#include <assert.h>

int32_t nondet_i32(void);

#ifndef __CPROVER
/* Чтобы гейт качества (gcc/clang-tidy/cppcheck) тоже разбирал этот файл; под
 * CBMC имя встроенное, и это объявление не компилируется. */
void __CPROVER_assume(int);
#endif

/* `nondet_i32` ОСТАЁТСЯ БЕЗ КОРПУСА СОЗНАТЕЛЬНО, и это не мелочь. Недетерминизм у
 * CBMC берётся именно из ОТСУТСТВИЯ тела; запасной корпус `return 0` (я его сперва
 * и написал, под `#ifndef __CPROVER`) сделал весь вход нулевым, и три прогона
 * отчитались «VERIFICATION SUCCESSFUL», доказав ПУСТОЕ: при всех уровнях, равных
 * нулю, второй слой не проходит проверку, ветка `ок` недостижима, и утверждения в
 * ней не выполняются ни на одном пути. Поймано негативным контролем достижимости
 * (`HZ_REACH`), а не глазами. Причина, почему запасной корпус вообще
 * скомпилировался: макрос `__CPROVER` этой сборкой CBMC НЕ определяется —
 * проверено опытом с `#error`. Поэтому в `tests/cbmc_sceneobj.c` корпуса и нет.
 * Гейт качества файл всё равно разбирает: он компилирует, но не линкует. */

#ifndef HZ_NLEV
#define HZ_NLEV 2
#endif
#ifndef HZ_NP
#define HZ_NP 2
#endif
#ifndef HZ_NND
#define HZ_NND 3
#endif

void harness(void);

void harness(void) {
  static hz_lodnode nd[HZ_NND];
  static int32_t lab[HZ_NLEV * HZ_NP];
  hz_lod L;
  memset(&L, 0, sizeof L);
  L.nlev = HZ_NLEV;
  L.np = HZ_NP;
  L.nnd = HZ_NND;
  /* Узлы и метки — НЕДЕТЕРМИНИРОВАННЫЕ, то есть «любой файл», а не придуманный
   * мной. Ограничения не ставятся вовсе: именно необузданный вход и есть
   * недоверенный. */
  for (int i = 0; i < HZ_NND; i++) {
    nd[i].level = nondet_i32();
    nd[i].parent = nondet_i32();
  }
  for (int i = 0; i < HZ_NLEV * HZ_NP; i++)
    lab[i] = nondet_i32();
  L.nd = nd;
  L.lab = lab;

  int rc = hz_lod_check(&L);
#ifdef HZ_REACH
  /* Опыт на ДОСТИЖИМОСТЬ: утверждение «ок не бывает». Провал значит, что ветка ок
   * достижима (и тогда доказательства не пусты); успех значит, что не достижима. */
  assert(rc != HZ_LODIO_OK);
#endif

  if (rc == HZ_LODIO_OK) {
#ifdef HZ_NEG
    /* НЕГАТИВНЫЙ КОНТРОЛЬ ФОРМАЛЬНОГО СЛОЯ. «VERIFICATION SUCCESSFUL» само по себе
     * не значит ничего: утверждения могли быть НЕДОСТИЖИМЫ, и тогда доказано
     * пустое. Здесь нарочно ложное утверждение — метка не может быть последним
     * узлом. Оно ОБЯЗАНО провалиться; если не провалилось, ветка `OK` не
     * достигается, и все успехи выше пусты. */
    assert(lab[0] != HZ_NND - 1);
#endif
    /* 2. МЕТКИ БЕЗОПАСНЫ ДЛЯ ИНДЕКСАЦИИ, УРОВЕНЬ СОВПАДАЕТ. */
    for (int lev = 0; lev < HZ_NLEV; lev++)
      for (int k = 0; k < HZ_NP; k++) {
        int32_t id = lab[lev * HZ_NP + k];
        assert(id >= 0 && id < HZ_NND);
        assert(nd[id].level == lev);
        int32_t par = nd[id].parent;
        assert(par == -1 || (par >= 0 && par < HZ_NND));
      }
    /* 3. ВЛОЖЕННОСТЬ — ПЕРЕБОРОМ ПАР, то есть НЕ тем способом, каким считалась. */
    for (int lev = 1; lev < HZ_NLEV; lev++)
      for (int a = 0; a < HZ_NP; a++)
        for (int b = 0; b < HZ_NP; b++)
          if (lab[(lev - 1) * HZ_NP + a] == lab[(lev - 1) * HZ_NP + b])
            assert(lab[lev * HZ_NP + a] == lab[lev * HZ_NP + b]);
  }
}
