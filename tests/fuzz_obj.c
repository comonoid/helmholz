/* fuzz_obj.c — фаззер НЕДОВЕРЕННОГО ВХОДА: разборщик OBJ (Ш2).
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ПРИБОР. У проекта четыре недоверенных входа (OBJ, PPM, HBLK,
 * KCAL-заголовок), и два дефекта там уже ловились руками: CWE-789 в kcalmk
 * (размер выделения из заголовка файла) и разошедшаяся сигнатура parse_fvert,
 * из-за которой CBMC-оснастка разборщика два месяца не компилировалась. CBMC
 * доказывает свойства В ГРАНИЦАХ раскрутки; фаззер подаёт произвольные байты и
 * ищет то, что не придёт в голову автору теста. Это ДОПОЛНЕНИЕ к формальному
 * слою, а не замена: находки у них разные.
 *
 * КОНТРАКТ ЦЕЛИ. hz_obj_parse берёт БУФЕР (не файл) и первым делом сам обнуляет
 * структуру — поэтому драйвер мал, а итерация дешёвая: файлового ввода нет.
 * objpath = NULL сознательно: тогда пропускается загрузка .mtl, которая
 * открывает файлы по именам ИЗ ДАННЫХ, то есть фаззила бы ещё и файловую
 * систему и зависела бы от окружения.
 *
 * hz_obj_free вызывается ВСЕГДА, включая неудачный разбор: иначе LeakSanitizer
 * утонет в «утечках» самого драйвера, и настоящая утечка разбора не будет видна.
 * Структуру обнуляем и здесь — чтобы free был безопасен на любом пути возврата.
 *
 * Запуск: make fuzz   (FUZZ_TIME=секунды на цель, по умолчанию 60)
 */
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "scene_obj.h"

/* Прототип — иначе gcc -Wmissing-prototypes считает определение сиротой */
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size);

/* Точку входа зовёт фреймворк libFuzzer, а не наш код — потому «не используется»;
 * пояснение отдельной строкой: cppcheck не терпит текст в самой директиве
 * (preprocessorErrorDirective — ловля гейта 07-10) */
/* cppcheck-suppress unusedFunction */
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
  /* Разборщик идёт до NUL-терминатора (шапка scene_obj.c), поэтому буфер
   * копируется и завершается: вход фаззера не терминирован. */
  char *buf = (char *)malloc(size + 1);
  if (buf == NULL) return 0;
  if (size > 0) memcpy(buf, data, size);
  buf[size] = '\0';

  hz_objmesh m;
  memset(&m, 0, sizeof m); /* безопасно, даже если разбор вернётся раньше memset'а */
  (void)hz_obj_parse(&m, buf, 1.0, NULL);
  hz_obj_free(&m);

  free(buf);
  return 0;
}
