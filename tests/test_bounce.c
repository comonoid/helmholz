/* test_bounce — НОРМИРОВКА ПЕРВОГО ОТСКОКА (О75, А537), ПРОВЕРЯЕМАЯ ДО СЦЕН.
 *
 * ЗАЧЕМ ЭТОТ СТЕНД СУЩЕСТВУЕТ ОТДЕЛЬНО. А537 (§281): «энергии в сегодняшнем
 * состоянии нет вовсе — фронт несёт ДОЛЮ, а доля безразмерна; нормировку
 * выписать ЯВНО и проверить на печи ДО всякой сцены, иначе предсказание
 * „десятки процентов добавки“ нечем отличить от промаха в 4π». Здесь и
 * выписано, и проверено — на случаях, у которых ответ известен ТОЧНО и не из
 * нашего кода.
 *
 * ЦЕПОЧКА НОРМИРОВКИ, ВЫПИСАННАЯ ЦЕЛИКОМ (это главный текст файла, а не тест):
 *
 *   1. ПРЯМОЙ ПРОХОД даёт долю открытого диска `f`. Облучённость поверхности
 *      с нормалью `n` от источника яркости `L_e`, занимающего телесный угол
 *      `Ω_s` вокруг направления `ω_s`:      E_dir = f · L_e · Ω_s · |ω_s·n|.
 *   2. ЛАМБЕРТОВО ПЕРЕИЗЛУЧЕНИЕ — единственное место, где появляется `π`:
 *                                            L_r = ρ · E / π.
 *      Проверяется законом сохранения: вышедший поток `M = ∫_{ω·n>0} L_r (ω·n) dω
 *      = π L_r = ρE`, то есть ушло ровно `ρ` от пришедшего.
 *   3. ПЕРЕНОС ЧЕРЕЗ ЯЧЕЙКУ. Пусть в ячейке геометрия площади `A_i` с нормалями
 *      `n_i`, а исходящая грань имеет проекционную площадь `A⊥`. Доля выходной
 *      грани, занятая проекцией геометрии, есть
 *                                            c = Σ A_i|n_i·ω| / A⊥,
 *      и это ТА ЖЕ ВЕЛИЧИНА, которую `pfront.c` уже считает как ПЕРЕКРЫТИЕ.
 *      Поток, вышедший из ячейки в телесный угол `dω`, есть
 *      `dΦ = L_r Σ A_i|n_i·ω| dω`, а яркость на выходной грани — `dΦ/(A⊥ dω)`.
 *      Отсюда правило переноса целиком:
 *                                            L_out = L_in·(1 − c) + L_r·c.
 *      **НИКАКИХ `π` И `4π` В САМОМ ПЕРЕНОСЕ НЕТ.** Они сидят только в шаге 2
 *      и в сборе (шаг 4). Это упрощение против плана §280, и оно существенно:
 *      эмиссия НЕ ТРЕБУЕТ новой геометрии — она пользуется уже вычисленным
 *      перекрытием, а сохранение энергии выходит по построению (при `L_r = L_in`
 *      правило тождественно, каково бы ни было `c`).
 *   4. СБОР У ПРИЁМНИКА:                     E = Σ_{ω·n<0} w_ω L(ω) |ω·n|,
 *      где `Σ w_ω = 4π`. Для постоянной яркости по полусфере это обязано дать
 *      `π L`, и вот эта единица — единственное, что связывает квадратуру с
 *      физикой.
 *
 * ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО (порознь, по образцу test_oven.c —
 * там смешанная проверка однажды уже сказала «перенос сломан» про угловую
 * ошибку):
 *   A. КВАДРАТУРА, БЕЗ ПЕРЕНОСА ВОВСЕ: `S(n) = Σ_{ω·n<0} w|ω·n| = π`. Чистое
 *      свойство набора направлений — и ЗАМЕР СРАЗУ ЖЕ ЕГО ПОПРАВИЛ: набор
 *      АНИЗОТРОПЕН. По оси `z` он точен до машинного нуля, по оси `x` при
 *      `ND = 128` ошибается на `2.1e-3`, а сходится лишь ПЕРВОГО порядка
 *      (наблюдаемый показатель `1.18…1.33`). Причина в устройстве набора:
 *      двойной Гаусс по `μ` берёт `∫|μ|dω` точно, но у наклонного приёмника
 *      излом подынтегральной функции идёт по ЕГО экватору, а узлы стоят по
 *      экватору набора. **Это и есть пол точности косвенного прохода, и печь
 *      усилит его в `1/(1−ρ)` раз** — при `ρ = 0.7` втрое. Знать это надо было
 *      ДО сцен, иначе «добавка десятки процентов» мерилась бы с необъявленной
 *      погрешностью, зависящей от ориентации стены.
 *   B. ПРАВИЛО ПЕРЕНОСА СОХРАНЯЕТ КОНСТАНТЫ: при `L_r = L_in` ответ равен
 *      `L_in` при ЛЮБОМ `c`, включая `0` и `1`. Это К6 («ограничитель обязан
 *      сохранять константы») и одновременно проверка, что энергия не рождается.
 *   C. БЕСКОНЕЧНАЯ ЛАМБЕРТОВА ПЛОСКОСТЬ: приёмник над плоскостью яркости `L_r`
 *      обязан получить `E = π L_r`, то есть РОВНО `ρ E_dir`. Это первый случай,
 *      где сходятся все четыре шага цепочки сразу.
 *   D. ПЕЧЬ: замкнутая полость с `L_e` и `ρ` даёт `L = L_e/(1−ρ)` ТОЧНО.
 *      Разрыв обязан совпасть с угловой ошибкой из A, усиленной рядом Неймана
 *      в `1/(1−ρ)` раз — если совпал, других источников ошибки нет.
 *
 * НЕГАТИВНЫЕ КОНТРОЛИ С ПРЕДСКАЗАННЫМ ПРОВАЛОМ:
 *   E. `ρ = 0` — косвенное обязано быть РОВНО ноль, побитово;
 *   F. веса сбиты на 1 % — печь обязана поехать, и ровно на процент, усиленный
 *      рядом Неймана;
 *   G. полость разорвана (часть направлений не приходит) — печь обязана уйти
 *      ВНИЗ. Без этого «баланс сошёлся» не значит ничего: он сойдётся и на
 *      неполном наборе (узор К13/К40/К94).
 */

#include "transport/dirs3.h"
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

static int failed = 0;

#define HZ_PI 3.14159265358979323846

/* ДОПУСК ОСЕВОГО СЛУЧАЯ. По оси квадратура точна: `∫|μ|dω` по полусфере есть
 * одномерный интеграл от многочлена первой степени, а двойной Гаусс берёт его
 * точно. Остаётся только округление, поэтому допуск — машинный, с запасом на
 * накопление по `n` слагаемым. */
#define TOL_AXIS 1e-13

/* РОВНО НОЛЬ, ЗАПИСАННЫЙ БЕЗ `==`. Гейт запрещает сравнение плавающих на
 * равенство (`-Wfloat-equal`), и он прав; но здесь проверяется именно точный
 * ноль — «косвенное при `ρ = 0` обязано быть нулём побитово», и ослаблять это
 * до допуска значит потерять весь смысл контроля. Двойное строгое неравенство
 * выражает то же самое и читается однозначно. */
static int is_zero(double x) {
  return !(x > 0.0) && !(x < 0.0);
}

static void ok(const char *what, int cond, double got, double want) {
  printf("  %-58s %s (получено %.12g, ожидалось %.12g)\n", what, cond ? "OK" : "ПРОВАЛ", got, want);
  if (!cond) failed = 1;
}

/* Сбор: облучённость от поля яркости, заданного функцией по направлению.
 * `n` — нормаль приёмника; берутся направления, ИДУЩИЕ К поверхности. */
static double gather(const tr3_dirs *d, const double *n, const double *L, double wscale) {
  double E = 0.0;
  for (int m = 0; m < d->n; m++) {
    double c = d->ox[m] * n[0] + d->oy[m] * n[1] + d->oz[m] * n[2];
    if (c < 0.0) E += d->w[m] * wscale * L[m] * (-c);
  }
  return E;
}

/* ПРАВИЛО ПЕРЕНОСА ЧЕРЕЗ ЯЧЕЙКУ — шаг 3 цепочки, одна строка. */
static double step_cell(double Lin, double Lr, double c) {
  return Lin * (1.0 - c) + Lr * c;
}

/* A. Квадратура: S(n) = π для любой нормали. */
static double quad_S(const tr3_dirs *d, const double *n) {
  double S = 0.0;
  for (int m = 0; m < d->n; m++) {
    double c = d->ox[m] * n[0] + d->oy[m] * n[1] + d->oz[m] * n[2];
    if (c < 0.0) S += d->w[m] * (-c);
  }
  return S;
}

int main(void) {
  printf("== test_bounce: НОРМИРОВКА ПЕРВОГО ОТСКОКА (А537), эталоны аналитические\n");

  tr3_dirs d;
  if (tr3_dirs_product(&d, 4, 4) != 0) {
    printf("отказ набора направлений\n");
    return 2;
  }
  double wsum = 0.0;
  for (int m = 0; m < d.n; m++)
    wsum += d.w[m];
  printf("-- набор: ND = %d, Σw = %.12g (обязано 4π = %.12g)\n", d.n, wsum, 4.0 * HZ_PI);

  /* --- A. КВАДРАТУРА ------------------------------------------------------ */
  printf("A. КВАДРАТУРА ПОЛУСФЕРЫ: S(n) = Σ_{ω·n<0} w|ω·n| = π\n");
  {
    /* НАБОР АНИЗОТРОПЕН, И ЭТО НЕ ДЕФЕКТ, А ЕГО УСТРОЙСТВО. По оси `z`
     * квадратура ТОЧНА: `∫|μ|dω` есть одномерный интеграл от многочлена первой
     * степени, и двойной Гаусс берёт его точно. По любой другой нормали
     * подынтегральная функция `|ω·n|` имеет излом по экватору ПРИЁМНИКА, а узлы
     * стоят по экватору ИСТОЧНИКА, и точности нет. Поэтому по `z` требуется
     * машинный ноль, а по остальным — СХОДИМОСТЬ, и она измеряется.
     *
     * ЭТО НАДО ЗНАТЬ ДО СЦЕН: точность косвенного прохода будет ЗАВИСЕТЬ ОТ
     * ОРИЕНТАЦИИ поверхности, и печь усилит эту ошибку в `1/(1−ρ)` раз. */
    double nz[3] = {0.0, 0.0, 1.0};
    double Sz = quad_S(&d, nz);
    ok("по оси z — ТОЧНО", fabs(Sz - HZ_PI) <= TOL_AXIS * HZ_PI, Sz, HZ_PI);
    static const double NRM[2][3] = {
        {1.0, 0.0, 0.0}, {0.577350269189625764, 0.577350269189625764, 0.577350269189625764}};
    static const char *NNM[2] = {"ось x", "(1,1,1)/√3"};
    for (int q = 0; q < 2; q++) {
      double prev = 1e300, first = 0.0, last = 0.0;
      int mono = 1, nfirst = 0, nlast = 0;
      printf("   %-12s — ошибка обязана УБЫВАТЬ с ND:\n", NNM[q]);
      for (int k = 1; k <= 4; k++) {
        tr3_dirs dk;
        if (tr3_dirs_product(&dk, 2 * k, 2 * k) != 0) continue;
        double S = quad_S(&dk, NRM[q]), e = fabs(S - HZ_PI) / HZ_PI;
        printf("     ND = %4d   S = %.9f   отн. ошибка %.3e\n", dk.n, S, e);
        if (e > prev) mono = 0;
        prev = e;
        if (k == 1) {
          first = e;
          nfirst = dk.n;
        }
        last = e;
        nlast = dk.n;
        tr3_dirs_free(&dk);
      }
      char msg[96];
      snprintf(msg, sizeof msg, "%s: ошибка убывает монотонно", NNM[q]);
      ok(msg, mono, mono ? 1.0 : 0.0, 1.0);
      /* Порядок сходимости — величина, а не впечатление. */
      double order = log(first / last) / log((double)nlast / (double)nfirst);
      printf("     наблюдаемый порядок по ND: %.2f (излом подынтегральной функции "
             "даёт около единицы)\n",
             order);
    }
  }

  /* --- B. ПРАВИЛО ПЕРЕНОСА СОХРАНЯЕТ КОНСТАНТЫ ---------------------------- */
  printf("B. ПЕРЕНОС СОХРАНЯЕТ КОНСТАНТЫ: L_r = L_in ⇒ L_out = L_in при любом c\n");
  {
    double worst = 0.0;
    for (int i = 0; i <= 64; i++) {
      double c = (double)i / 64.0;
      double L = 0.375;
      double e = fabs(step_cell(L, L, c) - L);
      if (e > worst) worst = e;
    }
    ok("наибольшее отклонение по 65 значениям c", is_zero(worst), worst, 0.0);
    /* И обратное: при `L_r = 0` и `c = 1` свет обязан ПОГАСНУТЬ полностью —
     * иначе стена прозрачна. */
    ok("глухая стена гасит: c = 1, L_r = 0", is_zero(step_cell(1.0, 0.0, 1.0)),
       step_cell(1.0, 0.0, 1.0), 0.0);
  }

  /* --- C. БЕСКОНЕЧНАЯ ЛАМБЕРТОВА ПЛОСКОСТЬ -------------------------------- */
  printf("C. ПЛОСКОСТЬ: приёмник над ламбертовой плоскостью получает E = π·L_r = ρ·E_dir\n");
  {
    const double rho = 0.5, Edir = 2.0;
    double Lr = rho * Edir / HZ_PI; /* шаг 2 цепочки */
    /* Марш по каждой ординате: пустые ячейки (c = 0), затем плоскость (c = 1).
     * Нижняя полусфера приёмника упирается в плоскость, верхняя уходит в пустоту. */
    double *L = calloc((size_t)d.n, sizeof *L);
    if (L == NULL) return 2;
    double nrec[3] = {0.0, 0.0, 1.0}; /* приёмник смотрит вверх, плоскость под ним */
    for (int m = 0; m < d.n; m++) {
      double Lm = 0.0; /* небо тёмное */
      if (d.oz[m] > 0.0) {
        /* направление идёт ВВЕРХ, то есть от плоскости к приёмнику */
        for (int cell = 0; cell < 5; cell++)
          Lm = step_cell(Lm, 0.0, 0.0); /* пустые ячейки не меняют яркость */
        Lm = step_cell(Lm, Lr, 1.0);    /* ячейка с плоскостью */
        for (int cell = 0; cell < 3; cell++)
          Lm = step_cell(Lm, 0.0, 0.0);
      }
      L[m] = Lm;
    }
    /* приёмник смотрит ВНИЗ, значит его нормаль (0,0,-1): свет идёт вверх */
    double ndown[3] = {0.0, 0.0, -1.0};
    (void)nrec;
    double E = gather(&d, ndown, L, 1.0);
    ok("E_ind = ρ·E_dir", fabs(E - rho * Edir) <= TOL_AXIS * rho * Edir, E, rho * Edir);
    /* E. НЕГАТИВНЫЙ КОНТРОЛЬ: ρ = 0 ⇒ РОВНО ноль, побитово. */
    for (int m = 0; m < d.n; m++)
      L[m] = (d.oz[m] > 0.0) ? step_cell(0.0, 0.0, 1.0) : 0.0;
    double E0 = gather(&d, ndown, L, 1.0);
    ok("E. ρ = 0 даёт РОВНО ноль", is_zero(E0), E0, 0.0);
    free(L);
  }

  /* --- D. ПЕЧЬ ------------------------------------------------------------ */
  printf("D. ПЕЧЬ: замкнутая полость, L = L_e/(1−ρ) ТОЧНО\n");
  {
    const double Le = 1.0, rho = 0.7;
    double Lref = Le / (1.0 - rho);
    /* Ряд Неймана по той же квадратуре: полость замкнута, значит с ЛЮБОГО
     * направления приходит яркость стенки. */
    double n[3] = {0.0, 0.0, 1.0};
    double S = quad_S(&d, n); /* обязано быть π; расхождение и есть угловая ошибка */
    double L = Le;
    for (int it = 0; it < 4096; it++) {
      double E = S * L;                   /* сбор со всей полусферы */
      double Lnew = Le + rho * E / HZ_PI; /* шаги 4 и 2 цепочки */
      if (fabs(Lnew - L) <= 1e-15 * fabs(Lnew)) {
        L = Lnew;
        break;
      }
      L = Lnew;
    }
    ok("неподвижная точка = L_e/(1−ρ)", fabs(L - Lref) <= 1e-12 * Lref, L, Lref);
    /* Проверка C старого образца: разрыв обязан быть угловой ошибкой,
     * усиленной рядом в 1/(1−ρ) раз. При точной квадратуре обе величины нули,
     * поэтому смысл имеет ОТНОШЕНИЕ, и оно проверяется на СБИТОЙ квадратуре. */
    printf("   F. НЕГАТИВНЫЙ КОНТРОЛЬ: веса сбиты на 1 %% — печь обязана поехать\n");
    double Sbad = S * 1.01;
    double Lb = Le;
    for (int it = 0; it < 4096; it++) {
      double Lnew = Le + rho * (Sbad * Lb) / HZ_PI;
      if (fabs(Lnew - Lb) <= 1e-15 * fabs(Lnew)) {
        Lb = Lnew;
        break;
      }
      Lb = Lnew;
    }
    double moved = fabs(Lb - Lref) / Lref;
    /* Предсказание ДО прогона: ошибка ε в квадратуре даёт в неподвижной точке
     * ρε/(1−ρ−ρε) ≈ 2.4 % при ρ = 0.7, ε = 1 %. */
    double want = rho * 0.01 / (1.0 - rho - rho * 0.01);
    ok("печь поехала на предсказанную величину", fabs(moved - want) <= 0.05 * want, moved, want);
    printf("   G. НЕГАТИВНЫЙ КОНТРОЛЬ: полость разорвана (полусфера открыта наружу)\n");
    double Sopen = 0.5 * S; /* половина направлений уходит в темноту */
    double Lo = Le;
    for (int it = 0; it < 4096; it++) {
      double Lnew = Le + rho * (Sopen * Lo) / HZ_PI;
      if (fabs(Lnew - Lo) <= 1e-15 * fabs(Lnew)) {
        Lo = Lnew;
        break;
      }
      Lo = Lnew;
    }
    ok("разорванная полость темнее замкнутой", Lo < Lref, Lo, Lref);
  }

  tr3_dirs_free(&d);
  printf(failed ? "== test_bounce: ПРОВАЛ\n" : "== test_bounce: ВСЁ СОШЛОСЬ\n");
  return failed;
}
