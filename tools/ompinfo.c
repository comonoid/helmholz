/* ompinfo — сколько потоков ВИДИТ программа, а не сколько их у машины.
 *
 * Часть стража `make check-simd`. Заведено отдельным файлом, а не строкой в
 * Makefile, ровно по правилу проекта: величина, которую докладывают, должна
 * быть получена кодом, который можно прочесть.
 *
 * Печатается ТРИ разных числа, и они не совпадают по построению:
 *   omp_get_num_procs      — сколько процессоров видит рантайм OpenMP;
 *   omp_get_max_threads    — сколько потоков заведёт `#pragma omp parallel`
 *                            (это `OMP_NUM_THREADS`, если задано);
 *   фактическое            — сколько их оказалось ВНУТРИ параллельной области.
 * Третье и есть ответ на вопрос «а точно ли считается на всех потоках»:
 * первые два — намерение, третье — факт.
 */

/* Сборка БЕЗ `-fopenmp` законна и обязана печатать это прямо, а не падать:
 * гейт качества (`scripts/ccheck.sh`) компилирует файлы своим набором флагов, и
 * страж, который не собирается под гейтом, — плохой страж. */
#include <stdio.h>
#ifdef _OPENMP
#include <omp.h>
#endif

int main(void) {
#ifdef _OPENMP
  int nfact = 0;
#pragma omp parallel
  {
#pragma omp master
    nfact = omp_get_num_threads();
  }
  printf("   OpenMP: процессоров %d, максимум потоков %d, ФАКТИЧЕСКИ в области %d\n",
         omp_get_num_procs(), omp_get_max_threads(), nfact);
#else
  printf("   OpenMP ВЫКЛЮЧЕН при сборке (-fopenmp не задан): счёт однопоточный\n");
#endif
  return 0;
}
