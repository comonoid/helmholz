/* pfront — НАСЫЩАЕТСЯ ЛИ СЛОЖНОСТЬ ФРОНТА ПРИ ХОДЕ.
 *
 * PLAN_ELEMENTS.md, шаг О55. Исполняемый текст плана — §172 (он сводит §166
 * после правок §168/§169/§171 и читается ВМЕСТО §166). Здесь — только код.
 *
 * ВОПРОС ОДНОЙ СТРОКОЙ. Собирающая формулировка платит за видимость У КАЖДОГО
 * приёмника (~300 членов, §155). Фронт обязан построить разрывы ОДИН раз и
 * везти их с собой. Всё держится на одном непроверенном условии: НАСЫЩАЕТСЯ ЛИ
 * ЧИСЛО ЖИВЫХ РАЗРЫВОВ по мере хода фронта, или растёт как `d²`.
 *
 * ОПРЕДЕЛЕНИЕ, ЗАФИКСИРОВАННОЕ ДО КОДА (А377). Живой разрыв = хорда контура,
 * порождённая пересечённым силуэтом и ещё не убитая слиянием или вкладом.
 * Сложность фронта = число живых хорд в оболочке. Без этого определения после
 * прогона сложностью можно назвать что угодно.
 *
 * ИСТОЧНИКОВ ДВА, И ВТОРОЙ ОБЯЗАТЕЛЕН (А383).
 *   СОЛНЦЕ — контроль МЕХАНИКИ счёта. Угловой размер солнца мал, всякий заслон
 *     крупнее полутени даёт тень ПОЛНОГО контраста, и порог по вкладу `η` там
 *     обязан дать РОВНО ноль смертей. Если гасит — считает не то, что названо.
 *   ПРОТЯЖЁННЫЙ (освещённая стена квартала) — там `η` и меряется, и ради него
 *     шаг относится к подцели: каждый разрыв кроит малую долю широкого
 *     источника, и модуляция мала по построению.
 *
 * ОБА ИСТОЧНИКА — ПРЯМОУГОЛЬНИКИ, И ЭТО СДЕЛАНО РАДИ ОДНОГО КОДА. Солнце есть
 * прямоугольник на расстоянии `PF_SUN_R` с угловым размером `PF_SUN_DEG`
 * (физическая величина, не порог: видимый диаметр Солнца `0.533°`). Тогда
 * «доля источника, закрываемая разрывом» считается ОДНОЙ формулой для обоих, и
 * предсказание П5 (ноль смертей на солнце) становится ВЫЧИСЛЕННЫМ результатом,
 * а не особым случаем в коде. Иначе НК2 был бы пустым.
 *
 * ЧТО СЧИТАЕТСЯ В ОБОЛОЧКЕ `[2^k, 2^{k+1})`:
 *   РОЖДЕНИЯ — силуэтные рёбра, чья середина легла в оболочку. Для СОЛНЦА
 *     силуэт определён по НАПРАВЛЕНИЮ (знак `n·ω` у двух смежных граней) и
 *     строится ОДНИМ проходом на всю сцену (А389), дальше только
 *     раскладывается по оболочкам. Для протяжённого — относительно ЦЕНТРА
 *     источника, и отдельным числом печатается, сколько рёбер меняют знак ПО
 *     ИСТОЧНИКУ: это и есть полутень.
 *   СМЕРТИ ПО ПОЛУТЕНИ — хорды, сошедшиеся ближе полутени. Полутень у хорды
 *     СВОЯ: `α·(d − d_рожд)`, то есть ноль в момент рождения и растёт с
 *     пройденным путём. Брать `α·d` было бы завышением и убивало бы больше, чем
 *     надо, — ошибка в сторону, ВЫГОДНУЮ гипотезе, и потому запрещена.
 *   СМЕРТИ ПО ВКЛАДУ — доля источника, закрываемая разрывом, ниже `η`. Доля
 *     считается ЗАМКНУТО: прямоугольник источника режется полуплоскостью через
 *     точку фронта и хорду, обе части — контурным форм-фактором `src/pff.h`
 *     (самопроверка `1.110e-16`, §151). Приближения «источник как точка» нет
 *     (А391): на близких оболочках оно завышало бы вклад в разы.
 *   ЖИВЫЕ — остаток. Баланс `живые(k) = живые(k−1) + рождения − смерти` есть
 *     ТОЖДЕСТВО (А378), его невязка печатается и обязана быть нулевой.
 *
 * СЕТКА ДЛЯ СМЕРТЕЙ — СВОЯ НА КАЖДУЮ ОБОЛОЧКУ (А388). Попарный перебор в лоб
 * даёт `5e7` пар на оболочку и `4e8` на восемь, то есть дороже собирающей
 * схемы, которую шаг и оценивает. Пары ищутся ТОЛЬКО ВНУТРИ ячейки размера
 * `α·d`, как предписано планом. Известная цена этого — пара, разошедшаяся по
 * соседним ячейкам, не находится; значит смертей считается МЕНЬШЕ настоящего,
 * и ошибка снова идёт против гипотезы.
 *
 * СЧЁТЧИКИ ОПЕРАЦИЙ ОБЯЗАТЕЛЬНЫ (А384). А349, А352, А361 трижды ловили класс
 * «выход мал ≠ искать дёшево». Печатаются: опрошено рёбер, проверено пар,
 * посчитано форм-факторов — и всё это НА ЭЛЕМЕНТ СЦЕНЫ рядом со сложностью.
 *
 * ЛОЖНАЯ ПОЛКА (А381). Габарит города `858` м; фронт «насытится» просто оттого,
 * что дальше нечего пересекать. Поэтому рядом с рождениями печатается ПЛОЩАДЬ
 * ПОВЕРХНОСТИ в оболочке, и полка засчитывается только там, где она не падает.
 *
 * КАРТИНКА И ЭТАЛОН (А385/А393). Марш фронта от солнца ЕСТЬ вычисление прямой
 * тени. Тень строится РАЗРЫВАМИ: силуэтные рёбра, спроецированные на плоскость
 * поперёк лучей, образуют границу теневого объёма, и точка в тени тогда и
 * только тогда, когда её число обходов по рёбрам ВЫШЕ ПО ФРОНТУ не ноль
 * (классический теневой объём Кроу, записанный как марш по глубине). Эталон —
 * лучи по треугольникам той же сеткой `src/pgrid.h`. Метрика — доля
 * НЕСОВПАВШИХ по бинарному «в тени/на свету»; яркость НЕ сравнивается, её у
 * фронта пока нет.
 *
 * ЧЕГО ШАГ НЕ ОТВЕТИТ, названо заранее: цены для ТОЧЕЧНОГО источника внутри
 * сцены (у солнца фронт плоский — самый лёгкий случай, А382: отрицательный
 * ответ переносится на тяжёлые, положительный нет); многократных отражений;
 * динамической геометрии.
 *
 * Запуск: `pfront [city|hall] [sun|wall|both] [nopic] [rows=ЧИСЛО]`.
 */
