typedef struct {
  double e0[3], e1[3]; /* концы силуэтного ребра в мире */
  double u[3];         /* направление хода фронта из источника, единичное */
  double zc[3];        /* точка на ЗАСЛОНЯЮЩЕЙ грани — ею выбирается закрытая сторона */
  double db;           /* расстояние от источника, где хорда родилась */
  int32_t shell;       /* оболочка рождения */
} pf_chord;

/* ---- ХЕШ-СЕТКА СЛИЯНИЯ ---------------------------------------------------
 * Ключ — целочисленная ячейка размера `α·d` (наибольшая возможная полутень в
 * оболочке). Таблица открытой адресации, цепочки — массивом `next`. Своя на
 * каждую оболочку: шаг ячейки растёт вместе с оболочкой (А388). */
static uint64_t cell_hash(int64_t x, int64_t y, int64_t z) {
  uint64_t h = 1469598103934665603ULL;
  uint64_t v[3] = {(uint64_t)x, (uint64_t)y, (uint64_t)z};
  for (int i = 0; i < 3; i++) {
    h ^= v[i];
    h *= 1099511628211ULL;
  }
  return h;
}

int main(int argc, char **argv) {
  int city = 1, do_sun = 1, do_wall = 1, do_pic = 1, rows = PF_ROWS, f32 = 0;
  double quant = 0.0;
  for (int i = 1; i < argc; i++) {
    if (strcmp(argv[i], "hall") == 0) city = 0;
    if (strcmp(argv[i], "city") == 0) city = 1;
    if (strcmp(argv[i], "sun") == 0) {
      do_sun = 1;
      do_wall = 0;
    }
    if (strcmp(argv[i], "wall") == 0) {
      do_sun = 0;
      do_wall = 1;
    }
    if (strcmp(argv[i], "both") == 0) {
      do_sun = 1;
      do_wall = 1;
    }
    if (strcmp(argv[i], "nopic") == 0) do_pic = 0;
    if (strncmp(argv[i], "rows=", 5) == 0) rows = (int)strtol(argv[i] + 5, NULL, 10);
    /* СКОЛЬКО РАЗРЯДОВ НУЖНО ГЕОМЕТРИИ — вопрос замеряемый, а не обсуждаемый.
     * `f32` округляет вершины до одинарной точности, `quant=X` — до сетки с
     * шагом `X` метров (то есть к целым числам с этим квантом). Всё остальное
     * считается как считалось; если ответ не меняется, разрядность лишняя. */
    if (strcmp(argv[i], "f32") == 0) f32 = 1;
    if (strncmp(argv[i], "quant=", 6) == 0) quant = strtod(argv[i] + 6, NULL);
  }
  if (rows < 16) rows = 16;

  /* САМОПРОВЕРКА ФОРМ-ФАКТОРА — ПЕРВОЙ, ДО ВСЯКОЙ СЦЕНЫ (А205). Порог `η`
   * сравнивается с величиной, которую даёт эта формула; ошибка в `2π` или в
   * знаке обхода пришла бы потом правдоподобным числом смертей, и отличить её
   * было бы нечем. Допуск `1e-9` — запас на округление double, фактическая
   * невязка на семь порядков меньше. */
  {
    double fb = 0.0, fu = 0.0, ru = 0.0;
    double worst = hz_pff_selftest(&fb, &fu, &ru);
    printf("== САМОПРОВЕРКА ФОРМ-ФАКТОРА: огромный квадрат %.15f; квадрат a=h %.15f против "
           "эталона %.15f; худшая невязка %.3e\n",
           fb, fu, ru, worst);
    if (!(worst < 1e-9)) {
      fprintf(stderr, "аналитика не сходится — дальше идти нельзя\n");
      return 1;
    }
  }

  double t_start = now_s();
  hz_objmesh m;
  if (hz_obj_load(&m, city ? HZ_CFG_CITY_OBJ : HZ_CFG_HALL_OBJ,
                  city ? HZ_CFG_CITY_SCALE : HZ_CFG_HALL_SCALE) != 0) {
    fprintf(stderr, "нет сцены\n");
    return 1;
  }
  double t_load = now_s() - t_start;

  /* ОГРУБЛЕНИЕ ВЕРШИН — ЗАМЕР ТРЕБОВАНИЯ К РАЗРЯДНОСТИ, а не режим работы.
   * Округление делается ОДИН раз, сразу после чтения, и дальше весь счёт идёт
   * прежним `double`: так изолируется вопрос ПРЕДСТАВЛЕНИЯ (сколько разрядов
   * нужно координате) от вопроса НАКОПЛЕНИЯ (сколько нужно сумме). Это разные
   * вопросы, и мерить их одним прогоном значило бы не измерить ни одного.
   * Габарит и коробка пересчитываются, иначе они остались бы от неокруглённых. */
  if (f32 || quant > 0.0) {
    for (int32_t i = 0; i < 3 * m.nv; i++) {
      if (quant > 0.0)
        m.v[i] = quant * floor(m.v[i] / quant + 0.5);
      else
        m.v[i] = (double)(float)m.v[i];
    }
    for (int a = 0; a < 3; a++) {
      m.lo[a] = 1e300;
      m.hi[a] = -1e300;
    }
    for (int32_t i = 0; i < m.nv; i++)
      for (int a = 0; a < 3; a++) {
        double c = m.v[3 * (size_t)i + (size_t)a];
        if (c < m.lo[a]) m.lo[a] = c;
        if (c > m.hi[a]) m.hi[a] = c;
      }
    if (quant > 0.0)
      printf("== ВЕРШИНЫ ОКРУГЛЕНЫ ДО СЕТКИ %.3g м (целые числа с этим квантом; на габарите "
             "%.0f м это %.1f разрядов)\n",
             quant, 655.0, log2(655.0 / quant));
    else
      printf("== ВЕРШИНЫ ОКРУГЛЕНЫ ДО ОДИНАРНОЙ ТОЧНОСТИ (float, 24 разряда мантиссы; на "
             "габарите 655 м это шаг %.2e м)\n",
             655.0 * 6.0e-8);
  }
  double ext[3], diag = 0.0;
  for (int a = 0; a < 3; a++) {
    ext[a] = m.hi[a] - m.lo[a];
    diag += ext[a] * ext[a];
  }
  diag = sqrt(diag);
  printf("== СЦЕНА: %s, треугольников %d, вершин %d, загрузка %.1f с\n",
         city ? HZ_CFG_CITY_OBJ : HZ_CFG_HALL_OBJ, m.nt, m.nv, t_load);
  printf("== ГАБАРИТ: %.2f x %.2f x %.2f м, диагональ %.2f м; оболочки k = %d…%d\n", ext[0], ext[1],
         ext[2], diag, PF_KMIN, PF_KMIN + PF_NSHELL - 1);
  fflush(stdout);

  /* ---- ХОЛОДНАЯ СБОРКА: СМЕЖНОСТЬ, ПЛОСКОСТИ, СЕТКА (А387) --------------
   * Время холодной сборки докладывается ОТДЕЛЬНО от кадра: связи привязаны к
   * СЦЕНЕ, и у статической геометрии строятся один раз. Сваливать их в кадр —
   * ровно та ошибка, которую §164 сделала с `3.91e8`. */
  double t_cold0 = now_s();
  hz_padj adj;
  if (hz_padj_build(&adj, &m) != 0) {
    fprintf(stderr, "нет памяти под смежность\n");
    return 2;
  }
  printf("== СМЕЖНОСТЬ: рёбер %lld; граничных %lld (%.2f %%), манифолдных %lld (%.2f %%), "
         "неманифолдных %lld (%.2f %%)\n",
         (long long)adj.ne, (long long)adj.nb1, 100.0 * (double)adj.nb1 / (double)adj.ne,
         (long long)adj.nb2, 100.0 * (double)adj.nb2 / (double)adj.ne, (long long)adj.nbm,
         100.0 * (double)adj.nbm / (double)adj.ne);
  printf("   СИЛУЭТ ОПРЕДЕЛЁН ТОЛЬКО НА МАНИФОЛДНЫХ. Граничные и неманифолдные тень кроят, но "
         "знака у них нет — это ИЗВЕСТНАЯ дыра метода, и она обязана быть видна в картинке.\n");
  fflush(stdout);

  /* Нормали граней (НЕ нормированные — нужен только знак) и площади. */
  double *fn = malloc((size_t)m.nt * 3 * sizeof *fn);
  double *fa = malloc((size_t)m.nt * sizeof *fa);
  double *fc = malloc((size_t)m.nt * 3 * sizeof *fc);
  if (fn == NULL || fa == NULL || fc == NULL) {
    fprintf(stderr, "нет памяти под грани\n");
    return 2;
  }
#pragma omp parallel for schedule(static)
  for (int32_t t = 0; t < m.nt; t++) {
    const double *p0 = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 0];
    const double *p1 = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 1];
    const double *p2 = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 2];
    double a[3], b[3], c[3];
    v_sub(p1, p0, a);
    v_sub(p2, p0, b);
    v_cross(a, b, c);
    for (int i = 0; i < 3; i++) {
      fn[3 * (size_t)t + (size_t)i] = c[i];
      fc[3 * (size_t)t + (size_t)i] = (p0[i] + p1[i] + p2[i]) / 3.0;
    }
    fa[t] = 0.5 * sqrt(v_dot(c, c));
  }

  hz_pgrid grid;
  memset(&grid, 0, sizeof grid);
  if (hz_pgrid_build(&grid, &m) != 0) {
    fprintf(stderr, "нет памяти под сетку\n");
    return 2;
  }
  double t_cold = now_s() - t_cold0;
  printf("== ХОЛОДНАЯ СБОРКА %.1f с: сетка ячейка %.3f м, %d x %d x %d, ссылок %lld\n", t_cold,
         grid.cs, grid.nc[0], grid.nc[1], grid.nc[2], (long long)grid.nref);
  fflush(stdout);

  /* УРОВЕНЬ ЗЕМЛИ — ЗАМЕРЕН, А НЕ НАЗНАЧЕН: медиана высот вершин. Стена
   * квартала ставится на него; ноль сюда поставить нельзя, у города земля
   * `≈ 4` м (§110), и стена ушла бы под грунт. */
  double ground;
  {
    int32_t step = m.nv > 200000 ? m.nv / 200000 : 1;
    int32_t n = 0;
    double *ys = malloc((size_t)(m.nv / step + 2) * sizeof *ys);
    if (ys == NULL) return 2;
    for (int32_t i = 0; i < m.nv; i += step)
      ys[n++] = m.v[3 * (size_t)i + 1];
    qsort(ys, (size_t)n, sizeof *ys, cmp_dbl);
    ground = ys[n / 2];
    free(ys);
  }
  printf("== УРОВЕНЬ ЗЕМЛИ (медиана высот вершин): %.2f м\n", ground);

  /* ---- ОПИСАНИЕ ИСТОЧНИКОВ ---------------------------------------------- */
  pf_src srcs[2];
  int nsrc = 0;
  double seu[2][3], sev[2][3], shu[2], shv[2];
  double sun_d0 = 0.0; /* плоскость входа для солнца */

  if (do_sun) {
    pf_src *S = &srcs[nsrc];
    S->directional = 1;
    S->le = PF_SRC_LE;
    S->name = "СОЛНЦЕ (направленный)";
    double w[3] = HZ_CFG_SUN_DIR;
    v_norm(w);
    for (int i = 0; i < 3; i++)
      S->w[i] = w[i];
    double ctr[3];
    for (int i = 0; i < 3; i++)
      ctr[i] = 0.5 * (m.lo[i] + m.hi[i]);
    for (int i = 0; i < 3; i++)
      S->c[i] = ctr[i] - PF_SUN_R * w[i];
    /* Рама источника: любая ортонормированная пара поперёк `w`. */
    double a[3] = {0.0, 0.0, 0.0}, b[3];
    int ax = (fabs(w[0]) < fabs(w[1])) ? ((fabs(w[0]) < fabs(w[2])) ? 0 : 2)
                                       : ((fabs(w[1]) < fabs(w[2])) ? 1 : 2);
    a[ax] = 1.0;
    double tmp[3];
    v_cross(w, a, tmp);
    v_norm(tmp);
    v_cross(w, tmp, b);
    v_norm(b);
    double h = PF_SUN_R * tan(0.5 * PF_SUN_DEG * M_PI / 180.0);
    /* Обход против часовой в раме `(tmp, b)`, у которой `tmp × b = ±w`; знак
     * итога снимается в `src_irr` (отрицательный форм-фактор есть «отвёрнут»),
     * поэтому порядок берётся тот, что даёт положительное значение. */
    double sgn[4][2] = {{-1, -1}, {1, -1}, {1, 1}, {-1, 1}};
    for (int k = 0; k < 4; k++)
      for (int i = 0; i < 3; i++)
        S->P[3 * k + i] = S->c[i] + sgn[k][0] * h * tmp[i] + sgn[k][1] * h * b[i];
    for (int i = 0; i < 3; i++) {
      seu[nsrc][i] = tmp[i];
      sev[nsrc][i] = b[i];
    }
    shu[nsrc] = h;
    shv[nsrc] = h;
    /* Плоскость входа: самый верхний по лучам угол габарита. */
    sun_d0 = 1e300;
    for (int c8 = 0; c8 < 8; c8++) {
      double q[3] = {(c8 & 1) ? m.hi[0] : m.lo[0], (c8 & 2) ? m.hi[1] : m.lo[1],
                     (c8 & 4) ? m.hi[2] : m.lo[2]};
      double s = v_dot(w, q);
      if (s < sun_d0) sun_d0 = s;
    }
    printf("== ИСТОЧНИК 1: %s, ω = (%.4f, %.4f, %.4f), угловой диаметр %.3f°, "
           "плоскость входа ω·x = %.2f\n",
           S->name, w[0], w[1], w[2], PF_SUN_DEG, sun_d0);
    nsrc++;
  }

  if (do_wall) {
    pf_src *S = &srcs[nsrc];
    S->directional = 0;
    S->le = PF_SRC_LE;
    S->name = "СТЕНА КВАРТАЛА (протяжённый)";
    S->c[0] = m.lo[0];
    S->c[1] = ground + 0.5 * PF_WALL_H;
    S->c[2] = 0.5 * (m.lo[2] + m.hi[2]);
    for (int i = 0; i < 3; i++)
      S->w[i] = 0.0;
    S->w[0] = 1.0; /* смотрит внутрь сцены */
    /* ПОРЯДОК ОБХОДА ЗНАЧИМ: контурный форм-фактор ждёт `eu × ev = нормаль
     * излучателя` (`pff.h`), а нормаль здесь `+x`. Пара `(0,0,1) × (0,1,0)`
     * даёт `−x` и обнуляет облучённость целиком — на этом стенд уже сбился
     * один раз, и потому ниже стоит самопроверка каждого источника. */
    double eu[3] = {0.0, 0.0, 1.0}, ev[3] = {0.0, -1.0, 0.0};
    double hu = 0.5 * PF_WALL_W, hv = 0.5 * PF_WALL_H;
    double sgn[4][2] = {{-1, -1}, {1, -1}, {1, 1}, {-1, 1}};
    for (int k = 0; k < 4; k++)
      for (int i = 0; i < 3; i++)
        S->P[3 * k + i] = S->c[i] + sgn[k][0] * hu * eu[i] + sgn[k][1] * hv * ev[i];
    for (int i = 0; i < 3; i++) {
      seu[nsrc][i] = eu[i];
      sev[nsrc][i] = ev[i];
    }
    shu[nsrc] = hu;
    shv[nsrc] = hv;
    printf("== ИСТОЧНИК %d: %s, центр (%.2f, %.2f, %.2f), %.0f x %.0f м, нормаль +x\n", nsrc + 1,
           S->name, S->c[0], S->c[1], S->c[2], PF_WALL_W, PF_WALL_H);
    nsrc++;
  }

  /* САМОПРОВЕРКА КАЖДОГО ИСТОЧНИКА НА АНАЛИТИКЕ — ДО МАРША.
   *
   * Заведена не «на всякий случай»: порядок обхода углов у стены был выбран
   * неверно, `eu × ev` смотрел ПРОТИВ нормали, форм-фактор выходил
   * отрицательным и обнулялся, и весь порог по вкладу молча становился
   * недействующим — ноль смертей при любом `η`, то есть таблица, которую
   * невозможно отличить от «механизм не гасит». Ошибка сценой не ловится, и
   * ловить её обязана аналитика.
   *
   * Проба ставится НА ОСИ источника на расстоянии, где источник заведомо мал:
   * `r = 100·max(hu, hv)`. Там точный форм-фактор обязан сойтись с дальним
   * пределом `A/(π r²)` — у прямоугольника это верно с точностью `(размер/r)²`,
   * то есть `1e-4`. Допуск `1e-3` — запас на эту самую поправку, а не на
   * численность. */
  for (int si = 0; si < nsrc; si++) {
    const pf_src *S = &srcs[si];
    double hmax = shu[si] > shv[si] ? shu[si] : shv[si];
    double r = 100.0 * hmax;
    double nrm[3];
    v_cross(seu[si], sev[si], nrm);
    v_norm(nrm);
    double p[3], nr[3];
    for (int i = 0; i < 3; i++) {
      p[i] = S->c[i] + r * nrm[i];
      nr[i] = -nrm[i];
    }
    double f = src_irr(S, p, nr, NULL, NULL);
    double ref = 4.0 * shu[si] * shv[si] / (M_PI * r * r) * S->le;
    double rel = fabs(f - ref) / (ref > 0.0 ? ref : 1.0);
    printf("== САМОПРОВЕРКА ИСТОЧНИКА %d: на оси при r = %.3g м получено %.6e, дальний предел "
           "A/(πr²) = %.6e, расхождение %.2e\n",
           si + 1, r, f, ref, rel);
    if (!(f > 0.0) || !(rel < 1.0e-3)) {
      fprintf(stderr, "источник %d считает не то (обход углов или нормаль) — дальше идти нельзя\n",
              si + 1);
      return 1;
    }
  }
  fflush(stdout);

  /* ================= МАРШ ФРОНТА ПО КАЖДОМУ ИСТОЧНИКУ ==================== */
  /* Тайминги для РАЗДЕЛЬНОГО доклада в конце (§172, пункт 8). */
  double t_sil_src[2] = {0.0, 0.0}, t_lead_src[2] = {0.0, 0.0};
  double t_pic_prim = 0.0, t_pic_ref = 0.0, t_pic_front = -1.0;
  double *shell_area = malloc((size_t)PF_NSHELL * sizeof *shell_area);
  int64_t *births = malloc((size_t)PF_NSHELL * sizeof *births);
  if (shell_area == NULL || births == NULL) return 2;

  pf_chord *ch = NULL;
  int64_t ch_cap = 0;

  for (int si = 0; si < nsrc; si++) {
    const pf_src *S = &srcs[si];
    printf("\n================================================================\n");
    printf("=== ИСТОЧНИК: %s\n", S->name);
    printf("================================================================\n");

    /* ---- ПЛОЩАДЬ ПОВЕРХНОСТИ ПО ОБОЛОЧКАМ (А381) ------------------------ */
    for (int k = 0; k < PF_NSHELL; k++)
      shell_area[k] = 0.0;
    for (int32_t t = 0; t < m.nt; t++) {
      double d;
      if (S->directional)
        d = v_dot(S->w, fc + 3 * (size_t)t) - sun_d0;
      else
        d = src_dist(S, fc + 3 * (size_t)t, seu[si], sev[si], shu[si], shv[si]);
      int k = (d < 1.0) ? 0 : (int)floor(log2(d)) - PF_KMIN;
      if (k < 0) k = 0;
      if (k >= PF_NSHELL) k = PF_NSHELL - 1;
      shell_area[k] += fa[t];
    }

    /* ---- РОЖДЕНИЯ: СИЛУЭТ ОДНИМ ПРОХОДОМ ПО ВСЕЙ СЦЕНЕ (А389) ------------
     * Для НАПРАВЛЕННОГО источника силуэт не зависит ни от расстояния, ни от
     * оболочки — знак `n·ω` у двух смежных граней; строится один раз и дальше
     * только раскладывается по оболочкам. Для ПРОТЯЖЁННОГО силуэт зависит от
     * точки источника, поэтому берётся относительно ЦЕНТРА, а число рёбер,
     * меняющих знак ПО источнику, печатается отдельно: это полутень. */
    double t_sil0 = now_s();
    int64_t op_edges = adj.ne; /* СЧЁТЧИК (А384): опрошено рёбер */
    int64_t nsil = 0, npen = 0, nskip_par = 0;
    for (int k = 0; k < PF_NSHELL; k++)
      births[k] = 0;

    if (adj.ne > ch_cap) {
      free(ch);
      ch = malloc((size_t)adj.ne * sizeof *ch);
      if (ch == NULL) {
        fprintf(stderr, "нет памяти под хорды\n");
        return 2;
      }
      ch_cap = adj.ne;
    }

    for (int64_t e = 0; e < adj.ne; e++) {
      if (adj.enf[e] != 2) continue; /* силуэт определён только на манифолдных */
      int32_t f0 = adj.ef[e * HZ_PADJ_MAXF], f1 = adj.ef[e * HZ_PADJ_MAXF + 1];
      const double *p0 = m.v + 3 * (size_t)adj.ea[e];
      const double *p1 = m.v + 3 * (size_t)adj.eb[e];
      double mid[3];
      for (int i = 0; i < 3; i++)
        mid[i] = 0.5 * (p0[i] + p1[i]);

      /* Направление НА источник (от него к ребру) и расстояние оболочки. */
      double u[3], d;
      if (S->directional) {
        for (int i = 0; i < 3; i++)
          u[i] = S->w[i];
        d = v_dot(S->w, mid) - sun_d0;
      } else {
        v_sub(mid, S->c, u);
        if (v_norm(u) <= 0.0) continue;
        d = src_dist(S, mid, seu[si], sev[si], shu[si], shv[si]);
      }
      if (!(d > 0.0)) d = 0.0;

      double s0 = v_dot(fn + 3 * (size_t)f0, u);
      double s1 = v_dot(fn + 3 * (size_t)f1, u);
      if (fabs(s0) < PF_PAR_TINY || fabs(s1) < PF_PAR_TINY) {
        nskip_par++;
        continue;
      }
      if ((s0 < 0.0) == (s1 < 0.0)) continue; /* обе лицевые либо обе изнаночные */

      /* ПОЛУТЕНЬ: меняется ли классификация ПО ИСТОЧНИКУ (А389). Проверяется
       * по четырём углам прямоугольника — у выпуклого источника этого хватает,
       * потому что `n·(mid − q)` линейна по `q`. */
      if (!S->directional) {
        int flip = 0;
        for (int q = 0; q < 4 && !flip; q++) {
          double uq[3];
          v_sub(mid, S->P + 3 * (size_t)q, uq);
          double a0 = v_dot(fn + 3 * (size_t)f0, uq);
          double a1 = v_dot(fn + 3 * (size_t)f1, uq);
          if (fabs(a0) < PF_PAR_TINY || fabs(a1) < PF_PAR_TINY) continue;
          if (((a0 < 0.0) == (a1 < 0.0)) != ((s0 < 0.0) == (s1 < 0.0))) flip = 1;
        }
        if (flip) npen++;
      }

      /* ЗАСЛОНЯЮЩАЯ ГРАНЬ — та, что повёрнута К источнику: `n·u < 0`, где `u`
       * направлено ОТ источника. Ею выбирается закрытая сторона при счёте
       * вклада; без неё «доля источника» была бы взята не с той стороны. */
      int32_t fo = (s0 < 0.0) ? f0 : f1;

      pf_chord *C = &ch[nsil];
      for (int i = 0; i < 3; i++) {
        C->e0[i] = p0[i];
        C->e1[i] = p1[i];
        C->u[i] = u[i];
        C->zc[i] = fc[3 * (size_t)fo + (size_t)i];
      }
      C->db = d;
      int k = (d < 1.0) ? 0 : (int)floor(log2(d)) - PF_KMIN;
      if (k < 0) k = 0;
      if (k >= PF_NSHELL) k = PF_NSHELL - 1;
      C->shell = k;
      births[k]++;
      nsil++;
    }
    double t_sil = now_s() - t_sil0;
    t_sil_src[si] = t_sil;
    printf("== СИЛУЭТ: %lld рёбер за %.2f с (опрошено %lld, пропущено параллельных %lld)\n",
           (long long)nsil, t_sil, (long long)op_edges, (long long)nskip_par);
    if (!S->directional)
      printf("   МЕНЯЮТ ЗНАК ПО ИСТОЧНИКУ (полутень): %lld (%.2f %% силуэта)\n", (long long)npen,
             nsil > 0 ? 100.0 * (double)npen / (double)nsil : 0.0);
    fflush(stdout);

    /* ---- ПЕРЕБОР ПОРОГОВ -------------------------------------------------- */
    unsigned char *alive = malloc((size_t)(nsil > 0 ? nsil : 1));
    int64_t *hhead = NULL, *hnext = malloc((size_t)(nsil > 0 ? nsil : 1) * sizeof *hnext);
    double *pos = malloc((size_t)(nsil > 0 ? nsil : 1) * 3 * sizeof *pos);
    int64_t *surv = malloc((size_t)PF_SURV_MAX * sizeof *surv);
    double *chext = malloc((size_t)(nsil > 0 ? nsil : 1) * sizeof *chext);
    if (alive == NULL || hnext == NULL || pos == NULL || chext == NULL || surv == NULL) return 2;
    int64_t hsize = 1;
    while (hsize < 4 * (nsil > 0 ? nsil : 1))
      hsize <<= 1;
    hhead = malloc((size_t)hsize * sizeof *hhead);
    if (hhead == NULL) return 2;
    int64_t *hkey = malloc((size_t)hsize * sizeof *hkey);
    if (hkey == NULL) return 2;

    for (int ia = 0; ia < PF_NALPHA; ia++) {
      for (int ie = 0; ie < PF_NETA; ie++) {
        double alpha = PF_ALPHA_DEG[ia] * M_PI / 180.0;
        double eta = PF_ETA[ie];
        int lead = (ia == PF_Q_ALPHA && ie == PF_Q_ETA);
        int nk1 = (ia == PF_A_ZERO && ie == PF_E_ZERO);
        double t_run0 = now_s();

        memset(alive, 0, (size_t)nsil);
        int64_t op_pairs = 0, op_ff = 0, chain_over = 0;
        int64_t live = 0, bad_balance = 0;
        int64_t livetab[PF_NSHELL], dptab[PF_NSHELL], dctab[PF_NSHELL];

        for (int k = 0; k < PF_NSHELL; k++) {
          /* ФРОНТ СТОИТ НА ДАЛЬНЕЙ ГРАНИЦЕ ОБОЛОЧКИ, а не на ближней, и это не
           * мелочь. Хорда рождается где-то ВНУТРИ `[2^k, 2^{k+1})`; если
           * положение фронта взять `2^k`, то в СВОЕЙ оболочке всякая хорда
           * имеет пройденный путь `≤ 0`, полутень нулевую и точку фронта прямо
           * на ребре — то есть ни слияния, ни вклада посчитать нельзя. На
           * дальней границе пройденный путь строго положителен у всех. */
          double dk = pow(2.0, (double)(k + PF_KMIN + 1));
          /* 1. РОЖДЕНИЯ: все хорды этой оболочки оживают. Протяжённость хорды
           *    при рождении есть длина породившего ребра; дальше она
           *    накапливается слияниями. */
          for (int64_t i = 0; i < nsil; i++)
            if (ch[i].shell == k) {
              alive[i] = 1;
              double eh[3];
              v_sub(ch[i].e1, ch[i].e0, eh);
              chext[i] = sqrt(v_dot(eh, eh));
            }
          live += births[k];

          /* 2. Положение живых хорд НА ФРОНТЕ: середина ребра, продвинутая
           *    вдоль хода на пройденный путь. */
          double cell = alpha * dk;
          int64_t ndp = 0, ndc = 0;

          if (cell > 0.0) {
            for (int64_t i = 0; i < nsil; i++) {
              if (!alive[i]) continue;
              double adv = dk - ch[i].db;
              if (adv < 0.0) adv = 0.0;
              for (int c = 0; c < 3; c++)
                pos[3 * i + c] = 0.5 * (ch[i].e0[c] + ch[i].e1[c]) + adv * ch[i].u[c];
            }
            /* 3. СМЕРТИ ПО ПОЛУТЕНИ — сетка своя на оболочку (А388). */
            for (int64_t s = 0; s < hsize; s++)
              hhead[s] = -1;
            for (int64_t i = 0; i < nsil; i++) {
              if (!alive[i]) continue;
              int64_t cx = (int64_t)floor(pos[3 * i] / cell);
              int64_t cy = (int64_t)floor(pos[3 * i + 1] / cell);
              int64_t cz = (int64_t)floor(pos[3 * i + 2] / cell);
              int64_t key = (int64_t)cell_hash(cx, cy, cz);
              int64_t s = (int64_t)((uint64_t)key & (uint64_t)(hsize - 1));
              while (hhead[s] >= 0 && hkey[s] != key)
                s = (s + 1) & (hsize - 1);
              if (hhead[s] < 0) {
                hkey[s] = key;
                hnext[i] = -1;
              } else {
                hnext[i] = hhead[s];
              }
              hhead[s] = i;
            }
            /* ПЕРЕБОР В ЯЧЕЙКЕ ИДЁТ ПО ВЫЖИВШИМ, А НЕ ПО ВСЕМ ПАРАМ, И ЭТО
             * ИСПРАВЛЕНИЕ ЗАМЕРЕННОЙ ОШИБКИ, А НЕ ОПТИМИЗАЦИЯ. Прежняя версия
             * при переполнении ячейки бросала ВСЮ ячейку целиком, а плотность
             * ячейки растёт как `α³`, — и `α = 0.5°` давало БОЛЬШЕ слияний, чем
             * `α = 1°` (`286 826` против `105 515` в оболочке 8), то есть
             * величина шла ПРОТИВ параметра, которым её меняют. Это ровно та
             * подпись артефакта, которую §4 велит ловить.
             *
             * Здесь хорда сравнивается только с уже ВЫЖИВШИМИ в ячейке и при
             * первом же попадании гаснет. В плотной ячейке выживших мало — там,
             * где старый код захлёбывался, этот сходится быстрее всего. Потолок
             * остаётся, но теперь он ограничивает СПИСОК ЦЕЛЕЙ, а не отменяет
             * ячейку: хорда сверх потолка живёт (не гаснет), значит слияний
             * считается МЕНЬШЕ истинного — ошибка против гипотезы. Считается
             * при этом ХОРДАМИ, а не цепочками: цепочка ни о чём не говорит,
             * когда в ней сто тысяч записей. */
            for (int64_t s = 0; s < hsize; s++) {
              if (hhead[s] < 0) continue;
              int64_t nsv = 0;
              for (int64_t i = hhead[s]; i >= 0; i = hnext[i]) {
                if (!alive[i]) continue;
                double wi = alpha * (dk - ch[i].db);
                int merged = 0;
                if (wi > 0.0) {
                  for (int64_t t2 = 0; t2 < nsv; t2++) {
                    int64_t j = surv[t2];
                    op_pairs++;
                    double wj = alpha * (dk - ch[j].db);
                    if (wj <= 0.0) continue;
                    double wmin = wi < wj ? wi : wj;
                    double dx = pos[3 * i] - pos[3 * j];
                    double dy = pos[3 * i + 1] - pos[3 * j + 1];
                    double dz = pos[3 * i + 2] - pos[3 * j + 2];
                    if (dx * dx + dy * dy + dz * dz < wmin * wmin) {
                      alive[i] = 0;         /* слились — остаётся ОДИН разрыв */
                      chext[j] += chext[i]; /* и его протяжённость — сумма (см. п. 4) */
                      ndp++;
                      merged = 1;
                      break;
                    }
                  }
                }
                if (merged) continue;
                if (nsv < PF_SURV_MAX)
                  surv[nsv++] = i;
                else
                  chain_over++; /* целью слияния уже не станет — слияний МЕНЬШЕ */
              }
            }
          }

          /* 4. СМЕРТИ ПО ВКЛАДУ — замкнутый форм-фактор (А380/А391). */
          if (eta > 0.0) {
            for (int64_t i = 0; i < nsil; i++) {
              if (!alive[i]) continue;
              double adv = dk - ch[i].db;
              if (!(adv > 0.0)) continue; /* фронт до хорды ещё не дошёл */
              double p[3], n[3];
              for (int c = 0; c < 3; c++) {
                p[c] = 0.5 * (ch[i].e0[c] + ch[i].e1[c]) + adv * ch[i].u[c];
                n[c] = -ch[i].u[c]; /* площадка смотрит НА источник */
              }
              double full = src_irr(S, p, n, NULL, NULL);
              op_ff++;
              if (!(full > 0.0)) continue; /* источника отсюда не видно — не гасим */
              /* РЕЖУЩАЯ ПЛОСКОСТЬ содержит РЕБРО и НАПРАВЛЕНИЕ ХОДА — это и
               * есть плоскость, которую точка фронта пересекает, переходя из
               * света в тень. Нормаль берётся как `ребро × ход`, а НЕ через
               * `(e0−p) × (e1−p)`: второе алгебраически то же самое, но при
               * малом пройденном пути обращается в разность почти
               * антипараллельных векторов, и направление плоскости вырождается
               * в шум. На солнце это давало «доля источника = 0» у хорд, только
               * что родившихся, то есть ложные смерти там, где их не может быть
               * вовсе, — поймано НК2. */
              double eh[3], mc[3];
              v_sub(ch[i].e1, ch[i].e0, eh);
              double elen = sqrt(v_dot(eh, eh));
              v_cross(eh, ch[i].u, mc);
              if (!(v_norm(mc) > PF_PAR_TINY * elen))
                continue; /* ребро вдоль хода: тени не кроит */
              double zr[3];
              v_sub(ch[i].zc, p, zr);
              if (v_dot(mc, zr) < 0.0)
                for (int c = 0; c < 3; c++)
                  mc[c] = -mc[c];
              /* ВТОРАЯ ПЛОСКОСТЬ — И БЕЗ НЕЁ ПОРОГ МЁРТВ. Одной полуплоскостью
               * через ребро источник делится примерно пополам ВСЕГДА: и у
               * стены дома, и у камешка. Такая «доля» ни от чего не зависит,
               * и `η` не гасит ничего ни при каком значении — замерено на зале
               * до этой правки (ноль смертей при `η = 1 %` на ПРОТЯЖЁННОМ
               * источнике, то есть ровно там, где А383 требует их видеть).
               *
               * Настоящая величина: разрыв кроит не полусферу, а ПОЛОСУ,
               * угловая ширина которой равна угловому размеру САМОЙ ХОРДЫ из
               * точки фронта, `θ = 2·atan(L/2·adv)`. Длинное ребро стены даёт
               * полосу шире источника — модуляция полная; метровое ребро с
               * `500` м даёт полосу в тысячу раз у́же — модуляция ничтожна, и
               * разрыв законно гаснет. Полоса задаётся второй плоскостью через
               * ту же точку, повёрнутой на `θ` вокруг ребра; обе плоскости
               * проходят через `p`, поэтому режет их тот же `hz_pff_clip_half`.
               *
               * ДЛИНА ХОРДЫ НАКАПЛИВАЕТСЯ ПРИ СЛИЯНИИ (`ext`): слившиеся хорды
               * есть ОДИН разрыв, и его протяжённость — сумма, а не одна из.
               * Сумма — верхняя оценка объединения, то есть модуляция берётся
               * ЗАВЫШЕННОЙ, и гаснет МЕНЬШЕ разрывов, чем на самом деле. Ошибка
               * идёт против гипотезы, как требует А380. */
              double th = 2.0 * atan(0.5 * chext[i] / adv);
              if (th > 0.5 * M_PI) th = 0.5 * M_PI;
              double mc2[3];
              for (int c = 0; c < 3; c++)
                mc2[c] = -(cos(th) * mc[c] - sin(th) * n[c]);
              double cut = src_irr(S, p, n, mc, mc2);
              op_ff++;
              if (cut / full < eta) {
                alive[i] = 0;
                ndc++;
              }
            }
          }

          live -= ndp + ndc;
          /* НК3: баланс есть ТОЖДЕСТВО. Пересчёт прямым перебором. */
          int64_t direct = 0;
          for (int64_t i = 0; i < nsil; i++)
            if (alive[i]) direct++;
          if (direct != live) bad_balance++;
          livetab[k] = live;
          dptab[k] = ndp;
          dctab[k] = ndc;
        }

        double t_run = now_s() - t_run0;
        if (lead) t_lead_src[si] = t_run;

        /* ---- ДОКЛАД ТАБЛИЦЫ ---------------------------------------------- */
        printf("\n-- α = %.2f°, η = %.3f %%%s%s   (кадр %.1f с)\n", PF_ALPHA_DEG[ia], 100.0 * eta,
               lead ? "   [ВЕДУЩАЯ ПАРА — по ней приёмка и УБИВАЕТ]" : "   [чувствительность]",
               nk1 ? "   [НК1]" : "", t_run);
        printf("   обол. фронт,м  рождений   смертей(полутень)  смертей(вклад)   ЖИВЫХ    "
               "площадь пов., м²\n");
        for (int k = 0; k < PF_NSHELL; k++)
          printf("   %4d %8.0f %10lld %18lld %16lld %8lld %17.4g\n", k + PF_KMIN,
                 pow(2.0, (double)(k + PF_KMIN + 1)), (long long)births[k], (long long)dptab[k],
                 (long long)dctab[k], (long long)livetab[k], shell_area[k]);

        /* Показатель роста: наклон log(живые) по log(d) на оболочках, где
         * поверхность НЕ падает (А381) — иначе меряется конец сцены. */
        double sx = 0, sy = 0, sxx = 0, sxy = 0;
        int nfit = 0, kfirst = -1, klast = -1;
        for (int k = 1; k < PF_NSHELL; k++) {
          if (livetab[k] <= 0 || !(shell_area[k] > 0.0)) continue;
          if (!(shell_area[k] >= shell_area[k - 1])) continue;
          double x = (double)(k + PF_KMIN) * log(2.0), y = log((double)livetab[k]);
          sx += x;
          sy += y;
          sxx += x * x;
          sxy += x * y;
          nfit++;
          if (kfirst < 0) kfirst = k;
          klast = k;
        }
        double slope = 0.0;
        if (nfit >= 2) {
          double den = (double)nfit * sxx - sx * sx;
          if (fabs(den) > 0.0) slope = ((double)nfit * sxy - sx * sy) / den;
        }
        /* ОТНОШЕНИЕ ДАЛЬНЕЙ К БЛИЖНЕЙ БЕРЁТСЯ ТОЛЬКО ПО ОБОЛОЧКАМ С ГЕОМЕТРИЕЙ
         * (А381). За концом сцены живые хорды продолжают лететь и сливаться, и
         * взятое там отношение мерило бы конец габарита, а не насыщение. */
        int knz0 = -1, knz1 = -1;
        for (int k = 0; k < PF_NSHELL; k++)
          if (livetab[k] > 0 && shell_area[k] > 0.0) {
            if (knz0 < 0) knz0 = k;
            knz1 = k;
          }
        double ratio =
            (knz0 >= 0 && knz1 > knz0) ? (double)livetab[knz1] / (double)livetab[knz0] : -1.0;
        int64_t peak = 0;
        for (int k = 0; k < PF_NSHELL; k++)
          if (shell_area[k] > 0.0 && livetab[k] > peak) peak = livetab[k];

        /* СКОЛЬКО ОБОЛОЧЕК ФРОНТ ИДЁТ УЖЕ ПО ПОЛНОЙ СЦЕНЕ. Пока поверхность в
         * оболочке РАСТЁТ, фронт ещё ВХОДИТ в сцену, и всякий показатель там
         * мерит вход, а не сложность фронта. А381 требовала не засчитывать
         * полку там, где поверхность падает; здесь виден второй край той же
         * беды, и он печатается числом, а не остаётся в рассуждении. */
        int kpeak = 0, ngeom = 0, npast = 0;
        for (int k = 0; k < PF_NSHELL; k++) {
          if (shell_area[k] > 0.0) ngeom++;
          if (shell_area[k] > shell_area[kpeak]) kpeak = k;
        }
        for (int k = kpeak + 1; k < PF_NSHELL; k++)
          if (shell_area[k] > 0.0) npast++;
        printf("   ОБОЛОЧЕК С ГЕОМЕТРИЕЙ %d из %d; пик поверхности на k = %d; ПОСЛЕ пика их %d "
               "— %s\n",
               ngeom, PF_NSHELL, kpeak + PF_KMIN, npast,
               npast >= 2 ? "установившийся ход есть"
                          : "УСТАНОВИВШЕГОСЯ ХОДА НЕТ, фронт ещё входит в сцену");
        printf("   ПОКАЗАТЕЛЬ роста живых по расстоянию: ");
        if (nfit >= 3)
          printf("%.2f (по %d оболочкам с растущей поверхностью: k = %d…%d)\n", slope, nfit,
                 kfirst + PF_KMIN, klast + PF_KMIN);
        else
          printf("НЕ ОПРЕДЕЛЁН — годных оболочек %d (нужно ≥ 3)\n", nfit);
        if (ratio >= 0.0)
          printf("   ОТНОШЕНИЕ дальней оболочки к ближней (только там, где есть поверхность): "
                 "%.2f (k = %d -> %d); ПОЛКА (максимум живых) %lld\n",
                 ratio, knz0 + PF_KMIN, knz1 + PF_KMIN, (long long)peak);
        else
          printf("   ОТНОШЕНИЕ дальней к ближней: НЕ ОПРЕДЕЛЕНО (оболочек с поверхностью меньше "
                 "двух); ПОЛКА %lld\n",
                 (long long)peak);
        printf("   БАЛАНС (НК3): оболочек с невязкой %lld из %d — %s\n", (long long)bad_balance,
               PF_NSHELL, bad_balance == 0 ? "СОШЁЛСЯ ТОЧНО" : "НЕ СОШЁЛСЯ, СЧЁТ НЕДЕЙСТВИТЕЛЕН");
        printf("   ЦЕНА (А384): рёбер опрошено %lld (%.2f на треугольник); пар проверено %lld "
               "(%.2f на треугольник); форм-факторов %lld (%.2f на треугольник)",
               (long long)op_edges, (double)op_edges / (double)m.nt, (long long)op_pairs,
               (double)op_pairs / (double)m.nt, (long long)op_ff, (double)op_ff / (double)m.nt);
        if (chain_over > 0)
          printf("; ХОРД СВЕРХ ПОТОЛКА ЦЕЛЕЙ %lld (остались живы, слияний НЕДОСЧИТАНО)",
                 (long long)chain_over);
        printf("\n");

        if (lead) {
          /* ПРИЁМКА ОБЪЯВЛЯЕТСЯ ТОЛЬКО ТАМ, ГДЕ ЕЙ ЕСТЬ НА ЧЁМ СТОЯТЬ. У сцены
           * с двумя-тремя оболочками «отношение ≤ 3» выполнится само собой, и
           * это был бы ровно тот класс, где величина перестаёт зависеть от
           * того, что ею меряют. */
          if (ratio < 0.0 || nfit < 3) {
            printf("   *** ПРИЁМКА (ведущая пара): НЕ ПРИМЕНИМА — оболочек с геометрией слишком "
                   "мало (годных для наклона %d, нужно ≥ 3). Сцена мала для вопроса.\n",
                   nfit);
          } else {
            int ok_ratio = (ratio <= 3.0);
            int ok_peak = (peak <= 10000);
            int ok_bal = (bad_balance == 0);
            printf("   *** ПРИЁМКА (ведущая пара): отношение ≤ 3 — %s; полка ≤ 1e4 — %s; баланс "
                   "точен — %s\n",
                   ok_ratio ? "ДА" : "НЕТ", ok_peak ? "ДА" : "НЕТ", ok_bal ? "ДА" : "НЕТ");
            printf("   *** УБИВАЕТ (§172): показатель выше 1.7 — %s (%.2f)\n",
                   slope > 1.7 ? "ДА, ПОДЦЕЛЬ ЗАКРЫТА ОТРИЦАТЕЛЬНО" : "нет", slope);
          }
        }
        if (nk1) {
          if (nfit < 3)
            printf("   *** НК1 (α = 0, η = 0): показатель не определён (годных оболочек %d) — "
                   "контроль НЕ ВЫПОЛНЕН, положительные итоги не засчитываются\n",
                   nfit);
          else
            printf("   *** НК1 (α = 0, η = 0): ничто не гаснет и не сливается, живые обязаны расти "
                   "как рождения, показатель 1.8…2.2 — получено %.2f: %s\n",
                   slope, (slope >= 1.8 && slope <= 2.2) ? "ПРОШЁЛ" : "НЕ ПРОШЁЛ");
        }
        if (S->directional && ie == PF_Q_ETA) {
          int64_t sumdc = 0;
          for (int k = 0; k < PF_NSHELL; k++)
            sumdc += dctab[k];
          if (lead)
            printf("   *** НК2 (солнце, ВЕДУЩАЯ ПАРА): смертей по вкладу обязано быть РОВНО ноль — "
                   "получено %lld: %s\n",
                   (long long)sumdc,
                   sumdc == 0 ? "ПРОШЁЛ" : "НЕ ПРОШЁЛ, ПОРОГ СЧИТАЕТ НЕ ТО, ЧТО НАЗВАН");
          else
            printf("   (НК2 не применим при α = %.2f°: довод А383 держится на том, что заслон "
                   "КРУПНЕЕ полутени, а при этом α полутень уже́ солнечного диска %.3f°, и хорды "
                   "мельче диска доживают до порога законно. Смертей по вкладу %lld.)\n",
                   PF_ALPHA_DEG[ia], PF_SUN_DEG, (long long)sumdc);
        }
        fflush(stdout);
      }
    }
    free(alive);
    free(hnext);
    free(hhead);
    free(hkey);
    free(pos);
    free(chext);
    free(surv);
  }

  /* ================= КАРТИНКА: ТЕНЬ РАЗРЫВАМИ ПРОТИВ ЛУЧЕЙ =============== */
  if (do_pic && do_sun) {
    printf("\n================================================================\n");
    printf("=== КАРТИНКА (А385/А393): тень РАЗРЫВАМИ ФРОНТА против эталона лучами\n");
    printf("================================================================\n");
    fflush(stdout);

    const pf_src *S = &srcs[0];
    double w[3];
    for (int i = 0; i < 3; i++)
      w[i] = S->w[i];

    /* Камера §110. */
    double eye[3] = HZ_CFG_CITY_EYE, at[3] = HZ_CFG_CITY_AT, up[3] = HZ_CFG_UP;
    if (!city) {
      double e2[3] = HZ_CFG_HALL_EYE, a2[3] = HZ_CFG_HALL_AT;
      for (int i = 0; i < 3; i++) {
        eye[i] = e2[i];
        at[i] = a2[i];
      }
    }
    double fwd[3], right[3], upv[3];
    v_sub(at, eye, fwd);
    v_norm(fwd);
    v_cross(fwd, up, right);
    v_norm(right);
    v_cross(right, fwd, upv);
    v_norm(upv);
    double tanh2 = tan(0.5 * HZ_CFG_FOV_DEG * M_PI / 180.0);
    int W = HZ_CFG_W, H = HZ_CFG_H;
    int64_t npix = (int64_t)W * H;

    /* calloc, а не malloc, и это не перестраховка: массивы заполняются в
     * ПАРАЛЛЕЛЬНОМ цикле, а gcc-analyzer сквозь OpenMP связь «заполнено —
     * прочитано» не видит и даёт ложное «use of uninitialized value» (тот же
     * класс, что описан в CLAUDE.md по поводу обёрток выделения). Нулевые
     * страницы от ядра приходят уже обнулёнными, так что цена нулевая. */
    double *px = calloc((size_t)npix * 3, sizeof *px);
    unsigned char *phit = malloc((size_t)npix);
    unsigned char *pref = malloc((size_t)npix);
    unsigned char *pfr = malloc((size_t)npix);
    int32_t *ptri = malloc((size_t)npix * sizeof *ptri);
    if (px == NULL || phit == NULL || pref == NULL || pfr == NULL || ptri == NULL) return 2;

    double far = 4.0 * diag;
    double t_pic0 = now_s();
#pragma omp parallel for schedule(dynamic, 16)
    for (int j = 0; j < H; j++) {
      for (int i = 0; i < W; i++) {
        int64_t q = (int64_t)j * W + i;
        double sx = (2.0 * ((double)i + 0.5) / (double)W - 1.0) * tanh2;
        double sy = (1.0 - 2.0 * ((double)j + 0.5) / (double)H) * tanh2;
        /* Инициализация нулём не «на всякий случай»: без неё gcc-analyzer теряет
         * связь цикла по трём осям с последующим использованием и даёт ложное
         * «use of uninitialized value» (тот же класс, что описан в CLAUDE.md). */
        double d[3] = {0.0, 0.0, 0.0};
        for (int c = 0; c < 3; c++)
          d[c] = fwd[c] + sx * right[c] + sy * upv[c];
        v_norm(d);
        double t = 0.0;
        int32_t ht = -1;
        if (hz_pgrid_trace_tri(&grid, &m, eye, d, 0.0, far, NULL, 0, 0, &t, &ht)) {
          phit[q] = 1;
          ptri[q] = ht;
          for (int c = 0; c < 3; c++)
            px[3 * q + c] = eye[c] + t * d[c];
        } else {
          phit[q] = 0;
          ptri[q] = -1;
          for (int c = 0; c < 3; c++)
            px[3 * q + c] = 0.0;
        }
      }
    }
    double t_prim = now_s() - t_pic0;
    t_pic_prim = t_prim;

    /* ЭТАЛОН: луч к источнику той же сеткой. */
    double t_ref0 = now_s();
    double mw[3] = {-w[0], -w[1], -w[2]};
#pragma omp parallel for schedule(dynamic, 16)
    for (int64_t q = 0; q < npix; q++) {
      if (!phit[q]) {
        pref[q] = 0;
        continue;
      }
      double o[3], t = 0.0;
      for (int c = 0; c < 3; c++)
        o[c] = px[3 * q + c] + PF_SHADOW_EPS * mw[c];
      pref[q] = hz_pgrid_trace(&grid, &m, o, mw, 0.0, far, NULL, 0, 1, &t) ? 1 : 0;
    }
    double t_ref = now_s() - t_ref0;
    t_pic_ref = t_ref;

    /* ---- ТЕНЬ РАЗРЫВАМИ ------------------------------------------------- */
    /* Рама поперёк лучей: `(a, b, w)` правая. Разрыв — силуэтное ребро,
     * спроецированное на `(a, b)`; точка в тени тогда и только тогда, когда
     * число обходов по рёбрам ВЫШЕ ПО ФРОНТУ не ноль. */
    double aa[3] = {0.0, 0.0, 0.0}, bb[3];
    {
      int ax = (fabs(w[0]) < fabs(w[1])) ? ((fabs(w[0]) < fabs(w[2])) ? 0 : 2)
                                         : ((fabs(w[1]) < fabs(w[2])) ? 1 : 2);
      double tmp[3] = {0.0, 0.0, 0.0};
      tmp[ax] = 1.0;
      v_cross(w, tmp, aa);
      v_norm(aa);
      v_cross(w, aa, bb);
      v_norm(bb);
    }

    double t_fr0 = now_s();
    /* Полоса по `v`, которую занимают видимые точки: разрывы вне неё строку не
     * пересекают вовсе. */
    double vlo = 1e300, vhi = -1e300, shi_ = -1e300;
    for (int64_t q = 0; q < npix; q++) {
      if (!phit[q]) continue;
      double v = v_dot(bb, px + 3 * q), s = v_dot(w, px + 3 * q);
      if (v < vlo) vlo = v;
      if (v > vhi) vhi = v;
      if (s > shi_) shi_ = s;
    }
    if (!(vhi > vlo)) {
      vlo = 0.0;
      vhi = 1.0;
    }
    double dv = (vhi - vlo) / (double)rows;

    /* ГРАНИЦА ОСВЕЩЁННОГО МНОЖЕСТВА, А НЕ ОДИН СИЛУЭТ — И ЭТО ИСПРАВЛЕНИЕ, А НЕ
     * УСЛОЖНЕНИЕ. Фронт, дойдя до глубины `s`, прошёл часть освещённых граней;
     * тень отбрасывает ИМЕННО ЭТА часть, и её граница есть разрывный контур.
     * Силуэт всей сцены такой границей НЕ является: ребро между двумя
     * освещёнными гранями, из которых пройдена только одна, тоже граница, и
     * перестаёт ею быть, лишь когда фронт пройдёт вторую. Поэтому в накопитель
     * кладутся ВСЕ три ребра каждой освещённой грани в её собственном порядке
     * обхода: у пройденной пары соседей общее ребро входит дважды с
     * противоположными знаками и гасится САМО. Считать нечего — сокращение
     * алгебраическое.
     *
     * ГЛУБИНА ГРАНИ БЕРЁТСЯ ПО САМОЙ ДАЛЬНЕЙ ЕЁ ВЕРШИНЕ. Тогда точка на грани
     * никогда не оказывается «позади самой себя», и известной болезни теневых
     * объёмов — самозатенения в крапинку — не возникает вовсе. Цена названа:
     * грань, чья глубина перекрывается с точкой, тени на неё не бросит, то есть
     * контакт тени слегка недооценивается. Ошибка в сторону НЕДОСТАЧИ тени. */
    int64_t nlitf = 0;
    for (int32_t t = 0; t < m.nt; t++)
      if (v_dot(fn + 3 * (size_t)t, w) < 0.0) nlitf++;

    /* Границы видимого: строка растра нужна только там, где есть пиксели, а
     * пересечения ЛЕВЕЕ самого левого пикселя не видит ни один запрос (сумма
     * берётся ПРАВЕЕ) и потому не хранится. */
    double umin = 1e300;
    for (int64_t q = 0; q < npix; q++)
      if (phit[q]) {
        double u = v_dot(aa, px + 3 * q);
        if (u < umin) umin = u;
      }

    /* Пиксели по строкам — CSR, один раз на всю картинку. */
    int64_t *prow = malloc((size_t)npix * sizeof *prow);
    int64_t *pcnt = calloc((size_t)rows + 2, sizeof *pcnt);
    if (prow == NULL || pcnt == NULL) return 2;
    for (int64_t q = 0; q < npix; q++) {
      if (!phit[q]) {
        prow[q] = -1;
        continue;
      }
      double v = v_dot(bb, px + 3 * q);
      int r = (int)floor((v - vlo) / dv);
      if (r < 0) r = 0;
      if (r >= rows) r = rows - 1;
      prow[q] = r;
      pcnt[r + 1]++;
    }
    for (int r = 0; r < rows; r++)
      pcnt[r + 1] += pcnt[r];
    int64_t *plist = malloc((size_t)(pcnt[rows] > 0 ? pcnt[rows] : 1) * sizeof *plist);
    if (plist == NULL) return 2;
    {
      int64_t *cur = malloc((size_t)rows * sizeof *cur);
      if (cur == NULL) return 2;
      for (int r = 0; r < rows; r++)
        cur[r] = pcnt[r];
      for (int64_t q = 0; q < npix; q++)
        if (prow[q] >= 0) plist[cur[prow[q]]++] = q;
      free(cur);
    }
    for (int64_t q = 0; q < npix; q++)
      pfr[q] = 0;

    /* СТРОКИ ОБРАБАТЫВАЮТСЯ ПОЛОСАМИ. Пересечений на всю картинку выходит
     * десятки миллионов, и держать их разом значит гигабайт; полоса стоит
     * лишнего прохода по граням (секунды) и снимает потолок памяти совсем. */
    int64_t nxr_tot = 0, nband = 0;
    double t_scan = 0.0; /* обход граней отдельно от развёртки строк — пункт 11 реестра */
    int nth = omp_get_max_threads();
    int64_t *roff = calloc((size_t)PF_BAND + 2, sizeof *roff);
    /* Счётчики строк ПО ПОТОКАМ: nth × (nr+1) при nr ≤ PF_BAND — тридцать
     * килобайт, то есть цена нулевая, а атомарных операций в обходе нет вовсе. */
    int64_t *tcnt = calloc((size_t)nth * (size_t)(PF_BAND + 1) + 1, sizeof *tcnt);
    if (roff == NULL || tcnt == NULL) return 2;
    double *xu = NULL, *xs = NULL;
    signed char *xg = NULL;
    int64_t xcap = 0;

    for (int rb = 0; rb < rows; rb += PF_BAND) {
      int rlo = rb, rhi = rb + PF_BAND < rows ? rb + PF_BAND : rows;
      int nr = rhi - rlo;
      int64_t npx_band = pcnt[rhi] - pcnt[rlo];
      if (npx_band == 0) continue;
      nband++;
      double bvlo = vlo + (double)rlo * dv, bvhi = vlo + (double)rhi * dv;
      int64_t nxr = 0;
      double t_sc0 = now_s();
      /* ОБХОД ГРАНЕЙ ПАРАЛЛЕЛЬНЫЙ, ДВА ПРОХОДА ПО ОДНОМУ И ТОМУ ЖЕ РАЗБИЕНИЮ.
       *
       * Счёт идёт в СВОЙ на поток массив строк; после редукции каждый поток
       * знает не только сколько он записал, но и КУДА — своё начало внутри
       * каждой строки. Тогда заполнение обходится без атомарных операций и без
       * блокировок, а порядок записей внутри строки от числа потоков не
       * зависит вовсе: строка потом всё равно сортируется.
       *
       * `schedule(static)` в ОБОИХ проходах обязателен и не косметичен: он
       * гарантирует, что поток получит РОВНО ТЕ ЖЕ грани, что и в проходе
       * счёта. С `dynamic` разбиение разъехалось бы, и потоки писали бы в чужие
       * места. */
      for (int i = 0; i <= nth * (nr + 1); i++)
        tcnt[i] = 0;
#pragma omp parallel
      {
        int tid = omp_get_thread_num();
        int64_t *cnt = tcnt + (size_t)tid * (size_t)(nr + 1);
#pragma omp for schedule(static)
        for (int32_t t = 0; t < m.nt; t++) {
          if (!(v_dot(fn + 3 * (size_t)t, w) < 0.0)) continue; /* грань не освещена */
          const double *A = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 0];
          const double *B = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 1];
          const double *C = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 2];
          double da = v_dot(w, A), db2 = v_dot(w, B), dc = v_dot(w, C);
          double dface = da > db2 ? (da > dc ? da : dc) : (db2 > dc ? db2 : dc);
          if (dface > shi_) continue; /* грань дальше всей картинки — тени не даёт */
          const double *vp[4] = {A, B, C, A};
          for (int k = 0; k < 3; k++) {
            double v0 = v_dot(bb, vp[k]), v1 = v_dot(bb, vp[k + 1]);
            double lo = v0 < v1 ? v0 : v1, hi = v0 < v1 ? v1 : v0;
            if (hi < bvlo || lo > bvhi) continue;
            int r0 = (int)floor((lo - vlo) / dv) - rlo, r1 = (int)floor((hi - vlo) / dv) - rlo;
            if (r0 < 0) r0 = 0;
            if (r1 >= nr) r1 = nr - 1;
            double u0 = v_dot(aa, vp[k]), u1 = v_dot(aa, vp[k + 1]);
            for (int r = r0; r <= r1; r++) {
              double vr = vlo + ((double)(rlo + r) + 0.5) * dv;
              /* Полуоткрытое правило: вершина ровно на строке считается ОДИН
               * раз, иначе у замкнутого контура вышло бы чётное число
               * пересечений там, где должно быть нечётное. */
              if ((v0 <= vr) == (v1 <= vr)) continue;
              double tt = (vr - v0) / (v1 - v0);
              if (u0 + tt * (u1 - u0) < umin) continue; /* левее всех пикселей */
              cnt[r]++;
            }
          }
        }
      }
      /* Редукция: строкам — начала CSR, потокам — их места внутри строк. */
      {
        int64_t acc = 0;
        for (int r = 0; r < nr; r++) {
          roff[r] = acc;
          for (int q = 0; q < nth; q++) {
            int64_t c = tcnt[(size_t)q * (size_t)(nr + 1) + (size_t)r];
            tcnt[(size_t)q * (size_t)(nr + 1) + (size_t)r] = acc;
            acc += c;
          }
        }
        roff[nr] = acc;
        nxr = acc;
      }
      if (nxr > xcap) {
        free(xu);
        free(xs);
        free(xg);
        xcap = nxr + nxr / 2 + 16;
        xu = calloc((size_t)xcap, sizeof *xu);
        xs = calloc((size_t)xcap, sizeof *xs);
        xg = calloc((size_t)xcap, 1);
        if (xu == NULL || xs == NULL || xg == NULL) return 2;
      }
#pragma omp parallel
      {
        int tid = omp_get_thread_num();
        int64_t *cur = tcnt + (size_t)tid * (size_t)(nr + 1);
#pragma omp for schedule(static)
        for (int32_t t = 0; t < m.nt; t++) {
          if (!(v_dot(fn + 3 * (size_t)t, w) < 0.0)) continue;
          const double *A = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 0];
          const double *B = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 1];
          const double *C = m.v + 3 * (size_t)m.f[(size_t)t * 3 + 2];
          double da = v_dot(w, A), db2 = v_dot(w, B), dc = v_dot(w, C);
          double dface = da > db2 ? (da > dc ? da : dc) : (db2 > dc ? db2 : dc);
          if (dface > shi_) continue;
          const double *vp[4] = {A, B, C, A};
          for (int k = 0; k < 3; k++) {
            double v0 = v_dot(bb, vp[k]), v1 = v_dot(bb, vp[k + 1]);
            double lo = v0 < v1 ? v0 : v1, hi = v0 < v1 ? v1 : v0;
            if (hi < bvlo || lo > bvhi) continue;
            int r0 = (int)floor((lo - vlo) / dv) - rlo, r1 = (int)floor((hi - vlo) / dv) - rlo;
            if (r0 < 0) r0 = 0;
            if (r1 >= nr) r1 = nr - 1;
            double u0 = v_dot(aa, vp[k]), u1 = v_dot(aa, vp[k + 1]);
            for (int r = r0; r <= r1; r++) {
              double vr = vlo + ((double)(rlo + r) + 0.5) * dv;
              if ((v0 <= vr) == (v1 <= vr)) continue;
              double tt = (vr - v0) / (v1 - v0);
              double uc = u0 + tt * (u1 - u0);
              if (uc < umin) continue;
              int64_t at2 = cur[r]++;
              xu[at2] = uc;
              xs[at2] = dface;
              xg[at2] = (signed char)((v1 > v0) ? 1 : -1);
            }
          }
        }
      }
      t_scan += now_s() - t_sc0;
      nxr_tot += nxr;

      /* СТРОКИ НЕЗАВИСИМЫ — И СЧИТАЮТСЯ ПАРАЛЛЕЛЬНО. Каждая строка держит своё
       * дерево Фенвика и свои сортировки, общего состояния нет вовсе; буферы
       * потому и заводятся ВНУТРИ параллельной области, по одному набору на
       * поток. До этой правки весь обход шёл в один поток и занимал `17` с из
       * `24` — то есть стенд мерил бы цену схемы по самой медленной из
       * возможных реализаций.
       *
       * СОРТИРОВКА ПЕРЕСЕЧЕНИЙ ПО ГЛУБИНЕ — `qsort`, А НЕ ВСТАВКАМИ. В строке
       * оказалось около `4 600` записей, а не «десятки», как было написано в
       * первой редакции: вставки давали `n²` и съедали почти всё время обхода.
       * Цена ошибки была видна только замером, поэтому она здесь и записана. */
      /* Наибольшая строка полосы — по ней и выделяется рабочая память, ОДИН
       * раз на поток. Выделять внутри цикла по строкам нельзя: тогда проверку
       * «выделилось ли» приходится ставить в середину цикла, и она перестаёт
       * доминировать над использованием — ровно то, на что справедливо ругается
       * gcc-analyzer. */
      int64_t maxc = 0, maxp = 0;
      for (int r = 0; r < nr; r++) {
        if (roff[r + 1] - roff[r] > maxc) maxc = roff[r + 1] - roff[r];
        if (pcnt[rlo + r + 1] - pcnt[rlo + r] > maxp) maxp = pcnt[rlo + r + 1] - pcnt[rlo + r];
      }
#pragma omp parallel
      {
        /* calloc по тому же доводу, что и у `px` выше: заполнение идёт циклом,
         * а анализатор связь «заполнено — прочитано» через него не проводит.
         * Буферы строчные, их размер — тысячи записей, цена обнуления никакая. */
        pf_xkey *ordt = calloc((size_t)(maxc + 2), sizeof *ordt);
        double *usortt = calloc((size_t)(maxc + 2), sizeof *usortt);
        int32_t *fent = calloc((size_t)(maxc + 2), sizeof *fent);
        int64_t *pordt = calloc((size_t)(maxp + 2), sizeof *pordt);
        if (ordt != NULL && usortt != NULL && fent != NULL && pordt != NULL) {
#pragma omp for schedule(dynamic, 8)
          for (int r = 0; r < nr; r++) {
            int64_t c0 = roff[r], nc = roff[r + 1] - c0;
            int64_t q0 = pcnt[rlo + r], nq = pcnt[rlo + r + 1] - q0;
            if (nq == 0) continue;
            for (int64_t i = 0; i < nc; i++) {
              ordt[i].s = xs[c0 + i];
              ordt[i].i = c0 + i;
            }
            qsort(ordt, (size_t)nc, sizeof *ordt, cmp_xkey);
            for (int64_t i = 0; i < nc; i++)
              usortt[i] = xu[c0 + i];
            qsort(usortt, (size_t)nc, sizeof *usortt, cmp_dbl);
            for (int64_t i = 0; i < nq; i++)
              pordt[i] = plist[q0 + i];
            /* Пикселей в строке сотни, и вставки здесь дешевле вызова `qsort` с
             * ключом через косвенность. */
            for (int64_t i = 1; i < nq; i++) {
              int64_t key = pordt[i], j = i - 1;
              double kd = v_dot(w, px + 3 * key);
              while (j >= 0 && v_dot(w, px + 3 * pordt[j]) > kd) {
                pordt[j + 1] = pordt[j];
                j--;
              }
              pordt[j + 1] = key;
            }
            for (int64_t i = 0; i <= nc + 1; i++)
              fent[i] = 0;
            int64_t ip = 0;
            for (int64_t i = 0; i < nq; i++) {
              int64_t q = pordt[i];
              double sq = v_dot(w, px + 3 * q), uq = v_dot(aa, px + 3 * q);
              while (ip < nc && ordt[ip].s < sq) {
                double uv = xu[ordt[ip].i];
                int64_t a = 0, b2 = nc;
                while (a < b2) {
                  int64_t md = (a + b2) / 2;
                  if (usortt[md] < uv)
                    a = md + 1;
                  else
                    b2 = md;
                }
                for (int64_t kk = a + 1; kk <= nc; kk += kk & (-kk))
                  fent[kk] += xg[ordt[ip].i];
                ip++;
              }
              int64_t a = 0, b2 = nc;
              while (a < b2) {
                int64_t md = (a + b2) / 2;
                if (usortt[md] <= uq)
                  a = md + 1;
                else
                  b2 = md;
              }
              int32_t pre = 0, tot = 0;
              for (int64_t kk = a; kk > 0; kk -= kk & (-kk))
                pre += fent[kk];
              for (int64_t kk = nc; kk > 0; kk -= kk & (-kk))
                tot += fent[kk];
              pfr[q] = (tot - pre) != 0 ? 1 : 0;
            }
          }
        }
        free(ordt);
        free(pordt);
        free(usortt);
        free(fent);
      }
    }
    printf("   освещённых граней %lld из %d; пересечений строк %lld при %d строках (шаг строки "
           "%.4f м, полос %lld)\n",
           (long long)nlitf, m.nt, (long long)nxr_tot, rows, dv, (long long)nband);
    printf("   ИЗ НИХ ОБХОД ГРАНЕЙ %.2f с (%d потоков, %d проходов по %d млн граней) — пункт 11 "
           "реестра\n",
           t_scan, nth, 2 * (int)nband, m.nt / 1000000);
    fflush(stdout);

    free(xu);
    free(xs);
    free(xg);
    free(roff);
    free(tcnt);
    double t_fr = now_s() - t_fr0;
    t_pic_front = t_fr;

    /* ---- МЕТРИКА (А393): доля НЕСОВПАВШИХ по бинарному признаку ---------- */
    int64_t nhit = 0, nmis = 0, nsh_ref = 0, nsh_fr = 0;
    for (int64_t q = 0; q < npix; q++) {
      if (!phit[q]) continue;
      nhit++;
      if (pref[q]) nsh_ref++;
      if (pfr[q]) nsh_fr++;
      if (pref[q] != pfr[q]) nmis++;
    }
    printf("   ПЕРВИЧНЫЕ ЛУЧИ %.1f с; ЭТАЛОН (луч к источнику) %.1f с; ФРОНТ (разрывы) %.1f с\n",
           t_prim, t_ref, t_fr);
    printf("   пикселей с геометрией %lld из %lld; в тени: эталон %lld (%.2f %%), фронт %lld "
           "(%.2f %%)\n",
           (long long)nhit, (long long)npix, (long long)nsh_ref,
           nhit > 0 ? 100.0 * (double)nsh_ref / (double)nhit : 0.0, (long long)nsh_fr,
           nhit > 0 ? 100.0 * (double)nsh_fr / (double)nhit : 0.0);
    printf("   *** ДОЛЯ НЕСОВПАВШИХ (метрика А393): %.2f %% — приёмка ≤ 2 %%: %s\n",
           nhit > 0 ? 100.0 * (double)nmis / (double)nhit : 0.0,
           (nhit > 0 && 100.0 * (double)nmis / (double)nhit <= 2.0) ? "ДА" : "НЕТ");
    /* ПОЛ МЕТРИКИ (§4, вторая подпись артефакта). У сцены, где в тени `94 %`
     * пикселей, ответ «всё в тени» даёт несовпадение `6 %` — то есть метрика
     * сама по себе не пуста, но и не строга. Пол печатается рядом с итогом:
     * без него «0.5 %» нечем отличить от «метрика ничего не различает». */
    {
      int64_t triv = nhit - nsh_ref; /* «всё в тени» ошибается на освещённых */
      printf("   ПОЛ МЕТРИКИ (негативный контроль): тривиальный ответ «ВСЁ В ТЕНИ» даёт %.2f %%; "
             "фронт ниже пола в %.1f раза\n",
             nhit > 0 ? 100.0 * (double)triv / (double)nhit : 0.0,
             nmis > 0 ? (double)triv / (double)nmis : 0.0);
    }

    /* ХУДШИЕ МЕСТА (А393): строки картинки с наибольшей долей расхождения. */
    {
      int wj = -1;
      double wf = -1.0;
      for (int j = 0; j < H; j++) {
        int64_t h2 = 0, mm = 0;
        for (int i = 0; i < W; i++) {
          int64_t q = (int64_t)j * W + i;
          if (!phit[q]) continue;
          h2++;
          if (pref[q] != pfr[q]) mm++;
        }
        if (h2 > 0 && (double)mm / (double)h2 > wf) {
          wf = (double)mm / (double)h2;
          wj = j;
        }
      }
      printf("   худшая строка кадра: %d, доля расхождения %.2f %%\n", wj, 100.0 * wf);
    }

    /* КАРТИНКИ — В `img/`, А НЕ В `build/` (CLAUDE.md).
     *
     * ТРИ РАЗНЫЕ КАРТИНКИ, И ПУТАТЬ ИХ НЕЛЬЗЯ. Первая — ЗАТЕНЁННЫЙ КАДР: то,
     * ради чего шаг делался, город при солнце с тенями, построенными разрывами
     * фронта. Вторая — тот же кадр эталоном. Третья — КАРТА РАСХОЖДЕНИЯ, и
     * только она относится к метрике.
     *
     * ЗАТЕНЕНИЕ НЕ МЕНЯЕТ НИ ОДНОГО ИЗМЕРЕННОГО ЧИСЛА. Метрика А393 бинарна
     * («в тени / на свету») и берётся до всякой раскраски; ламбертов косинус и
     * цвет материала прикладываются при ЧТЕНИИ поля, как и предписано правилом
     * Т1. Яркость с эталоном по-прежнему НЕ сравнивается — её у фронта нет. */
    {
      unsigned char *rgb = malloc((size_t)npix * 3);
      double *sh = malloc((size_t)npix * 3 * sizeof *sh);
      if (rgb != NULL && sh != NULL) {
        /* НЕБО — не чёрное: чёрный фон нельзя отличить от чёрной тени, и на
         * прошлой версии картинки башня читалась как силуэт в тени. */
        const double sky[3] = {0.55, 0.68, 0.85};
        /* ОКРУЖАЮЩИЙ СВЕТ. Косвенного света у фронта пока нет (реестр §170,
         * пункт 2), и без подсветки тень выходит абсолютно чёрной, чего в
         * природе не бывает. Число названо и в метрику не входит. */
        const double amb = 0.22;
        for (int cs = 0; cs < 2; cs++) { /* 0 — фронт, 1 — эталон */
          const unsigned char *msk = cs ? pref : pfr;
          for (int64_t q = 0; q < npix; q++) {
            double c3[3];
            if (!phit[q] || ptri[q] < 0) {
              for (int c = 0; c < 3; c++)
                c3[c] = sky[c];
            } else {
              int32_t t = ptri[q];
              double nn[3];
              for (int c = 0; c < 3; c++)
                nn[c] = fn[3 * (size_t)t + (size_t)c];
              v_norm(nn);
              /* Нормаль разворачивается К КАМЕРЕ: у воксельной сцены
               * ориентация части граней произвольна (те самые `9.16 %`
               * неманифолдных стыков), и без разворота половина стен была бы
               * чёрной по причине, к свету отношения не имеющей. */
              double vd[3];
              v_sub(eye, px + 3 * q, vd);
              if (v_dot(nn, vd) < 0.0)
                for (int c = 0; c < 3; c++)
                  nn[c] = -nn[c];
              double ndl = -v_dot(nn, w);
              if (ndl < 0.0) ndl = 0.0;
              double lit = msk[q] ? 0.0 : ndl;
              const double *kd = m.mtl[m.fm[t]].kd3;
              for (int c = 0; c < 3; c++)
                c3[c] = kd[c] * (amb + (1.0 - amb) * lit);
            }
            for (int c = 0; c < 3; c++) {
              double g2 = pow(c3[c] < 0.0 ? 0.0 : (c3[c] > 1.0 ? 1.0 : c3[c]), 1.0 / 2.2);
              rgb[3 * q + c] = (unsigned char)(255.0 * g2 + 0.5);
            }
          }
          const char *path = cs ? "img/pfront_ref.ppm" : "img/pfront_sun.ppm";
          if (hz_ppm_write_rgb(path, rgb, W, H) == 0)
            printf("   %s: %s\n", cs ? "эталон лучами   " : "ФРОНТОМ (разрывы)", path);
        }
        /* КАРТА РАСХОЖДЕНИЯ — отдельным файлом, чтобы кадр не был испорчен
         * отладочной раскраской, а расхождение не терялось на кадре. */
        for (int64_t q = 0; q < npix; q++) {
          unsigned char r = 30, g = 34, b = 40;
          if (phit[q]) {
            r = g = b = (unsigned char)(pfr[q] ? 60 : 200);
            if (pref[q] != pfr[q]) {
              r = 230;
              g = 30;
              b = 30;
            }
          }
          rgb[3 * q] = r;
          rgb[3 * q + 1] = g;
          rgb[3 * q + 2] = b;
        }
        if (hz_ppm_write_rgb("img/pfront_diff.ppm", rgb, W, H) == 0)
          printf("   карта расхождения: img/pfront_diff.ppm (красное — где фронт разошёлся с "
                 "эталоном)\n");
      }
      free(rgb);
      free(sh);
    }

    free(plist);
    free(pcnt);
    free(ptri);
    free(prow);
    free(px);
    free(phit);
    free(pref);
    free(pfr);
  }

  free(ch);
  free(shell_area);
  free(births);
  free(fn);
  free(fa);
  free(fc);
  hz_pgrid_free(&grid);
  hz_padj_free(&adj);
  hz_obj_free(&m);
  /* ВРЕМЯ ДОКЛАДЫВАЕТСЯ РАЗДЕЛЬНО (§172, пункт 8; А387; реестр §170, пункт 7).
   * Связи привязаны к СЦЕНЕ и у статической геометрии строятся ОДИН раз, а
   * кадром считается только то, что пересчитывается при движении. Свалить их в
   * одно число — ровно та ошибка, которую §164 сделала с `3.91e8`. */
  printf("\n== ВРЕМЯ, РАЗДЕЛЬНО\n");
  printf("   ХОЛОДНЫЙ СТАРТ (один раз на сцену): чтение %.2f с + смежность, нормали и сетка "
         "%.2f с = %.2f с\n",
         t_load, t_cold, t_load + t_cold);
  printf("   СИЛУЭТ НА ИСТОЧНИК (один раз на источник, при неподвижном свете — тоже холодный "
         "старт): ");
  for (int si = 0; si < nsrc; si++)
    printf("%s%.2f с", si ? ", " : "", t_sil_src[si]);
  printf("\n");
  printf("   КАДР (марш по оболочкам, ведущая пара): ");
  for (int si = 0; si < nsrc; si++)
    printf("%s%.2f с", si ? ", " : "", t_lead_src[si]);
  printf("\n");
  if (t_pic_front >= 0.0)
    printf("   КАДР КАРТИНКИ: первичные лучи %.2f с + тень фронтом %.2f с = %.2f с (эталон лучами "
           "%.2f с — он НЕ часть схемы, а мера точности)\n",
           t_pic_prim, t_pic_front, t_pic_prim + t_pic_front, t_pic_ref);
  printf("== ВСЕГО %.1f с (предсказание П6 — 15…40 мин)\n", now_s() - t_start);
  return 0;
}
