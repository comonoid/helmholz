static double now_s(void) {
  struct timespec ts;
  clock_gettime(CLOCK_MONOTONIC, &ts);
  return (double)ts.tv_sec + 1e-9 * (double)ts.tv_nsec;
}

/* Ключ сортировки пересечений по глубине: пара (глубина, индекс). Отдельным
 * типом, потому что `qsort` без контекста не умеет сортировать индексы по
 * чужому массиву, а тащить сюда свою сортировку — это ещё один класс ошибок
 * ради одного вызова. */
typedef struct {
  double s;
  int64_t i;
} pf_xkey;

static int cmp_xkey(const void *a, const void *b) {
  double x = ((const pf_xkey *)a)->s, y = ((const pf_xkey *)b)->s;
  return (x < y) ? -1 : ((x > y) ? 1 : 0);
}

static int cmp_dbl(const void *a, const void *b) {
  double x = *(const double *)a, y = *(const double *)b;
  return (x < y) ? -1 : ((x > y) ? 1 : 0);
}

static void v_sub(const double a[3], const double b[3], double o[3]) {
  for (int i = 0; i < 3; i++)
    o[i] = a[i] - b[i];
}

static double v_dot(const double a[3], const double b[3]) {
  return a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
}

static void v_cross(const double a[3], const double b[3], double o[3]) {
  o[0] = a[1] * b[2] - a[2] * b[1];
  o[1] = a[2] * b[0] - a[0] * b[2];
  o[2] = a[0] * b[1] - a[1] * b[0];
}

static double v_norm(double a[3]) {
  double l = sqrt(v_dot(a, a));
  if (l > 0.0)
    for (int i = 0; i < 3; i++)
      a[i] /= l;
  return l;
}

/* ---- ИСТОЧНИК ------------------------------------------------------------ */

typedef struct {
  int directional; /* 1 — солнце (прямоугольник далеко), 0 — стена */
  double w[3];     /* направление ЛУЧЕЙ, единичное (только directional) */
  double c[3];     /* центр прямоугольника */
  double P[12];    /* 4 угла в мире, обход против часовой из освещаемой стороны */
  double le;
  const char *name;
} pf_src;

/* Расстояние до БЛИЖАЙШЕЙ точки прямоугольника (А390). У прямоугольника это
 * замкнутая формула: разложить по его раме, зажать координаты в габарит,
 * собрать обратно. Для солнца оболочка — слой между ПЛОСКОСТЯМИ, и расстояние
 * берётся вдоль лучей от плоскости входа (`d0` вычитается снаружи). */
static double src_dist(const pf_src *S, const double x[3], double eu[3], double ev[3], double hu,
                       double hv) {
  double r[3];
  v_sub(x, S->c, r);
  double u = v_dot(r, eu), v = v_dot(r, ev);
  if (u > hu) u = hu;
  if (u < -hu) u = -hu;
  if (v > hv) v = hv;
  if (v < -hv) v = -hv;
  double q[3];
  for (int i = 0; i < 3; i++)
    q[i] = S->c[i] + u * eu[i] + v * ev[i] - x[i];
  return sqrt(v_dot(q, q));
}

/* ОБЛУЧЁННОСТЬ ОТ ИСТОЧНИКА В ТОЧКЕ `p` НА ПЛОЩАДКЕ С НОРМАЛЬЮ `n`, замкнуто.
 * `k1`, `k2` (любой может быть NULL) — секущие полуплоскости ЧЕРЕЗ `p`:
 * остаётся часть источника с `k·R > 0`. Приёмная полуплоскость применяется
 * всегда. Всё считает контурный форм-фактор `src/pff.h`, квадратуры нет. */
static double src_irr(const pf_src *S, const double p[3], const double n[3], const double *k1,
                      const double *k2) {
  double rel[15], b1[18], b2[21], b3[24];
  for (int k = 0; k < 4; k++)
    for (int i = 0; i < 3; i++)
      rel[3 * k + i] = S->P[3 * k + i] - p[i];
  int m = 4;
  const double *cur = rel;
  if (k1 != NULL) {
    m = hz_pff_clip_half(cur, m, k1, b1);
    if (m < 3) return 0.0;
    cur = b1;
  }
  if (k2 != NULL) {
    m = hz_pff_clip_half(cur, m, k2, b2);
    if (m < 3) return 0.0;
    cur = b2;
  }
  m = hz_pff_clip_half(cur, m, n, b3);
  if (m < 3) return 0.0;
  double f = hz_pff_loop(b3, m, n);
  return (f > 0.0) ? f * S->le : 0.0;
}

